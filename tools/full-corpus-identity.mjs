#!/usr/bin/env node
// full-corpus-identity.mjs — V4-5 cut-over INPUT (not the decision): run the three ported
// generators over the 27-aggregate full-corpus canonical and diff every emitted file
// byte-for-byte against the live ingested-app tree (freshness-gated separately via
// backend-codegen tools/kn_repo_freshness.mjs — exit 0 = the tree IS the current knowledge
// release's generator output, so committed bytes are the authoritative live reference).
//
// Faces compared: skeleton (CodegenMain) 6 non-shared kinds, rules (rules_domain_gen) 7 kinds
// (owning the shared Behaviors/CommandHelpers paths — the live pipeline order lets the rules
// face win them), api (gen_api_layer) 6 kinds + the conf/routes E301 BLOCK (V4-7 — compared at
// marker-region granularity: the live file is shared territory whose outer lines belong to
// hand/other-generator faces). Everything else on the live tree (persistence adapters,
// RepositoryImpl, Bootstrap, ExecutableSpec, projections, AggregateStateApi/Auth/…) belongs to
// faces truthsrc has not ported — out of scope by declaration, listed in the report header, not
// diffed.
//
// Output: golden/scala-cqrs-es-metarch/full-corpus.identity.json (machine) + .md (human).
//
// Usage: node tools/full-corpus-identity.mjs [--live /path/to/ingested-app]

import fs from 'node:fs';
import { join, resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan } from '../src/core/generate.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
function arg(name, dflt) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && i + 1 < process.argv.length ? process.argv[i + 1] : dflt;
}
const LIVE = resolve(arg('live', '/Users/zhongdj/Workspaces/ingested-app'));
const GOLD = join(ROOT, 'golden', 'scala-cqrs-es-metarch');
const CANON = join(GOLD, 'full-corpus.canonical.json');
const HASHES = join(GOLD, 'full-corpus.elementHashes.json');

const elementHashes = JSON.parse(fs.readFileSync(HASHES, 'utf8'));
const canonical = JSON.parse(fs.readFileSync(CANON, 'utf8'));
const aggNames = canonical.aggregates.map((a) => a.name);

const GENS = {
  skeleton: { dir: join(ROOT, 'generators', 'scala-cqrs-es'), options: { generatorVersion: 'a0fca3da', elementHashes } },
  rules: { dir: join(ROOT, 'generators', 'scala-cqrs-es-rules'), options: { generatedBy: 'rules_domain_gen:2026-08-23', elementHashes } },
  api: { dir: join(ROOT, 'generators', 'scala-cqrs-es-api'), options: { elementHashes } },
};

// truthsrc outDir path (di-poc module layout) → live single-module path. null = unmapped.
function mapPath(p) {
  if (p.startsWith('modules/kernel/src/main/scala/')) return 'app/' + p.slice('modules/kernel/src/main/scala/'.length);
  if (p.startsWith('modules/kernel/src/test/scala/')) return 'test/' + p.slice('modules/kernel/src/test/scala/'.length);
  if (p.startsWith('app/controllers/')) return p;
  if (p === 'conf/routes') return 'conf/routes';
  return null;
}

const liveRead = (rel) => {
  const p = join(LIVE, rel);
  return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
};

// First-difference excerpt: line-bounded, ≤6 lines total, byte offset included.
function excerpt(a, b) {
  let i = 0;
  const n = Math.min(a.length, b.length);
  while (i < n && a[i] === b[i]) i++;
  const lineStart = a.lastIndexOf('\n', i) + 1;
  const lineNo = a.slice(0, lineStart).split('\n').length;
  const ctx = a.slice(lineStart, lineStart + 400).split('\n').slice(0, 3);
  const got = b.slice(lineStart, lineStart + 400).split('\n').slice(0, 3);
  return { byte: i, line: lineNo, want: ctx.join('\n').slice(0, 300), got: got.join('\n').slice(0, 300) };
}

// live stamp → owner face. The live tree is multi-pass: each path belongs to whichever
// generator wrote it LAST (e.g. rules_domain_gen owns the event-handlers — a lineage-driven
// rewrite pass truthsrc hasn't ported; gen_api_layer owns 15 repositories — a minimal-form
// rewrite). Comparing across owner faces produces fake diffs, so every row is classified by
// the live file's actual first-line stamp before any byte comparison.
function liveOwner(rel) {
  const want = liveRead(rel);
  if (want === null) return null;
  const m = want.match(/^\/\/ @generated by ([^\n]+)$/m);
  const stamp = m ? m[1] : '(none)';
  // Face identity = the generator NAME; the version suffix is the driver-repo git hash at
  // generation time and changes on every pipeline run (2026-10-15 stamp refresh: a0fca3da →
  // 225ed28b across 718 files). Pinning the hash misclassified the whole skeleton face.
  // Exception — frozen territory: the repository directory is R6-Ⅰ-frozen in the live pipeline
  // (gen_pipeline WriteTerritory.FrozenTerritories — repos frozen until R6-Ⅱ), so its
  // CodegenMain-stamped files are pre-migration relics the chain never rewrites; their bytes are
  // neither the skeleton's current output nor the api face's — out of comparison scope.
  if (/^app\/net\/imadz\/metarch\/application\/aggregates\/repository\//.test(rel)) return { owner: 'frozen', stamp };
  if (stamp.startsWith('CodegenMain:')) return { owner: 'skeleton', stamp };
  if (stamp.startsWith('rules_domain_gen:')) return { owner: 'rules', stamp };
  if (stamp.startsWith('gen_api_layer:')) return { owner: 'api', stamp };
  return { owner: 'unknown', stamp };
}

// Byte identity modulo the driver-version stamp: when BOTH sides open with the `// @generated by`
// line, that line is a generation-run fact (options.generatorVersion) and never participates in
// the comparison (inc3 principle). Returns { equal, stampOnly }.
function contentEqualsModuloStamp(emitted, live) {
  const STAMP_RX = /^\/\/ @generated by [^\n]*\n/;
  const aStamp = STAMP_RX.test(emitted), bStamp = STAMP_RX.test(live);
  if (aStamp !== bStamp) return { equal: emitted === live, stampOnly: false };
  if (!aStamp) return { equal: emitted === live, stampOnly: false };
  const restA = emitted.replace(STAMP_RX, ''), restB = live.replace(STAMP_RX, '');
  return { equal: restA === restB, stampOnly: restA === restB && emitted !== live };
}
const FAMILY = { skeleton: 'skeleton', rules: 'rules', api: 'api' };

// --- run the three generators ---------------------------------------------------------------
const rows = [];
const genErrors = {};
const emitted = new Map(); // mapped live path → { face, kind, aggregate } (rules > api > skeleton wins shared)
for (const [face, g] of Object.entries(GENS)) {
  try {
    const { entries } = await plan({ canonicalFile: CANON, generatorDir: g.dir, options: g.options });
    for (const e of entries) {
      const livePath = mapPath(e.path);
      const row = { face, kind: e.kind, aggregate: e.families?.[0] ?? null, path: e.path, livePath, status: 'unmapped' };
      if (livePath) {
        const own = liveOwner(livePath);
        if (e.kind === 'routes') {
          // conf/routes: shared territory — compare the E301 marker REGION only (outer lines are
          // hand/other-generator faces, out of scope by declaration). Live-only lines should be
          // exactly the unported faces' output (27 aggregate-state — the vector face joined V4-13); anything
          // else is a real diff on the ported write/view lines.
          const liveText = liveRead(livePath);
          if (liveText === null) row.status = 'live-missing';
          else {
            const MARK_END = '# <<< gen_api_layer <<<';
            const b = liveText.indexOf('# >>> gen_api_layer (E301) >>>');
            const e2 = liveText.indexOf(MARK_END);
            if (b < 0 || e2 < 0) { row.status = 'diff'; row.excerpt = { byte: 0, line: 0, want: '(E301 marker block missing from live)', got: '(present)' }; }
            else {
              const liveLines = liveText.slice(b, e2 + MARK_END.length).split('\n');
              const mineLines = e.content.split('\n');
              const mineSet = new Set(mineLines);
              const liveSet = new Set(liveLines);
              const missing = liveLines.filter((l) => !mineSet.has(l));
              const extra = mineLines.filter((l) => !liveSet.has(l));
              const missingPorted = missing.filter((l) => !l.includes('/api/state/') && !l.includes('semantic-search'));
              row.routes = { liveLines: liveLines.length, emittedLines: mineLines.length, liveOnly: missing.length, emittedOnly: extra.length, liveOnlyOutsideUnportedFaces: missingPorted.length };
              row.status = missing.length === 0 && extra.length === 0 ? 'identical' : 'diff';
              if (row.status === 'diff') {
                row.excerpt = {
                  byte: 0, line: 0,
                  want: missingPorted.length ? missingPorted[0] : `${missing.length} live-only lines (unported faces: aggregate-state ×27 — vector joined V4-13)`,
                  got: extra.length ? extra[0] : `${extra.length} truthsrc-only lines`,
                };
              }
            }
          }
          rows.push(row);
          continue;
        }
        if (own === null) row.status = 'live-missing';
        else if (own.owner !== FAMILY[face]) {
          // live path written by a different face than the truthsrc generator being compared —
          // recorded, not diffed (the owning face's coverage is a report category of its own)
          row.status = 'owned-by-other';
          row.liveOwner = own.stamp;
        } else {
          const cmp = contentEqualsModuloStamp(e.content, liveRead(livePath));
          row.status = cmp.equal ? 'identical' : 'diff';
          if (cmp.stampOnly) row.stampOnly = true;
          if (row.status === 'diff') row.excerpt = excerpt(liveRead(livePath), e.content);
          row.liveOwner = own.stamp;
        }
        const prior = emitted.get(livePath);
        if (!prior || (prior.face === 'skeleton' && face !== 'skeleton')) emitted.set(livePath, { face, kind: e.kind, aggregate: row.aggregate });
      }
      rows.push(row);
    }
  } catch (err) {
    genErrors[face] = String(err?.message ?? err);
  }
}

// --- reverse coverage: ported kinds' live files with no truthsrc entry ------------------------
const pkgBase = 'app/net/imadz/metarch';
const perAggKinds = [
  ['protocol', `${pkgBase}/application/aggregates/<A>Protocol.scala`],
  ['aggregate-root', `${pkgBase}/application/aggregates/<A>Aggregate.scala`],
  ['entity', `${pkgBase}/domain/entities/<A>Entity.scala`],
  ['event-handler', `${pkgBase}/domain/entities/behaviors/<A>EventHandler.scala`],
  ['repository', `${pkgBase}/application/aggregates/repository/<A>Repository.scala`],
  ['factory', `${pkgBase}/application/aggregates/factories/<A>AggregateFactory.scala`],
  ['behaviors', `${pkgBase}/application/aggregates/behaviors/<A>Behaviors.scala`],
  ['command-helpers', `${pkgBase}/application/aggregates/behaviors/<A>CommandHelpers.scala`],
  ['rules', `${pkgBase}/domain/invariant/<A>Rules.scala`],
  ['rule-params', `${pkgBase}/domain/invariant/params/<A>RuleParams.scala`],
  ['rules-spec', `test/net/imadz/metarch/domain/invariant/<A>RulesSpec.scala`],
  ['policies', `${pkgBase}/domain/policy/<A>Policies.scala`],
  ['policies-spec', `test/net/imadz/metarch/domain/policy/<A>PoliciesSpec.scala`],
  ['controller', `app/controllers/<A>ApiController.scala`],
];
const globals = ['ViewKeys', 'CommandRoleMap', 'CommandDsl'].map((n) => [n === 'CommandDsl' ? 'command-dsl' : n, `${pkgBase}/infrastructure/${n === 'CommandDsl' ? 'api' : 'auth'}/${n}.scala`])
  .concat([['ViewApiController', 'app/controllers/ViewApiController.scala'], ['ViewWrites', 'app/controllers/ViewWrites.scala']]);
const reverseRows = [];
for (const [kind, tpl] of perAggKinds) {
  for (const a of aggNames) {
    const livePath = tpl.replaceAll('<A>', a);
    if (!emitted.has(livePath) && liveRead(livePath) !== null) reverseRows.push({ kind, aggregate: a, livePath });
  }
}
for (const [kind, livePath] of globals) {
  if (!emitted.has(livePath) && liveRead(livePath) !== null) reverseRows.push({ kind, aggregate: null, livePath });
}

// --- rollup -----------------------------------------------------------------------------------
const byStatus = {};
for (const r of rows) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;
const diffByKind = {};
for (const r of rows.filter((x) => x.status === 'diff')) diffByKind[r.kind] = (diffByKind[r.kind] ?? 0) + 1;
const identByFace = {};
for (const r of rows.filter((x) => x.status === 'identical')) identByFace[r.face] = (identByFace[r.face] ?? 0) + 1;
const stampOnlyCount = rows.filter((x) => x.stampOnly).length;

const report = {
  generatedAt: new Date().toISOString().slice(0, 10),
  live: LIVE,
  canonical: relative(ROOT, CANON),
  aggregates: aggNames.length,
  counts: { rows: rows.length, byStatus, identicalByFace: identByFace, diffByKind, stampOnlyDiff: stampOnlyCount, reverseRows: reverseRows.length, genErrors },
  rows, reverseRows,
};
const outJson = join(GOLD, 'full-corpus.identity.json');
fs.writeFileSync(outJson, JSON.stringify(report, null, 2) + '\n');

// --- markdown ---------------------------------------------------------------------------------
const line = [];
line.push(`# truthsrc 全语料恒等报告（V4-5·切流拍板输入·非拍板本身）`, '');
line.push(`- 日期：${report.generatedAt}；live 参照：\`${LIVE}\`（新鲜度门：backend-codegen \`tools/kn_repo_freshness.mjs\` exit 0·锚 8948/元素 2861 全 match）；canonical：\`${report.canonical}\`（27 聚合）`);
line.push(`- 范围：三面 20 kind＋conf/routes E301 块区（skeleton 8－共享 3＋rules 8＋api 7；共享 Behaviors/CommandHelpers/EventHandler 按 live 管线序归 rules 面所有——骨架面的同路径行留痕 owned-by-other，即台账 final-writer-wins 的行级呈现；routes 按标记区对表——块外领地属手写/它生成器面不在对表范围，块内 live 独有行应恰＝未移植面输出：aggregate-state ×27·vector 面已随 V4-13 移植）。storage/persistence/Bootstrap/ExecutableSpec/投影/AggregateStateApi/Auth 等其余**未移植面不在对表范围**（EP 不搬清单＋顺延批）。`, '');
line.push(`## 头条数字`, '');
line.push(`| 判定 | 件数 |`);
line.push(`|---|---|`);
for (const [k, v] of Object.entries(byStatus).sort((a, b) => b[1] - a[1])) line.push(`| ${k} | ${v} |`);
line.push('');
line.push(`**恒等按面**：${Object.entries(identByFace).map(([f, c]) => `${f} ${c}`).join(' · ')} ｜ **diff 按 kind**：${Object.entries(diffByKind).map(([k, c]) => `${k} ${c}`).join(' · ') || '（无）'}${stampOnlyCount ? ` ｜ 其中 ${stampOnlyCount} 行仅驱动版本戳行异（\`@generated by\`＝生成器侧事实·不参与比对）` : ''}`);
if (Object.keys(genErrors).length) line.push(`**生成器级失败**：${Object.entries(genErrors).map(([f, m]) => `${f} → ${m}`).join(' ｜ ')}`);
line.push('');
// ownership census: which live generator owns each ported path (multi-pass pipeline truth)
const ownerCensus = {};
for (const r of rows) if (r.liveOwner) ownerCensus[r.liveOwner] = (ownerCensus[r.liveOwner] ?? 0) + 1;
line.push(`## live 归属普查（按文件首行 stamp·多趟管线真相）`, '');
line.push(`| live stamp（生成器） | 文件数 |`);
line.push(`|---|---|`);
for (const [s, c] of Object.entries(ownerCensus).sort((a, b) => b[1] - a[1])) line.push(`| ${s} | ${c} |`);
line.push('');
line.push(`## 逐件明细（${rows.length} rows）`, '');
line.push(`| face | kind | aggregate | live path | 状态 | diff@line |`);
line.push(`|---|---|---|---|---|---|`);
for (const r of rows) {
  line.push(`| ${r.face} | ${r.kind} | ${r.aggregate ?? '—'} | ${r.livePath ?? r.path} | ${r.status} | ${r.excerpt ? r.excerpt.line : '—'} |`);
}
line.push('', `## 反向覆盖（live 有而 truthsrc 未发·${reverseRows.length} rows）`, '');
line.push(`| kind | aggregate | live path |`);
line.push(`|---|---|---|`);
for (const r of reverseRows) line.push(`| ${r.kind} | ${r.aggregate ?? '—'} | ${r.livePath} |`);
line.push('', `## diff 摘录（每件首差·≤3 行）`, '');
for (const r of rows.filter((x) => x.status === 'diff')) {
  line.push(`### ${r.livePath}（${r.kind}·首差 @line ${r.excerpt.line} byte ${r.excerpt.byte}）`, '');
  line.push('```scala', `--- live（want）`, r.excerpt.want, `+++ truthsrc（got）`, r.excerpt.got, '```', '');
}
const outMd = join(GOLD, 'full-corpus.identity.md');
fs.writeFileSync(outMd, line.join('\n') + '\n');

console.log(`rows=${rows.length}  ${Object.entries(byStatus).map(([k, v]) => `${k}:${v}`).join('  ')}`);
console.log(`genErrors: ${Object.keys(genErrors).length ? JSON.stringify(genErrors) : 'none'}`);
console.log(`reverse (live has, truthsrc not emitted): ${reverseRows.length}`);
console.log(`→ ${relative(ROOT, outJson)}`);
console.log(`→ ${relative(ROOT, outMd)}`);
