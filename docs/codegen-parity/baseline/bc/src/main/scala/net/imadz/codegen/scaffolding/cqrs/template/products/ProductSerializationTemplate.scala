package net.imadz.codegen.scaffolding.cqrs.template.products

import net.imadz.codegen.scaffolding.cqrs.TypeResolverDSL
import net.imadz.codegen.scaffolding.cqrs.model.products._
import net.imadz.codegen.structure.NamingConventions
import net.imadz.meta.products._

object ProductSerializationTemplate {
  private def sym(value: String): String = NamingConventions.productSymbol(value)
  private def typeText(ref: net.imadz.codegen.scaffolding.cqrs.TypeRef): String = ref.fqn +
    (if (ref.typeParams.isEmpty) "" else ref.typeParams.map(typeText).mkString("[", ", ", "]"))
  private def tpe(value: NominalType, model: ProductDomainModel): String = typeText(TypeResolverDSL.productType(value, model.packages))
  private def source(path: String, content: String, kind: String, nodes: Vector[ProductWireNode], model: ProductDomainModel): ProductSourceModel =
    ProductSourceModel(path, "// @generated by CodegenMain:semantic-products-1\n" + content, kind, nodes.flatMap(_.sources).distinct, model.footprint)
  def generate(model: ProductDomainModel): Vector[ProductSourceModel] = model.packages.values.toVector.sorted.flatMap { pkg =>
    val nodes = model.wire.filter(_.packageName == pkg)
    val pb = pkg + ".infrastructure.proto."
    def pbType(carrier: ProductWireCarrier): String = carrier match {
      case ProductWirePrimitive(n) => Map("string" -> "string", "boolean" -> "bool", "integer" -> "sint64", "decimal" -> "string")(n)
      case ProductWireNested(node) => node.name
    }
    val proto = "syntax = \"proto3\";\n\nimport \"scalapb/scalapb.proto\";\npackage " + pkg + ".infrastructure.proto;\noption (scalapb.options) = { flat_package: true };\n\n" + nodes.map { n =>
      "message " + n.name + " {\n" + (if (n.kind == "optional") "  bool present = 1;\n" else "") + n.fields.zipWithIndex.map { case (f, i) =>
        "  " + (if (f.repeated) "repeated " else "") + pbType(f.carrier) + " f" + i + " = " + (i + (if (n.kind == "optional") 2 else 1)) + ";\n"
      }.mkString + "}\n\n"
    }.mkString
    def nodeType(n: ProductWireNode): String = n.kind match {
      case "state" => pkg + ".domain." + sym(n.ref.get.id + "State")
      case "event" => pkg + ".domain." + sym(n.ref.get.owner.head + "Protocol") + "." + sym(n.ref.get.id)
      case "map-entry" => n.fields.map(f => carrierType(f.carrier)).mkString("(", ", ", ")")
      case _ => tpe(n.valueType.get, model)
    }
    def carrierType(c: ProductWireCarrier): String = c match {
      case ProductWirePrimitive(n) => Map("string" -> "String", "boolean" -> "Boolean", "integer" -> "Long", "decimal" -> "BigDecimal")(n)
      case ProductWireNested(n) => nodeType(n)
    }
    def encode(c: ProductWireCarrier, value: String): String = c match {
      case ProductWirePrimitive("decimal") => value + ".bigDecimal.toPlainString"
      case _: ProductWirePrimitive => value
      case ProductWireNested(n) => "encode" + n.name + "(" + value + ")"
    }
    def decode(c: ProductWireCarrier, value: String): String = c match {
      case ProductWirePrimitive("decimal") => "BigDecimal(" + value + ")"
      case _: ProductWirePrimitive => value
      case ProductWireNested(n) => "decode" + n.name + "(" + value + ")"
    }
    def field(c: ProductWireCarrier, value: String): String = c match {
      case _: ProductWireNested => "Some(" + encode(c, value) + ")"
      case _ => encode(c, value)
    }
    def required(c: ProductWireCarrier, value: String): String = decode(c, c match {
      case _: ProductWireNested => value + ".getOrElse(throw new IllegalArgumentException(\"required typed value missing\"))"
      case _ => value
    })
    val converters = new StringBuilder("package " + pkg + ".infrastructure.serialization\n\nobject DomainConverters {\n")
    converters.append("  private def fixed(value: BigDecimal, scale: Int): String = value.bigDecimal.setScale(scale, java.math.RoundingMode.UNNECESSARY).toPlainString\n")
    converters.append("  private def readExact(value: String, scale: Int, minor: Boolean): BigDecimal = {\n    require(value != null && value.length <= 80, \"bounded exact text required\")\n    val pattern = if (minor || scale == 0) \"-?(0|[1-9][0-9]*)\" else \"-?(0|[1-9][0-9]*)\\\\.[0-9]{\" + scale + \"}\"\n    require(value.matches(pattern) && !(value.startsWith(\"-\") && BigDecimal(value) == 0), \"noncanonical exact text\")\n    if (minor) BigDecimal(new java.math.BigDecimal(new java.math.BigInteger(value), scale)) else BigDecimal(value)\n  }\n")
    val header = converters.toString
    val groups = Vector.newBuilder[(ProductWireNode, String)]
    nodes.foreach { n =>
      val start = converters.length
      val actual = nodeType(n); val target = pb + n.name
      val (encoded, decoded) = n.kind match {
        case "exact" =>
          val exact = n.exact.get; val codec = n.codec.get
          val amount = "value." + sym(exact.amountMember.map(_.id).getOrElse("value")); val unit = exact.unitMember.map(r => "value." + sym(r.id))
          val minor = codec.format == "minor-units-text"
          val packed = if (minor) amount + ".bigDecimal.setScale(" + exact.scale + ", java.math.RoundingMode.UNNECESSARY).unscaledValue.toString" else "fixed(" + amount + ", " + exact.scale + ")"
          Vector("Wire" -> codec.wire, "PO" -> codec.po).foreach { case (suffix, representation) =>
            val rt = tpe(NominalType.Named(representation.ref), model)
            converters.append("  def " + sym(n.ref.get.id + "To" + suffix) + "(value: " + actual + "): " + rt + " = { val encoded = encode" + n.name + "(value); " + rt + "(encoded.f0" + (if (representation.unitMember.isDefined) ", encoded.f1" else "") + ") }\n")
            converters.append("  def " + sym(n.ref.get.id + "From" + suffix) + "(value: " + rt + "): " + actual + " = decode" + n.name + "(" + target + "(" + representation.amountMember.map(r => "value." + sym(r.id)).getOrElse("value.value") + representation.unitMember.map(r => ", value." + sym(r.id)).getOrElse("") + "))\n")
          }
          target + "(" + packed + unit.map(", " + _).getOrElse("") + ")" ->
            (actual + "(readExact(value.f0, " + exact.scale + ", " + minor + ")" + (if (unit.isDefined) ", value.f1" else "") + ")")
        case "optional" =>
          val c = n.fields.head.carrier
          val empty = c match { case _: ProductWireNested => "value.f0.isEmpty"; case ProductWirePrimitive("boolean") => "!value.f0"; case ProductWirePrimitive("integer") => "value.f0 == 0L"; case _ => "value.f0.isEmpty" }
          ("value match { case None => " + target + "(present = false); case Some(item) => " + target + "(present = true, f0 = " + field(c, "item") + ") }") ->
            ("if (!value.present) { require(" + empty + ", \"absent optional contains a value\"); None } else Some(" + required(c, "value.f0") + ")")
        case "sequence" =>
          val c = n.fields.head.carrier
          (target + "(value.map(item => " + encode(c, "item") + "))") -> ("value.f0.map(item => " + decode(c, "item") + ").toVector")
        case "map" =>
          val c = n.fields.head.carrier
          ("{ val rows = value.toVector.map(item => " + encode(c, "item") + ").sortBy(item => item.toByteArray.iterator.map(b => f\"${b & 0xff}%02x\").mkString); " + target + "(rows) }") ->
            ("{ val rows = value.f0.map(item => " + decode(c, "item") + ").toVector; require(rows.map(_._1).distinct.size == rows.size, \"duplicate typed map key\"); rows.toMap }")
        case _ =>
          val encoded = target + "(" + n.fields.zipWithIndex.map { case (f, i) => field(f.carrier, if (n.kind == "map-entry") "value._" + (i + 1) else "value." + sym(f.name)) }.mkString(", ") + ")"
          val args = n.fields.zipWithIndex.map { case (f, i) => required(f.carrier, "value.f" + i) }.mkString(", ")
          encoded -> (if (n.kind == "map-entry") "(" + args + ")" else actual + "(" + args + ")")
      }
      converters.append("  def encode" + n.name + "(value: " + actual + "): " + target + " = " + encoded + "\n")
      converters.append("  def decode" + n.name + "(value: " + target + "): " + actual + " = " + decoded + "\n")
      groups += n -> converters.substring(start)
    }
    converters.append("}\n")
    val converterSources = if (converters.length <= 60000) Vector(
      source(NamingConventions.productPackagePath(pkg, "infrastructure/serialization/DomainConverters.scala"), converters.toString, "converter", nodes, model))
    else {
      val parts = groups.result().foldLeft(Vector.empty[Vector[(ProductWireNode, String)]]) { (parts, group) =>
        if (parts.isEmpty || parts.last.map(_._2.length).sum + group._2.length > 48000) parts :+ Vector(group)
        else parts.init :+ (parts.last :+ group)
      }
      val names = parts.indices.map(i => "DomainConvertersPart" + i)
      val facade = header.replace("object DomainConverters {", "object DomainConverters extends " + names.mkString(" with ") + " {") + "}\n"
      val paths = names.map(name => NamingConventions.productPackagePath(pkg, "infrastructure/serialization/" + name + ".scala")).toVector
      Vector(source(NamingConventions.productPackagePath(pkg, "infrastructure/serialization/DomainConverters.scala"), facade, "converter", nodes, model).copy(dependencies = paths)) ++
        parts.zipWithIndex.map { case (part, i) =>
          val content = "package " + pkg + ".infrastructure.serialization\n\ntrait " + names(i) + " { self: DomainConverters.type =>\n" +
            header.substring(header.indexOf("  private def fixed")) + part.map(_._2).mkString + "}\n"
          source(NamingConventions.productPackagePath(pkg, "infrastructure/serialization/" + names(i) + ".scala"), content, "converter", part.map(_._1), model)
        }
    }
    Vector(source("app/protobuf/" + pkg.replace('.', '_') + "_domain.proto", proto, "proto", nodes, model)) ++ converterSources
  }
}
