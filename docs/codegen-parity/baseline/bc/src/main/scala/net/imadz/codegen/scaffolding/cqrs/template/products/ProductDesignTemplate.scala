package net.imadz.codegen.scaffolding.cqrs.template.products

import net.imadz.codegen.scaffolding.cqrs.model.products._
import net.imadz.meta.products._
import ujson.{Arr, Obj, Value}

object ProductDesignTemplate {
  private def ref(r: QualifiedReference): Value = Obj("context" -> r.context, "kind" -> r.kind, "owner" -> Arr.from(r.owner), "id" -> r.id)
  private def source(s: ProductSource): Value = Obj("document" -> s.document, "pointer" -> s.pointer)
  private def nodeRef(r: DesignNodeReference): Value = Obj("artifact" -> ref(r.artifact), "kind" -> r.kind, "id" -> r.id)
  private def tpe(t: NominalType): Value = t match {
    case NominalType.Primitive(name) => Obj("form" -> "primitive", "name" -> name)
    case NominalType.Named(r) => Obj("form" -> "nominal", "ref" -> ref(r))
    case NominalType.Record(members) => Obj("form" -> "record", "members" -> Arr.from(members.map(ref)))
    case NominalType.Optional(element) => Obj("form" -> "optional", "element" -> tpe(element))
    case NominalType.Sequence(element) => Obj("form" -> "sequence", "element" -> tpe(element))
    case NominalType.Mapping(key, value) => Obj("form" -> "map", "key" -> tpe(key), "value" -> tpe(value))
  }
  private def action(a: DesignAction): Value = Obj("command" -> ref(a.command), "actor" -> a.actor, "intent" -> a.intent,
    "parameters" -> Arr.from(a.parameters.map(p => Obj("parameter" -> ref(p.parameter), "valueType" -> tpe(p.valueType),
      "origin" -> p.origin.id, "slot" -> p.slot, "from" -> p.from.map(ref).getOrElse(ujson.Null), "source" -> source(p.source), "parameterSource" -> source(p.parameterSource)))),
    "source" -> source(a.source))
  private def feedback(f: DesignFeedback): Value = Obj("event" -> f.event.map(ref).getOrElse(ujson.Null), "state" -> f.state, "evidence" -> f.evidence.id,
    "resourceKeys" -> Arr.from(f.resourceKeys.map(k => Obj("ref" -> ref(k.ref), "valueType" -> tpe(k.valueType), "source" -> source(k.source)))),
    "watermark" -> f.watermark.map(w => Obj("slot" -> ref(w.slot), "valueType" -> tpe(w.valueType), "semantics" -> w.semantics, "source" -> source(w.source))).getOrElse(ujson.Null),
    "source" -> source(f.source))
  private def design(d: ProductDesign): Value = Obj("id" -> d.id, "version" -> d.version, "artifact" -> ref(d.artifact), "status" -> d.status,
    "provenance" -> Arr.from(d.provenance.map(source)), "approvalSource" -> d.approvalSource.map(source).getOrElse(ujson.Null),
    "references" -> Arr.from(d.references.map(ref)), "nodes" -> Arr.from(d.nodes.map(n => Obj("ref" -> nodeRef(n.ref), "plane" -> n.plane.id, "label" -> n.label,
      "references" -> Arr.from(n.references.map(ref)), "action" -> n.action.map(action).getOrElse(ujson.Null), "feedback" -> n.feedback.map(feedback).getOrElse(ujson.Null), "source" -> source(n.source)))),
    "relations" -> Arr.from(d.relations.map(r => Obj("id" -> r.id, "kind" -> r.kind, "from" -> nodeRef(r.from), "to" -> nodeRef(r.to), "source" -> source(r.source)))), "source" -> source(d.source))
  private def label(value: String): String = value.flatMap {
    case '&' => "&amp;"
    case '"' => "&quot;"
    case '<' => "&lt;"
    case '>' => "&gt;"
    case '[' => "&#91;"
    case ']' => "&#93;"
    case '{' => "&#123;"
    case '}' => "&#125;"
    case '\\' => "&#92;"
    case '\n' => "<br/>"
    case '\r' => ""
    case c if c.isControl => " "
    case c => c.toString
  }
  private def diagram(model: ProductDesignModel, plane: DesignPlane): String = {
    val body = model.designs.zipWithIndex.map { case (d, i) =>
      val selected = d.nodes.filter(_.plane == plane).map(_.ref).toSet
      val edges = d.relations.filter(r => selected(r.from) || selected(r.to))
      val visible = selected ++ edges.flatMap(r => Vector(r.from, r.to))
      def id(r: DesignNodeReference): String = "d" + i + "n" + d.nodes.indexWhere(_.ref == r)
      val rows = d.nodes.filter(n => visible(n.ref)).map { n =>
        val text = label(n.plane.id + ": " + n.ref.kind + " — " + n.label)
        s"""  ${id(n.ref)}["$text"]"""
      } ++ edges.map(r => s"  ${id(r.from)} -->|${r.kind}| ${id(r.to)}")
      rows.mkString("\n")
    }.mkString("\n")
    s"%% @generated by codegen-main; product-design-review@1; design-review-only; runnable=false\nflowchart TD\n$body\n"
  }
  def generate(model: ProductDesignModel): Vector[ProductSourceModel] = {
    val allSources = model.sources.flatMap(s => Vector(s.source) ++ s.related).distinct
    def entry(path: String, content: String, kind: String, sources: Vector[ProductSource]): ProductSourceModel =
      ProductSourceModel(path, content, kind, sources, model.footprint)
    val modelJson = Obj("schemaVersion" -> "truthsrc.product-design-review/v1", "purpose" -> "design-review-only", "runnable" -> false,
      "product" -> Obj("id" -> "product-design", "version" -> "1"), "designs" -> Arr.from(model.designs.map(design)))
    val index = Obj("schemaVersion" -> "truthsrc.product-design-source-index/v1", "purpose" -> "design-review-only", "runnable" -> false,
      "sources" -> Arr.from(model.sources.map(s => Obj("artifact" -> ref(s.artifact), "node" -> s.node.map(nodeRef).getOrElse(ujson.Null),
        "relation" -> s.relation.map(ujson.Str(_)).getOrElse(ujson.Null), "role" -> s.role, "source" -> source(s.source),
        "related" -> Arr.from(s.related.map(source)), "references" -> Arr.from(s.references.map(ref))))))
    def json(value: Value): String = {
      val pretty = ujson.write(value, indent = 2) + "\n"
      if (pretty.length <= 65536) pretty else ujson.write(value) + "\n"
    }
    Vector(entry("design/product-designs.json", json(modelJson), "design-model", allSources)) ++
      DesignPlane.values.map(p => entry("design/" + p.id + ".mmd", diagram(model, p), "design-plane", allSources)) ++
      Vector(entry("design/source-index.json", json(index), "design-source-index", allSources))
  }
}
