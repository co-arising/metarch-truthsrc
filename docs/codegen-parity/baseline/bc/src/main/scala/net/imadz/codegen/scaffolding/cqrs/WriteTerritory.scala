  )

  /** 路径是否落入冻结领地（分隔符归一）。 */
  def isFrozenTerritory(filePath: String): Boolean = {
    val normalized = filePath.replace('\\', '/')
    FrozenTerritories.exists(t => normalized.contains(t))
  }

  sealed trait Mode
  case object AddMode extends Mode
  case object MergeMode extends Mode
  case object CoverMode extends Mode
  case object KeepMode extends Mode

  /** 按目标文件现状判定唯一动作；标记态畸形直接抛（见类注释）。 */
  def judge(existing: Option[String]): Mode = existing match {
    case None => AddMode
    case Some(text) =>
      val hasAnyMarker =
        text.contains(ManualMarkerStart) || text.contains(ManualMarkerEnd)
      if (hasAnyMarker) {
        // manualRanges 畸形即抛；hasAnyMarker 为真且解析干净 → 必有至少一块
        val ranges = manualRanges(text)
        if (ranges.nonEmpty) MergeMode
        else if (hasFingerprint(text)) CoverMode
        else KeepMode
      } else if (hasFingerprint(text)) CoverMode
      else KeepMode
  }

  def hasFingerprint(text: String): Boolean =
    text
      .split("\n", -1)
      .take(FingerprintScanLines)
      .exists(_.contains(FingerprintMarker))

  /** MERGE：以 incoming（已含指纹头的新生成物）为基底，把 existing 的全部 MANUAL 段
    * 按**方法锚**（区块前最近的 def 方法名）植入对应区块位。
    * S2-48 挂账⑤-2 途中事故两级修复（2026-09-05）：
    * ①原实现只搬第一个标记对——多块文件（RepositoryImpl：upsert＋N 查询方法各带一块）
    *   其余块被新生成物占位 ??? 顶掉，42 件 -2853 行手写实现丢失（apply_manifest.mjs 同族）；
    * ②区块数判等不可用——新方法**中位插入**（findByTenantId 插在 findByWorkgroupId 前）
    *   既触发假阳性计数告警，又使位序对应错植（WorkgroupId 块植进 TenantId 槽）。
    * 终局语义：锚命中植入；incoming 新方法块（无既有对应）保留生成内容（待手工实现）；
    * 既有手写块无落点（方法被移除/改名）→ fail-fast 拒写（静默丢块＝数据丢失）。
    * 无 def 前缀的类级块按组内位序对应（双方锚为 null 的区块桶内顺序匹配）。 */
  def mergeManual(existing: String, incoming: String, target: Path): String = {
    val oldBlocks = manualRanges(existing)
    if (oldBlocks.isEmpty)
      throw new IllegalStateException(
        s"[WriteTerritory] $target 既有文件无 MANUAL 标记对——MERGE 前置判定与此处不一致，拒写"
      )
    val newBlocks = manualRanges(incoming)
    if (newBlocks.isEmpty)
      throw new IllegalStateException(
        s"[WriteTerritory] $target 新生成物丢失 MANUAL 标记对——继续写盘会静默吞掉既有" +
          s"手写实现（S2-36 冲毁事故同族）；请核对模板是否漏发标记块"
      )

    // 既有块按锚索引：具名锚（def 方法）**按出现序**（同名可多次——如 CommandHelpers 每个
    //   implicit object 各有 toParam）；无名锚（无 def 前缀·类级块）按组内位序。
    //   2026-09-21 EP_Improvement_Engine：改为「名 → 有序块列表」以支持重复方法名。
    val oldNamed = scala.collection.mutable.LinkedHashMap.empty[String, scala.collection.mutable.ListBuffer[(Int, Int)]]
    val oldAnon  = scala.collection.mutable.ListBuffer.empty[(Int, Int)]
    for (r <- oldBlocks) anchorOf(existing, r._1) match {
      case Some(a) => oldNamed.getOrElseUpdate(a, scala.collection.mutable.ListBuffer.empty) += r
      case None    => oldAnon += r
    }

    // 注意：scala.collection.mutable.StringBuilder 的 append(CharSequence, Int, Int) 会被
    // 变参 append 当作单 tuple 追加（实测 .toString 出 "(文本,起,止)" 链）——用 substring
    // 拼接段，走不可变风格（与管线其余同路数）。
    val parts = scala.collection.mutable.ListBuffer.empty[String]
    var cursor = 0
    var anonIdx = 0
    val consumed = scala.collection.mutable.Map.empty[String, Int]  // 锚名 → 已消耗块数
    for ((ns, ne) <- newBlocks) {
      parts += incoming.substring(cursor, ns)
      val a = anchorOf(incoming, ns)
      val slots = a.flatMap(oldNamed.get)
      a match {
        case Some(name) if slots.exists(consumed.getOrElse(name, 0) < _.size) =>
          val idx = consumed.getOrElse(name, 0)
          val r = slots.get(idx)
          parts += existing.substring(r._1, r._2)
          consumed(name) = idx + 1
        case None if anonIdx < oldAnon.size =>
          parts += existing.substring(oldAnon(anonIdx)._1, oldAnon(anonIdx)._2)
          anonIdx += 1
        case _ => parts += incoming.substring(ns, ne) // 新方法块：保留生成内容
      }
      cursor = ne
    }
    parts += incoming.substring(cursor)

    val orphanNamed = oldNamed.toList.flatMap { case (a, bl) =>
      val left = bl.size - consumed.getOrElse(a, 0)
      if (left > 0) List(s"def $a ×$left") else Nil
    }
    if (orphanNamed.nonEmpty || anonIdx < oldAnon.size) {
      val detail = (orphanNamed ++
        (if (anonIdx < oldAnon.size) List(s"无名锚块 ${oldAnon.size - anonIdx} 个") else Nil))
        .mkString("＋")
      throw new IllegalStateException(
        s"[WriteTerritory] $target 既有手写块无落点（$detail——方法已被生成器移除/改名）——" +
          s"拒写（防静默丢块）"
      )
    }
    parts.mkString
  }

  /** 区块锚：区块起始位之前最近的 def 方法名（无 → None，类级块）。 */
  private val DefAnchorRegex = """(?:override\s+)?def\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(""".r

  private def anchorOf(text: String, before: Int): Option[String] = {
    val ms = DefAnchorRegex.findAllMatchIn(text.take(before)).toList
    ms.lastOption.map(_.group(1))
  }

  /** 全部完整标记对区间（按出现序·含标记行整体·[start, end)）；无标记返回空表，
    * 标记态畸形（有起无止／有止无起／嵌套起）抛出（见类注释 fail-fast 精神）。 */
  private def manualRanges(text: String): List[(Int, Int)] = {
    @annotation.tailrec
    def collect(from: Int, acc: List[(Int, Int)]): List[(Int, Int)] = {
      val start = text.indexOf(ManualMarkerStart, from)
      if (start < 0) {
        if (text.indexOf(ManualMarkerEnd, from) >= 0)
          throw new IllegalStateException(
            s"[WriteTerritory] MANUAL 标记态畸形（有止无起）——不可静默处理，请手工修复标记对后重跑"
          )
        acc.reverse
      } else {
        val end = text.indexOf(ManualMarkerEnd, start + ManualMarkerStart.length)
        if (end < 0)
          throw new IllegalStateException(
            s"[WriteTerritory] MANUAL 标记态畸形（有起无止）——不可静默覆盖（会吞掉半手写领地），请手工修复标记对后重跑"
          )
        collect(end + ManualMarkerEnd.length, (start, end + ManualMarkerEnd.length) :: acc)
      }
    }
    collect(0, Nil)
  }
}
