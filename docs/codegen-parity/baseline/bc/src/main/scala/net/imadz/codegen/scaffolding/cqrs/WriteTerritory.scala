/** S2-48 批1：写盘领地判定（writeArtifact 四模式——gen_manifest.mjs C1-C5 判定原语的
  * Scala 写盘时刻化；MarkerBlockWriter 的姊妹件·方向相反）：
  * ①目标不存在 → ADD（新建·注入指纹头）；
  * ②目标含 MANUAL 标记对 → MERGE（新生成物为基底，既有文件的手写 MANUAL 段字节级植入——
  *   与 routes 的 MarkerBlockWriter 相反方向：routes 保段外手写〔文件主体是人写的〕，
  *   handler 保段内手写〔文件主体是生成的〕；S2-46 挂账① 182 个 handler 被冲 ??? 的根治）；
  * ③目标有指纹头 → COVER（整文件覆盖·原行为）；
  * ④目标无指纹头也无 MANUAL → KEEP（纯手写文件·拒绝覆盖＋警告——D6 拍板 2026-09-05；
  *   codegen.migrate=true 显式放行，对齐 gen_manifest --migrate 首次迁移语义）。
  * 标记态畸形（有起无止／有止无起）fail-fast：静默按 COVER 走会吞掉半手写领地
  * （MarkerBlockWriter／H052-H053 同精神——炸出优于静默错删）。
  * 新生成物丢失标记对而既有文件含标记 → fail-fast 拒写：继续写盘＝静默销毁手写实现
  * （S2-36 手缝接线被全量重生成冲毁同族事故模式）。
  * 幂等性：MERGE 后文件仍含标记对＋指纹头 → 复跑再判 MERGE，植入块＝原块 → 字节稳定
  * （双跑幂等门的实现基础）。 */
object WriteTerritory {

  /** MANUAL 标记词——与模板（ProjectionHandlerTemplate/ProjectionRepositoryImplTemplate）
    * 及 gen_manifest.mjs:76 hasManual 三方同文；缩进无关（行内子串匹配）。 */
  val ManualMarkerStart: String = "// ==== BEGIN MANUAL ===="
  val ManualMarkerEnd: String = "// ==== END MANUAL ===="

  /** 指纹标记——writeArtifact/writeProto 注入的 `@generated by` 头（gen_manifest.mjs:77
    * 同口径：只认首 8 行）。 */
  private val FingerprintMarker = "@generated by"
  private val FingerprintScanLines = 8

  /** S2-48 挂账⑥(b)（2026-09-05）：R6-Ⅰ 冻结领地——路径级恒 KEEP（内容判定之前）。
    * 拍板＝ingested-app repos frozen until R6-Ⅱ（golden MANIFEST reason 4）；与
    * gen_manifest.mjs FROZEN_RULES 同表（apply 一翼）——本表护 CodegenMain 直写一翼
