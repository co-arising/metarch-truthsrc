export const version = '1';
const planes = Object.freeze(['strategy', 'scope', 'structure', 'skeleton', 'surface']);
const nodeKey = r => JSON.stringify([r.artifact.context, r.artifact.kind, r.artifact.owner, r.artifact.id, r.kind, r.id]);
const label = value => value.replace(/[&"<>\[\]{}\\\n\r\x00-\x1f\x7f]/gu, c => ({
  '&': '&amp;', '"': '&quot;', '<': '&lt;', '>': '&gt;', '[': '&#91;', ']': '&#93;', '{': '&#123;', '}': '&#125;', '\\': '&#92;', '\n': '<br/>', '\r': '',
}[c] ?? ' '));
function sourceModel(designs) {
  return designs.flatMap(d => [
    { artifact: d.artifact, node: null, relation: null, role: 'design', source: d.source, related: [...d.provenance, ...(d.approvalSource ? [d.approvalSource] : [])], references: d.references },
    ...d.nodes.flatMap(n => [
      { artifact: d.artifact, node: n.ref, relation: null, role: 'node', source: n.source, related: [], references: n.references },
      ...(n.action ? [{ artifact: d.artifact, node: n.ref, relation: null, role: 'action', source: n.action.source, related: [], references: [n.action.command] }] : []),
      ...(n.action ? n.action.parameters.map(p => ({ artifact: d.artifact, node: n.ref, relation: null, role: 'action-parameter', source: p.source, related: [p.parameterSource], references: [p.parameter, ...(p.from ? [p.from] : [])] })) : []),
      ...(n.feedback ? [
        { artifact: d.artifact, node: n.ref, relation: null, role: 'feedback', source: n.feedback.source, related: [], references: n.feedback.event ? [n.feedback.event] : [] },
        ...n.feedback.resourceKeys.map(k => ({ artifact: d.artifact, node: n.ref, relation: null, role: 'feedback-resource-key', source: n.feedback.source, related: [k.source], references: [k.ref] })),
        ...(n.feedback.watermark ? [{ artifact: d.artifact, node: n.ref, relation: null, role: 'feedback-watermark', source: n.feedback.source, related: [n.feedback.watermark.source], references: [n.feedback.watermark.slot] }] : []),
      ] : []),
    ]),
    ...d.relations.map(r => ({ artifact: d.artifact, node: null, relation: r.id, role: 'relation', source: r.source, related: [], references: [] })),
  ]);
}
function diagram(designs, plane) {
  const body = designs.map((d, i) => {
    const selected = new Set(d.nodes.filter(n => n.plane === plane).map(n => nodeKey(n.ref)));
    const edges = d.relations.filter(r => selected.has(nodeKey(r.from)) || selected.has(nodeKey(r.to)));
    const visible = new Set([...selected, ...edges.flatMap(r => [nodeKey(r.from), nodeKey(r.to)])]);
    const id = r => 'd' + i + 'n' + d.nodes.findIndex(n => nodeKey(n.ref) === nodeKey(r));
    return [
      ...d.nodes.filter(n => visible.has(nodeKey(n.ref))).map(n => '  ' + id(n.ref) + '["' + label(n.plane + ': ' + n.ref.kind + ' — ' + n.label) + '"]'),
      ...edges.map(r => '  ' + id(r.from) + ' -->|' + r.kind + '| ' + id(r.to)),
    ].join('\n');
  }).join('\n');
  return '%% @generated by product-design-review; product-design-review@1; design-review-only; runnable=false\nflowchart TD\n' + body + '\n';
}

/** Only declared typed design products are read. No canonical reparsing or inferred view/runtime code. */
export function produce({ products, options }) {
  if (Object.keys(options).length) throw new TypeError('design review has no runtime or UI options');
  const designs = products['product-design'].designs;
  const layout = products['reference-layout'];
  const sources = sourceModel(designs);
  for (const design of designs) {
    const queue = [...design.references], seen = new Set();
    for (let i = 0; i < queue.length; i++) {
      const r = queue[i], key = JSON.stringify([r.context, r.kind, r.owner, r.id]);
      if (seen.has(key)) continue;
      seen.add(key);
      const declaration = layout.declarations.find(d => JSON.stringify([d.ref.context, d.ref.kind, d.ref.owner, d.ref.id]) === key);
      if (!declaration) throw new TypeError('typed design reference has no declared source');
      sources.push({ artifact: design.artifact, node: null, relation: null, role: 'domain-reference', source: declaration.source, related: [], references: [r] });
      queue.push(...declaration.dependencies);
    }
  }
  const footprint = [{ id: 'reference-layout', version: '1' }, { id: 'product-design', version: '1' }];
  const knowledgeIds = [...new Set(sources.flatMap(s => [s.source, ...s.related]).map(s => 'source:' + s.document + '#' + s.pointer))];
  const entry = (path, content, kind) => ({ path, content, kind, deps: [], knowledgeIds, productFootprint: footprint, merge: null });
  const model = { schemaVersion: 'truthsrc.product-design-review/v1', purpose: 'design-review-only', runnable: false, product: { id: 'product-design', version: '1' }, designs };
  const index = { schemaVersion: 'truthsrc.product-design-source-index/v1', purpose: 'design-review-only', runnable: false, sources };
  return [entry('design/product-designs.json', JSON.stringify(model, null, 2) + '\n', 'design-model'),
    ...planes.map(p => entry('design/' + p + '.mmd', diagram(designs, p), 'design-plane')),
    entry('design/source-index.json', JSON.stringify(index, null, 2) + '\n', 'design-source-index')];
}
