#!/usr/bin/env node
// ═══ repository-dsl emitter — 1:1 restoration of old codegen ═══
// Generates: <Name>Repository (trait) + <Name>RepositoryImpl (@Singleton)
// For aggregates: sharding-based EntityRef lookup
// For projections: MANUAL sections with scalikejdbc
// Usage: node emit.mjs <spec.json> <out-dir>

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";

const [specPath, outDir] = process.argv.slice(2);
const spec = JSON.parse(readFileSync(specPath, "utf8"));
mkdirSync(outDir, { recursive: true });

// DDD layering (ingested-app 1:1):
//   trait → spec.traitPackage (e.g. net.imadz.metarch.application.aggregates.repository)
//   impl  → spec.implPackage  (e.g. net.imadz.metarch.infrastructure.repositories.aggregate)
// When spec.projectRoot is set, files are written under
//   <projectRoot>/<package path>/ ; otherwise both land in outDir (legacy).
const pkg = spec.package || "net.imadz.infrastructure.repositories";
const traitPkg = spec.traitPackage || `${pkg}.aggregate`;
const implPkg = spec.implPackage || `${pkg}.aggregate`;
const dirFor = (p) =>
  spec.projectRoot ? join(spec.projectRoot, ...p.split(".")) : outDir;
const traitDir = dirFor(traitPkg);
const implDir = dirFor(implPkg);
mkdirSync(traitDir, { recursive: true });
mkdirSync(implDir, { recursive: true });
const name = spec.name; // e.g. "CreditBalance"
const kind = spec.kind || "aggregate"; // "aggregate" | "projection"

function emitAggregate() {
  const ifaceName = `${name}Repository`;
  const implName = `${name}RepositoryImpl`;
  const cmdFamily = `${name}CommandFamily`;
  const command = `${name}Command`;
  const aggPkg = spec.aggregatePackage || "net.imadz.application.aggregates";

  // PHASE1-TRANSITION (Decision 2): 12 aggregates' traits came from an older
  // CodegenMain template variant (duplicate ImplementedBy import, javax.inject
  // imports, Aggregate._ wildcard, long doc, Logic comment, trailing blank
  // line). spec.traitStamp selects the variant; the 66b5b602 batch additionally
  // carried the release line + aggregate @knowledge doc. Default (null) keeps
  // the gen_api_layer variant.
  const variantIface = () => {
    const withRelease = /66b5b602/.test(spec.traitStamp);
    const anchor = spec.aggNoteId
      ? `\n/**\n * @knowledge ${spec.aggElementHash ? `${spec.aggNoteId}@${spec.aggElementHash}` : spec.aggNoteId}\n */`
      : "";
    return `// @generated by ${spec.traitStamp}
${withRelease ? "// @knowledge-release 1.0.0\n" : ""}package ${traitPkg}

import akka.cluster.sharding.typed.scaladsl.EntityRef
import com.google.inject.ImplementedBy
import com.google.inject.ImplementedBy
import javax.inject.Inject
import javax.inject._
import ${aggPkg}.${name}Aggregate
import ${aggPkg}.${name}Aggregate._
import ${aggPkg}.${name}Protocol.${cmdFamily}
import ${implPkg}.${implName}

/**
 * ${ifaceName}: Application Layer Repository Interface for ${name}Aggregate
 * The abstraction for interacting with the Aggregate via sharding and persistence.
 */${withRelease ? anchor : ""}
@ImplementedBy(classOf[${implName}])
trait ${ifaceName} {

  def entityRef(id: String): EntityRef[${cmdFamily}]
  // Logic: sharding 实体引用（聚合隐式契约——对齐 gen_api_layer entityRef，2026-08-28 终局原则）

}

`;
  };

  const iface = spec.traitStamp ? variantIface() : `// @generated by gen_api_layer:2026-08-26
package ${traitPkg}

import akka.cluster.sharding.typed.scaladsl.EntityRef
import com.google.inject.ImplementedBy
import ${aggPkg}.${name}Aggregate
import ${aggPkg}.${name}Protocol.${cmdFamily}
import ${implPkg}.${implName}

/** ${ifaceName}: 聚合仓库（sharding 实体引用），gen_api_layer 直出 */
@ImplementedBy(classOf[${implName}])
trait ${ifaceName} {
  def entityRef(id: String): EntityRef[${cmdFamily}]${(spec.methods || []).length ? "\n" + (spec.methods || []).map(m =>
  `  def ${m.name}(${m.params}): EntityRef[${m.returnType}]`).join("\n") : ""}
}
`;

  const methodBlocks = (spec.methods || []).map(m =>
    `  override def ${m.name}(${m.params}): EntityRef[${m.returnType}] =
    sharding.entityRefFor(${name}Aggregate.entityTypeKey, ${m.idParam || "id"}.toString)`).join("\n\n");
  const tail = methodBlocks ? `\n${methodBlocks}\n` : "\n";

  const impl = `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${implPkg}

import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.cluster.sharding.typed.scaladsl.EntityRef
import javax.inject.Inject
import javax.inject.Singleton
import ${spec.aggregatePackage || "net.imadz.application.aggregates"}.${name}Aggregate
import ${spec.aggregatePackage || "net.imadz.application.aggregates"}.${name}Protocol.${cmdFamily}
import ${traitPkg}.${ifaceName}

/**
 * ${implName}: Aggregate Repository Implementation
 * Implementation of ${ifaceName} interface
 */
@Singleton
class ${implName} @Inject() (sharding: ClusterSharding) extends ${ifaceName} {

  override def entityRef(id: String): EntityRef[${cmdFamily}] =
    sharding.entityRefFor(${name}Aggregate.entityTypeKey, id.toString)
${tail}}
`;

  writeFileSync(join(traitDir, `${ifaceName}.scala`), iface);
  writeFileSync(join(implDir, `${implName}.scala`), impl);
  console.log(`emitted ${ifaceName}.scala, ${implName}.scala`);
}

function emitProjection() {
  const ifaceName = `${name}Repository`;
  const implName = `${name}RepositoryImpl`;

  const methods = (spec.methods || []).map(m => {
    const params = m.params || "";
    const ret = m.returnType || "Unit";
    return `  override def ${m.name}(${params}): ${ret} = {
    // ==== BEGIN MANUAL ====
    ???
    // ==== END MANUAL ====
  }`;
  }).join("\n\n");

  const ifaceMethods = (spec.methods || []).map(m =>
    `  def ${m.name}(${m.params || ""}): ${m.returnType || "Unit"}`
  ).join("\n");

  const iface = `// @generated by gen_api_layer:2026-08-26
package ${pkg}.projection

/**
 * ${ifaceName}: Projection Repository Interface
 */
trait ${ifaceName} {

${ifaceMethods}

}
`;

  const impl = `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${pkg}.projection

import javax.inject.Singleton
import ${spec.repositoryPackage || "net.imadz.application.projection.repository"}.${ifaceName}
import scala.concurrent.ExecutionContext
import scala.concurrent.Future
import scalikejdbc._

/**
 * ${implName}: Projection Repository Implementation
 */
@Singleton
class ${implName} extends ${ifaceName} {

${methods}

}
`;

  writeFileSync(join(outDir, `${ifaceName}.scala`), iface);
  writeFileSync(join(outDir, `${implName}.scala`), impl);
  console.log(`emitted ${ifaceName}.scala, ${implName}.scala`);
}

if (kind === "projection") emitProjection(); else emitAggregate();
