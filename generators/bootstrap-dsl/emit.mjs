#!/usr/bin/env node
// === bootstrap-dsl emitter — 1:1 restoration of old codegen ===
// Generates: <Name>Bootstrap (trait) + ApplicationBootstrap (@Singleton)
// Kinds: "aggregate" (default), "projection", "policy"
// Aggregate bootstraps carry the full EventSourcedBehavior wiring body;
// projection bootstraps the ShardedDaemonProcess ceremony (plain form, or
// the createProjectionFor<X> dispatch form when spec.forSources is set);
// ApplicationBootstrap wires aggregates (alphabetical) then projections
// (alphabetical), policies excluded (they wire via PolicyProjectionModule).
// Usage: node emit.mjs <spec.json> <out-dir>

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";

const [specPath, outDir] = process.argv.slice(2);
const spec = JSON.parse(readFileSync(specPath, "utf8"));
mkdirSync(outDir, { recursive: true });

const pkg = spec.package || "net.imadz.infrastructure.bootstrap";
const name = spec.name;
const kind = spec.kind || "aggregate";
const basePkg = spec.basePkg || "net.imadz.metarch";
const firstLower = (s) => s.charAt(0).toLowerCase() + s.slice(1);

// ── Projection bootstrap ──
function emitProjectionBootstrap() {
  const traitName = `${name}Bootstrap`;
  const viewName = name;
  const repositoryName = `${viewName}Repository`;
  const forSources = spec.forSources || null; // [aggBase, ...] → For-form
  const sources = forSources || [String(spec.sourceAggregate || "").replace(/Aggregate$/, "")];

  const imports = [
    "akka.actor.typed.ActorSystem",
    "akka.cluster.sharding.typed.ShardedDaemonProcessSettings",
    "akka.cluster.sharding.typed.scaladsl.ClusterSharding",
    "akka.cluster.sharding.typed.scaladsl.ShardedDaemonProcess",
    "akka.projection.ProjectionBehavior",
    ...sources.map((s) => `${basePkg}.application.aggregates.${s}Aggregate`),
    `${basePkg}.application.projection.${viewName}`,
    `${basePkg}.application.projection.repository.${repositoryName}`,
  ].sort();

  let behaviorFactory;
  let instances;
  if (forSources) {
    const prefixes = [];
    let acc = "";
    for (const s of sources) {
      acc = acc ? `${acc} + ${s}Aggregate.tags.size` : `${s}Aggregate.tags.size`;
      prefixes.push(acc);
    }
    instances = prefixes[prefixes.length - 1];
    const arms = sources
      .map((s, i) => {
        const offset = i === 0 ? "index" : `index - (${prefixes[i - 1]})`;
        const call = `ProjectionBehavior(${viewName}.createProjectionFor${s}(system, sharding, ${offset}, repository))`;
        if (i === 0)
          return `        if (index < ${prefixes[0]})\n          ${call}`;
        return `        else         if (index < ${prefixes[i]})\n          ${call}`;
      })
      .join("\n");
    behaviorFactory = `behaviorFactory = index => {
${arms}
        else throw new IllegalStateException(s"projection tag index out of range: $index / ${instances}")
      }`;
  } else {
    instances = `${sources[0]}Aggregate.tags.size`;
    behaviorFactory = `behaviorFactory = index => ProjectionBehavior(${viewName}.createProjection(system, sharding, index, repository))`;
  }

  return `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${pkg}

${imports.map((i) => `import ${i}`).join("\n")}

/**
 * ${traitName}: ProjectionBootstrapType 引导组件
 */
trait ${traitName} {


  def init${viewName}Projection(system: ActorSystem[_], sharding: ClusterSharding, repository: ${repositoryName}): Unit = {
    ShardedDaemonProcess(system).init(
      name = ${viewName}.projectionName,
      numberOfInstances = ${instances},
      ${behaviorFactory},
      settings = ShardedDaemonProcessSettings(system),
      stopMessage = Some(ProjectionBehavior.Stop)
    )
  }


}
`;
}

// ── Policy bootstrap: PolicyOn<X>Bootstrap ──
function emitPolicyBootstrap() {
  const traitName = `${name}Bootstrap`; // name already includes PolicyOn prefix
  const runnerName = `${name}Runner`;
  const aggregateName = spec.sourceAggregate;

  return `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${pkg}

import akka.actor.typed.ActorSystem
import akka.cluster.sharding.typed.ShardedDaemonProcessSettings
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.cluster.sharding.typed.scaladsl.ShardedDaemonProcess
import akka.projection.ProjectionBehavior
import ${basePkg}.application.aggregates.${aggregateName}
import ${basePkg}.application.projection.policy.${runnerName}

/**
 * ${traitName}: PolicyBootstrapType 引导组件（ShardedDaemonProcess 注册仪式）。
 */
trait ${traitName} {

  def init${runnerName}(system: ActorSystem[_], sharding: ClusterSharding): Unit = {
    ShardedDaemonProcess(system).init(
      name = ${runnerName}.projectionName,
      numberOfInstances = ${aggregateName}.tags.size,
      behaviorFactory = index => ProjectionBehavior(${runnerName}.createProjection(system, sharding, index)),
      settings = ShardedDaemonProcessSettings(system),
      stopMessage = Some(ProjectionBehavior.Stop)
    )
  }
}
`;
}

// ── Aggregate bootstrap: full EventSourcedBehavior wiring ──
// Import list is the old template's sorted-with-duplicates set (Entity and
// PersistenceId appear twice — mechanical, reproduced deliberately).
// spec.servicePorts ([{param, type}]) adds domain-service constructor
// params (only ModelCatalog in this corpus): their imports are inserted
// UNSORTED immediately after the `net.imadz.common.Id` line, and the
// handlers are called with the port arguments.
function emitAggregateBootstrap() {
  const traitName = `${name}Bootstrap`;
  const fam = `${name}CommandFamily`;
  const ports = spec.servicePorts || [];
  const portParams = ports.map((p) => `${p.param}: ${p.type}`).join(", ");
  const portArgs = ports.map((p) => p.param).join(", ");
  const initParams = portParams ? `, ${portParams}` : "";
  const applyArgs = portArgs ? `, ${portArgs}` : "";
  const cmdHandler = ports.length
    ? `${name}Behaviors.apply(${ports.filter((p) => p.type === "ConceptDeltaAdjudicator").map((p) => p.param).join(", ") || portArgs})`
    : `${name}Behaviors.apply`;
  const evtHandler = ports.length
    ? `${name}EventHandler.apply(${portArgs})`
    : `${name}EventHandler.apply`;

  const imports = [
    "akka.actor.typed.Behavior",
    "akka.actor.typed.LogOptions",
    "akka.actor.typed.SupervisorStrategy",
    "akka.actor.typed.scaladsl.Behaviors",
    "akka.cluster.sharding.typed.scaladsl.ClusterSharding",
    "akka.cluster.sharding.typed.scaladsl.Entity",
    "akka.cluster.sharding.typed.scaladsl.Entity",
    "akka.cluster.sharding.typed.scaladsl.EntityContext",
    "akka.cluster.sharding.typed.scaladsl.EntityTypeKey",
    "akka.persistence.typed.PersistenceId",
    "akka.persistence.typed.PersistenceId",
    "akka.persistence.typed.scaladsl.EventSourcedBehavior",
    "akka.persistence.typed.scaladsl.RetentionCriteria",
    "net.imadz.common.CommonTypes.Id",
    "net.imadz.common.Id",
    `${basePkg}.application.aggregates.${name}Aggregate`,
    `${basePkg}.application.aggregates.${name}Protocol`,
    `${basePkg}.application.aggregates.behaviors.${name}Behaviors`,
    `${basePkg}.domain.entities.${name}Entity`,
    `${basePkg}.domain.entities.${name}Entity.${name}State`,
    `${basePkg}.domain.entities.behaviors.${name}EventHandler`,
    `${basePkg}.infrastructure.persistence.${name}EventAdapter`,
    `${basePkg}.infrastructure.persistence.${name}SnapshotAdapter`,
    "org.slf4j.LoggerFactory",
    "org.slf4j.event.Level",
    "scala.concurrent.duration.DurationInt",
  ].sort();
  if (ports.length) {
    const idx = imports.indexOf("net.imadz.common.Id");
    imports.splice(
      idx + 1,
      0,
      ...ports.map((p) => `${basePkg}.domain.service.${p.type}`)
    );
  }

  return `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${pkg}

${imports.map((i) => `import ${i}`).join("\n")}

/**
 * ${traitName}: AggregateBootstrapType 引导组件
 */
trait ${traitName} {


  def init${name}Aggregate(sharding: ClusterSharding${initParams}): Unit = {
    val behaviorFactory: EntityContext[${name}Protocol.${fam}] => Behavior[${name}Protocol.${fam}] = { context =>
      val i = math.abs(context.entityId.hashCode % ${name}Aggregate.tags.size)
      val selectedTag = ${name}Aggregate.tags(i)
      apply(context.entityId, selectedTag${applyArgs})
    }

    sharding.init(Entity(${name}Aggregate.entityTypeKey)(behaviorFactory))
  }

  private def apply(entityId: String, tag: String${initParams}): Behavior[${name}Protocol.${fam}] =
    Behaviors.logMessages(LogOptions().withLogger(LoggerFactory.getLogger("iMadz")).withLevel(Level.INFO),
      Behaviors.setup { actorContext =>
        EventSourcedBehavior(
          persistenceId = PersistenceId(${name}Aggregate.entityTypeKey.name, entityId),
          // 标识符为 Id（UUID）的聚合走 Id.of；字符串 id 聚合（saga 真源树，
          // 标识符折叠 String）直接传 entityId——empty 的参数型即标识符型。
          emptyState = ${name}Entity.empty(${spec.idIsString ? "entityId" : "Id.of(entityId)"}),
          commandHandler = ${cmdHandler},
          // [FIX] 使用 EventHandler.apply
          eventHandler = ${evtHandler}
        ).withTagger(_ => Set(tag))
          .withRetention(RetentionCriteria.snapshotEvery(numberOfEvents = 100, keepNSnapshots = 3))
          .onPersistFailure(SupervisorStrategy.restartWithBackoff(200.millis, 5.seconds, 0.1).withStashCapacity(100))
          .eventAdapter(new ${name}EventAdapter)
          .snapshotAdapter(new ${name}SnapshotAdapter)
      })


}
`;
}

// ── Dispatch by kind ──
let traitContent, traitName;
if (kind === "projection") {
  traitName = `${name}Bootstrap`;
  traitContent = emitProjectionBootstrap();
} else if (kind === "policy") {
  traitName = `${name}Bootstrap`;
  traitContent = emitPolicyBootstrap();
} else {
  traitName = `${name}Bootstrap`;
  traitContent = emitAggregateBootstrap();
}

// ── ApplicationBootstrap ──
// spec: { aggTraits: [base names, alphabetical], viewTraits: [view names,
// alphabetical — wired projections only], servicePorts: [{param, type}] }
function emitApplicationBootstrap() {
  const aggTraits = [...(spec.aggTraits || [])].sort();
  const viewTraits = [...(spec.viewTraits || [])].sort();
  const ports = spec.servicePorts || [];
  const repoParams = viewTraits.map((v) => ({
    param: `${firstLower(v)}Repository`,
    type: `${v}Repository`,
  }));

  const imports = [
    "akka.actor.ActorSystem",
    "akka.actor.ExtendedActorSystem",
    "akka.actor.typed.scaladsl.adapter",
    "akka.actor.typed.scaladsl.adapter._",
    "akka.actor.typed.{ActorSystem => TypedActorSystem}",
    "akka.cluster.sharding.typed.scaladsl.ClusterSharding",
    "javax.inject.Inject",
    "javax.inject.Singleton",
    "javax.inject.{Inject, Singleton}",
    ...viewTraits.map((v) => `${basePkg}.application.projection.repository.${v}Repository`),
    "scala.concurrent.ExecutionContext",
  ].sort();
  if (ports.length) {
    const idx = imports.indexOf("javax.inject.{Inject, Singleton}");
    imports.splice(idx + 1, 0, ...ports.map((p) => `${basePkg}.domain.service.${p.type}`));
  }

  const paramLines = [
    "sharding: ClusterSharding",
    ...repoParams.map((r) => `${r.param}: ${r.type}`),
  ];
  if (ports.length) {
    const last = paramLines.length - 1;
    paramLines[last] += ports.map((p) => `, ${p.param}: ${p.type}`).join("");
  }
  const traits = [
    ...aggTraits.map((t) => `${t}Bootstrap`),
    ...viewTraits.map((t) => `${t}Bootstrap`),
  ];
  const portArgs = ports.map((p) => p.param).join(", ");
  const initCalls = [
    ...aggTraits.map((t) =>
      ports.length && t === "ModelCatalog"
        ? `  init${t}Aggregate(sharding, ${portArgs})`
        : `  init${t}Aggregate(sharding)`
    ),
    ...viewTraits.map(
      (v) => `  init${v}Projection(system, sharding, ${firstLower(v)}Repository)`
    ),
  ];

  return `// @generated by CodegenMain:225ed28b
// @knowledge-release 1.0.0
package ${pkg}

${imports.map((i) => `import ${i}`).join("\n")}

/**
 * ApplicationBootstrap: 应用引导类，负责初始化所有CQRS组件
 */
@Singleton
class ApplicationBootstrap @Inject()(classicSystem: ActorSystem,
  ${paramLines.join(",\n  ")}) extends ${traits.join(" with ")} {


  // 隐式转换环境
  private implicit val system: TypedActorSystem[Nothing] = classicSystem.toTyped
  private implicit val ec: scala.concurrent.ExecutionContext = system.executionContext

  // Initializations
${initCalls.join("\n")}


}
`;
}

if (!spec.skipTrait) {
  writeFileSync(join(outDir, `${traitName}.scala`), traitContent);
}
if (!spec.skipApp) {
  writeFileSync(join(outDir, `ApplicationBootstrap.scala`), emitApplicationBootstrap());
}
console.log(`emitted${spec.skipTrait ? "" : ` ${traitName}.scala`}${spec.skipApp ? "" : ", ApplicationBootstrap.scala"}`);
