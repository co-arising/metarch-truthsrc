import { at, fail, object, text } from '../../lib/products/request.mjs';
import { createClassicContext } from '../../lib/classic-architecture/context.mjs';
import { collectDependencies, fqn } from '../../lib/classic-architecture/types.mjs';
import { buildAggregateProtocol } from '../scala-cqrs-application-protocol/build-model.mjs';
import { renderAggregateProtocol } from '../scala-cqrs-application-protocol/template.mjs';
import { buildCommandHelpers } from '../scala-cqrs-command-helper/build-models.mjs';
import { renderCommandHelpers } from '../scala-cqrs-command-helper/templates/command-helpers.mjs';
import { buildAggregateBehavior } from '../scala-cqrs-play-service/build-aggregate-behavior-model.mjs';
import { renderAggregateBehavior } from '../scala-cqrs-play-service/templates/classic-aggregate-behavior.mjs';
import { buildDomainEntity } from '../scala-cqrs-domain/builders/domain-entity.mjs';
import { renderDomainEntity } from '../scala-cqrs-domain/templates/domain-entity.mjs';

export const version = '1';
const footprint = Object.freeze([{ id: 'classic-architecture', version: '1' }]);
function sourceKey(source) {
  return 'source:' + source.document + '#' + source.pointer;
}
function pathOf(model) {
  return 'app/' + model.selfType.packageName.replaceAll('.', '/') + '/' + model.selfType.name + '.scala';
}
function header(options) {
  text(options.generatorVersion, at('options', '/generatorVersion'));
  if (!/^[A-Za-z0-9._-]+$/u.test(options.generatorVersion)) fail('CLASSIC_STAMP', 'single token generator version required', at('options'));
  const generated = '// @generated by CodegenMain:' + options.generatorVersion + '\n';
  if (options.knowledgeRelease === null) return generated;
  text(options.knowledgeRelease, at('options', '/knowledgeRelease'));
  if (/[\r\n\x00]/u.test(options.knowledgeRelease)) fail('CLASSIC_STAMP', 'single-line knowledge release required', at('options'));
  return generated + '// @knowledge-release ' + options.knowledgeRelease + '\n';
}
function record(model, render, kind, source) {
  return { model, render, kind, source, path: pathOf(model) };
}
function buildArtifacts(product, ctx) {
  const { system, source } = product;
  const entities = system.domain.entities.map((meta, i) => record(buildDomainEntity(meta, ctx), renderDomainEntity, 'domain-entity',
    { document: source.document, pointer: source.pointer + '/domain/entities/' + i }));
  const aggregates = system.application.aggregates.flatMap((meta, i) => {
    const location = { document: source.document, pointer: source.pointer + '/application/aggregates/' + i };
    return [record(buildAggregateProtocol(meta, ctx), renderAggregateProtocol, 'application-protocol', location),
      record(buildCommandHelpers(meta, ctx), renderCommandHelpers, 'command-helper', location),
      record(buildAggregateBehavior(meta, ctx), renderAggregateBehavior, 'aggregate-behavior', location)];
  });
  return [...entities, ...aggregates];
}
function fieldTypes(definitions) {
  return definitions.flatMap(definition => [
    ...(definition.fields ?? []).map(field => field.typeRef), ...(definition.superTypes ?? []),
  ]);
}
function sourceReferences({ model, kind }) {
  const roots = [...(model.dependencies ?? [])];
  if (kind === 'domain-entity') roots.push(...fieldTypes([model.state, ...model.eventFamily.events, model.eventFamily]));
  if (kind === 'application-protocol') roots.push(model.stateType, model.eventType,
    ...fieldTypes([...model.commandFamily.commands, ...model.replies, model.commandFamily]));
  if (kind === 'command-helper') roots.push(...model.helpers.flatMap(helper =>
    [helper.commandType, helper.stateType, helper.paramType, helper.replyType, helper.errorType]));
  if (kind === 'aggregate-behavior') roots.push(model.commandHelpers, model.stateType, model.eventType, model.commandType);
  return collectDependencies(roots.filter(Boolean));
}
function localDependencies(artifact, owners) {
  const paths = new Set();
  for (const ref of sourceReferences(artifact)) {
    let owner = fqn(ref);
    while (owner) {
      const path = owners.get(owner);
      if (path && path !== artifact.path) paths.add(path);
      const end = owner.lastIndexOf('.');
      owner = end < 0 ? '' : owner.slice(0, end);
    }
  }
  return [...paths].sort();
}
function validatePackages(options) {
  for (const key of ['rootPackage', 'frameworkPackage', 'moduleName']) {
    text(options[key], at('options', '/' + key));
    if (!options[key].split('.').every(part => /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(part)))
      fail('CLASSIC_PACKAGE', 'package option must be a dotted identifier: ' + key, at('options', '/' + key));
  }
}

/** All four families share admitted metadata and the existing source-product writer. */
export function produce({ products, options }) {
  object(options, ['rootPackage', 'frameworkPackage', 'moduleName', 'generatorVersion', 'knowledgeRelease'], at('options'));
  validatePackages(options);
  const product = products['classic-architecture'];
  const ctx = createClassicContext(product.system, {
    rootPackage: options.rootPackage, frameworkPackage: options.frameworkPackage, moduleName: options.moduleName,
  });
  const stamp = header(options), artifacts = buildArtifacts(product, ctx);
  const owners = new Map(artifacts.map(artifact => [fqn(artifact.model.selfType), artifact.path]));
  return artifacts.map(artifact => ({
    path: artifact.path, content: stamp + artifact.render(artifact.model), kind: artifact.kind,
    deps: localDependencies(artifact, owners),
    knowledgeIds: [sourceKey(artifact.source)], productFootprint: footprint, merge: null,
  }));
}
