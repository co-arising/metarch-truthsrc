// scala-cqrs-es-policy-exec — the policy execution-side face (V4-19), ported verbatim from the
// production gen_policy_exec.mjs (债④余账批 2026-10-04): five files per executionSide policy —
//
//   app/.../application/projection/policy/<Cmd>Policy.scala              kernel 纯函数对 (decide 透传)
//   app/.../application/projection/policy/PolicyOn<Cmd>On<Evt>Handler.scala  四段装配壳 (PolicyMachine.run)
//   app/.../application/projection/policy/<Cmd>Mechanics.scala           execute 机制束 (sharding ask)
//   app/.../application/projection/policy/PolicyOn<Cmd>Runner.scala      atLeastOnceAsync 投影
//   app/.../infrastructure/bootstrap/PolicyOn<Cmd>Bootstrap.scala        ShardedDaemonProcess 注册
//
// Source: policy notes with info.executionSide=true (five in the corpus). Wiring facts travel the
// canonical policies slot (augment-rules V4-19 extension: executionSide/entityIdField/dispose);
// the signature facts (command params minus replyTo, reply type) resolve from the aggregate's
// canonical commands — the same authority the engine's staging-signature parse read (the Protocol
// is generated from those same rows, so the two agree). 宁缺勿造: a policy whose command/reply/
// entityIdField cannot resolve fails the run (half a policy file is worse than none).
//
// The stamp line is the tool's fixed literal (its version never moved) — headerOf pins it.
// Shared runtime (PolicyMachine/DlqBury/FailureVerdict) is handwritten territory — referenced,
// never emitted (ContentFingerprint precedent).
import { scalaSig } from '../scala-cqrs-es/builders/types.mjs';
import { toSnakeCase } from '../scala-cqrs-es/builders/protos.mjs';

const STAMP = '// @generated by gen_policy_exec:2026-10-04（policy 执行侧·glue policy 生成面批）';
const POLICY_PKG = 'net.imadz.metarch.application.projection.policy';
const BOOT_PKG = 'net.imadz.metarch.infrastructure.bootstrap';
const SCALA_KW = new Set(['type', 'object', 'class', 'trait', 'def', 'val', 'var', 'for', 'while', 'if', 'else', 'match', 'case', 'import', 'package', 'extends', 'with', 'new', 'return', 'throw', 'try', 'catch', 'finally', 'null', 'true', 'false', 'this', 'super', 'sealed', 'implicit', 'lazy', 'override', 'private', 'protected', 'abstract', 'final', 'yield', 'do']);
const scalaRef = (f) => (SCALA_KW.has(f) ? `\`${f}\`` : f);

const headerOf = (env) => `${STAMP}\n// @knowledge-release ${env.knowledgeRelease}\n`;
// dispose 纯函数体（白名单真源化）— gen_policy_exec.mjs disposeBody verbatim.
const disposeBody = (dispose) => {
  if (!dispose || !dispose.permanentOn || !dispose.permanentOn.length) {
    return '    FailureVerdict.Retryable(err)';
  }
  const conds = dispose.permanentOn.map((c) => `err.code == "${c}"`).join(' || ');
  const msg = String(dispose.message || '').replace(/\{code\}/g, '${err.code}');
  return `    if (${conds})\n      FailureVerdict.Permanent(s"${msg}", err)\n    else\n      FailureVerdict.Retryable(err)`;
};

export function policyExecModels(canonical, env) {
  const rows = [];
  const fatals = [];
  for (const a of canonical.aggregates ?? []) {
    for (const p of a.policies ?? []) {
      if (!p.executionSide) continue;
      const cmd = (a.commands ?? []).find((x) => x.name === p.cmdName);
      const cmdParams = cmd?.parameters ?? null;
      const replyT = cmd?.reply?.name ?? null;
      const srcAgg = p.evtHostAgg;
      const evt = p.evtName;
      const entityIdField = p.entityIdField
        ?? (cmdParams ?? []).find((x) => x.name.toLowerCase() === a.name.toLowerCase() + 'id')?.name
        ?? null;
      if (!cmdParams || !replyT || !entityIdField || !srcAgg || !p.evtPayloads) {
        fatals.push(`${p.name}：签名解析缺（cmd=${!!cmdParams} reply=${!!replyT} entityIdField=${entityIdField} entity=${!!p.evtPayloads}）`);
        continue;
      }
      const pn = 'PolicyOn' + p.cmdName;
      const poPkg = toSnakeCase(srcAgg);
      const poObj = `${srcAgg}EventPO`;
      const convObj = `${srcAgg}ProtoConverters`;
      const cmdForward = cmdParams.filter((x) => x.name !== 'replyTo').map((x) => `p.${scalaRef(x.name)}`).join(', ');
      const shardingKey = `p.${scalaRef(entityIdField)}.toString`;
      const noteIds = p.noteId ? [p.noteId] : [];
      const base = { cmd: p.cmdName, agg: a.name, evt, srcAgg, pn, noteIds, cmdForward, shardingKey, replyT, paramsName: `${p.cmdName}Params`, poPkg, poObj, convObj, conv: `${evt}Conv`, dispose: p.dispose, idempotencyKey: p.idempotencyKey, policyName: p.name };

      rows.push({
        path: `app/net/imadz/metarch/application/projection/policy/${p.cmdName}Policy.scala`,
        kind: 'policy-exec', schemaCategory: 'policy-exec', schemaNode: `${p.cmdName}Policy`, families: [], deps: [], noteIds,
        render: (env2) => renderPolicy(base, env2),
      });
      rows.push({
        path: `app/net/imadz/metarch/application/projection/policy/${pn}On${evt}Handler.scala`,
        kind: 'policy-exec', schemaCategory: 'policy-exec', schemaNode: `${pn}On${evt}Handler`, families: [], deps: [], noteIds,
        render: (env2) => renderHandler(base, env2),
      });
      rows.push({
        path: `app/net/imadz/metarch/application/projection/policy/${p.cmdName}Mechanics.scala`,
        kind: 'policy-exec', schemaCategory: 'policy-exec', schemaNode: `${p.cmdName}Mechanics`, families: [], deps: [], noteIds,
        render: (env2) => renderMechanics(base, env2),
      });
      rows.push({
        path: `app/net/imadz/metarch/application/projection/policy/${pn}Runner.scala`,
        kind: 'policy-exec', schemaCategory: 'policy-exec', schemaNode: `${pn}Runner`, families: [], deps: [], noteIds,
        render: (env2) => renderRunner(base, env2),
      });
      rows.push({
        path: `app/net/imadz/metarch/infrastructure/bootstrap/${pn}Bootstrap.scala`,
        kind: 'policy-exec', schemaCategory: 'policy-exec', schemaNode: `${pn}Bootstrap`, families: [], deps: [], noteIds,
        render: (env2) => renderBootstrap(base, env2),
      });
    }
  }
  if (fatals.length) throw new Error(`policy-exec 宁缺勿造：${fatals.join(' · ')}`);
  return rows;
}

// The five template strings mirror gen_policy_exec.mjs verbatim (s"" interpolations included).
const renderPolicy = (m, env) => `${headerOf(env)}package ${POLICY_PKG}

import net.imadz.metarch.domain.entities.${m.srcAgg}Entity.${m.evt}
import net.imadz.metarch.domain.invariant.params.${m.agg}RuleParams.${m.paramsName}
import net.imadz.metarch.domain.policy.${m.agg}Policies.${m.pn}

/** ${m.cmd} 策略纯函数对（真源 policy 便签「${m.policyName}」info.executionSide 直发）：
  * decide＝${m.pn}.on 透传（kernel 声明已是纯）；dispose${(m.dispose && m.dispose.permanentOn) ? `＝白名单分类（${m.dispose.permanentOn.join('/')}→Permanent·${(m.dispose.sources || '真源 info.dispose').replace(/\n/g, ' ')}）` : '＝一切 Retryable（重试族·契约：命令幂等·失败传播 offset 不提交 at-least-once）'}。 */
object ${m.cmd}Policy {

  type Command = ${m.paramsName}

  def decide(e: ${m.evt}): List[Command] =
    ${m.pn}.on(e)

  def dispose(e: ${m.evt}, err: net.imadz.common.CommonTypes.iMadzError): FailureVerdict =
${disposeBody(m.dispose)}
}
`;

const renderHandler = (m, env) => `${headerOf(env)}package ${POLICY_PKG}

import akka.Done
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.projection.eventsourced.EventEnvelope
import akka.projection.scaladsl.Handler
import net.imadz.metarch.domain.entities.${m.srcAgg}Entity.${m.evt}
import net.imadz.metarch.infrastructure.persistence.converters.${m.convObj}.${m.conv}
import net.imadz.metarch.infrastructure.proto.${m.poPkg}.${m.poObj}

import scala.concurrent.{ExecutionContext, Future}
class ${m.pn}On${m.evt}Handler(sharding: ClusterSharding)(implicit ec: ExecutionContext)
    extends Handler[EventEnvelope[${m.poObj}.Event]] {

  override def process(envelope: EventEnvelope[${m.poObj}.Event]): Future[Done] =
    PolicyMachine.run[${m.evt}, ${m.cmd}Policy.Command](
      envelope,
      aggType = "${m.srcAgg}",
      decode = {
        case ${m.poObj}.Event.${m.evt}(po) =>
          Some(${m.conv}.fromProto(po))
        case _ => None
      },
      decide = ${m.cmd}Policy.decide,
      execute = ${m.cmd}Mechanics.execute(sharding),
      dispose = ${m.cmd}Policy.dispose,
      bury = DlqBury(_, "${m.srcAgg}", _),
    )
}
`;

const renderMechanics = (m, env) => `${headerOf(env)}package ${POLICY_PKG}

import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.util.Timeout
import net.imadz.common.CommonTypes.iMadzError
import net.imadz.metarch.application.aggregates.${m.agg}Aggregate
import net.imadz.metarch.application.aggregates.${m.agg}Protocol.{${m.cmd}, ${m.replyT}}
import net.imadz.metarch.domain.invariant.params.${m.agg}RuleParams.${m.paramsName}

import scala.concurrent.duration._
import scala.concurrent.{ExecutionContext, Future}

/** ${m.cmd} 机制函数束（真源 policy 便签「${m.policyName}」直发）。 */
object ${m.cmd}Mechanics {

  private implicit val askTimeout: Timeout = Timeout(10.seconds)

  def execute(sharding: ClusterSharding)(implicit ec: ExecutionContext): ${m.paramsName} => Future[Either[iMadzError, Unit]] =
    p =>
      sharding
        .entityRefFor(${m.agg}Aggregate.entityTypeKey, ${m.shardingKey})
        .ask[${m.replyT}](${m.cmd}(${m.cmdForward}, _))
        .map {
          case ${m.replyT}(None)    => Right(())
          case ${m.replyT}(Some(e)) => Left(e)
        }
}
`;

const projectionIdOf = (pn) => pn.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase().replace(/^policy_on_/, 'policy_on_');

const renderRunner = (m, env) => `${headerOf(env)}package ${POLICY_PKG}

import akka.actor.typed.ActorSystem
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.contrib.persistence.mongodb.MongoReadJournal
import akka.persistence.query.Offset
import akka.projection.ProjectionId
import akka.projection.eventsourced.EventEnvelope
import akka.projection.eventsourced.scaladsl.EventSourcedProvider
import akka.projection.jdbc.scaladsl.JdbcProjection
import akka.projection.scaladsl.{AtLeastOnceProjection, SourceProvider}
import net.imadz.common.application.projection.ScalikeJdbcSession
import net.imadz.metarch.infrastructure.proto.${m.poPkg}.${m.poObj}

/**
 * ${m.pn} 的执行侧投影（应用层）。
 * 订阅 ${m.srcAgg} 事件流，命中 ${m.evt} 时驱动「${m.policyName}」策略。
 * atLeastOnceAsync（非 exactlyOnce）：命令发出后才推进 offset，重放窗口由策略声明的
 * 幂等语义（idempotencyKey: ${m.idempotencyKey || 'command-level'}）兜底。
 */
object ${m.pn}Runner {

  val projectionName = "${m.pn}Runner"

  private def sourceProvider(tag: String)(implicit system: ActorSystem[_]): SourceProvider[Offset, EventEnvelope[${m.poObj}.Event]] =
    EventSourcedProvider.eventsByTag[${m.poObj}.Event](
      system = system,
      readJournalPluginId = MongoReadJournal.Identifier,
      tag = tag
    )

  def createProjection(system: ActorSystem[_], sharding: ClusterSharding, index: Int): AtLeastOnceProjection[Offset, EventEnvelope[${m.poObj}.Event]] = {
    implicit val sys: ActorSystem[_] = system
    implicit val ec: scala.concurrent.ExecutionContext = system.executionContext
    val tag = s"${m.srcAgg}Tag$index"
    JdbcProjection.atLeastOnceAsync(
      projectionId = ProjectionId("${projectionIdOf(m.pn)}", tag),
      sourceProvider = sourceProvider(tag),
      sessionFactory = () => new ScalikeJdbcSession(),
      handler = () => new ${m.pn}On${m.evt}Handler(sharding)
    )
  }
}
`;

const renderBootstrap = (m, env) => `${headerOf(env)}package ${BOOT_PKG}

import akka.actor.typed.ActorSystem
import akka.cluster.sharding.typed.ShardedDaemonProcessSettings
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.cluster.sharding.typed.scaladsl.ShardedDaemonProcess
import akka.projection.ProjectionBehavior
import net.imadz.metarch.application.aggregates.${m.srcAgg}Aggregate
import net.imadz.metarch.application.projection.policy.${m.pn}Runner

/**
 * ${m.pn}Bootstrap: PolicyBootstrapType 引导组件（ShardedDaemonProcess 注册仪式）。
 */
trait ${m.pn}Bootstrap {

  def init${m.pn}Runner(system: ActorSystem[_], sharding: ClusterSharding): Unit = {
    ShardedDaemonProcess(system).init(
      name = ${m.pn}Runner.projectionName,
      numberOfInstances = ${m.srcAgg}Aggregate.tags.size,
      behaviorFactory = index => ProjectionBehavior(${m.pn}Runner.createProjection(system, sharding, index)),
      settings = ShardedDaemonProcessSettings(system),
      stopMessage = Some(ProjectionBehavior.Stop)
    )
  }
}
`;

export function generate({ canonical, options = {} }) {
  const env = { knowledgeRelease: canonical.knowledgeRelease };
  return policyExecModels(canonical, env).map((r) => {
    const { render, ...rest } = r;
    return { ...rest, content: render(env) };
  });
}
