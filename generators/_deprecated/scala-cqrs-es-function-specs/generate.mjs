// scala-cqrs-es-function-specs — the Function oracle-spec face (V4-22), ported from the
// production gen_function_specs.mjs (EP 行为层锚·2026-09-21): one ContentFingerprintSpec.scala
// whose assertions come verbatim from the handwritten yaml oracle tables (functions.yaml +
// cases/*.yaml — distilled to the function-spec-inputs sidecar; the generator never reads
// production code). Per-case `// @knowledge <noteId>` = the Function's anchoredTo note.
export function generate({ canonical, options = {} }) {
  const inputs = options.functionSpecs ?? {};
  const functions = inputs.functions ?? [];
  const cases = inputs.cases ?? [];
  const tripleQuoteSafe = (s) => s.replace(/"""/g, '\\"\\"\\"');

  const body = [];
  for (const fn of functions) {
    const fnCases = cases.filter((c) => c.function === fn.id);
    if (!fnCases.length) continue;
    const anchor = fn.anchoredNoteId ?? null;
    body.push(`  "${fn.id}" should {`);
    for (const c of fnCases) {
      const givenJson = JSON.stringify(c.given ?? {});
      const outs = Object.entries(c.then?.output ?? {});
      const asserts = outs.map(([k, v]) => `      got("${k}") shouldBe "${v}"`).join('\n');
      const noteLine = anchor ? `    // @knowledge ${anchor}\n` : '';
      body.push(`${noteLine}    "${c.id} ${String(c.zh || '').replace(/"/g, "'")}" in {`);
      body.push(`      val got = ContentFingerprint.invoke("${fn.id}", play.api.libs.json.Json.parse("""${tripleQuoteSafe(givenJson)}"""))`);
      body.push(asserts);
      body.push('    }');
    }
    body.push('  }');
    body.push('');
  }

  const content = `// @generated by gen_function_specs.mjs（EP 行为层锚·2026-09-21）—— 请勿手改
// 输入：knowledge_base/functions/functions.yaml + cases/*.yaml（手写 oracle）
// 语义：断言值来自 yaml（**不是**从 ContentFingerprint 实现反推）；改实现不该动本文件。
package net.imadz.metarch.domain.service

import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

class ContentFingerprintSpec extends AnyWordSpec with Matchers {

${body.join('\n')}}

`;
  return [{
    path: 'test/net/imadz/metarch/domain/service/ContentFingerprintSpec.scala',
    content,
    kind: 'function-spec', schemaCategory: 'global', schemaNode: 'ContentFingerprintSpec', families: [], deps: [], noteIds: [],
  }];
}
