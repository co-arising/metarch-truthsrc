// scala-cqrs-es-ddl — the projection DDL face (V4-14), ported from the production
// gen_projection_ddl.mjs (EP_Generated_Patch_Pipeline §九 + M3 vector dialect 批D).
//
// Two entries over the canonical:
//   • conf/sql/2.sql — the MySQL dialect (H2 MODE=MySQL test-compatible) over the ③-layer
//     GATED DecisionViews. Exclusions ported: graph cards have no SQL dialect (S2-65 批D —
//     Neo4j nodes/edges land via the ④ Impl's GraphMutationExecutor delegation) and mongo
//     document views don't produce MySQL DDL (视图存储重设计 2026-10-08 — collections are
//     created by MongoViewStore.ensureCollections; old tables not dropped = rollback-safe).
//     Type map: String/uuid→VARCHAR(255), Integer→INT, Long→BIGINT, Boolean→TINYINT(1),
//     BigDecimal/Decimal→DECIMAL(19,2), Instant→BIGINT (epoch millis), List<*>/unknown→TEXT
//     (JSON text; List check FIRST so enriched List<String (UUID)> stays TEXT);
//     description/content/info→TEXT (MysqlDataTruncation 毒丸判例·S2-75/S2-82-B4a),
//     payloadJson→MEDIUMTEXT (S2-82-B4c TSP 三兄弟件 64KB 截断判例). PRIMARY KEY = faithful
//     key metadata, sorted key names (no silent key-gap filling — BACKLOG owns the semantics).
//   • conf/sql/5-pgvector.sql — the M3 vector dialect over the ①-layer vectorViews slot
//     (不经 ③层门 — the vector corpus and the decision-view face stay unmixed): CREATE
//     EXTENSION + per-view table (camel→snake columns, key columns VARCHAR(255) NOT NULL) +
//     embedding vector(dims) NOT NULL + declaration-order composite PK + tenant index + HNSW
//     index (distance→ops map; cosine→vector_cosine_ops).
//
// Ledger parity: 2.sql families = the承载视图 sourceAggregates union (bounded-wide; DDL is the
// derived container carrying its views' identity), noteIds = the views' ①-layer readModel
// note ids via canonical.viewNoteIds; 5-pgvector families = [] (vector views have no
// sourceAggregates truth source — global artifact, same口径 as VectorSearchApiController),
// noteIds = the vector view note ids.
import { gateViews } from '../scala-cqrs-es-api/builders/rolemap.mjs';

// HNSW distance → operator class (批D 同源映射)
const HNSW_OPS = { cosine: 'vector_cosine_ops', l2: 'vector_l2_ops', inner_product: 'vector_ip_ops' };
const isList = (t) => /^list[<[]/i.test(String(t));

// gen_projection_ddl.mjs sqlTypeOf verbatim port (判例注记保持——每条都是停投影事故的墓碑)
const sqlTypeOf = (dataType, fieldName) => {
  const t = String(dataType || 'String');
  if (/^(description|content|info)$/i.test(String(fieldName || ''))) return 'TEXT';
  if (/^payloadJson$/i.test(String(fieldName || ''))) return 'MEDIUMTEXT';
  if (isList(t)) return 'TEXT';
  if (t === 'String' || /uuid/i.test(t)) return 'VARCHAR(255)';
  if (t === 'Integer') return 'INT';
  if (t === 'Long') return 'BIGINT';
  if (t === 'Boolean') return 'TINYINT(1)';
  if (t === 'BigDecimal' || t.startsWith('Decimal')) return 'DECIMAL(19,2)';
  if (t === 'Instant') return 'BIGINT';
  return 'TEXT';
};

const vecSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const vecColType = (f) => {
  if (f.isKey) return 'VARCHAR(255) NOT NULL';
  const t = String(f.dataType || 'String');
  if (t === 'Integer') return 'INT';
  if (t === 'Long') return 'BIGINT';
  if (t === 'Instant') return 'BIGINT';
  if (t === 'Boolean') return 'BOOLEAN';
  return 'TEXT';
};

export function generate({ canonical, options = {} }) {
  // --- conf/sql/2.sql: gated DecisionViews − graph − mongo ------------------------------------
  const models = gateViews(canonical.readModels ?? [], canonical.viewFieldNotes ?? [], { tool: 'scala-cqrs-es-ddl' });
  const graphViewNames = new Set((canonical.graphViews ?? []).map((g) => g.name));
  const mongoViewNames = new Set(canonical.mongoViewNames ?? []);
  let views = models.filter((m) => m.name.endsWith('DecisionView'));
  views = views.filter((m) => !graphViewNames.has(m.name));
  views = views.filter((m) => !mongoViewNames.has(m.name));

  const lines = [
    '-- GENERATED by gen_projection_ddl.mjs (EP_Generated_Patch_Pipeline §九)',
    `-- Source: story/readmodels.json | Views: ${views.length} | Regenerate: node tools/gen_projection_ddl.mjs --out <ingested-app>/conf/sql/2.sql`,
    '-- MySQL dialect; H2 test-compatible via jdbc:h2:mem:...;MODE=MySQL',
    '',
  ];
  for (const v of views) {
    const table = `${v.name.toLowerCase()}_table`;
    const keys = v.fields.filter((f) => f.isKey).map((f) => f.name).sort();
    lines.push(`CREATE TABLE IF NOT EXISTS \`${table}\` (`);
    const colLines = v.fields.map((f) => `  \`${f.name}\` ${sqlTypeOf(f.dataType, f.name)}`);
    if (keys.length > 0) colLines.push(`  PRIMARY KEY (${keys.map((k) => `\`${k}\``).join(', ')})`);
    lines.push(colLines.join(',\n'));
    lines.push(');');
    lines.push('');
  }

  // --- conf/sql/5-pgvector.sql: the ①-layer vector slot ---------------------------------------
  const vecViews = canonical.vectorViews ?? [];
  const out = [
    '-- GENERATED by gen_projection_ddl.mjs (M3 vector dialect · pgvector)',
    `-- Source: .ingest/metarch.json storage.kind=vector | Views: ${vecViews.length} | Regenerate: node tools/gen_projection_ddl.mjs --vector-out <ingested-app>/conf/sql/5-pgvector.sql`,
    '-- PostgreSQL dialect (pgvector ≥0.8); 与 ProjectionRepositoryImplBuilder.buildVector 列映射同源（camel→snake）',
    '',
    'CREATE EXTENSION IF NOT EXISTS vector;',
    '',
  ];
  for (const v of vecViews) {
    const st = v.storage || {};
    const table = st.table || `${v.name.toLowerCase()}_table`;
    const embCol = st.embeddingColumn || 'embedding';
    const dims = Number(st.dims || 0);
    const distance = String(st.distance || 'cosine');
    const ops = HNSW_OPS[distance] || HNSW_OPS.cosine;
    if (!dims || dims <= 0) throw new Error(`vector view ${v.name}: storage.dims 缺失/非法`);
    const cols = v.fields.map((f) => `  ${vecSnake(f.name)} ${vecColType(f)}`);
    cols.push(`  ${embCol} vector(${dims}) NOT NULL`);
    const keyCols = v.fields.filter((f) => f.isKey).map((f) => vecSnake(f.name));
    if (keyCols.length) cols.push(`  PRIMARY KEY (${keyCols.join(', ')})`);
    out.push(`CREATE TABLE IF NOT EXISTS ${table} (`);
    out.push(cols.join(',\n'));
    out.push(');');
    out.push(`CREATE INDEX IF NOT EXISTS idx_${table}_tenant ON ${table} (${keyCols[0] || vecSnake(v.fields[0]?.name || 'tenant_id')});`);
    out.push(`CREATE INDEX IF NOT EXISTS idx_${table}_${embCol} ON ${table} USING ${String(st.index || 'hnsw')} (${embCol} ${ops});`);
    out.push('');
  }

  // --- ledger parity ---------------------------------------------------------------------------
  const ddlFamilies = [...new Set(views.flatMap((v) => v.sourceAggregates || []))].sort();
  const ddlNoteIds = [...new Set(views.map((v) => canonical.viewNoteIds?.[v.name]).filter(Boolean))].sort();
  const vecNoteIds = [...new Set(vecViews.map((v) => v.noteId).filter(Boolean))].sort();

  return [
    {
      path: 'conf/sql/2.sql',
      content: lines.join('\n'),
      kind: 'projection-ddl', schemaCategory: 'projection', schemaNode: 'DecisionViewDdl',
      families: ddlFamilies, deps: [], noteIds: ddlNoteIds,
    },
    {
      path: 'conf/sql/5-pgvector.sql',
      content: out.join('\n'),
      kind: 'vector-ddl', schemaCategory: 'projection', schemaNode: 'VectorDdl',
      families: [], deps: [], noteIds: vecNoteIds,
    },
  ];
}
