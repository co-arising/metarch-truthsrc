// templates/projection.mjs — the Akka Projection DEFINITION renderer (V4-14), ported from
// the engine's ProjectionTemplate.scala (single-project mode). Three shapes, byte-faithful
// to the live corpus:
//   • standard composite (handlers > 1, single aggregate) — per-event wiring + composite
//     dispatcher (挂账⑥(a) BUG-014 回移植 form)
//   • single handler (1 event) — direct wiring, no composite class
//   • multi-aggregate (aggregateSources > 1, e.g. KnowledgeSemanticView = Note+Concept) —
//     per-aggregate sourceProvider/createProjectionFor/<View><Agg>CompositeHandler variants
// Import order = plain String sort over [framework block (with the engine's two dup lines —
// the base∩additional overlap of the dependency algebra), per-view items]; `JdbcHandler`
// rides only when a composite dispatcher exists.
import { decap, snake } from '../builders/views.mjs';

const TAG = '// @generated by CodegenMain:225ed28b\n// @knowledge-release 1.0.0';

function importsOf(view) {
  const primaryPoPkg = view.activeGroups[0].poPkg;
  const frame = [
    'akka.actor.typed.ActorSystem',
    'akka.actor.typed.ActorSystem', // engine dup: base deps ∩ additionalImports (no dedup across)
    'akka.cluster.sharding.typed.scaladsl.ClusterSharding',
    'akka.contrib.persistence.mongodb.MongoReadJournal',
    'akka.contrib.persistence.mongodb.MongoReadJournal', // engine dup
    'akka.persistence.query.Offset',
    'akka.projection.Projection',
    'akka.projection.ProjectionId',
    'akka.projection.eventsourced.EventEnvelope',
    'akka.projection.eventsourced.scaladsl.EventSourcedProvider',
    'akka.projection.jdbc.scaladsl.JdbcProjection',
    'akka.projection.scaladsl.{ExactlyOnceProjection, SourceProvider}',
    'javax.inject.Inject',
    'javax.inject.Singleton',
    'net.imadz.common.application.projection.ScalikeJdbcSession',
    'net.imadz.common.application.projection.ScalikeJdbcSetup',
    'net.imadz.common.application.projection.{ScalikeJdbcSession, ScalikeJdbcSetup}',
    `${primaryPoPkg}._`,
  ];
  if (view.isComposite || view.isMultiAgg) frame.splice(10, 0, 'akka.projection.jdbc.scaladsl.JdbcHandler');
  const perView = [];
  for (const a of view.activeGroups) {
    perView.push(`net.imadz.metarch.application.aggregates.${a.agg}Aggregate`);
    perView.push(`${a.poPkg}.${a.poObj}`);
    if (view.isMultiAgg) perView.push(`${a.poPkg}.${a.poObj}.Event`);
  }
  for (const h of view.events) {
    perView.push(`net.imadz.metarch.application.projection.handlers.${h.handler}`);
    perView.push(`net.imadz.metarch.domain.entities.${h.agg}Entity.${h.name}`);
  }
  perView.push(`net.imadz.metarch.application.projection.repository.${view.name}Repository`);
  return [...frame, ...new Set(perView)].sort().map((i) => `import ${i}`).join('\n');
}

function compositeSection(view) {
  const po = view.aggGroups[0];
  const wiring = view.events
    .map((h) => `        new ${h.handler}(repository)`)
    .join(',\n');
  const arms = view.events
    .map((h) => `        case ${po.poObj}.Event.${h.name}(_) => ${decap(h.name)}.process(session, envelope)`)
    .join('\n');
  const ctorParams = view.events
    .map((h) => `    ${decap(h.name)}: ${h.handler}`)
    .join(',\n');
  return `  // Akka Persistence Query Source Provider
  private def sourceProvider(tag: String)(implicit system: ActorSystem[_]): SourceProvider[Offset, EventEnvelope[${po.poObj}.Event]] = {
    EventSourcedProvider.eventsByTag[${po.poObj}.Event](
      system = system,
      readJournalPluginId = MongoReadJournal.Identifier,
      tag = tag
    )
  }


  
  /**
   * 创建 Projection 实例，使用 ExactlyOnce 语义。
   * @param index 分片索引，用于计算 Tag (e.g. tag-0, tag-1)
   */
  def createProjection(system: ActorSystem[_], sharding: ClusterSharding, index: Int, repository: net.imadz.metarch.application.projection.repository.${view.name}Repository): ExactlyOnceProjection[Offset, EventEnvelope[${po.poObj}.Event]] = {
    implicit val sys: ActorSystem[_] = system
    // [FIX] 计算 Tag: baseName + index (需要与 Aggregate Bootstrap 保持一致)
    val tag = s"${view.primaryAgg}Tag$index"

    JdbcProjection.exactlyOnce(
      projectionId = ProjectionId("${view.projectionId}", tag),
      sourceProvider = sourceProvider(tag),
      handler = () => new ${view.name}CompositeHandler(
${wiring}
      ), // [FIX 挂账⑥(a) BUG-014] 组合分发器：修复单 handler 装配缺陷（原仅接线单事件 handler，其余事件落入 ??? 兜底中断投影流）
      sessionFactory = () => new ScalikeJdbcSession()
    )
  }


  /**
   * ${view.name} 组合分发器：按事件类型把 envelope 路由到对应 per-event Handler；
   * 未知事件优雅跳过（不抛异常、不打日志），保证投影流不中断。
   */
  private class ${view.name}CompositeHandler(
${ctorParams}
  ) extends JdbcHandler[EventEnvelope[${po.poObj}.Event], ScalikeJdbcSession] {

    override def process(session: ScalikeJdbcSession, envelope: EventEnvelope[${po.poObj}.Event]): Unit =
      envelope.event match {
${arms}
        case _ => ()
      }
  }
`;
}

function singleHandlerSection(view) {
  const po = view.aggGroups[0];
  const h = view.events[0];
  return `  // Akka Persistence Query Source Provider
  private def sourceProvider(tag: String)(implicit system: ActorSystem[_]): SourceProvider[Offset, EventEnvelope[${po.poObj}.Event]] = {
    EventSourcedProvider.eventsByTag[${po.poObj}.Event](
      system = system,
      readJournalPluginId = MongoReadJournal.Identifier,
      tag = tag
    )
  }


  
  /**
   * 创建 Projection 实例，使用 ExactlyOnce 语义。
   * @param index 分片索引，用于计算 Tag (e.g. tag-0, tag-1)
   */
  def createProjection(system: ActorSystem[_], sharding: ClusterSharding, index: Int, repository: net.imadz.metarch.application.projection.repository.${view.name}Repository): ExactlyOnceProjection[Offset, EventEnvelope[${po.poObj}.Event]] = {
    implicit val sys: ActorSystem[_] = system
    // [FIX] 计算 Tag: baseName + index (需要与 Aggregate Bootstrap 保持一致)
    val tag = s"${view.primaryAgg}Tag$index"

    JdbcProjection.exactlyOnce(
      projectionId = ProjectionId("${view.projectionId}", tag),
      sourceProvider = sourceProvider(tag),
      handler = () => new ${h.handler}(repository), // [FIX] Instantiate Handler with Repo
      sessionFactory = () => new ScalikeJdbcSession()
    )
  }
`;
}

function multiAggSection(view) {
  const repoFq = `net.imadz.metarch.application.projection.repository.${view.name}Repository`;
  const sections = view.activeGroups.map((g) => {
    const wiring = g.events.map((h) => `        new ${h.handler}(repository)`).join(',\n');
    const ctorParams = g.events.map((h) => `    ${decap(h.name)}: ${h.handler}`).join(',\n');
    const arms = g.events
      .map((h) => `        case ${g.poObj}.Event.${h.name}(_) => ${decap(h.name)}.process(session, envelope)`)
      .join('\n');
    return `
  /** [M3 多聚合投影] ${g.agg} 源聚合的事件流（信封 ${g.poObj}.Event，与本视图其他聚合流互不混流） */
  private def sourceProvider${g.agg}(tag: String)(implicit system: ActorSystem[_]): SourceProvider[Offset, EventEnvelope[${g.poObj}.Event]] = {
    EventSourcedProvider.eventsByTag[${g.poObj}.Event](
      system = system,
      readJournalPluginId = MongoReadJournal.Identifier,
      tag = tag
    )
  }

  /**
   * [M3 多聚合投影] ${g.agg} 流投影实例（ExactlyOnce·tag=<${g.agg}Tag><index>·offset 独立）。
   * @param index 该聚合 tag 分片索引（由 Bootstrap 按聚合顺序偏移后传入）
   */
  def createProjectionFor${g.agg}(system: ActorSystem[_], sharding: ClusterSharding, index: Int, repository: ${repoFq}): ExactlyOnceProjection[Offset, EventEnvelope[${g.poObj}.Event]] = {
    implicit val sys: ActorSystem[_] = system
    val tag = s"${g.agg}Tag$index"

    JdbcProjection.exactlyOnce(
      projectionId = ProjectionId("${view.projectionId}", tag),
      sourceProvider = sourceProvider${g.agg}(tag),
      handler = () => new ${view.name}${g.agg}CompositeHandler(
${wiring}),
      sessionFactory = () => new ScalikeJdbcSession()
    )
  }

  /**
   * ${view.name} ${g.agg} 流组合分发器：按事件类型把 envelope 路由到对应 per-event Handler；
   * 未知事件（其他聚合 tag 流不可达，防御性）优雅跳过，保证投影流不中断。
   */
  private class ${view.name}${g.agg}CompositeHandler(
${ctorParams}
  ) extends JdbcHandler[EventEnvelope[${g.poObj}.Event], ScalikeJdbcSession] {

    override def process(session: ScalikeJdbcSession, envelope: EventEnvelope[${g.poObj}.Event]): Unit =
      envelope.event match {
${arms}
        case _ => ()
      }
  }
`; // first section's leading newline is trimmed by the caller (the `  ` separator line abuts it)
  });
  return sections.join('\n');
}

export function renderProjectionDef(view) {
  const section = view.isMultiAgg
    ? multiAggSection(view).replace(/^\n/, '')
    : view.isComposite ? compositeSection(view)
      : singleHandlerSection(view);
  void view.aggGroups;
  // trailing blanks per shape (live census): composite 4 · single-handler 5 · multi-agg 3
  const tail = view.isMultiAgg ? '\n\n}' : view.isComposite ? '\n\n\n}' : '\n\n\n\n}';
  // the multi-aggregate form has no `  ` separator line between the projectionName block and
  // the first section (its section opens with the M3 doc comment directly)
  const sep = view.isMultiAgg ? '' : '  \n';
  return `${TAG}
package net.imadz.metarch.application.projection

${importsOf(view)}

/**
 * ${view.name}: Akka Projection 定义。
 * 负责从事件源 (${view.primaryAgg}Aggregate) 读取事件并协调给 Handler。
 */
@Singleton
object ${view.name} {


  val projectionName = "${view.name}"


${sep}${section}
${tail}
`;
}
