// templates/repository.mjs — the projection repository INTERFACE renderer (V4-14), ported
// from ProjectionRepositoryTemplate.scala + ProjectionRepositoryBuilder/AssemblyEngine:
//   • Table companion object (the DTO case class, fields sorted by name, Instant columns
//     Option-wrapped) + the @param knowledge anchors (field noteId + elementHashes suffix —
//     the EP_GenerationTime_Code_Anchors P1 rm-face anchor)
//   • the trait: upsert + findByIdentity(sorted keys) + findBy<Id>*(sorted idNames) + findAll
//     (+ findByTenantPaged/countByTenant for mongo; the graph four-verb set; the vector
//     fixed 4-set), each with its `// Logic:` intent line and parameter anchors (B4 形态③).
import { id } from '../builders/views.mjs';
import { depsOf } from '../builders/views.mjs';

const TAG = '// @generated by CodegenMain:225ed28b\n// @knowledge-release 1.0.0';
const REPO_PKG = 'net.imadz.metarch.application.projection.repository';
const IMPL_PKG = 'net.imadz.metarch.infrastructure.repositories.projection';

// fieldDoc (KnowledgeAnchorDoc.fieldDoc port): `@param <name> <description>  @knowledge <id>@<hash>`
// lines sorted with the fields; no anchors when a field lacks a noteId (not emitted, 不编造).
function fieldDoc(fields, hashes, indent = '') {
  const lines = fields
    .filter((f) => f.noteId)
    .map((f) => {
      const h = hashes?.[f.noteId];
      return `${indent} * @param ${id(f.name)}${f.description ? ` ${f.description}` : ''}  @knowledge ${f.noteId}${h ? `@${h}` : ''}`;
    });
  if (!lines.length) return '';
  return `${indent}/**
${lines.join('\n')}
${indent} */
`;
}

export function implNameOf(view) {
  return view.storageKind === 'mongo' ? `${view.name}MongoRepositoryImpl` : `${view.name}RepositoryImpl`;
}

// ── methods per storage kind (AssemblyEngine tableRepositoryMethods / graphRepositoryMethods
//    / ProjectionRepositoryBuilder.buildVector port). Each: {name, params:[{name, sig, noteId,
//    description}], ret, logic}.
export function methodsOf(view) {
  const V = view.name;
  const dto = V;
  const listRet = `Future[List[${dto}]]`;
  const optRet = `Future[Option[${dto}]]`;
  const param = (n, sig, noteId, description) => ({ name: n, sig, noteId, description });
  const keyParams = view.keyNames.map((k) => {
    const f = view.dtoFields.find((x) => x.name === k);
    return param(k, 'String', f?.noteId);
  });
  if (view.storageKind === 'vector') {
    return [
      { name: 'upsert', params: [param('view', dto)], ret: 'Unit', logic: `投影写侧 upsert ${dto} 行（同步嵌入）` },
      { name: 'findByIdentity', params: [param('tenantId', 'String'), param('sourceType', 'String'), param('sourceId', 'String')], ret: optRet, logic: `按标识键 (tenantId, sourceType, sourceId) 查单条 ${dto}` },
      { name: 'delete', params: [param('sourceType', 'String'), param('sourceId', 'String')], ret: 'Unit', logic: `按 (sourceType, sourceId) 删 ${dto} 行（sourceId 全局唯一·删除事件折叠）` },
      { name: 'search', params: [param('tenantId', 'String'), param('queryEmbedding', 'Array[Float]'), param('k', 'Int'), param('sourceType', 'Option[String]')], ret: listRet, logic: `租户内向量近邻检索 ${dto}（cosine·k 截断·sourceType 过滤）` },
    ];
  }
  if (view.storageKind === 'graph') {
    const g = view.storage;
    const props = 'Map[String, String]';
    const methods = [
      { name: 'upsertNode', params: [param('key', 'String'), param('props', props)], ret: 'Unit', logic: `图节点 MERGE 写侧（${g.nodeLabel}·${g.keySpace ?? 'kn'}: 空间前缀键）` },
      { name: 'updateNodeProps', params: [param('key', 'String'), param('props', props)], ret: 'Unit', logic: `图节点属性 SET（${g.nodeLabel}）` },
      { name: 'deleteNode', params: [param('key', 'String'), param('tenantId', 'String')], ret: 'Unit', logic: `图节点 DETACH DELETE（${g.nodeLabel}）` },
      { name: 'mergeLinkTolerant', params: [param('fromExternalId', 'String'), param('toName', 'String'), param('linkType', 'String'), param('linkTarget', 'String'), param('tenantId', 'String')], ret: 'Unit', logic: 'Note→Note LINKS 边 MERGE（悬空端点弃置·CM-11 三段式扩边 2026-10-02）' },
    ];
    if (view.burnableEdges.length) {
      const types = [...new Set(view.burnableEdges.map((e) => e.edgeType))];
      methods.push({ name: 'mergeEdge', params: [param('edgeType', 'String'), param('fromKey', 'String'), param('toKey', 'String'), param('tenantId', 'String')], ret: 'Unit', logic: `图边 MERGE（edgeType 白名单 [${types.join(', ')}]·端点结构烧进 Impl）` });
    }
    return methods;
  }
  // table / mongo: the CRUD set
  const methods = [
    { name: 'upsert', params: [param('view', dto)], ret: 'Unit', logic: `投影写侧 upsert ${V} 行` },
  ];
  if (view.keyNames.length > 0) {
    methods.push({ name: 'findByIdentity', params: keyParams, ret: optRet, logic: `按标识键 (${view.keyNames.join(', ')}) 查单条 ${V}` });
  }
  for (const idn of view.idNames) {
    const f = view.dtoFields.find((x) => x.name === idn);
    // method-parameter docs carry NO description (live: `@param tenantId  @knowledge …`)
    methods.push({ name: `findBy${pascalLocal(idn)}`, params: [param(idn, 'String', f?.noteId)], ret: listRet, logic: `按 ${idn} 查 ${V} 列表` });
  }
  methods.push({ name: 'findAll', params: [], ret: listRet, logic: `查全部 ${V} 行` });
  if (view.storageKind === 'mongo') {
    methods.push({ name: 'findByTenantPaged', params: [param('tenantId', 'String', view.dtoFields.find((f) => f.name === 'tenantId')?.noteId), param('limit', 'Int'), param('offset', 'Long')], ret: listRet, logic: `按 tenantId 分页查 ${V}（SQL 级租户下推·limit/offset）` });
    methods.push({ name: 'countByTenant', params: [param('tenantId', 'String', view.dtoFields.find((f) => f.name === 'tenantId')?.noteId)], ret: 'Future[Long]', logic: `按 tenantId 计数 ${V}（分页 total）` });
  }
  return methods;
}

function pascalLocal(s) { return s.charAt(0).toUpperCase() + s.slice(1); }

export function renderRepository(view, hashes) {
  const V = view.name;
  const impl = implNameOf(view);
  const methods = methodsOf(view);
  const table = view.storageKind === 'vector' && view.storage.table
    ? view.storage.table : `${V.toLowerCase()}_table`;
  const cols = view.dtoFields;

  // imports: deps sorted + distinct (template: sortBy fqn, distinct). Graph interfaces are
  // DTO-free (值参数面) — the DTO import rides only when a method signature mentions it;
  // Future/List ride the method return types (graph methods are Unit-valued: neither).
  const FB = 'net.imadz.common';
  const depRows = [];
  for (const f of cols) depRows.push(...depsOf(f.sig, FB, V));
  for (const m of methods) {
    depRows.push(...depsOf(m.ret, FB, V));
    for (const p of m.params) depRows.push(...depsOf(p.sig, FB, V));
  }
  const mentionsDto = methods.some((m) => m.ret.includes(V) || m.params.some((p) => p.sig === V));
  const fqns = new Set();
  const add = (f) => { if (f) fqns.add(f); };
  add('com.google.inject.ImplementedBy');
  add('javax.inject.Inject');
  if (methods.some((m) => m.ret.startsWith('Future['))) add('scala.concurrent.Future');
  if (methods.some((m) => m.ret.includes('List[') || m.params.some((p) => p.sig.includes('List[')))) add('scala.collection.immutable.List');
  for (const r of depRows) add(r.fqn);
  if (mentionsDto) add(`${REPO_PKG}.${V}Table.${V}`);
  add(`${IMPL_PKG}.${impl}`);
  const imports = [...fqns]
    .filter((f) => f && !f.startsWith('java.lang'))
    .sort()
    .map((f) => `import ${f}`)
    .join('\n');

  // DTO companion
  const caseFields = cols.map((f) => `${f.id}: ${f.sig}`).join(', ');
  const dtoDoc = fieldDoc(cols, hashes);

  // methods block
  const rendered = methods.map((m) => {
    const params = m.params.map((p) => `${id(p.name)}: ${p.sig}`).join(', ');
    const doc = fieldDoc(m.params, hashes, '  ');
    return `${doc}  def ${m.name}(${params}): ${m.ret}
  // Logic: ${m.logic}`;
  }).join('\n\n');

  return `${TAG}
package ${REPO_PKG}

${imports}

object ${V}Table {
${dtoDoc}case class ${V}(${caseFields}) {

}
}

/**
 * ${V}Repository: Projection Layer Repository Interface (Read Side)
 * DTOs are defined in the companion object.
 */

@ImplementedBy(classOf[${impl}])
trait ${V}Repository {

  import ${V}Table._

${rendered}

}

`;
}

