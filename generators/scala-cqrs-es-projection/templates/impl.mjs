// ProjectionRepositoryImplBuilder readExpr port (rs column → DTO value).
function readExpr(f) {
  const sig = f.sig;
  if (sig === 'Int') return `rs.int("${f.name}")`;
  if (sig === 'Long') return `rs.long("${f.name}")`;
  if (sig === 'Boolean') return `rs.boolean("${f.name}")`;
  if (sig === 'BigDecimal') return `rsBigDecimal("${f.name}")`;
  if (sig === 'Option[Instant]') return `rs.longOpt("${f.name}").map(java.time.Instant.ofEpochMilli)`;
  const listM = sig.match(/^List\[(.+)\]$/);
  if (listM) return `Json.parse(rs.string("${f.name}")).as[List[${listM[1]}]]`;
  if (sig === 'Id') return `Id.of(rs.string("${f.name}"))`;
  return `rs.string("${f.name}")`;
}

// bindExpr port (DTO value → bound parameter).
function bindExpr(f) {
  const fid = f.id;
  if (f.sig === 'Option[Instant]') return `(view.${fid}.map(x => java.lang.Long.valueOf(x.toEpochMilli)).orNull)`;
  if (f.sig.startsWith('List[')) return `Json.toJson(view.${fid}).toString()`;
  if (f.sig === 'Id') return `view.${fid}.toString`;
  return `view.${fid}`;
}

const isListSig = (s) => s.startsWith('List[');
const isOptInstant = (s) => s === 'Option[Instant]';

function tableMethods(view, methods, tableName) {
  const cols = view.dtoFields;
  const keyCols = cols.filter((f) => f.isKey).map((f) => f.name);
  return methods.map((m) => {
    let body;
    if (m.name === 'upsert') {
      const colList = cols.map((f) => `\`${f.name}\``).join(', ');
      const placeholders = cols.map(() => '?').join(', ');
      const updates = cols.map((f) => f.name).filter((c) => !keyCols.includes(c))
        .map((c) => `\`${c}\` = VALUES(\`${c}\`)`).join(', ');
      const binds = cols.map(bindExpr).join(',\n          ');
      body = `DB.localTx { implicit session =>
  sql"""INSERT INTO ${tableName}
        (${colList})
        VALUES (${placeholders})
        ON DUPLICATE KEY UPDATE ${updates}"""
    .bind(
          ${binds}
        )
    .update.apply()
}`;
    } else {
      const terminal = m.ret.includes('Option[') ? 'headOption' : 'list';
      const selectCols = cols.map((f) => `\`${f.name}\``).join(', ');
      const where = m.params.length
        ? `\n              WHERE ${m.params.map((p) => `\`${p.name}\` = ?`).join(' AND ')}`
        : '';
      const binds = m.params.map((p) => p.name).join(', ');
      const bindClause = binds ? `\n          .bind(${binds})` : '';
      const mapBody = cols.map((f) => `${f.id} = ${readExpr(f)}`).join(',\n            ');
      body = `Future {
      DB readOnly { implicit session =>
        sql"""SELECT ${selectCols}
              FROM ${tableName}${where}"""${bindClause}
          .map(rs => ${view.name}(
            ${mapBody}
          ))
          .${terminal}.apply()
      }
    }`;
    }
    return { ...m, body };
  });
}

function mongoMethods(view, methods, meta) {
  const { collection, keyField, kindValue: kv } = meta;
  const keyCol = kv ? '_id' : keyField;
  const compositeKey = (expr) => (kv ? `"${kv}:" + ${expr}` : expr);
  const V = view.name;
  const cols = view.dtoFields;
  const writeExpr = (f) => {
    const fid = f.id;
    if (isOptInstant(f.sig)) return `view.${fid}.map(x => JsString(x.toString))`;
    if (f.sig === 'Id') return `(if (view.${fid} == null) JsNull else Json.toJson(view.${fid}))`;
    return `Json.toJson(view.${fid})`;
  };
  const readExprMongo = (f) => {
    const j = `(v \\ "${f.name}")`;
    if (isOptInstant(f.sig)) return `${j}.asOpt[Long].map(java.time.Instant.ofEpochMilli).orElse(${j}.asOpt[String].map(java.time.Instant.parse))`;
    if (f.sig === 'Id') return `${j}.asOpt[${f.sig}].getOrElse(null)`;
    const listM = f.sig.match(/^List\[(.+)\]$/);
    if (listM) return `${j}.asOpt[List[${listM[1]}]].getOrElse(Nil)`;
    return `${j}.as[${f.sig}]`;
  };
  const kindEntry = kv ? `,\n      "kind" -> JsString("${kv}")` : '';
  const safeRowDef = kv
    ? `  /** [6合1 kind 判别式] decode 前 kind 门——同 collection 多视图列同形不设防＝静默混族读：
    * kind 不匹配按毒行跳过（与字段级 decode 失败同路径） */
  private def safeRowToView(json: String): Option[${V}] =
    for {
      v <- scala.util.Try(play.api.libs.json.Json.parse(json)).toOption
      k <- (v \\\\ "kind").headOption.flatMap(_.asOpt[String]) if k == "${kv}"
      row <- scala.util.Try(rowToView(v)).toOption
    } yield row

  private def rowToView(v: play.api.libs.json.JsValue): ${V} = ${V}(
      ${cols.map((f) => `${f.id} = ${readExprMongo(f)}`).join(',\n      ')})`
    : `  /** JSON 串 → DTO·毒行隔离 wrapper（S9 反例验证 2026-10-08：decode 失败＝单行披露跳过不炸集合——
    * guards 型全表 500 事故的 Mongo 路免疫面；对照 store 侧 docsToJsons 只挡 toJson 失败，本层挡字段级 decode 失败） */
  private def safeRowToView(json: String): Option[${V}] =
    scala.util.Try(rowToView(json)).toOption

  private def rowToView(json: String): ${V} = {
    val v = play.api.libs.json.Json.parse(json)
    ${V}(
      ${cols.map((f) => `${f.id} = ${readExprMongo(f)}`).join(',\n      ')})
  }`;
  const dtoToJson = `/** DTO → JSON 串（视图行整取整写——Mongo 文档载体；字段级显式 codec） */
  private def viewToJson(view: ${V}): String =
    play.api.libs.json.Json.stringify(play.api.libs.json.Json.obj(
      ${cols.map((f) => `"${f.name}" -> ${writeExpr(f)}`).join(',\n      ')}${kindEntry}))`;

  const bodies = {
    upsert: `viewStore.putDocument("${collection}", "${keyCol}", ${compositeKey(`view.${id(keyField)}.toString`)}, viewToJson(view))`,
    findByIdentity: `viewStore.findByKey("${collection}", "${keyCol}", ${compositeKey(`${keyField}.toString`)}).map(_.flatMap(safeRowToView))`,
    findByTenantPaged: `viewStore.findByTenantPaged("${collection}", tenantId, limit, offset, ${kv ? `Map("kind" -> "${kv}")` : 'Map.empty'}).map(rows => rows.flatMap(safeRowToView).toList)`,
    countByTenant: `viewStore.findAll("${collection}").map(rows => rows.flatMap(safeRowToView).count(_.tenantId == tenantId))`,
    findAll: `viewStore.findAll("${collection}").map(rows => rows.flatMap(safeRowToView).toList)`,
  };
  return {
    extra: `${dtoToJson}

${safeRowDef}`,
    methods: methods.map((m) => {
      const logic = bodies[m.name] ?? (() => {
        const conds = (kv ? [`"kind" -> "${kv}"`] : []).concat(m.params.map((p) => `"${p.name}" -> ${id(p.name)}`));
        return `viewStore.findByFields("${collection}", Map(${conds.join(', ')})).map(rows => rows.flatMap(safeRowToView).toList)`;
      })();
      return { ...m, body: logic };
    }),
  };
}

