export function renderImpl(view, hashes) {
  const V = view.name;
  const impl = implNameOf(view);
  const methods = methodsOf(view);
  const tableName = view.storageKind === 'vector' && view.storage.table
    ? view.storage.table : `${V.toLowerCase()}_table`;

  let extra = null;
  let withBodies;
  if (view.storageKind === 'table') {
    withBodies = tableMethods(view, methods, tableName);
  } else if (view.storageKind === 'mongo') {
    const r = mongoMethods(view, methods, {
      collection: view.storage.collection ?? '',
      keyField: view.storage.keyField ?? view.keyNames[0] ?? '',
      kindValue: view.storage.kindValue ?? '',
    });
    extra = r.extra; withBodies = r.methods;
  } else if (view.storageKind === 'graph') {
    withBodies = graphMethods(view, methods);
  } else {
    const r = vectorMethods(view, methods);
    extra = r.extra; withBodies = r.methods;
  }

  // imports — per-kind framework deps (builder parity):
  //   table:  Future/bare-EC + Json (List columns) + CommonTypes.Id (Id columns) + List<VO> inners;
  //           NO field-type deps (read/bind expressions are FQ-qualified — java.time stays unimported)
  //   mongo:  + MongoViewStore/JsString(+JsNull) + FULL field-type deps (Instant 等 — the only
  //           kind whose builder folds schemaFields.collectAllDependencies)
  //   graph:  executor only — no Future/bare-EC (Unit-valued verbs)
  //   vector: stores + Future/bare-EC
  const kind = view.storageKind;
  const FB = 'net.imadz.common';
  const depRows = [];
  if (kind === 'mongo') for (const f of view.dtoFields) depRows.push(...depsOf(f.sig, FB, V));
  for (const m of withBodies) for (const p of m.params) depRows.push(...depsOf(p.sig, FB, V));
  const fqns = new Set();
  const add = (f) => { if (f) fqns.add(f); };
  add('javax.inject.Singleton');
  add('scalikejdbc._');
  add('scala.concurrent.ExecutionContext.Implicits.global');
  add(`${REPO_PKG}.${V}Repository`);
  add(`${REPO_PKG}.${V}Table._`);
  if (kind === 'table' || kind === 'mongo' || kind === 'vector') {
    add('scala.concurrent.ExecutionContext');
    add('scala.concurrent.Future');
  }
  for (const r of depRows) add(r.fqn);
  const usesIdSig = view.dtoFields.some((f) => /\bId\b/.test(f.sig));
  if (kind === 'table') {
    if (view.dtoFields.some((f) => isListSig(f.sig))) add('play.api.libs.json.Json');
    if (usesIdSig) add('net.imadz.common.CommonTypes.Id');
  }
  if (kind === 'mongo') {
    add('play.api.libs.json.Json');
    add('play.api.libs.json.JsString');
    add('net.imadz.metarch.infrastructure.persistence.mongo.MongoViewStore');
    if (usesIdSig) add('play.api.libs.json.JsNull');
  }
  if (kind === 'graph') add('net.imadz.metarch.infrastructure.graph.GraphMutationExecutor');
  if (kind === 'vector') {
    add('net.imadz.metarch.infrastructure.persistence.vector.PgVectorStore');
    add('net.imadz.metarch.infrastructure.persistence.vector.OllamaEmbeddingClient');
  }
  if (kind === 'vector' || kind === 'mongo') add('javax.inject.Inject');
  const ctor = kind === 'vector' ? ' @Inject() (pgVectorStore: PgVectorStore, embeddingClient: OllamaEmbeddingClient)'
    : kind === 'mongo' ? ' @Inject() (viewStore: MongoViewStore)' : '';
  const imports = [...fqns]
    .filter((f) => f && !f.startsWith('java.lang'))
    .sort()
    .map((f) => `import ${f}`)
    .join('\n');

  const methodsCode = withBodies.map((m) => {
    const params = m.params.map((p) => `${id(p.name)}: ${p.sig}`).join(', ');
    const doc = implFieldDoc(m.params, hashes, '  ');
    const body = m.body.split('\n').map((l) => `    ${l}`).join('\n');
    return `${doc}  override def ${m.name}(${params}): ${m.ret} = {
    // ==== BEGIN MANUAL ====
${body}
    // ==== END MANUAL ====
  }`;
  }).join('\n\n');
  const tailBlock = extra ? `${extra}\n\n}` : '}';

  return `${TAG}
package ${IMPL_PKG}

${imports}

/**
 * ${impl}: Projection Repository Implementation
 */
@Singleton
class ${impl}${ctor} extends ${V}Repository {

${methodsCode}

${tailBlock}
`;
}
