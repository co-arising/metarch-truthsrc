// MANUAL decision (final-state semantics of the live pipeline):
//   1. derive the rewriter form (table / vector / graph channel from the metadata
//      referenceCodes — verbatim port including the PO whitelist guards);
//   2. if the derived form equals the live manual block → emit derived (the port's proof);
//   3. else emit the live block verbatim from the manual-blocks sidecar (the MERGE-preserved
//      handwritten reality — R10/S2-72 comment style et al.; some refCodes drifted after the
//      fill, e.g. the strOr() removal, so derivation and live text legitimately diverge).
// Guards that would revert to a stub in the live rewriter never fire in the live corpus
