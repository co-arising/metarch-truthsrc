import { id, defaultOf, valueExpr } from '../builders/views.mjs';

const TAG = '// @generated by CodegenMain:225ed28b\n// @knowledge-release 1.0.0';

const PO_RX = /([A-Za-z_][A-Za-z0-9_]*)\s*=\s*event\.([A-Za-z_][A-Za-z0-9_]*)/g;
const LIT_RX = /([A-Za-z_][A-Za-z0-9_]*)\s*=\s*("(?:[^"\\]|\\.)*"|\d+L?|true|false)\s*[,)]/g;

// ── table channel (gen_projection_handlers main loop port) ──────────────────────────────────
function tableManual(view, ev, protoFields) {
  const expr = view.refCodes[ev];
  if (!expr || !expr.includes('view.copy')) return null;
  const fields = view.rmFields; // ③-layer gated, declaration order (rewriter input)
  const keys = view.keysDecl;
  const typeByName = new Map(fields.map((f) => [f.name, String(f.dataType || 'String')]));
  const pairs = [...expr.matchAll(PO_RX)].map((m) => [m[1], m[2]]);
  const literalPairs = [...expr.matchAll(LIT_RX)]
    .filter(([vf]) => !pairs.some(([pf]) => pf === vf))
    .map((m) => [m[1], m[2]]);
  const keyPairs = keys.filter((k) => pairs.some(([vf]) => vf === k.name));
  if (keys.length > 0 && keyPairs.length !== keys.length) return null; // live: skip → MERGE kept handwritten
  const eventArgs = pairs.map(([vf, ef]) => {
    const exprOf = valueExpr(typeByName.get(vf) || 'String', `po.${ef}`);
    return exprOf === null ? null : `${id(vf)} = ${exprOf}`;
  });
  if (eventArgs.includes(null)) return null; // VO-list without converter → sidecar
  const literalArgs = literalPairs.map(([vf, lit]) => `${id(vf)} = ${lit}`);
  const defaults = fields.map((f) => `${id(f.name)} = ${defaultOf(String(f.dataType || 'String'))}`).join(', ');
  const keyArgs = keys.map((k) => `po.${pairs.find(([vf]) => vf === k.name)[1]}`).join(', ');
  // PO field whitelist (proto sidecar) — a miss reverted to a stub in live; none exist, so a
  // miss here means the refCode post-dates the fill → sidecar.
  const msgFields = protoFields[`${ev}PO`];
  if (msgFields && pairs.some(([, ef]) => !msgFields[ef])) return null;
  const poObj = view.events.find((e) => e.name === ev)?.poObj;
  return `        // 投影意图（元数据 referenceCode）：${expr.trim()}
        event match {
          case ${poObj}.Event.${ev}(po) =>
            val dtoFq = net.imadz.metarch.application.projection.repository.${view.name}Table.${view.name}
            val existing = scala.concurrent.Await.result(${view.repoParam}.findByIdentity(${keyArgs}), scala.concurrent.duration.Duration("10s"))
            val view = existing.getOrElse(dtoFq(
                  ${defaults}
                )).copy(${[...eventArgs, ...literalArgs].join(', ')})
            ${view.repoParam}.upsert(view)
          case _ => () // 非本投影关注事件
        }`;
}

// ── vector channel (gen_projection_handlers M3 vector loop port) ────────────────────────────
function vectorManual(view, ev, protoFields) {
  const expr = String(view.refCodes[ev] ?? '').trim();
  if (!expr) return null;
  const fields = view.fieldsMeta; // ①-layer declaration order
  const keys = fields.filter((f) => f.isKey);
  if (!fields.length) return null;
  const poObj = view.events.find((e) => e.name === ev)?.poObj;
  const msgFields = protoFields[`${ev}PO`];
  const eventRefs = [...expr.matchAll(/event\.([A-Za-z_][A-Za-z0-9_]*)/g)].map((m) => m[1]);
  if (msgFields && eventRefs.some((f) => !msgFields[f])) return null;
  // fold pairs: vf = "lit" | vf = event.f (po access, keyword-escaped)
  const pairs = [...expr.matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:"([^"]*)"|event\.([A-Za-z_][A-Za-z0-9_]*))/g)]
    .map((m) => [m[1], m[2] !== undefined ? `"${m[2]}"` : `po.${id(m[3])}`]);

  if (expr.startsWith('view.delete')) {
    const argOf = (name) => pairs.find(([vf]) => vf === name);
    const st = argOf('sourceType');
    const sid = argOf('sourceId');
    if (!st || !sid) return null;
    return `        // 删除事件折叠（fold 词表 view.delete·元数据 referenceCode）：${expr}
        event match {
          case ${poObj}.Event.${ev}(po) =>
            ${view.repoParam}.delete(${st[1]}, ${sid[1]}) // (sourceType, sourceId) 删行——sourceId 全局唯一·租户门由行键承载
          case _ => () // 非本投影关注事件
        }`;
  }
  if (!expr.includes('view.copy')) return null;
  const keyVals = [];
  for (const k of keys) {
    const p = pairs.find(([vf]) => vf === k.name);
    if (p) keyVals.push(p[1]);
    else if (msgFields && msgFields[k.name]) keyVals.push(`po.${id(k.name)}`); // tenantId 戳兜底（BUG-019）
    else return null;
  }
  const copyArgs = pairs.map(([vf, ve]) => `${id(vf)} = ${ve}`).join(', ');
  const defaults = fields.map((f) => `${id(f.name)} = ${defaultOf(f.dataType)}`).join(', ');
  const dtoFq = `net.imadz.metarch.application.projection.repository.${view.name}Table.${view.name}`;
  return `        // 投影意图（元数据 referenceCode）：${expr}
        event match {
          case ${poObj}.Event.${ev}(po) =>
            val existing = scala.concurrent.Await.result(${view.repoParam}.findByIdentity(${keyVals.join(', ')}), scala.concurrent.duration.Duration("10s"))
            val view = existing.getOrElse(${dtoFq}(
                  ${defaults}
                )).copy(${copyArgs})
            ${view.repoParam}.upsert(view) // 投影内同步嵌入（bge-m3·1024d）在 Impl upsert 内完成——M3 拍板
          case _ => () // 非本投影关注事件
        }`;
}

// ── graph channel (gen_projection_handlers S2-65 graph loop port) ───────────────────────────
function graphManual(view, ev, protoFields) {
  const expr = String(view.refCodes[ev] ?? '').trim();
  if (!expr || expr.startsWith('graph.manual')) return null;
  const fields = view.fieldsMeta;
  if (!fields.length) return null;
  const fieldNames = new Set(fields.map((f) => f.name));
  const nodeKey = view.storage.nodeKey;
  const burnableTypes = new Set(view.burnableEdges.map((e) => e.edgeType));
  const stmts = expr.split(';').map((s) => s.trim()).filter(Boolean);
  if (!stmts.length || stmts.some((s) => !/^graph\.(upsertNode|updateNodeProps|deleteNode|mergeEdge)\(/.test(s))) return null;
  const poObj = view.events.find((e) => e.name === ev)?.poObj;
  const msgFields = protoFields[`${ev}PO`];
  const msgTypes = msgFields ?? new Map();
  const eventRefs = [...expr.matchAll(/event\.([A-Za-z_][A-Za-z0-9_]*)/g)].map((m) => m[1]);
  if (msgFields && eventRefs.some((f) => !msgFields[f])) return null;
  // graph props are all String — non-string PO types go .toString
  const valOf = (ef) => {
    const access = `po.${id(ef)}`;
    const t = msgTypes[ef];
    return t && t !== 'string' ? `${access}.toString` : access;
  };
  const calls = [];
  for (const s of stmts) {
    const sm = s.match(/^graph\.(\w+)\(([\s\S]*)\)$/);
    if (!sm) return null;
    const verb = sm[1];
    const argsRaw = sm[2];
    const argOf = (name) => {
      const am = argsRaw.match(new RegExp(`${name}\\s*=\\s*(?:"([^"]*)"|event\\.(\\w+))`));
      return am ? { lit: am[1] !== undefined ? am[1] : null, ef: am[2] || null } : null;
    };
    if (verb === 'upsertNode' || verb === 'updateNodeProps') {
      const key = argOf('key');
      const props = argsRaw.match(/props\s*=\s*\{([^}]*)\}/);
      if (!key || !key.ef || !props) return null;
      const entries = [...props[1].matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:"([^"]*)"|event\.([A-Za-z_][A-Za-z0-9_]*))/g)];
      if (!entries.length) return null;
      const undeclared = entries.map((e) => e[1]).filter((n) => !fieldNames.has(n));
      if (undeclared.length) return null;
      calls.push(`${view.repoParam}.${verb}(${valOf(key.ef)}, Map(${entries.map((e) => `"${e[1]}" -> ${e[2] !== undefined ? `"${e[2]}"` : valOf(e[3])}`).join(', ')}))`);
    } else if (verb === 'deleteNode') {
      const key = argOf('key');
      const tid = argOf('tenantId');
      if (!key || !key.ef || !tid || !tid.ef) return null;
      calls.push(`${view.repoParam}.deleteNode(${valOf(key.ef)}, ${valOf(tid.ef)})`);
    } else if (verb === 'mergeEdge') {
      const et = argOf('edgeType');
      const tk = argOf('toKey');
      if (!et || !et.lit || !tk || !tk.ef) return null;
      if (!msgFields || !msgFields[nodeKey]) return null;
      if (!burnableTypes.has(et.lit)) return null;
      calls.push(`${view.repoParam}.mergeEdge("${et.lit}", ${valOf(nodeKey)}, ${valOf(tk.ef)})`);
    } else return null;
  }
  return `        // 图投影意图（元数据 referenceCode·graph 方言）：${expr}
        event match {
          case ${poObj}.Event.${ev}(po) =>
${calls.map((c) => `            ${c}`).join('\n')} // 结构（label/keyName/keySpace 前缀/端点 match）烧在 ④Impl——Strict 悬空停车场
          case _ => () // 非本投影关注事件
        }`;
}

// MANUAL block = derived rewriter form when it matches the live block, else the live block
// (MERGE-preserved handwritten). The skeleton's `投影意图` logic line always renders the
// CURRENT refCode (engine-side fact) — the MANUAL line inside a filled block renders the
// expr text the rewriter saw.
export function manualBlockFor(view, ev, { manualBlocks, protoFields }) {
  const channel = view.storageKind === 'graph' ? graphManual
    : view.storageKind === 'vector' ? vectorManual
      : tableManual;
  const body = channel(view, ev, protoFields ?? {});
  // the rewriter's replacement begins with the newline after the BEGIN marker text
  const derived = body === null ? null : `\n${body}`;
  const key = `${view.name}On${ev}Handler.scala`;
  const live = manualBlocks?.[key];
  if (live !== undefined) return { content: derived !== null && derived === live ? derived : live, derivedMatches: derived !== null && derived === live };
  if (derived !== null) return { content: derived, derivedMatches: true };
  throw new Error(`projection handler ${key}: no manual block in sidecar and derivation skipped — cannot emit`);
}

