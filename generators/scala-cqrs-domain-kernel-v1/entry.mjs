import { copyImmutableData } from '../../lib/immutable-data.mjs';
import { at, object, pointer, text } from '../../lib/products/request.mjs';
import { validateCodeMappings } from '../../src/core/code-mappings.mjs';

const kernelHeader = '// @generated by truthsrc scala-cqrs-domain-kernel:1\n';
const aggregateHeader = '// @generated by truthsrc scala-cqrs-aggregate-core:1\n';
const moduleSeamsHeader = '// @generated by truthsrc scala-cqrs-module-seams:1\n';
function knowledge(raw) {
  const source = copyImmutableData(raw);
  object(source, ['document', 'pointer'], at('source-entry'));
  text(source.document, at('source-entry'));
  if (source.document.includes('#')) throw new TypeError('source document identity cannot contain the knowledge-key delimiter');
  pointer(source.pointer, at('source-entry'));
  return 'source:' + source.document + '#' + source.pointer;
}

export function sourceEntry(raw, render) { return mappedEntry(raw, render, kernelHeader); }

export function aggregateSourceEntry(raw, render) { return mappedEntry(raw, render, aggregateHeader); }

export function moduleSeamsSourceEntry(raw, render) { return mappedEntry(raw, render, moduleSeamsHeader); }

/** Templates append mapped fragments; offsets always refer to the final UTF-8 entry. */
function mappedEntry(raw, render, header) {
  const spec = copyImmutableData(raw);
  object(spec, ['path', 'kind', 'sources', 'footprint', 'deps'], at('source-entry'));
  const formatHeader = spec.path.endsWith('.properties') ? header.replace('//', '#') : header;
  const knowledgeIds = new Set(spec.sources.map(knowledge));
  const chunks = [formatHeader], mappings = [];
  let offset = Buffer.byteLength(formatHeader);
  render(Object.freeze({
    append(content, sources = []) {
      if (typeof content !== 'string' || !content.isWellFormed()) throw new TypeError('well-formed template text required');
      if (!Array.isArray(sources) || sources.length && !content.length) throw new TypeError('mapped fragments must have content');
      const end = offset + Buffer.byteLength(content);
      for (const key of new Set(sources.map(knowledge))) {
        knowledgeIds.add(key);
        const span = { start: offset, end, text: content };
        mappings.push({ knowledgeKey: key, span, scope: span });
      }
      chunks.push(content); offset = end;
    },
  }));
  const entry = { path: spec.path, content: chunks.join(''), kind: spec.kind, deps: spec.deps,
    knowledgeIds: [...knowledgeIds], productFootprint: spec.footprint, merge: null, codeMappings: mappings };
  validateCodeMappings(entry);
  return copyImmutableData(entry);
}
