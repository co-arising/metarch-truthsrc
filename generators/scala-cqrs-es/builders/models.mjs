// builders/ — model builders: canonical atom → pure model object (no strings).
// Mirrors the internal Builder→Model→Template triad; templates render, builders decide.
// inc4 (2026-10-12): baseline switched from banking/CreditBalance (Examples) to the metarch
// truth source. That brings four mechanics absorbed here (all mirror the internal generator):
//   ① @knowledge anchors — fields carry noteId; env.anchor(noteId) appends `@<hash16>` looked up
//      from the elementHashes sidecar (knowledge-side fact, like the internal elementHashes map;
//      miss → bare noteId, no suffix). Anchor doc blocks are rendered by templates from the
//      {name,description,anchor} rows the builders produce.
//   ② naming slots — commandFamily (trait name), handler alias = commandFamily."Command"→
//      "CommandHandler", per-command reply names, verbatim tagPrefix.
//   ③ empty() neutral-value derivation + case-class defaults derived from type (types.mjs).
//   ④ triggeredBy — an ordinary command/event parameter (no anchor on commands, anchored on events).
// Imports are the sorted multiset over distinct fully-qualified TypeRefs (types.mjs).
import { kebab, scalaIdentifier } from './naming.mjs';
import { scalaSig, typeDeps, fieldDefault, neutralValue, renderImports } from './types.mjs';

const baseOf = (a) => `${a.pkg ?? 'net.imadz'}.${a.ctxPackage ?? ''}.`;
const protoFqn = (a) => `${baseOf(a)}application.aggregates.${a.name}Protocol`;
const entityName = (a) => a.entity ?? `${a.name}Entity`;
const entityFqn = (a) => `${baseOf(a)}domain.entities.${entityName(a)}`;
const aggFqn = (a) => `${baseOf(a)}application.aggregates.${a.name}Aggregate`;
const commandFamilyOf = (a) => a.commandFamily ?? `${a.name}Command`;
// Scala `String.replace` replaces ALL occurrences (AggregateProtocolTemplate.scala:102) — a family
// name containing two "Command"s (RoleCommandBindingCommandFamily) must render
// RoleCommandHandlerBindingCommandHandlerFamily; JS first-only `.replace` silently drops the Handler.
const handlerAliasOf = (a) => commandFamilyOf(a).replaceAll('Command', 'CommandHandler');

// Excluded state-field natures (EP_Field_Nature_And_Concern_Anchors Phase 3(a) port). Live:
// GeneratorContext.isStateFieldExcluded — fields whose `nature` is in the concern-anchored
// exclusion set (concerns.json `credential-store`: StateField/credential/aggregateColumn) are not
// emitted into the aggregate state column. Missing/empty slot = zero behavior change (live default).
const emittedStateFieldsOf = (a, env) => {
  const excluded = new Set(env.excludedStateFieldNatures ?? []);
  return (a.stateFields ?? []).filter((f) => !(f.nature && excluded.has(f.nature)));
};

export function headerOf(env) {
  const kr = env.knowledgeRelease ? `// @knowledge-release ${env.knowledgeRelease}\n` : '';
  return `// @generated by CodegenMain:${env.generatorVersion}\n${kr}`;
}

// anchor row for a field/param: { name, description, anchor } where anchor = `<uuid>@<hash>` | `<uuid>` | null
const anchorRow = (env, f) => ({
  name: scalaIdentifier(f.name),
  description: f.description ?? '',
  anchor: f.noteId ? `${f.noteId}${env.anchor(f.noteId)}` : null,
});

const replyNameOf = (a, c) =>
  !c.reply || c.reply === 'aggregate'
    ? (a.aggregateReply?.name ?? `${c.name}Confirmation`)
    : (typeof c.reply === 'string' ? c.reply : (c.reply?.name ?? `${c.name}Confirmation`));

function replyNames(a) {
  const seen = new Set(), out = [];
  for (const c of a.commands ?? []) {
    const rn = replyNameOf(a, c);
    if (!seen.has(rn)) { seen.add(rn); out.push(rn); }
  }
  return out;
}

const voImportOf = (f) => f.typeImport ?? null;

export function protocolModel(a, env) {
  const name = a.name, fam = commandFamilyOf(a), fb = env.frameworkBase;
  // optionality (AssemblyEngine paramMeta optional → Option[T]; the `= None` default rides the
  // Protocol case class but NOT the Factory signature — CemEdge factory is the canon case)
  const sigOf = (p) => (p.optional ? `Option[${scalaSig(p.dataType)}]` : scalaSig(p.dataType));
  const commands = (a.commands ?? []).map((c) => ({
    name: c.name,
    extendsFamily: fam,
    docRows: (c.parameters ?? []).map((p) => anchorRow(env, p)),
    params: [...(c.parameters ?? []).map((p) => ({ name: scalaIdentifier(p.name), type: sigOf(p), defaultValue: p.optional ? 'None' : undefined })),
      { name: 'replyTo', type: `ActorRef[${replyNameOf(a, c)}]` }],
  }));
  const replies = replyNames(a).map((rn) => {
    const c = (a.commands ?? []).find((x) => replyNameOf(a, x) === rn);
    return { name: rn, fields: (!c.reply || c.reply === 'aggregate' ? a.aggregateReply?.fields : c.reply?.fields) ?? [{ name: 'error', type: 'Option[iMadzError]' }] };
  });
  // import deps: command param types + reply field types (+ event/state refs, self-qualified)
  const rows = [];
  for (const c of a.commands ?? []) for (const p of c.parameters ?? []) rows.push(...typeDeps(sigOf(p), fb, voImportOf(p)));
  for (const r of replies) for (const f of r.fields) rows.push(...typeDeps(f.type, fb, null));
  const selfQualified = [
    ...replyNames(a).map((rn) => `${protoFqn(a)}.${rn}`),
    `${protoFqn(a)}.${fam}`,
    `${entityFqn(a)}.${name}Event`,
    `${entityFqn(a)}.${name}State`,
  ];
  const importRows = [
    { fqn: 'akka.actor.typed.ActorRef' },
    { fqn: `${fb}.CborSerializable` },
    ...rows,
    ...selfQualified.map((f) => ({ fqn: f })),
  ];
  return {
    header: headerOf(env), base: baseOf(a), name, family: fam,
    handlerAlias: handlerAliasOf(a),
    imports: renderImports(importRows, { distinctFqn: true }), commands, replies,
  };
}

export function rootModel(a, env) {
  const name = a.name, fam = commandFamilyOf(a), fb = env.frameworkBase;
  const importRows = [
    { fqn: 'akka.cluster.sharding.typed.scaladsl.EntityTypeKey' },
    { fqn: 'akka.persistence.typed.scaladsl.Effect' },
    { fqn: `${protoFqn(a)}.${fam}` },
    { fqn: `${baseOf(a)}application.aggregates.behaviors.${name}Behaviors` },
    { fqn: `${entityFqn(a)}.${name}Event` },
    { fqn: `${entityFqn(a)}.${name}State` },
  ];
  // rules_domain_gen 债④批尾（kernel Aggregate 行重写·3365-3457）：有 port 聚合的零参接线升带参
  // 闭包形——签名收并集（rules 面 ports ∪ fold 面 foldPorts·按 trait FQ 码位序），转发只传 cmd 面
  // （rules expr 引用者）；参数类型全限定（CodegenMain 骨架零 import 侵入原则——本行是唯一改动点）。
  const portUnion = new Map();
  for (const p of a.foldPorts ?? []) portUnion.set(`${p.fqPkg}.${p.trait}`, p);
  for (const p of a.ports ?? []) portUnion.set(`${p.fqPkg}.${p.trait}`, p);
  const byTraitFq = (x, y) => {
    const fx = `${x.fqPkg}.${x.trait}`, fy = `${y.fqPkg}.${y.trait}`;
    return fx < fy ? -1 : fx > fy ? 1 : 0;
  };
  const portAll = [...portUnion.values()].sort(byTraitFq).filter((p) => p.member);
  const cmdMembers = [...(a.ports ?? [])].sort(byTraitFq).map((p) => p.member).join(', ');
  const commandHandlerPorts = portAll.length
    ? { sig: portAll.map((p) => `${p.member}: ${p.fqPkg}.${p.trait}`).join(', '), args: cmdMembers }
    : null;
  return {
    header: headerOf(env), base: baseOf(a), name, family: fam,
    imports: renderImports(importRows, { distinctFqn: true }),
    commandHandlerFqn: `${protoFqn(a)}.${handlerAliasOf(a)}`,
    commandHandlerPorts,
    typeKey: a.persistence?.typeKey ?? a.name,
    tagCount: a.persistence?.tagCount ?? 5,
    tagPrefix: a.persistence?.tagPrefix ?? `${kebab(name)}-`,
  };
}

export function entityModel(a, env) {
  const name = a.name, fb = env.frameworkBase;
  const idName = a.identifier;
  const stateFields = emittedStateFieldsOf(a, env);
  const fields = stateFields.map((f) => {
    const sig = scalaSig(f.dataType);
    // numeric `version` state field → optimistic-lock counter initial 0 (EP_Catalog_Concept_Write_Model
    // §3.5; create-events must emit (0,1), not (1,2) — ModelCatalog.version is a semantic string, excluded)
    const neutral = f.name === 'version' && ['Int', 'Integer', 'Long'].includes(sig)
      ? (sig === 'Long' ? '0L' : '0')
      : neutralValue(sig, fb);
    return { name: scalaIdentifier(f.name), type: sig, defaultValue: fieldDefault(sig), neutral, isId: f.name === idName, doc: anchorRow(env, f) };
  });
  const events = (a.events ?? []).map((e) => ({
    name: e.name,
    docRows: (e.payloads ?? []).map((p) => anchorRow(env, p)),
    params: (e.payloads ?? []).map((p) => {
      const sig = p.optional ? `Option[${scalaSig(p.dataType)}]` : scalaSig(p.dataType);
      return { name: scalaIdentifier(p.name), type: sig, defaultValue: sig.startsWith('Option[') ? 'None' : undefined };
    }),
  }));
  const idType = scalaSig(a.identifierType ?? 'string (uuid)');
  // import deps: all state field + event payload types (+ VO imports), Cbor singleton, self id
  const rows = [{ fqn: `${fb}.CborSerializable`, key: 'Cbor' }];
  for (const f of stateFields) rows.push(...typeDeps(scalaSig(f.dataType), fb, voImportOf(f)));
  for (const e of a.events ?? []) for (const p of e.payloads ?? []) rows.push(...typeDeps(scalaSig(p.dataType), fb, voImportOf(p)));
  if (idType === 'Id') rows.push(...typeDeps('Id', fb, null));
  return {
    header: headerOf(env), base: baseOf(a), name,
    imports: renderImports(rows), fields, events, idType, identifier: idName,
    conceptAnchor: a.noteId ? `${a.noteId}${env.anchor(a.noteId)}` : null,
  };
}

export function eventHandlerModel(a, env) {
  const name = a.name, fb = env.frameworkBase;
  const javaImports = [], valueImports = new Set();
  for (const h of a.stateHelpers ?? [])
    for (const p of h.params ?? []) {
      if (!p.typeImport) continue;
      if (p.typeImport.startsWith('java.')) { if (!javaImports.includes(p.typeImport)) javaImports.push(p.typeImport); }
      else valueImports.add(p.typeImport);
    }
  const entityQualified = [
    `${name}Event`, `${name}EventHandler`, `${name}EventHandler`, `${name}State`,
    ...(a.events ?? []).map((e) => e.name),
  ].map((n) => `${entityFqn(a)}.${n}`);
  const values = [...valueImports].map((t) => (t.includes('.') ? t : `${baseOf(a)}domain.values.${t}`));
  const usesMap = (a.stateHelpers ?? []).some((h) => (h.returnType ?? '').startsWith('Map['));
  const imports = [...javaImports, ...entityQualified, ...values, ...(usesMap ? ['scala.collection.immutable.Map'] : [])].sort();
  // ALL events get a handler case (not only those with folds). Empty folds → identity (`state`);
  // fold exprs are rendered via foldRhs (literal:→quoted string, expr:→strip prefix, event./fn:→
  // verbatim) — mirrors AssemblyEngine.foldAssignmentsToRefCode.
  const events = (a.events ?? [])
    .map((e) => ({ name: e.name, folds: (e.foldAssignments ?? []).map((f) => ({ slot: f.slot, expr: foldRhs(f.expr) })) }));
  return { header: headerOf(env), base: baseOf(a), name, imports, events, helpers: a.stateHelpers ?? [] };
}

// Fold RHS rendering (AssemblyEngine.foldAssignmentsToRefCode): type-aware literal quoting,
// expr: prefix stripping, event./fn:/other passthrough.
function foldRhs(value) {
  const v = String(value).trim();
  if (v.startsWith('literal:')) {
    const raw = v.slice(8);
    if (/^-?\d+[Ld]?$/.test(raw) || raw === 'true' || raw === 'false' || raw === 'Nil' || raw === 'null' || raw.startsWith('"')) return raw;
    return `"${raw}"`;
  }
  if (v.startsWith('event.')) return v;
  if (v.startsWith('expr:')) return v.slice(5);
  return v;
}

export function repositoryModel(a, env) {
  const name = a.name, fam = commandFamilyOf(a), fb = env.frameworkBase;
  const repo = a.repository ?? {};
  // entityRef return family: default = the aggregate command family (Subdomain case); the banking
  // Examples corpus references a gen_api_layer "<Name>AggregateCommandFamily" instead → slots.
  const entityRefFamily = repo.entityRefFamily ?? fam;
  const entityRefFamilyImport = repo.entityRefFamilyImport ?? `${protoFqn(a)}.${fam}`;
  const finders = (repo.finders ?? []).map((f) => ({
    name: f.name, param: `${f.param.name}: ${scalaSig(f.param.dataType)}`,
    logic: f.logic ?? '通过 Sharding 获取聚合根引用',
    cmdType: `${name}Command`,
  }));
  // EntityRef import once per DISTINCT EntityRef[X] usage (multiset over type args).
  const entityRefUses = [entityRefFamily, ...finders.map((f) => f.cmdType)];
  const importRows = [
    ...entityRefUses.map((x) => ({ fqn: 'akka.cluster.sharding.typed.scaladsl.EntityRef', key: `ref:${x}` })),
    { fqn: 'com.google.inject.ImplementedBy' },
    { fqn: 'com.google.inject.ImplementedBy', key: 'dup' },
    { fqn: 'javax.inject.Inject' },
    { fqn: 'javax.inject._' },
    { fqn: aggFqn(a) },
    { fqn: `${aggFqn(a)}._` },
    { fqn: entityRefFamilyImport },
    ...(finders.length ? [{ fqn: `${protoFqn(a)}.${name}Command` }] : []),
    { fqn: `${baseOf(a)}infrastructure.repositories.aggregate.${name}RepositoryImpl` },
    ...(finders.length ? [{ fqn: `${fb}.CommonTypes.Id` }] : []),
  ];
  return {
    header: headerOf(env), base: baseOf(a), name, family: fam,
    imports: renderImports(importRows),
    implName: `${name}RepositoryImpl`,
    conceptAnchor: a.noteId ? `${a.noteId}${env.anchor(a.noteId)}` : null,
    entityRefMethod: `  def entityRef(id: String): EntityRef[${entityRefFamily}]
  // Logic: sharding 实体引用（聚合隐式契约——对齐 gen_api_layer entityRef，2026-08-28 终局原则）`,
    finders,
  };
}

export function factoryModel(a, env) {
  const name = a.name, fam = commandFamilyOf(a), fb = env.frameworkBase;
  const aggBase = name.replace(/Aggregate$/, '');
  const identifier = a.identifier ?? 'id';
  const idStateField = (a.stateFields ?? []).find((f) => f.name === identifier);
  const initCmd = (a.commands ?? []).find((c) => (c.parameters ?? []).length > 0 && !c.readOnly);
  if (!initCmd) throw new Error(`aggregate ${name}: no non-readOnly command with parameters — cannot build factory init method`);
  const initName = (a.factoryMethods ?? []).find((m) => (m.params ?? []).length > 0)?.name ?? `create${aggBase}WithInitialValue`;

  const idParam = { name: identifier, type: 'Id', import: `${fb}.CommonTypes.Id`, noteId: idStateField?.noteId };
  // factory wraps optional params as Option[T] but carries NO `= None` default (positional
  // pass-through into the command — live CemEdgeAggregateFactory canon)
  const business = (initCmd.parameters ?? [])
    .filter((p) => p.name !== 'replyTo')
    .map((p) => ({ name: p.name, type: p.optional ? `Option[${scalaSig(p.dataType)}]` : scalaSig(p.dataType), import: p.typeImport ?? null, noteId: p.noteId }));
  const hasIdParam = business.some((p) => p.name === identifier);
  const methodParams = hasIdParam ? business : [idParam, ...business];
  const askArgs = [...(hasIdParam ? methodParams : business).map((p) => scalaIdentifier(p.name)), '_'].join(', ');
  const reply = replyNameOf(a, initCmd);

  const docRow = (p) => ({ name: scalaIdentifier(p.name), description: '', anchor: p.noteId ? `${p.noteId}${env.anchor(p.noteId)}` : null });
  const refMethod = {
    name: `create${aggBase}WithoutBalance`,
    docRows: [docRow(idParam)],
    params: [{ name: scalaIdentifier(idParam.name), type: idParam.type }],
    ret: `EntityRef[${fam}]`,
    body: `    clusterSharding.entityRefFor(${name}Aggregate.entityTypeKey, ${identifier}.toString)`,
  };
  const initMethod = {
    name: initName,
    docRows: methodParams.map(docRow),
    params: methodParams.map((p) => ({ name: scalaIdentifier(p.name), type: p.type })),
    ret: `Future[Either[iMadzError, EntityRef[${fam}]]]`,
    body: [
      `    val entityRef: EntityRef[${fam}] = clusterSharding`,
      `      .entityRefFor[${fam}](${name}Aggregate.entityTypeKey, ${identifier}.toString)`,
      `    for {`,
      `      confirmation <- entityRef.ask[${reply}](${initCmd.name}(${askArgs}))`,
      `    } yield {`,
      `      confirmation.error`,
      `        .map(Left.apply[iMadzError, EntityRef[${fam}]])`,
      `        .getOrElse(Right(entityRef))`,
      `    }`,
    ].join('\n'),
  };

  const protoQualified = (a.commands ?? []).map((c) => `${protoFqn(a)}.${c.name}`);
  for (const rn of replyNames(a)) protoQualified.push(`${protoFqn(a)}.${rn}`);
  protoQualified.push(`${protoFqn(a)}.${fam}`);
  const rows = [
    { fqn: 'akka.cluster.sharding.typed.scaladsl.ClusterSharding' },
    { fqn: 'akka.cluster.sharding.typed.scaladsl.EntityRef' },
    { fqn: 'akka.util.Timeout' },
    { fqn: 'javax.inject.Inject' },
    { fqn: aggFqn(a) },
    ...protoQualified.map((f) => ({ fqn: f })),
    { fqn: `${fb}.CommonTypes.iMadzError` },
    { fqn: 'scala.concurrent.ExecutionContext' },
    { fqn: 'scala.concurrent.Future' },
    { fqn: 'scala.concurrent.Future', key: 'dup' },
    { fqn: 'scala.concurrent.duration._' },
  ];
  // method-parameter type deps (Id from the identifier, value objects, collection wrappers).
  for (const p of methodParams) rows.push(...typeDeps(p.type, fb, p.import));
  return { header: headerOf(env), base: baseOf(a), name, imports: renderImports(rows), refMethod, initMethod };
}

export function behaviorsModel(a, env) {
  const name = a.name, fam = commandFamilyOf(a), fb = env.frameworkBase;
  const commands = a.commands ?? [];
  const readOnly = commands.filter((c) => c.readOnly);
  const groups = (a.behaviors ?? []).map((g) => ({
    method: g.name.charAt(0).toLowerCase() + g.name.slice(1),
    handlers: (g.flows ?? []).map((f) => ({ command: f.command, ruleType: `${f.rule}Rule`, helper: `${f.command}Helper` })),
  }));
  const queryHandlers = readOnly.map((c) => {
    const rn = replyNameOf(a, c);
    const expr = rn.startsWith('Get') && rn.endsWith('StateReply') ? `${rn}(state)` : '???';
    return { command: c.name, replyExpr: expr };
  });
  const methods = [...groups.map((g) => g.method), ...(queryHandlers.length ? ['queryBehaviors'] : [])];
  const chain = `${methods[0]}(state)` + methods.slice(1).map((mth) => `.orElse(${mth}(state))`).join('') + '.apply(command)';

  const protoQualified = [`${protoFqn(a)}.${fam}`, ...commands.map((c) => `${protoFqn(a)}.${c.name}`)];
  for (const c of readOnly) protoQualified.push(`${protoFqn(a)}.${replyNameOf(a, c)}`);
  const ruleImports = [];
  for (const g of a.behaviors ?? []) for (const f of g.flows ?? []) ruleImports.push(`${baseOf(a)}domain.invariant.${f.rule}Rule`);
  const rows = [
    { fqn: 'akka.persistence.typed.scaladsl.Effect' },
    { fqn: `${fb}.application.CommandHandlerReplyingBehavior.runReplyingPolicy` },
    { fqn: `${fb}.application.CommandHandlerReplyingBehavior.runReplyingPolicy`, key: 'dup' },
    { fqn: protoFqn(a) },
    ...protoQualified.map((f) => ({ fqn: f })),
    { fqn: `${protoFqn(a)}._` },
    { fqn: entityFqn(a) },
    { fqn: `${entityFqn(a)}.${name}Event` },
    { fqn: `${entityFqn(a)}.${name}State` },
    ...ruleImports.map((f) => ({ fqn: f })),
    { fqn: 'scala.concurrent.duration._' },
  ];
  return { header: headerOf(env), base: baseOf(a), name, family: fam, imports: renderImports(rows), groups, queryHandlers, chain };
}

export function helpersModel(a, env) {
  const name = a.name, fb = env.frameworkBase;
  const commands = a.commands ?? [];
  const flows = new Map();
  for (const g of a.behaviors ?? []) for (const f of g.flows ?? []) flows.set(f.command, f);
  const helpers = commands.map((c) => {
    const params = (c.parameters ?? []).filter((p) => p.name !== 'replyTo');
    let paramSig, toParam;
    if (params.length === 1) { paramSig = scalaSig(params[0].dataType); toParam = `command.${params[0].name}`; }
    else if (params.length > 1) {
      paramSig = `(${params.map((p) => scalaSig(p.dataType)).join(', ')})`;
      toParam = `(${params.map((p) => `command.${p.name}`).join(', ')})`;
    } else { paramSig = 'Unit'; toParam = '()'; }
    const reply = c.readOnly ? replyNameOf(a, c) : (flows.get(c.name)?.successReply ?? 'Unit');
    const unit = reply === 'Unit';
    const tuple = params.length > 1;
    return {
      name: `${c.name}Helper`, command: c.name, paramSig, toParam, reply,
      success: unit ? '()' : tuple ? `${reply}(param._1, None)` : `${reply}(param, None)`,
      failure: unit ? '()' : tuple ? `${reply}(param._1, Some(error))` : `${reply}(param, Some(error))`,
    };
  });
  const protoQualified = commands.map((c) => `${protoFqn(a)}.${c.name}`);
  for (const c of commands) if (c.readOnly) protoQualified.push(`${protoFqn(a)}.${replyNameOf(a, c)}`);
  for (const rn of replyNames(a)) if (!commands.some((c) => c.readOnly && replyNameOf(a, c) === rn)) {
    // write-command replies are referenced only when a flow maps them; unmapped writes use Unit → no import
    if (flowReplyReferenced(a, rn)) protoQualified.push(`${protoFqn(a)}.${rn}`);
  }
  const paramRows = [];
  for (const c of commands) for (const p of c.parameters ?? []) if (p.name !== 'replyTo') paramRows.push(...typeDeps(scalaSig(p.dataType), fb, voImportOf(p)));
  // CommandHelpers import the ELEMENT types (Id / value objects) but not the collection wrappers
  // (List/Map): the internal builder expands tuple params but scala.collection types are not
  // surfaced here (empirical — Protocol/Entity do import them, helpers do not).
  const elementRows = paramRows.filter((r) => !r.fqn.startsWith('scala.collection'));
  const rows = [
    ...elementRows,
    { fqn: `${fb}.CommonTypes.iMadzError` },
    { fqn: `${fb}.application.CommandHandlerReplyingBehavior.CommandHelper` },
    ...protoQualified.map((f) => ({ fqn: f })),
    { fqn: `${entityFqn(a)}.${name}State` },
  ];
  return { header: headerOf(env), base: baseOf(a), name, imports: renderImports(rows), helpers, state: `${name}State` };

  function flowReplyReferenced(agg, rn) {
    for (const g of agg.behaviors ?? []) for (const f of g.flows ?? []) if ((f.successReply ?? replyNameOf(agg, { name: f.command, reply: undefined })) === rn) return true;
    return false;
  }
}
