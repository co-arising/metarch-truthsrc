const keywords = new Set(['abstract','case','catch','class','def','do','else','extends','false','final','finally','for','forSome','if','implicit','import','lazy','match','new','null','object','override','package','private','protected','return','sealed','super','this','throw','trait','try','true','type','val','var','while','with','yield','_']);
export function symbol(name) {
  if (typeof name !== 'string' || !/^[A-Za-z_][A-Za-z0-9_]*$/u.test(name)) throw new TypeError('target symbol requires an explicit safe identifier');
  return keywords.has(name) ? '`' + name + '`' : name;
}
export function packageFor(context, options) {
  if (!Array.isArray(options.packages)) throw new TypeError('explicit context packages required');
  const rows = options.packages.filter(p => p.context === context);
  if (rows.length !== 1 || Object.keys(rows[0]).sort().join(',') !== 'context,package') throw new TypeError('one exact package binding per context required');
  const name = rows[0].package;
  if (typeof name !== 'string' || !name.split('.').every(p => /^[a-z][a-z0-9_]*$/u.test(p) && !keywords.has(p))) throw new TypeError('package must be a safe explicit Scala package');
  return name;
}
export const key = ref => JSON.stringify([ref.context, ref.kind, ref.owner, ref.id]);
export function typeName(type, options) {
  if (type.form === 'primitive') return { string: 'String', boolean: 'Boolean', integer: 'Long', decimal: 'BigDecimal' }[type.name];
  if (type.form === 'nominal') return packageFor(type.ref.context, options) + '.domain.values.' + symbol(type.ref.id);
  if (type.form === 'optional') return 'Option[' + typeName(type.element, options) + ']';
  if (type.form === 'sequence') return 'Vector[' + typeName(type.element, options) + ']';
  if (type.form === 'map') return 'Map[' + typeName(type.key, options) + ', ' + typeName(type.value, options) + ']';
  throw new TypeError('unsupported target type');
}
export const pathFor = (pkg, relative) => 'app/' + pkg.replaceAll('.', '/') + '/' + relative;
export const knowledge = source => 'source:' + source.document + '#' + source.pointer;
export function entry(path, content, kind, sources, footprint, deps = [], codeMappings = []) {
  const header = '// @generated by truthsrc scala-cqrs-domain:1\n';
  const span = value => ({ start: Buffer.byteLength(header + content.slice(0, value.start)),
    end: Buffer.byteLength(header + content.slice(0, value.end)), text: content.slice(value.start, value.end) });
  return { path, content: header + content, kind, deps,
    knowledgeIds: [...new Set([...sources.map(knowledge), ...codeMappings.map(m => knowledge(m.source))])], productFootprint: footprint, merge: null,
    ...(codeMappings.length ? { codeMappings: codeMappings.map(m => ({ knowledgeKey: knowledge(m.source), span: span(m.span), scope: span(m.scope) })) } : {}) };
}
