// templates/state_api.mjs — the S1 aggregate-state face (V4-14), ported from the engine's
// AggregateStateControllerBuilder/Model/Template (2026-09-27 用户拍板): ONE controller, one
// method per aggregate — api.global.read() (auth simplified tier) → IdGuard :id parse →
// repository.entityRef(id).ask(Get<X>State) → the reply returned directly.
// Serialization is CONTROLLER-OWNED (用户裁决: play-json never enters domain/application):
// per-aggregate private `writes<X>State: OWrites[<X>State]` hand-written field-by-field —
// no macros (>22-field case classes have no synthetic unapply — Json.format breaks at 23
// fields); the shared Instant/Id Writes are declared before the state writes (scoping).
import { scalaSig } from '../../scala-cqrs-es/builders/types.mjs';
import { depsOf } from '../../scala-cqrs-es-projection/builders/views.mjs';

const TAG = '// @generated by CodegenMain:225ed28b\n// @knowledge-release 1.0.0';
const camel = (s) => s.charAt(0).toLowerCase() + s.slice(1);
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
// Scala keyword identifiers get backticks at ACCESS sites (st.`type`) — NamingConventions port
const SCALA_KEYWORDS = new Set(['type', 'class', 'def', 'val', 'var', 'object', 'trait', 'package', 'import', 'case', 'match', 'else', 'then', 'yield', 'while', 'return', 'throw', 'new', 'extends', 'with', 'final', 'sealed', 'abstract', 'lazy', 'override', 'implicit', 'private', 'protected', 'this', 'super', 'try', 'catch', 'finally', 'for', 'do']);
const id = (name) => (SCALA_KEYWORDS.has(name) ? `\`${name}\`` : name);

// route lines: `GET      /api/state/<kebab>/:id  controllers.AggregateStateApiController.<camel>(id: String)`
export function stateRouteLines(aggregates) {
  return aggregates.map((a) => `GET      /api/state/${kebab(a.name)}/:id  controllers.AggregateStateApiController.${camel(a.name)}(id: String)`);
}

export function renderStateApiController(aggregates) {
  const entries = aggregates.map((a) => {
    const base = a.name;
    const stateFqn = `net.imadz.metarch.domain.entities.${base}Entity.${base}State`;
    const protocolFqn = `net.imadz.metarch.application.aggregates.${base}Protocol`;
    return {
      base,
      methodName: camel(base),
      routeSegment: kebab(base),
      repoName: `${camel(base)}Repository`,
      repoFqn: `net.imadz.metarch.application.aggregates.repository.${base}Repository`,
      idParam: a.identifier,
      cmdFqn: `${protocolFqn}.Get${base}State`,
      replyFqn: `${protocolFqn}.Get${base}StateReply`,
      stateFqn,
      // nature-excluded state fields (AggregateStateControllerBuilder: DomainEntityBuilder
      // parity — credential fields never enter the state signature/serialization face)
      stateFields: (a.stateFields ?? [])
        .filter((f) => f.nature !== 'credential')
        .map((f) => ({ name: f.name, id: id(f.name), sig: scalaSig(f.dataType) })),
      noteId: a.noteId ?? null,
    };
  });

  // imports: sorted deps + the fixed block appended (distinct keeps the sorted first occurrence
  // — AggregateStateControllerTemplate.scala:19-33)
  const depFqns = new Set();
  const add = (f) => { if (f) depFqns.add(f); };
  for (const e of entries) {
    add(e.repoFqn); add(e.cmdFqn); add(e.replyFqn); add(e.stateFqn);
    for (const f of e.stateFields) for (const d of depsOf(f.sig, 'net.imadz.common')) add(d.fqn);
  }
  const fixed = [
    'java.time.Instant',
    'javax.inject.Inject',
    'javax.inject.Singleton',
    'net.imadz.common.CommonTypes.Id',
    'net.imadz.common.auth.Endpoint',
    'net.imadz.common.auth.ApiError',
    'net.imadz.metarch.infrastructure.api.IdGuard',
    'play.api.libs.json.{JsValue, Json, OWrites, Writes}',
    'play.api.mvc._',
    'scala.concurrent.ExecutionContext',
    'scala.concurrent.duration._',
  ];
  const importLines = [...depFqns].sort()
    .concat(fixed.filter((f) => !depFqns.has(f)))
    .map((i) => `import ${i}`)
    .join('\n');

  const anyInstant = entries.some((e) => e.stateFields.some((f) => f.sig.includes('Instant')));
  const anyId = entries.some((e) => e.stateFields.some((f) => f.sig.includes('Id') && !f.sig.startsWith('String')));
  const sharedWriters = (anyInstant
    ? `  // Instant → ISO-8601 串（用户裁决：序列化收 controller 层——不进 domain）
  //  null-safe：empty 状态的 Instant 中性值是 null（生成器 empty 工厂），写 JsNull 不炸（J-11：Option 组合子形）
  private implicit val s1InstantWrites: Writes[java.time.Instant] =
    (i: java.time.Instant) => play.api.libs.json.Json.toJson(Option(i).map(_.toString))
`
    : '') + (anyId
    ? `  // Id(UUID) → 串（同上·controller 层私有·null-safe）
  private implicit val s1IdWrites: Writes[net.imadz.common.CommonTypes.Id] =
    (i: net.imadz.common.CommonTypes.Id) => play.api.libs.json.Json.toJson(Option(i).map(_.toString))
`
    : '');

  const writers = entries.map((e) => {
    const pairs = e.stateFields
      .map((f) => `"${f.name}" -> play.api.libs.json.Json.toJson[${f.sig}](st.${f.id})`)
      .join(',\n    ');
    return `  /** S1 聚合面：${e.stateFqn.split('.').pop()} → JSON（逐字段手写·无字段数上限） */
  private val writes${e.base}State: OWrites[${e.stateFqn}] = (st: ${e.stateFqn}) => play.api.libs.json.Json.obj(
    ${pairs})
`;
  }).join('\n');

  const replyWriters = entries.map((e) => `  /** S1 聚合面：${e.replyFqn.split('.').pop()} 信封（state 字段平铺）——implicit 供 DSL apply[T] 隐参取用 */
  private implicit val writes${e.replyFqn.split('.').pop()}: OWrites[${e.replyFqn}] =
    (r: ${e.replyFqn}) => (writes${e.base}State: OWrites[${e.stateFqn}]).writes(r.state)`).join('\n');

  const methods = entries.map((e) => `  /** S1 聚合面：${e.routeSegment} 写侧状态强一致查询（Get<X>State → Reply·不产事件） */
  def ${e.methodName}(id: String): play.api.mvc.Action[play.api.mvc.AnyContent] =
    api.global.read().apply[${e.replyFqn}] {
      _ => {
        IdGuard.parse("${e.idParam}" -> id) match {
          case Right(Seq(${e.idParam}Cid)) =>
            ${e.repoName}.entityRef(id).ask {
              (replyTo: akka.actor.typed.ActorRef[${e.replyFqn}]) => ${e.cmdFqn}(${e.idParam}Cid, replyTo)
            }.map(reply => Right(reply): Either[ApiError, ${e.replyFqn}])
          case Left(err) => scala.concurrent.Future.successful(Left(err): Either[ApiError, ${e.replyFqn}])
        }
      }
    }`).join('\n\n');

  const ctor = entries.map((e) => `${e.repoName}: ${e.repoFqn}`).join(', ');

  return `${TAG}
package controllers

${importLines}

/** AggregateStateApiController: S1 聚合面写侧强一致状态查询（每聚合 Get<X>State 直读·2026-09-27 生成范式）
  * 序列化收在 controller 层（用户裁决：domain/application 不引入 play-json）。 */
@Singleton
class AggregateStateApiController @Inject() (api: Endpoint, ${ctor}, val cc: ControllerComponents)(implicit ec: ExecutionContext) extends BaseController {

  override def controllerComponents: ControllerComponents = cc
  private implicit val timeout: akka.util.Timeout = akka.util.Timeout(5.seconds)

${sharedWriters}
${writers}
${replyWriters}

${methods}

}`;
}
