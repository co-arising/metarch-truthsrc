// scala-cqrs-es-api — the api support face (V4-4), ported from the production
// gen_api_layer family (gen_api_controllers + rolemap_export). It is a THIRD generator over the
// same canonical (+ the api-face slots attached by tools/augment-api-canonical.mjs).
//
// inc11 scope: the three GLOBAL support artifacts — ViewKeys.scala and CommandRoleMap.scala
// (infrastructure/auth) and CommandDsl.scala (infrastructure/api). These cover the whole workshop
// corpus, not one aggregate: the role co-link derivation (roles(c) = ∪ role: targets of notes
// that link command:c), the S2-88 read/write split, the S2-56 ③-layer field-note gate and the
// view-key kebab/rename resolution are all ported here (builders/rolemap.mjs).
//
// inc12 scope: + the per-aggregate CONTROLLER face — <Agg>ApiController.scala (B2 DSL endpoints:
// Lane-A addressing, tier gates, Id/Instant guards, Req VOs with per-endpoint @knowledge anchors).
// The command IR comes from parsing this suite's own skeleton output: generate renders
// <Agg>Protocol.scala via the scala-cqrs-es generator (byte-identical to live CodegenMain per its
// own golden gate) and parseProtocol reads that text — the same self-consistency the live
// two-pass pipeline has (gen_api_layer parses the Protocol file the skeleton pass wrote).
// ViewApi/ViewWrites (the read side) follow in a later increment.
import { ROLE_CONSTANTS, constNameOf, deriveCommandRoles, deriveViewReadRoles, aggregateByView, gateViews, viewKeyModel, newViewKeyOf, kebabViewStrict } from './builders/rolemap.mjs';
import { parseProtocol, buildAggregateController } from './builders/controller.mjs';
import { renderViewKeys, renderCommandRoleMap, renderCommandDsl } from './templates/scala.mjs';
import { renderControllerFile } from './templates/controller.mjs';
import { protocolModel } from '../scala-cqrs-es/builders/models.mjs';
import { renderProtocol } from '../scala-cqrs-es/templates/scala.mjs';

const MODULE = 'modules/kernel';

// env.header = the file preamble (FP) gen_api_layer prepends: a hardcoded `@generated by` stamp
// (generator-side fact, never compared) plus the `@knowledge-release` line from the canonical.
export function generate({ canonical, options = {} }) {
  const generatedBy = options.generatedBy ?? 'gen_api_layer:2026-08-26';
  const kr = canonical.knowledgeRelease;
  const fp = `// @generated by ${generatedBy}${kr != null ? `\n// @knowledge-release ${kr}` : ''}`;
  const elementHashes = options.elementHashes ?? {};
  // S7 #1b anchor emitter (patch_core.noteAnchor port): `// @knowledge <uuid>@<hash16>` — hash
  // from the elementHashes sidecar (same option contract as the other generators), miss → bare.
  const noteAnchor = (noteId, indent = '') => {
    if (!noteId) return '';
    const clean = String(noteId).replace(/["'\n\r]/g, '');
    const h = elementHashes[clean] ?? null;
    return `${indent}// @knowledge ${clean}${h ? '@' + h : ''}\n`;
  };

  const renameMap = new Map((canonical.viewKeyRenames ?? []).map((e) => [e.old, e.new]));
  const kebabNew = (viewName) => newViewKeyOf(kebabViewStrict(viewName), renameMap);

  // ── 语义推导（决策输入）── 原始输入＝canonical 的 api 面 RAW 槽（augment-api-canonical）
  const commandRoles = deriveCommandRoles(canonical.roleLinkNotes ?? []);
  // S2-56 ③层门：只留注记视图＋dataType 富化（原 gateViews 逐字移植·注记源＝viewFieldNotes）
  const rmViews = gateViews(canonical.readModels ?? [], canonical.viewFieldNotes ?? [], { tool: 'scala-cqrs-es-api' });
  const viewRoles = aggregateByView(commandRoles, { readModels: rmViews }, deriveViewReadRoles(canonical.roleLinkNotes ?? []));
  const { views, keyOf } = viewKeyModel(rmViews, renameMap);
  const vm = {
    views: views.map((v) => ({ ...v, constName: constNameOf(v.key) })),
    viewConstOf: (viewName) => constNameOf(keyOf(viewName)),
  };

  // Controller-face ctx: decision-view lookup (OkReceipt's dv literal), param origins (④-layer
  // template registry), per-command noteIds (canonical command-level projection) and the VO
  // field registry (valueObjectSigs ≡ the live voFieldsOf metarch scan, Scala-sig typed).
  const cmdDecisionView = new Map();
  for (const v of rmViews) for (const c of v.decisionSupport ?? []) {
    if (!cmdDecisionView.has(c)) cmdDecisionView.set(c, kebabNew(v.name));
  }
  const dvLiteral = (cmdName) => { const dv = cmdDecisionView.get(cmdName); return dv ? `"${dv}"` : 'play.api.libs.json.JsNull'; };
  const dvJsExpr = (cmdName) => { const dv = cmdDecisionView.get(cmdName); return dv ? `play.api.libs.json.JsString("${dv}")` : 'play.api.libs.json.JsNull'; };
  const originMap = new Map(Object.entries(canonical.paramOrigins ?? {}));
  const paramOrigin = (agg, cmdName, paramName) => originMap.get(`${agg}.${cmdName}.${paramName}`) || '';
  const commandNoteIdOf = (() => {
    const m = new Map();
    for (const a of canonical.aggregates ?? []) for (const c of a.commands ?? []) {
      if (c.noteId && !m.has(c.name)) m.set(c.name, c.noteId);
    }
    return (c) => m.get(c) ?? null;
  })();
  const voFieldsOf = (() => {
    const m = new Map();
    for (const vo of canonical.valueObjectSigs ?? []) {
      if (vo?.name && !m.has(vo.name)) m.set(vo.name, (vo.params ?? []).map((p) => String(p.type ?? '')));
    }
    return (name) => m.get(name) ?? null;
  })();

  const entries = [];
  // 包根：全局件随 workshop 上下文命名空间（首个聚合的 pkg/ctxPackage；空语料回退 workshop 名）
  const a0 = (canonical.aggregates ?? [])[0];
  const pkgPath = `${a0?.pkg ?? 'net.imadz'}${a0?.ctxPackage ? `.${a0.ctxPackage}` : ''}`.replaceAll('.', '/');
  const parkConceptHasTenant = (rmViews.find((m) => m.name === 'ParkConceptDecisionView')?.fields || [])
    .some((f) => f.name === 'tenantId'); // R4：查重租户条件随 park-concept 视图补列自动生效
  const ctrlCtx = { fp, parkConceptHasTenant, noteAnchor };

  // Global artifacts once (concern semantics: families=[] — 全局件不参与族过滤).
  entries.push(
    {
      path: `${MODULE}/src/main/scala/${pkgPath}/infrastructure/auth/ViewKeys.scala`,
      content: renderViewKeys(vm, fp),
      kind: 'view-keys', schemaCategory: 'projection', families: [], deps: [],
    },
    {
      path: `${MODULE}/src/main/scala/${pkgPath}/infrastructure/auth/CommandRoleMap.scala`,
      content: renderCommandRoleMap({ commandRoles, viewRoles, viewConstOf: vm.viewConstOf }, fp),
      kind: 'command-role-map', schemaCategory: 'aggregate', families: [], deps: ['view-keys'],
    },
    {
      path: `${MODULE}/src/main/scala/${pkgPath}/infrastructure/api/CommandDsl.scala`,
      content: renderCommandDsl(fp),
      kind: 'command-dsl', schemaCategory: 'aggregate', families: [], deps: [],
    },
  );

  for (const a of canonical.aggregates ?? []) {
    // Controller face: parse THIS suite's own skeleton Protocol rendering (self-consistency —
    // the skeleton generator's byte-identity gate makes derived ≡ generated), then build.
    const protoEnv = {
      frameworkBase: canonical.framework?.base ?? 'net.imadz.common',
      anchor: (noteId) => (elementHashes[noteId] ? `@${elementHashes[noteId]}` : ''),
      generatorVersion: 'api',
      knowledgeRelease: kr,
    };
    const proto = parseProtocol(renderProtocol(protocolModel(a, protoEnv)), a.name);
    const model = buildAggregateController(
      { parkConceptHasTenant, dvLiteral, dvJsExpr, paramOrigin, voFieldsOf, commandNoteIdOf },
      a.name, proto,
    );
    const rendered = renderControllerFile(model, ctrlCtx);
    entries.push({
      path: `app/controllers/${rendered.fileName}`,
      content: rendered.source,
      kind: 'controller', schemaCategory: 'aggregate', families: [a.name], deps: [],
      skippedNote: rendered.skippedNote,
    });
  }

  return entries;
}

export { ROLE_CONSTANTS };
