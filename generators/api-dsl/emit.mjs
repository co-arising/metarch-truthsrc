#!/usr/bin/env node
// === api-dsl emitter — 1:1 restoration of old codegen ===
// Ported from: gen_api_controllers/ (tpl_dsl.mjs + tpl_controller.mjs, old
// backend-codegen). The MODEL decisions (addressing, tiers, guards, ctor
// args, Req fields, skips) are made by the spec builder in run-all.mjs —
// a faithful port of builder.mjs/core.mjs; this file is ONLY the template
// layer (text assembly), exactly like the old tpl_* modules.
// Generates: <Agg>ApiController.scala + routes.fragment (route lines only)
// Usage: node emit.mjs <spec.json> <out-dir>
//   spec: { aggregate, basePkg, actions: [EndpointModel...], reqVos,
//           valuesImports, flags, parkConceptHasTenant, routeLines }

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";

const [specPath, outDir] = process.argv.slice(2);
const spec = JSON.parse(readFileSync(specPath, "utf8"));
mkdirSync(outDir, { recursive: true });

// ─── viewkeys mode ───
// Emits infrastructure/auth/ViewKeys.scala from the read-model catalog:
// one val per view, const name = PascalCase(viewKey), sorted alphabetical
// (golden: gen_api_layer:2026-08-26; keys = viewkey_rename_map.v1 authority).
if (spec.mode === "viewkeys") {
  const pascalKebab = (k) =>
    k.split("-").filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  const entries = (spec.views || [])
    .filter((v) => v.viewKey)
    .map((v) => ({ const: pascalKebab(v.viewKey), key: v.viewKey }))
    .sort((a, b) => (a.const < b.const ? -1 : a.const > b.const ? 1 : 0));
  const vals = entries.map((e) => `  val ${e.const} = "${e.key}"`).join("\n");
  const out = `// @generated by gen_api_layer:2026-08-26
// @knowledge-release 1.0.0
package ${spec.basePkg || "net.imadz.metarch"}.infrastructure.auth

/** ViewKeys —— ⚠️ GENERATED（gen_api_layer 从 readmodels ＋ viewkey_rename_map.v1 导出；手改无效）。
  * 读侧语义命名（用户拍板 2026-08-27）：快照型→资源复数名；动作记录型→过去分词复数。
  * 硬切无过渡期：旧 key（命令名风格）路由不再发射，直接 404 VIEW_NOT_FOUND/缺路由。 */
object ViewKeys {
${vals}
}
`;
  writeFileSync(join(outDir, "ViewKeys.scala"), out);
  console.log(`emitted ViewKeys.scala (${entries.length} keys)`);
  process.exit(0);
}

const agg = spec.aggregate;           // e.g., "Concept"
const basePkg = spec.basePkg || "net.imadz.metarch";
const ctrlName = `${agg}ApiController`;
const actions = spec.actions || [];
const reqVos = spec.reqVos || [];
const valuesImports = spec.valuesImports || [];
const flags = spec.flags || {};
const parkConceptHasTenant = !!spec.parkConceptHasTenant;

// ─── tpl_dsl.mjs port (verbatim text assembly) ───
function askBody(ep) {
  const inner = [
    ...(!ep.generatedId ? [] : [
      '        val generatedId = java.util.UUID.randomUUID().toString',
      ...(ep.multiTarget ? ['        // TODO(待裁决): 多目标 List 寻址——当前 entityRef=randomUUID 为工厂语义，操作已有实体需确认主聚合'] : []),
    ]),
    `        repository.entityRef(${ep.entityExprRaw}).ask {`,
    `          (replyTo: akka.actor.typed.ActorRef[${ep.reply}]) => ${ep.cmdName}(${ep.ctorArgsDsl}, replyTo)`,
    `        }.map { reply =>`,
    `          reply.error.fold[Either[net.imadz.common.auth.ApiError, net.imadz.metarch.infrastructure.api.OkReceipt]](`,
    `            Right(net.imadz.metarch.infrastructure.api.OkReceipt(${ep.entityExprRaw}, ${ep.dvExpr}))`,
    `          )(e => Left(net.imadz.common.auth.ApiError.badRequest(e.code, e.message)))`,
    `        }`,
  ];
  if (ep.enrich) {
    return [
      `        ${ep.enrich.serviceVar}.${ep.enrich.method}(${ep.enrich.ctxVar}, req).flatMap { q =>`,
      ...inner.map((l) => (l.trim() === '' ? l : `  ${l}`)),
      `        }`,
    ];
  }
  return inner;
}

function guardWrapped(ep, body) {
  let handlerBody = body;
  if (ep.instantGuard) {
    handlerBody = [
      `          InstantGuard.parse(${ep.instantGuard.pairs}) match {`,
      `            case Right(Seq(${ep.instantGuard.names})) =>`,
      ...handlerBody.map((l) => (l.trim() === '' ? l : `  ${l}`)),
      `            case Left(err) => Future.successful(Left(err))`,
      `          }`,
    ];
  }
  if (ep.idGuard) {
    handlerBody = [
      `          IdGuard.parse(${ep.idGuard.pairs}) match {`,
      `            case Right(Seq(${ep.idGuard.cids})) =>`,
      ...handlerBody.map((l) => (l.trim() === '' ? l : `  ${l}`)),
      `            case Left(err) => Future.successful(Left(err))`,
      `          }`,
    ];
  }
  return handlerBody;
}

function renderStandardEndpoint(ep) {
  const gate = ep.tier === 'tenant'
    ? {
        comment: 'tenant 档——api.tenant.write + CommandRoleMap 命令粒度角色',
        decl: `api.tenant.write[${ep.reqName}](CommandRoleMap.ofCommand("${ep.cmdName}"): _*)`,
        ctx: '(ts, req)',
      }
    : {
        comment: 'global 档——api.global.write 空 roles＝scope 兜底（D1：已登录、无租户承诺；与 Migration/Enforce 双模式行为等价）',
        decl: `api.global.write[${ep.reqName}]()`,
        ctx: '(gc, req)',
      };
  const handlerBody = guardWrapped(ep, askBody(ep));
  return `  /** B2 DSL：${ep.cmdName}（${gate.comment}） */
  def ${ep.actionName}${ep.sig}: play.api.mvc.Action[play.api.mvc.AnyContent] =
    ${gate.decl}
      .apply[net.imadz.metarch.infrastructure.api.OkReceipt] { ${gate.ctx} =>
${handlerBody.join('\n')}
      }
`;
}

function renderEstablishEndpoint(ep) {
  const tenantCond = parkConceptHasTenant ? ' && v.tenantId == ts.tenantId' : '';
  const preCheck = [
    `        parkConceptViewRepository.findAll().flatMap { all =>`,
    `          val conflict = all.find(v => v.contextId == req.contextId && v.name == req.name && v.conceptId.toString != id && v.removedAt.isEmpty${tenantCond})`,
    `          if (conflict.isDefined) {`,
    `            Future.successful(Left(net.imadz.common.auth.ApiError.conflict("CONCEPT_NAME_TAKEN",`,
    `              "(contextId,name) already established", ConceptNameTaken(conflict.get.conceptId.toString))))`,
    `          } else {`,
    ...guardWrapped(ep, askBody(ep)).map((l) => (l.trim() === '' ? l : `  ${l}`)),
    `          }`,
    `        }`,
  ];
  return `  /** B5-L：${ep.cmdName}（tenant 档——409 查重前置＋typed payload·三键顶层逐字节保持） */
  def ${ep.actionName}${ep.sig}: play.api.mvc.Action[play.api.mvc.AnyContent] =
    api.tenant.write[${ep.reqName}](CommandRoleMap.ofCommand("${ep.cmdName}"): _*)
      .apply[net.imadz.metarch.infrastructure.api.OkReceipt] { (ts, req) =>
${preCheck.join('\n')}
      }
`;
}

function renderFlowDelegateEndpoint(ep) {
  if (ep.flowScoped) {
    const flowCall = ep.flowArgs ? `${ep.flowService}.${ep.flowMethod}(${ep.flowArgs})` : `${ep.flowService}.${ep.flowMethod}(id, ts)`;
    return `  /** B5-L：${ep.cmdName}（tenant 档——api.tenant.write + CommandRoleMap 命令粒度角色；服务端装配下沉手写 ${ep.flowService}·批1-B item 7） */
  def ${ep.actionName}${ep.sig}: play.api.mvc.Action[play.api.mvc.AnyContent] =
    api.tenant.write[${ep.reqName}](CommandRoleMap.ofCommand("${ep.cmdName}"): _*)
      .apply[net.imadz.metarch.infrastructure.api.OkReceipt] { (ts, req) =>
        ${flowCall}
      }
`;
  }
  return `  /** B5-L：${ep.cmdName}（anonymous 档——api.anonymous 免登录；五步编排下沉手写 ${ep.flowService}·D3） */
  def ${ep.actionName}${ep.sig}: play.api.mvc.Action[play.api.mvc.AnyContent] =
    api.anonymous.write[${ep.reqName}]
      .apply[net.imadz.metarch.infrastructure.api.OkReceipt] { (req, body) =>
        ${ep.flowService}.${ep.flowMethod}(${ep.flowArgs})
      }
`;
}

function renderDslEndpoint(ep) {
  if (ep.flowDelegate) return renderFlowDelegateEndpoint(ep);
  if (ep.establish409) return renderEstablishEndpoint(ep);
  return renderStandardEndpoint(ep);
}

// ─── tpl_controller.mjs port ───
function renderController() {
  const extraInjection = [flags.needsParkRepo
    ? `, parkConceptViewRepository: ${basePkg}.application.projection.repository.ParkConceptDecisionViewRepository`
    : '', flags.needsRegisterFlow ? `, registerUserFlow: ${basePkg}.application.RegisterUserFlow` : '',
    flags.needsDoRFlow ? `, requestDoRFlow: ${basePkg}.application.RequestDoRFlow` : '',
    flags.needsParamEnricher ? `, ${agg.charAt(0).toLowerCase()}${agg.slice(1)}ParamEnricher: ${basePkg}.application.${agg}ParamEnricher` : ''].join('');
  const dslInjection = flags.aggHasDsl ? `api: net.imadz.common.auth.Endpoint, ` : '';
  const controllerImports = [
    'import javax.inject.{Inject, Singleton}',
    `import ${basePkg}.application.aggregates.${agg}Protocol._`,
    `import ${basePkg}.application.aggregates.repository.${agg}Repository`,
    ...(valuesImports.length ? [`import ${basePkg}.domain.values.{${valuesImports.join(', ')}}`] : []),
    'import net.imadz.common.auth.ApiError',
    `import ${basePkg}.infrastructure.auth.CommandRoleMap`,
    `import ${basePkg}.infrastructure.api.{IdGuard, InstantGuard, OkReceipt}`,
    'import play.api.libs.json.{JsValue, Json}',
    'import play.api.mvc._',
    '',
    'import scala.concurrent.ExecutionContext',
    'import scala.concurrent.Future',
    'import scala.concurrent.duration._',
  ].join('\n');
  const noteAnchor = (ep) => ep.noteId ? `  // @knowledge ${ep.elementHash ? `${ep.noteId}@${ep.elementHash}` : ep.noteId}\n` : '';
  const actionTexts = actions.map((ep) => `${noteAnchor(ep)}${renderDslEndpoint(ep)}`).join('\n');
  return `// @generated by gen_api_layer:2026-08-26
// @knowledge-release 1.0.0
package controllers

${controllerImports}

/** ${ctrlName}: ${agg} 命令 API（gen_api_layer 直出·B2 DSL 形态） */
@Singleton
class ${ctrlName} @Inject() (${dslInjection}repository: ${agg}Repository${extraInjection}, val cc: ControllerComponents)(implicit ec: ExecutionContext) extends BaseController {

  override def controllerComponents: ControllerComponents = cc
  private implicit val timeout: akka.util.Timeout = akka.util.Timeout(5.seconds)${flags.aggHasEmptyBody ? `
  /** 空 body 命令通道（write[JsObject]）：任意合法 JSON 体即过——与旧 parse.json 行为等价（body 必须是合法 JSON） */
  private implicit val emptyBodyReads: play.api.libs.json.Reads[play.api.libs.json.JsObject] =
    play.api.libs.json.Reads(_ => play.api.libs.json.JsSuccess(play.api.libs.json.Json.obj()))` : ''}

${actionTexts}
}
${reqVos.length ? '\n' + reqVos.map((r) => (r.voKind === 'format' ? `/** B5-L（样例 B·VO 归属裁定）：409 typed payload——companion＋Json.format（OFormat 写侧对称），与命令 M2 Req 相邻。 */
final case class ${r.reqName}(${r.reqFields})
object ${r.reqName} {
  implicit val format: play.api.libs.json.OFormat[${r.reqName}] = play.api.libs.json.Json.format
}` : `/** M2（EP_S2_9c 余量并入 B2）：命令载荷 VO——typed Reads 派生，缺键/类型错 → 400 PARAM_INVALID（含字段明细）。 */
final case class ${r.reqName}(${r.reqFields})
object ${r.reqName} {
  // S2-82-B3（2026-09-11）：D3 companion 嵌套 VO Reads 退役——VO 自带 companion jsonFormat
  //（ValueObjectTemplate 发射）全域自动发现。原按字母序的 8 隐式存在初始化序险：嵌套 List<VO>
  // 的 traversal 在内层 VO Reads 初始化前捕获 null（declare-command 非空 parameters NPE 实证）。
  implicit val reads: play.api.libs.json.Reads[${r.reqName}] = play.api.libs.json.Json.reads
}`)).join('\n\n') : ''}
`;
}

// ─── Emit ───
writeFileSync(join(outDir, `${ctrlName}.scala`), renderController());
const routeLines = spec.routeLines || [];
if (routeLines.length) {
  writeFileSync(join(outDir, "routes.fragment"), routeLines.join("\n") + "\n");
}
console.log(`emitted ${ctrlName}.scala (${actions.length} endpoints)`);
