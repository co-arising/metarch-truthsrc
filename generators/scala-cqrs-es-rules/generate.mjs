// scala-cqrs-es-rules — the rules face (V4-3), ported from the production rules_domain_gen pipeline.
// It is a SECOND generator over the same canonical (+ the rules-face slots attached by
// tools/augment-rules-canonical.mjs): where CodegenMain (the scala-cqrs-es generator) emits the
// aggregate skeleton, rules_domain_gen OVERWRITES the behaviors glue and adds the domain rules. The
// two mirror the real two-pass pipeline (skeleton, then rules overwrite the overlapping paths).
//
// inc6 scope: CommandHelpers (the Command → RuleParams VO projection). Behaviors (runReplyingPolicy
// wiring + port injection), RuleParams, Rules (exprToScala) and Policies follow in later increments.
import { commandHelpersModel } from './builders/models.mjs';
import { renderHelpers } from './templates/scala.mjs';

const MODULE = 'modules/kernel';

// env.header = the file preamble (FP) rules_domain_gen prepends: a hardcoded `@generated by` stamp
// (generator-side fact, like CodegenMain's generatorVersion — never compared) plus the
// `@knowledge-release` line from the canonical (knowledge-side; omitted when absent).
export function generate({ canonical, options = {} }) {
  const generatedBy = options.generatedBy ?? `rules_domain_gen:${new Date().toISOString().slice(0, 10)}`;
  const kr = canonical.knowledgeRelease;
  const header = `// @generated by ${generatedBy}\n${kr != null ? `// @knowledge-release ${kr}\n` : ''}`;
  const env = { header };

  const entries = [];
  for (const a of canonical.aggregates ?? []) {
    const pkgPath = `${a.pkg ?? 'net.imadz'}${a.ctxPackage ? `.${a.ctxPackage}` : ''}`.replaceAll('.', '/');
    entries.push({
      path: `${MODULE}/src/main/scala/${pkgPath}/application/aggregates/behaviors/${a.name}CommandHelpers.scala`,
      content: renderHelpers(commandHelpersModel(a, env)),
      kind: 'command-helpers-rules', schemaCategory: 'aggregate', families: [a.name], deps: [],
    });
  }
  return entries;
}
