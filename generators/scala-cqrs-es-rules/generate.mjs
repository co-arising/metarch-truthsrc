// scala-cqrs-es-rules — the rules face (V4-3), ported from the production rules_domain_gen pipeline.
// It is a SECOND generator over the same canonical (+ the rules-face slots attached by
// tools/augment-rules-canonical.mjs): where CodegenMain (the scala-cqrs-es generator) emits the
// aggregate skeleton, rules_domain_gen OVERWRITES the behaviors glue and adds the domain rules. The
// two mirror the real two-pass pipeline (skeleton, then rules overwrite the overlapping paths).
//
// inc9 scope: + Rules (the exprToScala-driven invariant object: checkAggregate gate, per-command
// Rule classes/objects with guards-ordered checks, ④-layer emissions/emitWhen/forEach dispatch,
// EVENT_POSTCONDITION firstBad<Event> chain) and RulesSpec (the pure-domain ScalaTest suite driven
// by executable_cases with the patch-for-cases completeness patcher). Policies follow later.
// inc10 scope: + Policies and PoliciesSpec (the S2-44 reaction face: on(event) => List[Params]
// objects driven by policy-note info.bindings, with the fanOut/fanOutWhere differentiated-sentinel
// machinery). The rules face (inc6-inc9) is complete for ModelCatalog.
import { behaviorsModel, commandHelpersModel, ruleParamsModel } from './builders/models.mjs';
import { rulesFaceModel } from './builders/rules_face.mjs';
import { policiesModel, parseRuleParamsSigs } from './builders/policies_face.mjs';
import { renderBehaviors, renderHelpers, renderPolicies, renderPoliciesSpec, renderRuleParams, renderRules, renderRulesSpec } from './templates/scala.mjs';

const MODULE = 'modules/kernel';

// env.header = the file preamble (FP) rules_domain_gen prepends: a hardcoded `@generated by` stamp
// (generator-side fact, like CodegenMain's generatorVersion — never compared) plus the
// `@knowledge-release` line from the canonical (knowledge-side; omitted when absent). The Policy
// face carries its own hardcoded stamp (rules_domain_gen:2026-09-05 (S2-44)).
// env.elementHashes = the knowledge-side sidecar { noteId: hash } driving the `@<hash>` anchor
// suffix (same option contract as the scala-cqrs-es skeleton generator).
export function generate({ canonical, options = {} }) {
  const generatedBy = options.generatedBy ?? `rules_domain_gen:${new Date().toISOString().slice(0, 10)}`;
  const generatedByPolicy = options.generatedByPolicy ?? 'rules_domain_gen:2026-09-05 (S2-44)';
  const kr = canonical.knowledgeRelease;
  const releaseLine = kr != null ? `// @knowledge-release ${kr}\n` : '';
  const env = {
    header: `// @generated by ${generatedBy}\n${releaseLine}`,
    headerPolicy: `// @generated by ${generatedByPolicy}\n${releaseLine}`,
    elementHashes: options.elementHashes ?? {},
    voNames: canonical.voNames ?? [],
    voSigs: canonical.valueObjectSigs ?? [],
  };

  const entries = [];
  // deps are generated-artifact class names (file stems — live ledger parity), resolved by the
  // concerns closure through the schemaNode/file-stem double key; the skeleton generator writes
  // the same Behaviors/CommandHelpers paths, and the merged ledger's final-writer-wins upsert
  // lets these rows (and their deps) describe the on-disk truth after this face runs.
  for (const a of canonical.aggregates ?? []) {
    const pkgPath = `${a.pkg ?? 'net.imadz'}${a.ctxPackage ? `.${a.ctxPackage}` : ''}`.replaceAll('.', '/');
    const ruleParamsContent = renderRuleParams(ruleParamsModel(a, env));
    entries.push({
      path: `${MODULE}/src/main/scala/${pkgPath}/domain/invariant/params/${a.name}RuleParams.scala`,
      content: ruleParamsContent,
      kind: 'rule-params', schemaCategory: 'aggregate', schemaNode: `${a.name}RuleParams`, families: [a.name], deps: [],
    });
    const face = rulesFaceModel(a, env);
    entries.push({
      path: `${MODULE}/src/main/scala/${pkgPath}/domain/invariant/${a.name}Rules.scala`,
      content: renderRules(face.rules),
      kind: 'rules', schemaCategory: 'aggregate', schemaNode: `${a.name}Rules`, families: [a.name], deps: [`${a.name}RuleParams`],
    });
    entries.push({
      path: `${MODULE}/src/test/scala/${pkgPath}/domain/invariant/${a.name}RulesSpec.scala`,
      content: renderRulesSpec(face.spec),
      kind: 'rules-spec', schemaCategory: 'aggregate', schemaNode: `${a.name}RulesSpec`, families: [a.name], deps: [`${a.name}Rules`],
    });
    entries.push({
      path: `${MODULE}/src/main/scala/${pkgPath}/application/aggregates/behaviors/${a.name}CommandHelpers.scala`,
      content: renderHelpers(commandHelpersModel(a, env)),
      kind: 'command-helpers-rules', schemaCategory: 'aggregate', schemaNode: `${a.name}CommandHelpers`, families: [a.name], deps: [`${a.name}RuleParams`],
    });
    entries.push({
      path: `${MODULE}/src/main/scala/${pkgPath}/application/aggregates/behaviors/${a.name}Behaviors.scala`,
      content: renderBehaviors(behaviorsModel(a, env)),
      kind: 'behaviors-rules', schemaCategory: 'aggregate', schemaNode: `${a.name}Behaviors`, families: [a.name], deps: [`${a.name}Rules`, `${a.name}CommandHelpers`],
    });
    // Policies (inc10): the S2-44 reaction face — the Params-field types come from the rendered
    // RuleParams signature (the source reads the file it wrote earlier in the same run). No
    // surviving objects → no files (source `if (!objects.length) continue`).
    const pol = (a.policies ?? []).length ? policiesModel(a, env, parseRuleParamsSigs(ruleParamsContent)) : null;
    if (pol && pol.objects.length) {
      entries.push({
        path: `${MODULE}/src/main/scala/${pkgPath}/domain/policy/${a.name}Policies.scala`,
        content: renderPolicies(pol),
        kind: 'policies', schemaCategory: 'aggregate', schemaNode: `${a.name}Policies`, families: [a.name], deps: [`${a.name}RuleParams`],
      });
      entries.push({
        path: `${MODULE}/src/test/scala/${pkgPath}/domain/policy/${a.name}PoliciesSpec.scala`,
        content: renderPoliciesSpec(pol),
        kind: 'policies-spec', schemaCategory: 'aggregate', schemaNode: `${a.name}PoliciesSpec`, families: [a.name], deps: [`${a.name}Policies`],
      });
    }
  }
  return entries;
}
