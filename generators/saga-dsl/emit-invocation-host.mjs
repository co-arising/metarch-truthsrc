// ═══ saga-dsl emit-invocation-host — InvocationPipelineHost + monarch child plan ═══
// P14 批B：组合面宿主（per (pipelineId, opKey) 持久 actor）。
//   journal：OperationStarted(全输入 start-record) → InvocationIntentPersisted →
//   IdentityObserved(轮询首见时从协调器权威状态摘取) → StepCheckpointed →
//   ChildProgressMirrored(仅派生，非权威) → OperationConcluded；恢复=confirmed-prefix。
//   invokeSaga 步：intent 落盘 → 同 identity Start → GetStatus 轮询 → terminal →
//   checkpoint；awaitChildRun 步：intent 落盘 → StartRun(派生 runId，already-in-state
//   拒绝=已挂接吞掉) → eventsByPersistenceId live 观察子终态 → checkpoint。
//   恢复：identity 已落盘 → Attach（saga-core 观察命令首次生成面接线，零新 saga
//   事件）；identity 未落盘（intent 已存/Start 未发）→ 同 txid 重发 Start（idempotent
//   补发，恰一 saga pid）。RunFailedEvt → child-failed 停（补偿≠阶段恢复）。
// Scala 侧全程字符串拼接（无 s"" 插值），模板转义面保持最小。
import { emitMonarchPlan } from "./emit-invocation-plan.mjs";

const jstr = (s) => JSON.stringify(String(s));

export function emitInvocationHostFiles(model, { header } = {}) {
  const h = header || "// @generated by truthsrc run-all invocation-host\n";
  const m = model;
  const fail = (msg) => { throw new Error(`emit-invocation-host: ${msg}`); };
  if (!m.split || !m.merge || !m.child) fail("model requires split/merge saga refs and the child plan");
  const awaitId = m.steps.find((s) => s.kind === "awaitChildRun").id;
  const invokeIds = m.steps.filter((s) => s.kind === "invokeSaga").map((s) => s.id);
  const splitId = invokeIds[0];
  const mergeId = invokeIds[1];
  const pkgTail = m.pkg.split(".").pop();

  const childPlan = emitMonarchPlan(m.child, { header });

  // ── FabCompositionHost.scala ──
  const host = `${h}package ${m.pkg}

import akka.actor.typed.{ActorRef, ActorSystem, Behavior, Scheduler}
import akka.actor.typed.scaladsl.{AbstractBehavior, ActorContext, Behaviors}
import akka.actor.typed.scaladsl.AskPattern._
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.cluster.typed.{ClusterSingleton, SingletonActor}
import akka.contrib.persistence.mongodb.ScalaDslMongoReadJournal
import akka.persistence.query.PersistenceQuery
import akka.persistence.typed.PersistenceId
import akka.persistence.typed.scaladsl.{Effect, EventSourcedBehavior}
import akka.stream.{KillSwitches, Materializer, SystemMaterializer, UniqueKillSwitch}
import akka.stream.scaladsl.{Keep, Sink}
import akka.util.Timeout
import net.imadz.common.CborSerializable
import net.imadz.infra.saga.strict.{CodecPin, Evidence, OperationIdentity, Phase, StrictSagaCoordinator, StrictState, StrictStatus, TransactionIdentity}
import net.imadz.monarch.persistence.PersistentMonarch
import ${m.split.pkg}.{FabSplitSagaModule, FixtureHost => SplitFixtureHost}
import ${m.merge.pkg}.{FabMergeSagaModule, FixtureHost => MergeFixtureHost}
import scala.concurrent.{ExecutionContext, Future}
import scala.concurrent.duration._
import scala.util.{Failure, Success, Try}

/** Generated invocation pipeline host ("${m.pipelineId}"): drives the composed
  * ${splitId} → ${awaitId} → ${mergeId} plan on the shared durable Mongo journal.
  * Journal (authoritative, confirmed-prefix recovery):
  *   OperationStarted → InvocationIntentPersisted → IdentityObserved →
  *   StepCheckpointed → ChildProgressMirrored (derived only) → OperationConcluded.
  * The mirrored child progress is NEVER authoritative — the child run's own
  * journal is. A failed child stops the operation (child-failed); it never
  * auto-compensates the parent (compensation is not stage recovery). No timeout
  * ever infers failure: an unanswered poll is retried, never judged. */
object ${m.hostName} {
  val StepIds: Vector[String] = Vector(${m.steps.map((s) => jstr(s.id)).join(", ")})
  val SplitStep: String = ${jstr(splitId)}
  val AwaitStep: String = ${jstr(awaitId)}
  val MergeStep: String = ${jstr(mergeId)}

  sealed trait Command extends CborSerializable
  final case class BeginOperation(operation: String, occurrence: String, from: String, to: String,
                                  wafers: Vector[String], manifest: String,
                                  replyTo: ActorRef[OperationReply]) extends Command
  final case class GetProgress(replyTo: ActorRef[ProgressReport]) extends Command
  private[${pkgTail}] final case class SagaPolled(stepId: String, reply: Try[StrictSagaCoordinator.Reply]) extends Command
  private[${pkgTail}] final case class AdvanceAfterCheckpoint(stepId: String) extends Command
  private[${pkgTail}] final case class OpenStep(stepId: String) extends Command
  private[${pkgTail}] final case class ChildObserved(code: Option[(String, String)]) extends Command
  private[${pkgTail}] final case class ChildRefused(reason: String) extends Command
  private[${pkgTail}] final case class ChildProgressed(cursor: String) extends Command

  sealed trait Event extends CborSerializable
  final case class OperationStarted(operation: String, occurrence: String, from: String, to: String,
                                    wafers: Vector[String], manifest: String) extends Event
  final case class InvocationIntentPersisted(stepId: String, key: String) extends Event
  /** The coordinator's authoritative transaction identity for an invoked step,
    * observed on the first poll and carried in THIS journal so recovery can
    * Attach without reconstructing saga digests. */
  final case class IdentityObserved(stepId: String, transactionId: String, definitionName: String,
                                    definitionVersion: Int, argsDigest: String, definitionDigest: String,
                                    argsCodecId: String, argsCodecVersion: Int, planDigest: String) extends Event {
    def toIdentity: TransactionIdentity = TransactionIdentity(transactionId, definitionName, definitionVersion,
      argsDigest, definitionDigest, CodecPin(argsCodecId, argsCodecVersion), planDigest)
  }
  final case class StepCheckpointed(stepId: String, code: String, outputs: Map[String, String]) extends Event
  final case class ChildProgressMirrored(cursor: String) extends Event
  final case class OperationConcluded(code: String) extends Event

  final case class ComposedState(started: Option[OperationStarted], intents: Map[String, String],
                                 identities: Map[String, IdentityObserved],
                                 checkpoints: Map[String, StepCheckpointed],
                                 concluded: Option[OperationConcluded]) {
    def terminal: Boolean = concluded.isDefined
    /** First step with an intent but no checkpoint (resume face), else the first
      * step never started (advance face). */
    def activeStep: Option[String] =
      StepIds.find(id => intents.contains(id) && !checkpoints.contains(id))
        .orElse(StepIds.find(id => !intents.contains(id)))
  }

  final case class OperationReply(accepted: Boolean, reason: String) extends CborSerializable
  final case class ProgressReport(started: Boolean, checkpoints: Vector[(String, String)],
                                  concluded: Option[String], childRunKey: Option[String]) extends CborSerializable

  /** durable-parent-step derivation: parent operation key + exact step id +
    * durable occurrence token. No clock, random, or attempt. */
  def txidFor(operation: String, occurrence: String, stepId: String): String =
    "op-" + operation + "-" + stepId + "-" + occurrence
  def childRunKey(operation: String, occurrence: String): String =
    "op-" + operation + "-" + AwaitStep + "-" + occurrence
  def childPersistenceId(operation: String, occurrence: String): String =
    "${m.child.pidPrefix}/" + childRunKey(operation, occurrence)

  def persistenceIdFor(operation: String, occurrence: String): PersistenceId =
    {
      require(operation != null && operation.nonEmpty && occurrence != null && occurrence.nonEmpty,
        "explicit operation and occurrence required")
      PersistenceId.ofUniqueId("${m.pidPrefix}/" + operation + "-" + occurrence)
    }

  private[${pkgTail}] final case class TestHooks(
    beforeEffect: (String, String) => Boolean = (_, _) => true,
    beforeChildCheckpoint: () => Boolean = () => true,
    recovered: (Long, ComposedState) => Unit = (_, _) => (),
    stopped: () => Unit = () => ())

  private def singletonName(operation: String, occurrence: String): String =
    "composition-" + java.security.MessageDigest.getInstance("SHA-256")
      .digest(persistenceIdFor(operation, occurrence).id.getBytes(java.nio.charset.StandardCharsets.UTF_8))
      .map(b => "%02x".format(b & 0xff)).mkString

  /** A stable singleton for this operation; every node gets a proxy, not a second writer. */
  def spawnClusterSingleton(system: ActorSystem[_], sharding: ClusterSharding,
               splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
               mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
               operation: String, occurrence: String)
              (implicit ec: ExecutionContext): ActorRef[Command] =
    spawnClusterSingletonForTest(system, sharding, splitCoordinator, mergeCoordinator,
      operation, occurrence, TestHooks())

  private[${pkgTail}] def spawnClusterSingletonForTest(system: ActorSystem[_], sharding: ClusterSharding,
               splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
               mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
               operation: String, occurrence: String, hooks: TestHooks)
              (implicit ec: ExecutionContext): ActorRef[Command] =
    ClusterSingleton(system).init(SingletonActor(
      build(system, sharding, splitCoordinator, mergeCoordinator, operation, occurrence, hooks),
      singletonName(operation, occurrence)))

  def behavior(system: ActorSystem[_], sharding: ClusterSharding,
               splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
               mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
               operation: String, occurrence: String)
              (implicit ec: ExecutionContext): Behavior[Command] =
    build(system, sharding, splitCoordinator, mergeCoordinator, operation, occurrence, TestHooks())

  private[${pkgTail}] def behaviorForTest(system: ActorSystem[_], sharding: ClusterSharding,
               splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
               mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
               operation: String, occurrence: String, beforeEffect: (String, String) => Boolean)
              (implicit ec: ExecutionContext): Behavior[Command] =
    build(system, sharding, splitCoordinator, mergeCoordinator, operation, occurrence, TestHooks(beforeEffect = beforeEffect))

  private def build(system: ActorSystem[_], sharding: ClusterSharding,
               splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
               mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
               operation: String, occurrence: String, hooks: TestHooks)
              (implicit ec: ExecutionContext): Behavior[Command] =
    Behaviors.setup { ctx =>
      implicit val mat: Materializer = SystemMaterializer(system).materializer
      new ${m.hostName}(ctx, system, sharding, splitCoordinator, mergeCoordinator,
        persistenceIdFor(operation, occurrence), hooks).receive()
    }
}

/** One host actor per (pipeline, operation, occurrence). All effects (saga Start,
  * child StartRun, journal observation) run only after the matching intent event
  * has been persisted (intent-before-start). */
final class ${m.hostName}(ctx: ActorContext[${m.hostName}.Command],
                          system: ActorSystem[_],
                          sharding: ClusterSharding,
                          splitCoordinator: ActorRef[StrictSagaCoordinator.Command],
                          mergeCoordinator: ActorRef[StrictSagaCoordinator.Command],
                          val persistenceId: PersistenceId,
                          hooks: ${m.hostName}.TestHooks)
                         (implicit ec: ExecutionContext, mat: Materializer) {
  import ${m.hostName}._

  private implicit val scheduler: Scheduler = system.scheduler
  private val splitHost = new SplitFixtureHost(system, sharding)
  private val mergeHost = new MergeFixtureHost(system, sharding)
  private val sagaReplySink: ActorRef[StrictSagaCoordinator.Reply] =
    ctx.spawnAnonymous(Behaviors.ignore[StrictSagaCoordinator.Reply])
  private val lotReplySink: ActorRef[net.imadz.metarch.application.aggregates.LotProtocol.LotReply] =
    ctx.spawnAnonymous(Behaviors.ignore[net.imadz.metarch.application.aggregates.LotProtocol.LotReply])
  private val beforeEffect = hooks.beforeEffect
  @volatile private var ownerClosed = false
  private var scheduledPolls = Map.empty[String, akka.actor.Cancellable]
  private var childWatch: Option[UniqueKillSwitch] = None
  private var childActor: Option[ActorRef[PersistentMonarch.Command[${m.child.planObj}.${m.child.stateType}]]] = None

  def receive(): Behavior[Command] =
    EventSourcedBehavior[Command, Event, ComposedState](
      persistenceId,
      ComposedState(None, Map.empty, Map.empty, Map.empty, None),
      (state, command) => onCommand(state, command),
      (state, event) => onEvent(state, event))
      .receiveSignal {
        case (state, akka.persistence.typed.RecoveryCompleted) =>
          hooks.recovered(EventSourcedBehavior.lastSequenceNumber(ctx), state)
          onRecovered(state)
        case (_, akka.actor.typed.PostStop) =>
          ownerClosed = true
          scheduledPolls.values.foreach(_.cancel())
          childWatch.foreach(_.shutdown())
          hooks.stopped()
      }

  // ── commands ──
  private def onCommand(state: ComposedState, command: Command): Effect[Event, ComposedState] =
    command match {
      case GetProgress(replyTo) =>
        replyTo ! ProgressReport(state.started.isDefined,
          StepIds.filter(state.checkpoints.contains).map(id => (id, state.checkpoints(id).code)).toVector,
          state.concluded.map(_.code),
          state.intents.get(AwaitStep))
        Effect.none

      case BeginOperation(operation, occurrence, from, to, wafers, manifest, replyTo) =>
        if (persistenceIdFor(operation, occurrence) != persistenceId) {
          replyTo ! OperationReply(false, "operation does not match this persistence identity")
          Effect.none
        } else if (state.started.isDefined) {
          replyTo ! OperationReply(false, "operation already started (single-writer)")
          Effect.none
        } else {
          val started = OperationStarted(operation, occurrence, from, to, wafers, manifest)
          val intent = InvocationIntentPersisted(SplitStep, txidFor(operation, occurrence, SplitStep))
          Effect.persist(started, intent).thenRun { _: ComposedState =>
            replyTo ! OperationReply(true, "")
          }.thenRun { s: ComposedState =>
            startSagaStep(SplitStep, s)
          }
        }

      case OpenStep(stepId) =>
        // Open the next step after a confirmed prefix: persist THIS journal's
        // intent first (intent-before-start), then start the step's effect.
        if (state.started.isEmpty || state.intents.contains(stepId) || state.terminal) Effect.none
        else stepId match {
          case AwaitStep =>
            val st = state.started.get
            Effect.persist(InvocationIntentPersisted(AwaitStep, childRunKey(st.operation, st.occurrence)))
              .thenRun { s: ComposedState => startChildStep(s) }
          case sagaStep =>
            val st = state.started.get
            Effect.persist(InvocationIntentPersisted(sagaStep, txidFor(st.operation, st.occurrence, sagaStep)))
              .thenRun { s: ComposedState => startSagaStep(sagaStep, s) }
        }

      case AdvanceAfterCheckpoint(stepId) =>
        // Journal already carries the checkpoint; open the next step's intent first.
        if (state.checkpoints.contains(stepId) && !state.terminal) {
          val idx = StepIds.indexOf(stepId)
          if (idx + 1 < StepIds.size) ctx.self ! OpenStep(StepIds(idx + 1))
          Effect.none
        } else Effect.none

      case SagaPolled(stepId, reply) =>
        if (state.started.isEmpty || state.checkpoints.contains(stepId)) Effect.none
        else reply match {
          case Success(StrictSagaCoordinator.Status(s)) =>
            if (s.identity.exists(_ => true) && s.identity.isDefined && !state.identities.contains(stepId)) {
              val ident = s.identity.get
              Effect.persist(IdentityObserved(stepId, ident.transactionId, ident.definitionName,
                ident.definitionVersion, ident.argsDigest, ident.definitionDigest,
                ident.argsCodec.id, ident.argsCodec.version, ident.planDigest))
                .thenRun { _: ComposedState => ctx.self ! SagaPolled(stepId, reply) }
            } else onSagaState(stepId, s)
          case Success(StrictSagaCoordinator.ConflictingIdentity) =>
            // Same transaction identity, different payload: fail closed, never retry.
            ctx.log.error("conflicting identity on {}", stepId)
            Effect.persist(OperationConcluded("ConflictingIdentity"))
          case Success(other) =>
            ctx.log.warn("unexpected coordinator reply on {}: {}", stepId, other)
            scheduleNextPoll(stepId)
            Effect.none
          case Failure(t) =>
            // An unanswered poll is never a failure verdict — poll again.
            ctx.log.warn("status poll failed on {}: {}", stepId, t.getMessage)
            scheduleNextPoll(stepId)
            Effect.none
        }

      case ChildRefused(reason) =>
        if (reason != null && reason.contains("already in state")) {
          // Re-attach: the run exists on the durable journal; keep observing.
          Effect.none
        } else {
          ctx.log.error("child start refused: {}", reason)
          Effect.persist(StepCheckpointed(AwaitStep, "ChildRejected", Map.empty),
            OperationConcluded("ChildRejected"))
        }

      case ChildObserved(Some((code, wafersCsv))) =>
        if (state.checkpoints.contains(AwaitStep) || state.terminal) Effect.none
        else if (!hooks.beforeChildCheckpoint()) Effect.none
        else code match {
          case "ChildCompleted" =>
            val runKey = state.intents.getOrElse(AwaitStep, "")
            Effect.persist(StepCheckpointed(AwaitStep, "ChildCompleted",
              Map("wafers" -> wafersCsv, "childRun" -> runKey)))
              .thenRun { _: ComposedState => ctx.self ! OpenStep(MergeStep) }
          case other =>
            Effect.persist(StepCheckpointed(AwaitStep, other, Map.empty), OperationConcluded(other))
        }

      case ChildObserved(None) => Effect.none

      case ChildProgressed(cursor) =>
        // Derived mirror only — never authoritative for any decision.
        if (state.checkpoints.contains(AwaitStep)) Effect.none
        else Effect.persist(ChildProgressMirrored(cursor))
    }

  private def onSagaState(stepId: String, s: StrictState): Effect[Event, ComposedState] =
    if (s.terminal) {
      val code = s.status match {
        case StrictStatus.Succeeded => "Succeeded"
        case StrictStatus.Aborted =>
          val prepareConfirmed = s.evidence.values.exists {
            case Evidence.Confirmed(op, _) => op.phase == Phase.Prepare
            case _ => false
          }
          if (prepareConfirmed) "Compensated" else "Rejected"
        case StrictStatus.RecoveryRequired => "RecoveryRequired"
        case other => throw new IllegalStateException("unmapped coordinator terminal status: " + other)
      }
      code match {
        case "Succeeded" if stepId == MergeStep =>
          Effect.persist(
            StepCheckpointed(MergeStep, "Succeeded", Map("txid" -> s.identity.map(_.transactionId).getOrElse(""))),
            OperationConcluded("AllStepsSucceeded"))
        case "Succeeded" =>
          Effect.persist(StepCheckpointed(stepId, "Succeeded",
            Map("txid" -> s.identity.map(_.transactionId).getOrElse(""))))
            .thenRun { _: ComposedState => ctx.self ! AdvanceAfterCheckpoint(stepId) }
        case stopCode =>
          Effect.persist(StepCheckpointed(stepId, stopCode, Map.empty), OperationConcluded(stopCode))
      }
    } else {
      scheduleNextPoll(stepId)
      Effect.none
    }

  // ── effects (intent is already persisted when any of these run) ──
  private def startSagaStep(stepId: String, state: ComposedState): Unit = {
    val st = state.started.getOrElse(throw new IllegalStateException("step start without a started operation"))
    val txid = state.intents(stepId)
    if (!beforeEffect(stepId, txid)) return
    val wafersForStep: Vector[String] = stepId match {
      case MergeStep =>
        // Merge consumes the durable completed-child manifest, never a mirror.
        state.checkpoints(AwaitStep).outputs("wafers").split(",").toVector
      case _ => st.wafers
    }
    val source = new net.imadz.metarch.application.aggregates.LotProtocol.StartTransfer(
      txid,
      if (stepId == MergeStep) st.to else st.from,
      if (stepId == MergeStep) st.from else st.to,
      wafersForStep.toList,
      st.manifest,
      lotReplySink)
    val start =
      if (stepId == MergeStep) FabMergeSagaModule.from_commandTriggerStart(source, mergeHost, sagaReplySink)
      else FabSplitSagaModule.from_commandTriggerStart(source, splitHost, sagaReplySink)
    val coordinator = if (stepId == MergeStep) mergeCoordinator else splitCoordinator
    coordinator ! start
    pollSaga(stepId, coordinator)
  }

  private def pollSaga(stepId: String, coordinator: ActorRef[StrictSagaCoordinator.Command]): Unit = {
    // GetStatus is read-only and idempotent; overlapping polls are harmless.
    implicit val timeout: Timeout = Timeout(2.seconds)
    coordinator.ask(replyTo => StrictSagaCoordinator.GetStatus(replyTo))
      .onComplete(tried => ctx.self ! SagaPolled(stepId, tried.map(r => r: StrictSagaCoordinator.Reply)))
    ()
  }

  private def scheduleNextPoll(stepId: String): Unit = {
    scheduledPolls.get(stepId).foreach(_.cancel())
    val pending = system.scheduler.scheduleOnce(200.millis, new Runnable {
      def run(): Unit = if (!ownerClosed)
        pollSaga(stepId, if (stepId == MergeStep) mergeCoordinator else splitCoordinator)
    })(ec)
    scheduledPolls = scheduledPolls + (stepId -> pending)
  }

  private def startChildStep(state: ComposedState): Unit = {
    val st = state.started.getOrElse(throw new IllegalStateException("child start without a started operation"))
    val runKey = state.intents(AwaitStep)
    if (!beforeEffect(AwaitStep, runKey)) return
    val pid = childPersistenceId(st.operation, st.occurrence)
    val initial = ${m.child.planObj}.${m.child.stateType}(st.wafers, 0)
    val ref = childActor.getOrElse {
      val spawned = ctx.spawn(${m.child.planObj}.behavior(PersistenceId.ofUniqueId(pid)), pid.replace('/', '-'))
      childActor = Some(spawned)
      spawned
    }
    implicit val timeout: Timeout = Timeout(5.seconds)
    ref.ask((replyTo: ActorRef[PersistentMonarch.RunReply]) => PersistentMonarch.StartRun(runKey, initial, replyTo)).onComplete {
      case Success(PersistentMonarch.Accepted(_)) => ()
      case Success(PersistentMonarch.Rejected(_, reason)) => ctx.self ! ChildRefused(reason)
      case Success(other) => ctx.log.warn("unexpected child reply: {}", other)
      case Failure(t) =>
        // An unanswered StartRun is unknown, not absent — the durable journal
        // remains the reconciliation face; observation decides, never a timeout.
        ctx.log.warn("child StartRun unanswered: {}", t.getMessage)
    }
    watchChild(pid, csvOf(st.wafers))
  }

  /** Observe the child run's durable journal (live, from offset 0 so history
    * replays into the same decisions). This journal is the only authoritative
    * terminal source for the child. */
  private def watchChild(pid: String, wafersCsv: String): Unit = {
    if (childWatch.isEmpty) {
      val readJournal = PersistenceQuery(system)
        .readJournalFor[ScalaDslMongoReadJournal]("akka-contrib-mongodb-persistence-readjournal")
      childWatch = Some(readJournal.eventsByPersistenceId(pid, 0L, Long.MaxValue)
        .viaMat(KillSwitches.single)(Keep.right)
        .toMat(Sink.foreach { envelope =>
          envelope.event match {
            case _: PersistentMonarch.RunCompleted => ctx.self ! ChildObserved(Some(("ChildCompleted", wafersCsv)))
            case fe: PersistentMonarch.RunFailedEvt => ctx.self ! ChildObserved(Some(("ChildFailed", fe.reason)))
            case sd: PersistentMonarch.StageDone => ctx.self ! ChildProgressed(sd.cursor)
            case _ => ()
          }
        })(Keep.left)
        .run())
    }
  }

  private def csvOf(wafers: Vector[String]): String = wafers.mkString(",")

  // ── events (pure) ──
  private def onEvent(state: ComposedState, event: Event): ComposedState = event match {
    case started: OperationStarted => state.copy(started = Some(started))
    case InvocationIntentPersisted(stepId, key) => state.copy(intents = state.intents + (stepId -> key))
    case observed: IdentityObserved => state.copy(identities = state.identities + (observed.stepId -> observed))
    case checkpoint: StepCheckpointed => state.copy(checkpoints = state.checkpoints + (checkpoint.stepId -> checkpoint))
    case ChildProgressMirrored(_) => state
    case concluded: OperationConcluded => state.copy(concluded = Some(concluded))
  }

  // ── recovery: confirmed-prefix replay, then reattach every unfinished step ──
  private def onRecovered(state: ComposedState): Unit = {
    if (state.terminal) return
    state.activeStep match {
      case None => () // every step checkpointed; the conclusion replay follows the same prefix
      case Some(stepId) =>
        if (state.started.isEmpty) () // fresh actor, empty journal: BeginOperation starts the chain
        else if (!state.intents.contains(stepId)) {
          // The step never opened: open it now from the durable start-record
          // (the very first step also needs its OperationStarted, which a
          // confirmed-prefix replay already carries).
          if (stepId == SplitStep) {
            val st = state.started.get
            ctx.self ! BeginOperation(st.operation, st.occurrence, st.from, st.to, st.wafers, st.manifest,
              ctx.spawnAnonymous(Behaviors.ignore[OperationReply]))
          } else ctx.self ! OpenStep(stepId)
        } else stepId match {
          case AwaitStep =>
            watchChild(childPersistenceId(state.started.get.operation, state.started.get.occurrence),
              csvOf(state.started.get.wafers))
            // Re-issue StartRun with the same identity: already-in-state means
            // attached (the refusal is swallowed; observation continues).
            startChildStep(state)
          case sagaStep =>
            // Attach with the carried authoritative identity (zero new saga
            // journal events); without one (Start was never answered), re-issue
            // the idempotent Start with the same transaction id.
            state.identities.get(sagaStep) match {
              case Some(observed) =>
                val coordinator = if (sagaStep == MergeStep) mergeCoordinator else splitCoordinator
                coordinator ! StrictSagaCoordinator.Attach(observed.toIdentity, sagaReplySink)
                scheduleNextPoll(sagaStep)
              case None =>
                startSagaStep(sagaStep, state)
            }
        }
    }
  }
}
`;

  return [
    { name: `${m.hostName}.scala`, content: host },
    ...childPlan,
  ];
}
