// ═══ saga-dsl emit-invocation-spec — FixtureCompositionSpec（P14 批B 验证族）═══
// E1 全链（split→child→merge wafer 守恒+无重复 effect）；E2 saga 终态已存/checkpoint
// 未存（宿主 journal 前缀截断→重启→Attach 补账→saga journal 零新事件）；E3 checkpoint
// 已存/镜像截断（子 journal 权威对账）；E4 intent 已存/Start 未答（同 txid 重发补发）；
// E5 同 txid 异 args=ConflictingIdentity fail-closed。Mongo 不可达=assume 显式 canceled。
// E-D 物理面（双 JVM+SIGTERM+singleton 迁移）=D4 机理复用，独立批段。
import { readFileSync } from 'node:fs';
const recoveryTemplate = readFileSync(new URL('./templates/composition-recovery.scala.tpl', import.meta.url), 'utf8');
const deploymentTemplate = readFileSync(new URL('./templates/composition-deployment.scala.tpl', import.meta.url), 'utf8');
const jstr = (s) => JSON.stringify(String(s));

export function emitInvocationSpecFiles(model, { header } = {}) {
  const h = header || "// @generated by truthsrc run-all invocation-host\n";
  const m = model;
  const host = m.hostName;
  const splitEntry = `${m.split.pkg}.${m.split.entryName}`;
  const mergeEntry = `${m.merge.pkg}.${m.merge.entryName}`;
  const splitModule = `${m.split.pkg}.${m.split.moduleObj}`;
  const mergeModule = `${m.merge.pkg}.${m.merge.moduleObj}`;
  const replacements = {
    HOST: host, SPLIT_ENTRY: splitEntry, MERGE_ENTRY: mergeEntry,
    ENTITY_KEY: 'net.imadz.metarch.application.aggregates.LotAggregate',
    CHILD_PLAN: m.child.planObj, CHILD_STATE: m.child.stateType,
  };
  const recovery = recoveryTemplate.replace(/@([A-Z_]+)@/g, (_, key) => {
    if (!(key in replacements)) throw new Error('unresolved recovery template token: ' + key);
    return replacements[key];
  });

  const spec = `${h}package ${m.specPkg || m.pkg}

import akka.actor.testkit.typed.scaladsl.ActorTestKit
import akka.actor.typed.{ActorRef, ActorSystem}
import akka.actor.typed.scaladsl.AskPattern._
import akka.cluster.sharding.typed.scaladsl.{ClusterSharding, EntityRef}
import akka.util.Timeout
import com.typesafe.config.ConfigFactory
import net.imadz.infra.saga.strict.{StrictSagaCoordinator, StrictStatus}
import ${m.split.pkg}.{FabSplitSagaModule, FixtureHost => SplitFixtureHost}
import ${m.merge.pkg}.{FabMergeSagaModule, FixtureHost => MergeFixtureHost}
import ${m.pkg}.${host}
import org.mongodb.scala.MongoClient
import org.mongodb.scala.bson.collection.immutable.Document
import org.mongodb.scala.model.Sorts
import scala.concurrent.{Await, ExecutionContext}
import scala.concurrent.duration._

/** Composition acceptance (P14): the split → await-child → merge plan driven
  * through the generated InvocationPipelineHost against a shared durable Mongo
  * journal. Crash windows are constructed by prefix-truncating the HOST's
  * journal documents directly in Mongo — recovery sees exactly the surviving
  * prefix verified across all atomic batches after writer termination. Test-only
  * effect barriers prove intent-before-send; raw event bytes and typed journal
  * facts prove identity and persisted effect counts, not merely final balances. */
final class FixtureCompositionSpec extends org.scalatest.wordspec.AnyWordSpec with org.scalatest.matchers.should.Matchers {

  private val MongoHostPort = sys.env.getOrElse("SAGA_MONGO_HOSTPORT", "127.0.0.1:27017")
  private def mongoUri(db: String): String = s"mongodb://\$MongoHostPort/\$db"

  private def mongoReachable(): Boolean = try {
    val parts = MongoHostPort.split(":")
    val socket = new java.net.Socket()
    try socket.connect(new java.net.InetSocketAddress(parts(0), parts(1).toInt), 2000) finally socket.close()
    true
  } catch { case _: Throwable => false }

  private val ReconcileToken = "composition-reconcile-token"
  private val SeedWafers = Vector("w-001", "w-002", "w-003", "w-004")
  private val SplitWafers = Vector("w-001", "w-002")
  private val ChildBaseWafers = Vector("w-101")
  private val ManifestSeed = "manifest-seed-v1"
  private val From = "parent-lot"
  private val To = "child-lot"

  private def freePort(): Int = {
    val socket = new java.net.ServerSocket(0)
    try socket.getLocalPort finally socket.close()
  }

  private def compositionConfig(name: String, port: Int, uri: String): com.typesafe.config.Config = {
    val seed = "akka://" + name + "@127.0.0.1:" + port
    ConfigFactory.parseString(
    s\"\"\"
      akka.loglevel = "WARNING"
      akka.actor.provider = cluster
      akka.remote.artery.canonical.hostname = "127.0.0.1"
      akka.remote.artery.canonical.port = \$port
      akka.remote.artery.bind.hostname = "127.0.0.1"
      akka.remote.artery.bind.port = \$port
      akka.cluster.seed-nodes = ["\$seed"]
      akka.cluster.jmx.multi-mbeans-in-same-jvm = on
      akka.persistence.journal.plugin = "akka-contrib-mongodb-persistence-journal"
      akka.persistence.snapshot-store.plugin = "akka-contrib-mongodb-persistence-snapshot"
      akka.contrib.persistence.mongodb.mongo.driver = "akka.contrib.persistence.mongodb.RxMongoPersistenceExtension"
      akka.contrib.persistence.mongodb.mongo.mongouri = "\$uri"
    \"\"\".stripMargin).withFallback(ConfigFactory.load())
  }

  private def aggregateBehavior(entityId: String): akka.actor.typed.Behavior[net.imadz.metarch.application.aggregates.LotProtocol.LotCommandFamily] =
    akka.persistence.typed.scaladsl.EventSourcedBehavior(
      persistenceId = akka.persistence.typed.PersistenceId(net.imadz.metarch.application.aggregates.LotAggregate.entityTypeKey.name, entityId),
      emptyState = net.imadz.metarch.domain.entities.LotEntity.empty(entityId),
      commandHandler = net.imadz.metarch.application.aggregates.behaviors.LotBehaviors.apply,
      eventHandler = net.imadz.metarch.domain.entities.behaviors.LotEventHandler.apply)

  private def initSharding(kit: ActorTestKit): ClusterSharding = {
    import net.imadz.metarch.application.aggregates.LotAggregate
    val sharding = ClusterSharding(kit.system)
    sharding.init(
      akka.cluster.sharding.typed.scaladsl.Entity(LotAggregate.entityTypeKey)(ctx => aggregateBehavior(ctx.entityId)))
    sharding
  }

  private def waitClusterUp(kit: ActorTestKit): Unit = {
    val c = akka.cluster.typed.Cluster(kit.system)
    val deadline = 20.seconds.fromNow
    while (c.state.members.size < 1 && deadline.hasTimeLeft()) Thread.sleep(100)
    require(c.state.members.nonEmpty, "cluster membership never came up")
  }

  private def entityRef(sharding: ClusterSharding, entityId: String): EntityRef[net.imadz.metarch.application.aggregates.LotProtocol.LotCommandFamily] =
    sharding.entityRefFor(net.imadz.metarch.application.aggregates.LotAggregate.entityTypeKey, entityId)

  private implicit val timeout: Timeout = Timeout(10.seconds)

  private def askNow[Cmd, Res](kit: ActorTestKit, ref: akka.actor.typed.RecipientRef[Cmd])(f: ActorRef[Res] => Cmd): Res = {
    implicit val system: ActorSystem[_] = kit.system
    implicit val timeout: Timeout = Timeout(15.seconds)
    Await.result(ref.ask(f), 15.seconds)
  }

  private def stateOf(kit: ActorTestKit, ref: akka.actor.typed.RecipientRef[net.imadz.metarch.application.aggregates.LotProtocol.LotCommandFamily]): net.imadz.metarch.domain.entities.LotEntity.LotState =
    askNow(kit, ref)(replyTo => net.imadz.metarch.application.aggregates.LotProtocol.GetLotState(replyTo)).state

  private def carriedOf(kit: ActorTestKit, ref: akka.actor.typed.RecipientRef[net.imadz.metarch.application.aggregates.LotProtocol.LotCommandFamily]): Set[String] =
    stateOf(kit, ref).carried.keySet.toSet

  /** Command-face funding on the shared journal (deployment-honest seeding). */
  private def seedFunds(kit: ActorTestKit, sharding: ClusterSharding, entityId: String, txid: String, wafers: Vector[String] = SeedWafers): Unit = {
    val ref = entityRef(sharding, entityId)
    val import_ = net.imadz.metarch.application.aggregates.LotProtocol
    val r1 = askNow(kit, ref)(replyTo => import_.ReserveAddWafer(txid, entityId, wafers.toList, replyTo))
    val r2 = askNow(kit, ref)(replyTo => import_.CommitAddWafer(txid, entityId, wafers.toList, replyTo))
    assert(r1.error.isEmpty && r2.error.isEmpty, s"seeding failed for \$entityId")
  }

  private def spawnHost(kit: ActorTestKit, sharding: ClusterSharding, operation: String, occurrence: String,
                        audit: Option[(String, String) => Boolean] = None): ActorRef[${host}.Command] = {
    implicit val ec: ExecutionContext = kit.system.executionContext
    val splitCoordinator = ${splitEntry}.spawnClusterSingleton(kit.system, sharding, ReconcileToken)
    val mergeCoordinator = ${mergeEntry}.spawnClusterSingleton(kit.system, sharding, ReconcileToken)
    val behavior = audit match {
      case Some(check) => ${host}.behaviorForTest(kit.system, sharding, splitCoordinator, mergeCoordinator, operation, occurrence, check)
      case None => ${host}.behavior(kit.system, sharding, splitCoordinator, mergeCoordinator, operation, occurrence)
    }
    kit.spawn(behavior, s"composition-\$operation-\$occurrence")
  }

  private def begin(kit: ActorTestKit, hostRef: ActorRef[${host}.Command], operation: String, occurrence: String,
                    wafers: Vector[String]): ${host}.OperationReply = {
    implicit val system: ActorSystem[_] = kit.system
    implicit val ec: ExecutionContext = kit.system.executionContext
    Await.result(hostRef.ask(replyTo => ${host}.BeginOperation(operation, occurrence, From, To, wafers, ManifestSeed, replyTo)), 15.seconds)
  }

  private def progressOf(kit: ActorTestKit, hostRef: ActorRef[${host}.Command]): ${host}.ProgressReport = {
    implicit val system: ActorSystem[_] = kit.system
    implicit val ec: ExecutionContext = kit.system.executionContext
    Await.result(hostRef.ask(replyTo => ${host}.GetProgress(replyTo)), 15.seconds)
  }

  private def awaitConcluded(kit: ActorTestKit, hostRef: ActorRef[${host}.Command], maxSeconds: Int = 60): ${host}.ProgressReport = {
    val deadline = maxSeconds.seconds.fromNow
    var report = progressOf(kit, hostRef)
    while (report.concluded.isEmpty && deadline.hasTimeLeft()) { Thread.sleep(150); report = progressOf(kit, hostRef) }
    assert(report.concluded.isDefined, s"operation never concluded: \$report")
    report
  }

${recovery}

  "E5 same txid with different args: fail closed on the occupied terminal" in withCluster("CompositionE5") { (kit, sharding, _) =>
    seedFunds(kit, sharding, From, "seed-e5-from")
    seedFunds(kit, sharding, To, "seed-e5-to", ChildBaseWafers)
    // Pre-occupy the derived split txid with DIFFERENT args (a direct command
    // trigger through the split coordinator — deployment-honest conflict seed).
    implicit val system: ActorSystem[_] = kit.system
    implicit val ec: ExecutionContext = kit.system.executionContext
    val splitCoordinator = ${splitEntry}.spawnClusterSingleton(kit.system, sharding, ReconcileToken)
    val splitHost = new SplitFixtureHost(kit.system, sharding)
    val txid = ${host}.txidFor("op-e5", "occ-1", "split")
    val occupier = net.imadz.metarch.application.aggregates.LotProtocol.StartTransfer(
      txid, From, To, Vector("w-901", "w-902").toList, ManifestSeed,
      kit.createTestProbe[net.imadz.metarch.application.aggregates.LotProtocol.LotReply]().ref)
    splitCoordinator ! ${splitModule}.from_commandTriggerStart(occupier, splitHost, kit.createTestProbe[StrictSagaCoordinator.Reply]().ref)
    // Let the occupier saga reach a terminal state on the journal first.
    val probe = kit.createTestProbe[Any]()
    probe.awaitAssert({
      val status = Await.result(splitCoordinator.ask((r: ActorRef[StrictSagaCoordinator.Reply]) => StrictSagaCoordinator.GetStatus(r)), 10.seconds)
      status match {
        case StrictSagaCoordinator.Status(s) => assert(s.terminal)
        case other => fail("unexpected reply " + other)
      }
    }, 40.seconds, 500.millis)
    val hostRef = spawnHost(kit, sharding, "op-e5", "occ-1")
    begin(kit, hostRef, "op-e5", "occ-1", SplitWafers) // same derived txid, different wafer set
    val report = awaitConcluded(kit, hostRef)
    // saga-core 0.2 folds a same-identity different-args Start into "return the
    // existing transaction's terminal state" (no second effect ever starts).
    // The host inherits the occupier's terminal rejection and STOPS — fail-closed
    // with zero effects from the host's own args.
    assert(report.concluded.contains("Rejected"),
      s"same txid with different args must fail closed on the occupied terminal, got: \$report")
    assert(carriedOf(kit, entityRef(sharding, From)) == SeedWafers.toSet,
      "the occupier's rejection must not leak effects from the host's different args")
  }
}
`;
  const facts = (recoveryTemplate.slice(0, recoveryTemplate.indexOf('  private def stoppedWriter')) +
    recoveryTemplate.slice(recoveryTemplate.indexOf('  private def hostPid'), recoveryTemplate.indexOf('  private def effectAudit')))
    .replace(/^  private /gm, '  ');
  const deploymentTokens = {
    ...replacements, PACKAGE: m.pkg, PACKAGE_TAIL: m.pkg.split('.').pop(), FACTS: facts,
    COMMAND_FAMILY: 'net.imadz.metarch.application.aggregates.LotProtocol.LotCommandFamily',
    ENTITY: 'net.imadz.metarch.domain.entities.LotEntity',
    BEHAVIORS: 'net.imadz.metarch.application.aggregates.behaviors.LotBehaviors',
    EVENT_HANDLER: 'net.imadz.metarch.domain.entities.behaviors.LotEventHandler',
    PROTOCOL: 'net.imadz.metarch.application.aggregates.LotProtocol',
    SEED_WAFERS: 'wafers.toList',
  };
  const replace = (text) => text.replace(/@([A-Z_]+)@/g, (_, key) => {
    if (!(key in deploymentTokens)) throw new Error('unresolved deployment template token: ' + key);
    return deploymentTokens[key];
  });
  const deployment = replace(replace(deploymentTemplate));
  return [{ name: "FixtureCompositionSpec.scala", content: spec },
    { name: "FixtureCompositionDeploymentSpec.scala", content: deployment }];
}
