// ═══ saga-dsl emit-invocation-plan — monarch child plan module ═══
// P14 批B：组合管线的 child stages 计划（树原子 monarch 块 → monarch-persistence
// 0.2.1 可恢复 run Scala）。stage 逻辑=fixture 语义固定模板（receive=吸收初始集、
// process=标记处理计数、finalize=冻结 completed manifest；无设备 I/O，如实注记）。
// 复用 monarch-dsl 的 MonarchSpec 形状约定（bank.binding 先例）。
export function emitMonarchPlan(child, { header } = {}) {
  const h = header || "// @generated by truthsrc run-all invocation-host\n";
  const fail = (msg) => { throw new Error(`emit-invocation-plan: ${msg}`); };
  const cursors = child.stages.map((s) => s.cursor || s.id || s);
  if (!cursors.length) fail("child plan requires at least one stage cursor");
  const receive = cursors[0];
  const process = cursors[1] || cursors[0];
  const finalize = cursors[2] || cursors[cursors.length - 1];
  const stateType = child.stateType || "ChildPlanState";
  const stageType = child.stageType || "ChildStage";
  const planObj = child.planObj || "FabChildPlan";

  // Fixture stage semantics (declared in the tree atom's monarch block):
  // every stage is an in-JVM bounded transform over the child wafer set.
  const logic = cursors.map((c) => {
    if (c === receive) return `      case ${stageType}.${pascal(c)} => state // absorb the StartRun initial state`;
    if (c === process) return `      case ${stageType}.${pascal(c)} => state.copy(processedCount = state.wafers.size)`;
    return `      case ${stageType}.${pascal(c)} => state // fixture transform: no equipment I/O`;
  }).join("\n");

  const plan = `${h}package ${child.pkg}

import akka.actor.typed.Behavior
import akka.persistence.typed.PersistenceId
import akka.persistence.typed.scaladsl.EventSourcedBehavior
import net.imadz.monarch.persistence.{PersistentMonarch, RunObserver, StateCodec}
import net.imadz.monarch.persistence.PersistentMonarch.Command
import scala.concurrent.{ExecutionContext, Future}

/** Generated monarch child plan ("${child.planId}"): ${cursors.length} bounded
  * stages over the child wafer set — fixture semantics, no equipment I/O.
  * Durability/recovery is owned by monarch-persistence 0.2.1 (event journal:
  * RunStarted/StageDone/RunCompleted/RunFailedEvt); the parent host observes
  * THIS journal for the terminal state — its mirror is never authoritative. */
object ${planObj} {
  sealed trait ${stageType}
  object ${stageType} {
${cursors.map((c) => `    case object ${pascal(c)} extends ${stageType}`).join("\n")}

    val chain: Seq[${stageType}] = Seq(${cursors.map((c) => pascal(c)).join(", ")})

    def stageName(s: ${stageType}): String = s match {
${cursors.map((c) => `      case ${pascal(c)} => ${JSON.stringify(c)}`).join("\n")}
    }
  }

  final case class ${stateType}(wafers: Vector[String], processedCount: Int)
  object ${stateType} {
    // Wire format "w-101,w-102:2" — wafer ids carry no colons/commas (bounded ids).
    val codec: StateCodec[${stateType}] = StateCodec[${stateType}](
      enc = st => (st.wafers.mkString(",") + ":" + st.processedCount)
        .getBytes(java.nio.charset.StandardCharsets.UTF_8),
      dec = bytes => {
        val text = new String(bytes, java.nio.charset.StandardCharsets.UTF_8)
        val sep = text.lastIndexOf(':')
        val wafers = text.substring(0, sep)
        ${stateType}(if (wafers.isEmpty) Vector.empty else wafers.split(",").toVector, text.substring(sep + 1).toInt)
      }
    )
  }

  /** Host's stage logic. Must be idempotent: at-least-once recovery may replay it. */
  private def runStage(stage: ${stageType}, state: ${stateType})(implicit ec: ExecutionContext): Future[${stateType}] =
    Future {
      stage match {
${logic}
      }
    }

  def behavior(pid: PersistenceId)(implicit ec: ExecutionContext): Behavior[Command[${stateType}]] =
    PersistentMonarch.behavior[${stageType}, ${stateType}](
      pid,
      ${stageType}.chain,
      (stage: ${stageType}, state: ${stateType}) => runStage(stage, state),
      ${stateType}.codec,
      (stage: ${stageType}) => ${stageType}.stageName(stage),
      scala.None,
      RunObserver.nop[${stateType}]
    )
}
`;
  return [{ name: `${planObj}.scala`, content: plan }];
}

function pascal(s) {
  return String(s).split(/[-_]/).map((p) => p ? p[0].toUpperCase() + p.slice(1) : p).join("");
}
