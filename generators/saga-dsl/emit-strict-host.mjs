import { emitStrictFiles } from "./emit-strict.mjs";

const jstr = (s) => JSON.stringify(String(s));
const scalaId = (n) => n;

export function emitStrictHostFiles(model, { header } = {}) {
  const h = header || "// @generated by truthsrc run-all strict-scala\n";
  const m = model;

  // ── FixtureHost.scala ──
  const face = m.faces[0]; // 单聚合面（serial）；多聚合时 per-face helpers 命名同款
  const fbase = firstLower(face.base);
  const entityRefHelper = `  private def ${fbase}EntityRef(id: String): akka.cluster.sharding.typed.scaladsl.EntityRef[${face.commandsFamilyFqn}] =
    sharding.entityRefFor(${face.aggregateKeyFqn}, id)`;
  const replyAskHelper = `  /** Durable command ask: the aggregate replies through EventSourcedBehavior
    * thenReply, so a None error is a persisted-fact confirmation. */
  private def ${fbase}ReplyAsk(id: String, construct: akka.actor.typed.ActorRef[${face.replyFqn}] => ${face.commandsFamilyFqn}): Future[${face.replyFqn}] =
    ${fbase}EntityRef(id).ask(construct)`;
  const stateAskHelper = `  /** Read-only state ask (the aggregate's query-command face) for evidence queries. */
  private def ${fbase}StateAsk(id: String): Future[${face.queryReplyFqn}] =
    ${fbase}EntityRef(id).ask(replyTo => ${face.queryCommandFqn}(replyTo))`;

  const phaseBindings = m.phases.map((p) => {
    const receiptCtor = `${m.moduleObj}.${p.receiptType}(${p.outputs.map((o) => `input.${scalaId(o.slot)}`).join(", ")})`;
    const commandCall = `${face.protocolFqn}.${p.commandName}(${p.inputs.map((i) => `input.${scalaId(i.slot)}`).join(", ")}, replyTo)`;
    const textR = p.receiptFields.filter((f) => f.shape === "text");
    const moneyR = p.receiptFields.filter((f) => f.shape === "money");
    const encodeBody = [...textR.map((f) => `        StrictWire.lengthPrefixed(value.${scalaId(f.name)})`), ...moneyR.map((f) => `        ${m.moneyCodecName}.encode(value.${scalaId(f.name)})`)].join(" ++\n");
    const decodeBody = !moneyR.length
      ? `    StrictWire.readPrefixed(bytes, ${textR.length}).flatMap { case (Vector(${textR.map((f) => scalaId(f.name)).join(", ")}), rest0) =>
        if (rest0.isEmpty) Success(${p.receiptType}(${textR.map((f) => scalaId(f.name)).join(", ")}))
        else Failure(new IllegalArgumentException("${p.receiptType} receipt wire: trailing bytes after the declared fields"))
    }`
      : `    StrictWire.readPrefixed(bytes, ${textR.length}).flatMap { case (Vector(${textR.map((f) => scalaId(f.name)).join(", ")}), rest0) =>
${moneyR.map((f, i) => `      ${m.moneyCodecName}.decodeWithRest(rest${i}).flatMap { case (${scalaId(f.name)}, rest${i + 1}) =>`).join("\n")}
        if (rest${moneyR.length}.isEmpty) Success(${p.receiptType}(${p.receiptFields.map((f) => scalaId(f.name)).join(", ")}))
        else Failure(new IllegalArgumentException("${p.receiptType} receipt wire: trailing bytes after the declared fields"))
${moneyR.map(() => "      }").join("\n")}
    }`;
    return `  def ${p.member}: ${m.moduleObj}.${p.hostTrait} = new ${m.moduleObj}.${p.hostTrait} {
    private val codec: PayloadCodec[${m.moduleObj}.${p.receiptType}] = new PayloadCodec[${m.moduleObj}.${p.receiptType}] {
      override val pin: CodecPin = CodecPin(${jstr(p.pinId)}, 1)
      override def encode(value: ${m.moduleObj}.${p.receiptType}): ByteString =
${encodeBody}
      override def decode(bytes: ByteString): Try[${m.moduleObj}.${p.receiptType}] =
${decodeBody}
    }
    override def contract: PhaseContract = ${m.moduleObj}.${p.contractMember}
    override def receiptCodec: PayloadCodec[${m.moduleObj}.${p.receiptType}] = codec
    override def querySafety: QuerySafety = QuerySafety.DeclaredReadOnly
    override def execute(identity: OperationIdentity, input: ${m.moduleObj}.${p.inputType}): Future[PhaseOutcome[${m.moduleObj}.${p.receiptType}]] =
      ${fbase}ReplyAsk(input.${p.resourceInput.slot}, replyTo => ${commandCall}).map {
        case ${face.replyFqn}(None) =>
          ConfirmedReceipt(identity, ${receiptCtor})
        case ${face.replyFqn}(Some(error)) =>
          NotExecuted(identity, s"aggregate rejected $${'{'}error.code${'}'}: $${'{'}error.message${'}'}; no events persisted", safeToRetry = true)
      }
    override def query(identity: OperationIdentity, input: ${m.moduleObj}.${p.inputType}): Future[PhaseOutcome[${m.moduleObj}.${p.receiptType}]] =
      ${fbase}StateAsk(input.${p.resourceInput.slot}).map { view =>
        if (view.state.${p.evidence}.contains(input.${p.txidSlot}))
          ConfirmedReceipt(identity, ${receiptCtor})
        else
          NotExecuted(identity, s"durable aggregate state: ${p.evidence} does not contain txid $${'{'}input.${p.txidSlot}${'}'}", safeToRetry = true)
      }.recover { case ex => Unknown(identity, s"phase evidence query failed: $${'{'}ex.getMessage${'}'}") }
  }`;
  }).join("\n\n");

  const triggerBindings = m.triggers.map((t) => {
    const requires = t.argSources.filter((a) => a.shape === "text").map((a) =>
      `    require(source.${scalaId(a.slot)} != null && source.${scalaId(a.slot)}.length >= ${a.bounds[0]} && source.${scalaId(a.slot)}.length <= ${a.bounds[1]},
      "trigger slot ${a.slot} outside the declared bounded text shape")`).join("\n");
    const moneyRequires = t.moneySlots.map((s2) =>
      `    require(source.${scalaId(s2)} != null && source.${scalaId(s2)}.currency != null && source.${scalaId(s2)}.currency.nonEmpty,
      "trigger money slot ${s2} carries no currency")`).join("\n");
    const argsCtor = `${m.moduleObj}.Args(${m.argsFields.map((f) => `source.${scalaId(f.name)}`).join(", ")})`;
    return `  def ${t.member}: ${m.moduleObj}.${t.bindingTrait} = new ${m.moduleObj}.${t.bindingTrait} {
    override def contract: TriggerContract = ${m.moduleObj}.${t.contractMember}
    // Whole typed trigger, including the explicit idempotency source; never first/drop remaining.
    override def map(source: ${t.sourceFqn}): ${m.moduleObj}.TriggerStart = {
${requires}
${moneyRequires}
      ${m.moduleObj}.TriggerStart(source.${scalaId(t.idempotencyField)}, ${argsCtor})
    }
  }`;
  }).join("\n\n");

  const completionBindings = m.completions.map((c) => {
    return `  def ${c.member}: ${m.moduleObj}.${c.bindingTrait} = new ${m.moduleObj}.${c.bindingTrait} {
    override def contract: CompletionContract = ${m.moduleObj}.${c.contractMember}
    override def map(identity: TransactionIdentity, input: ${m.moduleObj}.${c.inputType}): ${c.eventFqn} = ${c.eventFqn}(${c.slots.map((s2) => `input.${scalaId(s2)}`).join(", ")})
  }`;
  }).join("\n\n");

  const fixtureHost = `${h}package ${m.pkg}

import akka.actor.typed.{ActorSystem, Scheduler}
import akka.actor.typed.scaladsl.AskPattern._
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.persistence.typed.PersistenceId
import akka.util.Timeout
import com.google.protobuf.ByteString
import net.imadz.infra.saga.strict._
import ${face.protocolFqn.split(".").slice(0, -1).join(".")}.{${face.base}Aggregate, ${face.base}Protocol}
import scala.concurrent.{ExecutionContext, Future}
import scala.util.{Failure, Success, Try}
import StrictWire._

/** Generated fixture host: the concrete ${m.moduleObj}.Host for the SagaModule example.
  * Declarations, not runtime certification — upstream readiness flags stay untouched.
  *   - execute = ask the aggregate entity with the phase command; a None error is a
  *     persisted-fact confirmation, a guard rejection persisted no events and reports
  *     NotExecuted(safeToRetry = true) — the TCC auto-compensate path;
  *   - prepare query = four-field precise determination: the state field whose
  *     writtenBy lineage names the confirmation event and the txid slot contains(txid);
  *   - commit/compensate query = the phase-marker fields (SCHEMA.md P5): the
  *     committed/compensated maps put-keyed by every confirmation, contains(txid)
  *     precise determination — Confirmed skips re-execution of a durable fact;
  *   - ask failures = Unknown (a timeout is never an absence). */
object FixtureHost {
  /** What this emitted implementation actually provides — requireImplemented declares
    * against this set, never against an echo of the contract. */
  val SupportedCapabilities: Set[String] = Set(${m.caps.map(jstr).join(", ")})
  val DeclaredInvariants: Set[String] = Set(${m.saga.contract.definition.payload.invariants.map(jstr).join(", ")})
}

final class FixtureHost(system: ActorSystem[_], sharding: ClusterSharding)(implicit ec: ExecutionContext) extends ${m.moduleObj}.Host {
  import ${m.moduleObj}._

  private val canonicalArgsCodec = new ${m.argsCodecName}
  // Ask enablers in scope for every port body and helper (AskPattern contract).
  private implicit val askTimeout: Timeout = Timeout(settings.interactionTimeout)
  private implicit val askScheduler: Scheduler = system.scheduler

  override def argsCodec: PayloadCodec[Args] = canonicalArgsCodec
  // Explicit reconcile budget; interactionTimeout carries the contract phase pin.
  override def settings: StrictSagaCoordinator.Settings =
    StrictSagaCoordinator.Settings(scala.concurrent.duration.FiniteDuration(${m.interactionTimeoutMs}, java.util.concurrent.TimeUnit.MILLISECONDS), 32)

  // Fail closed when the requirement set exceeds what this implementation declares.
  // Returning normally is a host declaration, not runtime certification.
  override def requireImplemented(requirements: HostRequirements, types: Vector[TypeContract], argsCodec: ArgsCodecContract): Unit = {
    val unsupported = requirements.capabilities.filterNot(FixtureHost.SupportedCapabilities)
    require(unsupported.isEmpty, s"fixture host capabilities not implemented: $${'{'}unsupported.mkString(", ")${'}'}")
    require(
      requirements.commitDecision == "${m.safetyWire.commitDecision}" &&
      requirements.abortDecision == "${m.safetyWire.abortDecision}" &&
      requirements.afterCommit == "${m.safetyWire.afterCommit}" &&
      requirements.unknown == "${m.safetyWire.unknown}" &&
      requirements.compensation == "${m.safetyWire.compensation}" &&
      requirements.cancelBeforePrepare == "${m.safetyWire.cancelBeforePrepare}" &&
      requirements.retryIdentity == "${m.safetyWire.retryIdentity}" &&
      requirements.manualRecovery == "${m.safetyWire.manualRecovery}",
      "safety contract drift against the generated fixture host")
    require(requirements.totalDeadlineMs > 0 && requirements.maxParticipants > 0 && requirements.maxInFlight > 0 &&
      requirements.maxAttempts > 0 && requirements.phaseTimeoutMs > 0 && requirements.queryTimeoutMs > 0,
      "deadline/admission requirements must be positive")
    require(requirements.durableManifest, "fixture host requires the durable manifest")
    require(requirements.businessInvariants.forall(FixtureHost.DeclaredInvariants), "undeclared business invariant")
    require(argsCodec.runtimePin == CodecPin("${m.saga.contract.binding.codec.id}", ${runtimeArgsVersion(m)}), "args codec pin drift")
    require(types.map(_.id).toSet == Set(${m.typeAliases.map((t) => jstr(t.id)).join(", ")}), "type contract drift against the generated fixture types")
  }

  override def requireIndependentNamespace(persistenceId: PersistenceId): Unit =
    require(persistenceId.id.startsWith("${m.namespacePrefix}/"),
      s"independent strict persistence namespace required (prefix \\"${m.namespacePrefix}/\\"), got $${'{'}persistenceId.id${'}'}")

${entityRefHelper}

${replyAskHelper}

${stateAskHelper}

${m.addressMembers.map((a) => `  override def ${a.member}Contract: AddressContract = ${m.moduleObj}.${a.member}Contract
  override def ${a.member}(resource: String): String = resource // exact-resource addressing; no I/O`).join("\n")}

${phaseBindings}

${triggerBindings}

${completionBindings}
}
`;
  function runtimeArgsVersion(mm) {
    return mm.saga.runtimeBinding?.saga?.argsCodec?.runtimeVersion ?? 1;
  }

  // ── StrictSagaEntry.scala ──
  const cmdTrigger = m.triggers.find((t) => t.isCommand);
  const eventTriggers = m.triggers.filter((t) => !t.isCommand);
  const completionMatches = m.completions.map((c) =>
    `      case ev: ${c.eventFqn} => entityRef.ask(replyTo => ${c.publicationCommandFqn}(identity.transactionId, replyTo))`).join("\n");
  const entry = `${h}package ${m.pkg}

import akka.actor.typed.{ActorRef, ActorSystem, Scheduler}
import akka.actor.typed.scaladsl.AskPattern._
import akka.actor.typed.scaladsl.Behaviors
import akka.cluster.sharding.typed.scaladsl.ClusterSharding
import akka.cluster.typed.{ClusterSingleton, SingletonActor}
import akka.contrib.persistence.mongodb.ScalaDslMongoReadJournal
import akka.persistence.query.PersistenceQuery
import akka.persistence.typed.PersistenceId
import akka.stream.{KillSwitches, Materializer, SystemMaterializer, UniqueKillSwitch}
import akka.stream.scaladsl.{Keep, Sink}
import akka.util.Timeout
import net.imadz.infra.saga.strict._
import ${face.protocolFqn}
import scala.concurrent.{ExecutionContext, Future}

/** Binding entrypoint (${b_entry(m)}): spawns the strict coordinator in the
  * independent "strict-saga/" persistence namespace, wires the command trigger and
  * exposes the terminal-completion mapping plus the durable idempotent result publication
  * onto the aggregate journal (SCHEMA.md P5 result-publication convention: the mapped
  * result event's producing command is asked on the initiating entity, where the
  * map-absent sagaResults guard makes republication an empty success). The event
  * trigger path is wired by installEventSource: the shared durable journal's live
  * event stream drives the idempotent Start from persisted trigger events — the only
  * event source every node of a physical multi-JVM cluster observes. */
object ${m.entryName} {
  val NamespacePrefix = "${m.namespacePrefix}"
  def persistenceId: PersistenceId = PersistenceId.ofUniqueId(s"$NamespacePrefix/$${'{'}${m.moduleObj}.Name${'}'}")

  def spawn(system: ActorSystem[_], sharding: ClusterSharding, reconcileToken: String)(implicit ec: ExecutionContext): ActorRef[StrictSagaCoordinator.Command] = {
    require(reconcileToken != null && reconcileToken.nonEmpty, "explicit reconciliation token required (manual-evidence-authorization)")
    val host = new FixtureHost(system, sharding)
    system.systemActorOf(${m.moduleObj}.behavior(persistenceId, host, FixtureReconcileAuthorizer(reconcileToken)),
      s"$${'{'}${m.moduleObj}.Name${'}'}-strict-saga-coordinator")
  }

  /** Cluster-topology spawn: exactly one coordinator cluster-wide (a singleton), with
    * every node holding a proxy ActorRef. Spawning the same persistenceId on several
    * nodes through systemActorOf would be a persistence-identity collision. */
  def spawnClusterSingleton(system: ActorSystem[_], sharding: ClusterSharding, reconcileToken: String)(implicit ec: ExecutionContext): ActorRef[StrictSagaCoordinator.Command] = {
    require(reconcileToken != null && reconcileToken.nonEmpty, "explicit reconciliation token required (manual-evidence-authorization)")
    val host = new FixtureHost(system, sharding)
    ClusterSingleton(system).init(SingletonActor(
      ${m.moduleObj}.behavior(persistenceId, host, FixtureReconcileAuthorizer(reconcileToken)),
      s"$${'{'}${m.moduleObj}.Name${'}'}-strict-saga-coordinator"))
  }

  /** Command-trigger wiring: map the typed trigger to the idempotent Start. */
  def start(coordinator: ActorRef[StrictSagaCoordinator.Command], host: ${m.moduleObj}.Host,
            source: ${cmdTrigger ? cmdTrigger.sourceFqn : "Any"}, replyTo: ActorRef[StrictSagaCoordinator.Reply]): StrictSagaCoordinator.Start =
    ${m.moduleObj}.${cmdTrigger.member}Start(source, host, replyTo)

  /** Event-trigger wiring — the deployment-face event-stream source. Subscribes to the
    * shared durable journal's live event stream through Persistence Query and drives
    * the coordinator's idempotent Start from each persisted trigger event. The journal
    * (not the in-JVM ActorSystem event stream) is the only event source every node of
    * a physical multi-JVM cluster can observe. Idempotency: a coordinator Start with
    * the same identity and args returns the existing state, so a replayed event — or
    * several nodes running this source against the same journal — cannot double-start
    * a transaction. Install once per system (the reply sink is a named system actor).
    * Stream failure surfaces as an absent trigger: journal liveness is a deployment
    * precondition this wiring cannot restore. */
  def installEventSource(system: ActorSystem[_], sharding: ClusterSharding,
                         coordinator: ActorRef[StrictSagaCoordinator.Command])(implicit ec: ExecutionContext): UniqueKillSwitch = {
    val host = new FixtureHost(system, sharding)
    implicit val mat: Materializer = SystemMaterializer(system).materializer
    val replySink = system.systemActorOf(
      Behaviors.receiveMessage[StrictSagaCoordinator.Reply](_ => Behaviors.same),
      s"$${'{'}${m.moduleObj}.Name${'}'}-event-source-reply-sink")
    val readJournal = PersistenceQuery(system).readJournalFor[ScalaDslMongoReadJournal]("akka-contrib-mongodb-persistence-readjournal")
    readJournal.allEvents()
      .viaMat(KillSwitches.single)(Keep.right)
      .map(envelope => envelope.event)
      .toMat(Sink.foreach[Any] {
${eventTriggers.map((t) => `        case ev: ${t.sourceFqn} => coordinator ! ${m.moduleObj}.${t.member}Start(ev, host, replySink)`).join("\n")}
        case _ => () // non-trigger journal events: participant folds, results, coordinator internals
      })(Keep.left)
      .run()
  }

  def status(coordinator: ActorRef[StrictSagaCoordinator.Command])(implicit timeout: Timeout, scheduler: Scheduler, ec: ExecutionContext): Future[StrictState] =
    coordinator.ask(replyTo => StrictSagaCoordinator.GetStatus(replyTo)).map {
      case StrictSagaCoordinator.Status(state) => state
      case other => throw new IllegalStateException(s"unexpected coordinator reply: $$other")
    }

  /** Terminal-state to completion-event mechanical mapping: non-terminal states map to
    * None; an Aborted state with any confirmed prepare is compensated, otherwise
    * rejected-before-effects. The mapped event value is returned to the caller. */
  def completionEvent(identity: TransactionIdentity, args: ${m.moduleObj}.Args, host: ${m.moduleObj}.Host, state: StrictState): Option[${face.entityFqn}.${face.eventsFamily}] = {
    val kind = state.status match {
      case StrictStatus.Succeeded => Some("succeeded")
      case StrictStatus.Aborted =>
        val prepareConfirmed = state.evidence.values.exists {
          case Evidence.Confirmed(op, _) => op.phase == Phase.Prepare
          case _ => false
        }
        Some(if (prepareConfirmed) "compensated" else "rejected-before-effects")
      case StrictStatus.RecoveryRequired => Some("recovery-required")
      case _ => None
    }
    kind.map {
${m.completions.map((c) => `      case "${c.kindWire}" => ${m.moduleObj}.${c.member}Event(identity, args, host)`).join("\n")}
      case other => throw new IllegalStateException(s"unmapped completion kind: $$other")
    }
  }

  /** Durable, idempotent result publication (P5): decode the state's identity and args,
    * map the terminal state to its result event and ask the event's producing command on
    * the initiating entity (${m.publicationSlot}). Reply None = the result event was
    * persisted, or a republication hit the succeed-empty guard (idempotent, zero events).
    * Non-terminal states fail explicitly; ask failures surface to the caller, whose
    * retry stays idempotent by the aggregate guard. */
  def publishCompletion(sharding: ClusterSharding, host: ${m.moduleObj}.Host, state: StrictState)(implicit timeout: Timeout, scheduler: Scheduler, ec: ExecutionContext): Future[${face.replyFqn}] = {
    val identity = state.identity.getOrElse(throw new IllegalStateException("publishCompletion: state carries no transaction identity"))
    val args = host.argsCodec.decode(state.argsBytes).get
    val event = completionEvent(identity, args, host, state).getOrElse(throw new IllegalStateException("publishCompletion: state is not terminal — nothing to publish"))
    val entityRef = sharding.entityRefFor(${face.aggregateKeyFqn}, args.${m.publicationSlot})
    event match {
${completionMatches}
      case other => throw new IllegalStateException(s"unmapped publication event: $$other")
    }
  }
}

/** Synchronous, I/O-free authorization (ReconcileAuthorizer contract): Right is the
  * principal recorded for the reconciliation. No lenient default. */
final case class FixtureReconcileAuthorizer(expected: String) extends ReconcileAuthorizer {
  override def authorize(identity: TransactionIdentity, token: String): Either[String, String] = {
    val provided = if (token == null) Array.emptyByteArray else token.getBytes(java.nio.charset.StandardCharsets.UTF_8)
    val expectedBytes = if (expected == null) Array.emptyByteArray else expected.getBytes(java.nio.charset.StandardCharsets.UTF_8)
    if (expectedBytes.length > 0 && java.security.MessageDigest.isEqual(provided, expectedBytes)) Right("fixture-reconciler")
    else Left("reconciliation token mismatch")
  }
}
`;
  function b_entry(mm) { return `${mm.pkg}.${mm.entryName}`; }

  return [
    { name: "FixtureHost.scala", content: fixtureHost },
    { name: `${m.entryName}.scala`, content: entry },
  ];
}

function firstLower(s) { return s ? s[0].toLowerCase() + s.slice(1) : s; }
