import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileProductSet } from '../lib/products/compile.mjs';
import { generate } from '../generators/scala-cqrs-play-service/generate.mjs';
import { validateCodeMappings } from '../src/core/code-mappings.mjs';
import { serviceApplicationFixture } from './service-application-fixture.mjs';

const reference = new URL('./reference/aggregate-layers/warehouse/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('../generators/scala-cqrs-play-service/generator.json', import.meta.url), 'utf8'));
const { request, options } = serviceApplicationFixture();
const compilation = compileProductSet(request);
assert.deepEqual(compilation.diagnostics, []);
const generated = generate({ compilation, manifest, options });
assert.deepEqual(generated.diagnostics, []);
const files = [
  'domain/WarehouseState.scala',
  'domain/entities/WarehouseEntity.scala',
  'application/aggregates/WarehouseProtocol.scala',
  'application/aggregates/WarehouseAggregate.scala',
  'application/aggregates/WarehouseAggregateFactory.scala',
  'application/aggregates/behaviors/WarehouseBehaviors.scala',
  'infrastructure/bootstrap/WarehouseBootstrap.scala'
].map(file => 'app/example/inventory/' + file);
const header = '// @generated by truthsrc scala-cqrs-domain:1\n';

for (const path of files) test('compatible reference matches the complete Scala source: ' + path, () => {
  const entry = generated.plan.entries.find(entry => entry.path === path);
  assert.ok(entry, path);
  assert.ok(entry.content.startsWith(header));
  assert.equal(entry.content.slice(header.length), readFileSync(new URL(path, reference), 'utf8'));
  validateCodeMappings(entry);
});

test('behavior grouping retains every exact command and external source mapping', () => {
  const entries = generated.plan.entries.filter(e => e.path.includes('/aggregates/behaviors/'));
  for (const entry of entries) {
    const mappings = validateCodeMappings(entry);
    assert.ok(mappings.length > 0);
    const aggregate = entry.path.endsWith('/WarehouseBehaviors.scala') ? 'Warehouse' : 'AllocationOrder';
    const products = Object.fromEntries(compilation.result.products.map(p => [p.id, p.payload]));
    const commands = products['reference-layout'].declarations.filter(d => d.ref.kind === 'command' && d.ref.owner[0] === aggregate);
    const producers = products['domain-dependencies'].externalProducers.filter(p => p.event.owner[0] === aggregate);
    const key = source => 'source:' + source.document + '#' + source.pointer;
    assert.deepEqual(mappings.map(m => m.knowledgeKey), [...producers, ...commands].map(row => key(row.source)));
    for (const command of commands) {
      const mapping = mappings.find(m => m.knowledgeKey === key(command.source));
      assert.ok(mapping.span.text.includes('Payload.' + command.ref.id + ' =>'));
      assert.ok(mapping.span.text.includes(aggregate + 'Rules.' + command.ref.id + '(state, p, hosts)'));
    }
    for (const producer of producers) {
      const mapping = mappings.find(m => m.knowledgeKey === key(producer.source));
      assert.ok(mapping.span.text.includes('authority.authorize(' + JSON.stringify(producer.id)));
    }
    for (const mapping of mappings) {
      assert.match(mapping.span.text, /^\s*case /);
      assert.ok(mapping.span.text.includes('Rules.') || mapping.span.text.includes('authority.authorize'));
    }
  }
  const external = entries.find(e => e.path.endsWith('AllocationOrderBehaviors.scala'));
  assert.equal(external.codeMappings.filter(m => m.span.text.includes('authority.authorize')).length, 5);
  assert.ok(external.content.indexOf('externalBehavior(authority)') < external.content.indexOf('queryBehavior'));
});
