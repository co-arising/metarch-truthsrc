// scala-cqrs-es-metarch-modelcatalog.test.mjs — inc5 gate: golden byte identity against LIVE
// CodegenMain output from the REAL metarch truth source (IngestedSystem, multi-module), for the
// ModelCatalog aggregate — the richest write-behavior aggregate (8 write commands + 1 query, 8
// events with folds, 5 value objects, semantic-version String field, fn:/literal:/event. fold
// vocabulary). Complements the Subdomain gate (simplest aggregate) with breadth: the import
// multiset over distinct TypeRefs, VO imports, 9 CommandHelpers, all-events EventHandler, and
// the fold-expr transform (literal:→quoted, fn:/event. passthrough).
//
// NOTE: CodegenMain emits only the aggregate SKELETON — the behaviors file wires queryBehaviors
// only; the runReplyingPolicy write-flow wiring is produced LATER by rules_domain_gen (a separate
// generator, V4-3 face), confirmed by the live ingested-app file's `@generated by rules_domain_gen`
// header. So this gate validates the skeleton port's breadth, not the policy wiring.
//
// The canonical + elementHashes sidecar are produced by tools/extract-metarch-canonical.mjs from
// the pinned graph export v55 (a structural projection — all code-shaping stays in the generator).
import { equal, ok } from 'node:assert';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { plan } from '../src/core/generate.mjs';

const GEN = join(import.meta.dirname, '..', 'generators', 'scala-cqrs-es');
const GOLD = join(import.meta.dirname, '..', 'golden', 'scala-cqrs-es-metarch');
const GOLDEN_VERSION = '581683f4';
const elementHashes = JSON.parse(readFileSync(join(GOLD, 'model-catalog.elementHashes.json'), 'utf8'));

const { entries } = await plan({
  canonicalFile: join(GOLD, 'model-catalog.canonical.json'),
  generatorDir: GEN,
  options: { generatorVersion: GOLDEN_VERSION, elementHashes, relics: { skipValueObjects: ['UcStep'] } }, // V4-16: VO face rides along (global voCatalog slot)
});
equal(entries.filter((e) => e.kind === 'value-object').length, 30, 'V4-16: 30 value objects ride the same canonical');
for (const e of entries.filter((e) => e.kind !== 'value-object' && e.kind !== 'proto' && e.kind !== 'proto-shared')) {
  const want = readFileSync(join(GOLD, 'expected', e.path), 'utf8');
  equal(e.content, want, `byte identity: ${e.path}`);
}

// EventHandler: an empty-fold event renders identity `state`, a literal: fold renders a quoted
// string, and a fn: fold passes through verbatim — the fold-expr vocabulary Subdomain never hit.
const eh = entries.find((e) => e.path.endsWith('ModelCatalogEventHandler.scala')).content;
ok(/case event: MetadataExported =>\n\s+state\n/.test(eh), 'empty-fold event → identity state');
ok(eh.includes('status = "CONFLICT_DETECTED"'), 'literal: fold → quoted string');
ok(eh.includes('conceptIndex = fn:ApplyConceptDeltas'), 'fn: fold → verbatim passthrough');

// Entity: the import multiset emits `scala.collection.immutable.List` once per DISTINCT List[X]
// (List[Id], List[CatalogConflict], List[ConceptIndexEntry], List[ConceptDelta] = 4 lines).
const ent = entries.find((e) => e.path.endsWith('ModelCatalogEntity.scala')).content;
equal((ent.match(/^import scala\.collection\.immutable\.List$/gm) || []).length, 4, 'List import multiset over distinct TypeRefs');

console.log('✅ scala-cqrs-es-metarch-modelcatalog — golden byte identity (ModelCatalog, 8 kinds, live metarch + @knowledge + fold vocab)');
