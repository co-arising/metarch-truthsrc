async function renderInput(input) {
  const { render } = await import('../generators/scala-cqrs-domain-kernel-v1/render.mjs');
  const model = buildModels(input), graph = serializationModel(model);
  return { model, graph, entries: render(model, graph, footprint) };
}
function inputFixture() {
  const fixture = domainKernelFixture();
  return { products: structuredClone(fixture.products), options: structuredClone(fixture.config.options) };
}
function body(entry) { return entry.content.slice(headerFor(entry.path).length); }
function findDeclaration(input, kind, id, owner) {
  const declaration = input.products['reference-layout'].declarations.find(row => row.ref.kind === kind && row.ref.id === id && (!owner || row.ref.owner.join('/') === owner));
  assert.ok(declaration, kind + ' ' + id);
  return declaration;
}
function bind(input, kind, id, role, name, owner) {
  input.options.names.push({ ref: findDeclaration(input, kind, id, owner).ref, role, name });
}

