test('aggregate lexical identities never leak into converter method syntax', async () => {
  for (const id of ['stock-count', '计数器𝄞']) {
    const input = inputFixture();
    const rename = value => {
      if (Array.isArray(value)) return value.map(rename);
      if (!value || typeof value !== 'object') return value;
      const ref = value.context === 'counter' && typeof value.kind === 'string' && Array.isArray(value.owner);
      return Object.fromEntries(Object.entries(value).map(([key, member]) => [key,
        ref && key === 'id' && value.kind === 'aggregate' && member === 'Counter' ? id :
        ref && key === 'owner' ? member.map(part => part === 'Counter' ? id : part) : rename(member)]));
    };
    const changed = rename(input);
    if (id.includes('计')) {
      const ref = findDeclaration(changed, 'aggregate', id).ref;
      changed.options.names.push(...[['protocol', 'CounterProtocol'], ['state', 'CounterState'], ['computations', 'CounterComputations'],
        ['rule-params', 'CounterRuleParams']].map(([role, name]) => ({ ref, role, name })));
    }
    const { entries } = await renderInput(changed);
    const source = body(entries.find(row => row.kind === 'converter'));
    assert.doesNotMatch(source, /def (?:encode|decode)(?:stock-count|计数器)/);
    assert.ok(source.includes(id === 'stock-count' ? 'def encodeStockCountCountSet' : 'def encodeCounterProtocolCountSet'));
  }
});

