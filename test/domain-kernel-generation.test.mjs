test('every independently authored project body matches completely after the one header', async () => {
  const { entries } = await rendered();
  const byPath = new Map(entries.map(entry => [entry.path, entry]));
  const referencePaths = new Map(referenceFiles().map(file => [relative(domainKernelReference, file).replaceAll('\\', '/'), file]));
  const mismatches = [];
  for (const [path, file] of referencePaths) {
    const expected = readFileSync(file, 'utf8');
    const entry = byPath.get(path);
    if (!entry) { mismatches.push({ path, reason: 'missing output' }); continue; }
    const formatHeader = headerFor(path);
    assert.ok(entry.content.startsWith(formatHeader), path + ' generated header');
    const actual = entry.content.slice(formatHeader.length);
    if (actual !== expected) {
      const expectedLines = expected.split('\n'), actualLines = actual.split('\n');
      const line = expectedLines.findIndex((text, index) => text !== actualLines[index]);
      mismatches.push({ path, line: line + 1, expected: expectedLines[line], actual: actualLines[line] });
    }
  }
  assert.deepEqual(mismatches, [], 'Independent reference mismatches (no golden refresh permitted)');
  const additional = entries.filter(entry => !referencePaths.has(entry.path));
  assert.ok(additional.length > 0, 'generated basic tests are separate from independent project/oracle bodies');
  assert.ok(additional.every(entry => entry.path.startsWith('modules/glue/src/test/scala/')), 'only declared generated-test support is additional');
});

test('all final entries have canonical UTF-8 mappings and complete real output dependency closure', async () => {
  const { model, entries } = await rendered();
  const paths = new Set(entries.map(entry => entry.path));
  assert.equal(paths.size, entries.length, 'one entry per actual output');
  const canonicalSources = new Set(model.artifacts.flatMap(artifact => artifact.sources).map(source => 'source:' + source.document + '#' + source.pointer));
  for (const entry of entries) {
    assert.ok(Object.isFrozen(entry));
    assert.deepEqual(entry.productFootprint, footprint);
    assert.ok(entry.knowledgeIds.length, entry.path + ' canonical provenance');
    assert.ok(entry.codeMappings.length, entry.path + ' mapped body');
    validateCodeMappings(entry);
    for (const id of entry.knowledgeIds) assert.ok(canonicalSources.has(id), 'no invented source: ' + id);
    for (const id of entry.knowledgeIds) assert.ok(entry.codeMappings.some(mapping => mapping.knowledgeKey === id), 'source has actual mapped text: ' + id);
    const contentBytes = Buffer.from(entry.content);
    for (const mapping of entry.codeMappings) {
      assert.ok(mapping.span.start >= Buffer.byteLength(headerFor(entry.path)));
      assert.equal(contentBytes.subarray(mapping.span.start, mapping.span.end).toString('utf8'), mapping.span.text);
    }
    for (const dep of entry.deps) {
      assert.ok(paths.has(dep), entry.path + ' has real dependency ' + dep);
      assert.notEqual(dep, entry.path);
      for (const transitive of entries.find(row => row.path === dep).deps) assert.ok(entry.deps.includes(transitive), entry.path + ' transitive closure');
    }
  }
});

