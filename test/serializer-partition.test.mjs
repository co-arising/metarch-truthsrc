const root = new URL('./fixtures/tickets-domain-v4-products/', import.meta.url);
const json = url => JSON.parse(readFileSync(url, 'utf8'));
const manifest = json(new URL('../generators/scala-cqrs-domain-v2/generator.json', import.meta.url));
const options = json(new URL('options.json', root));
const pkg = options.packages[0].package;
const context = options.packages[0].context;
const marker = '// @generated by truthsrc scala-cqrs-domain:1\n';
const serializerPath = packageName => pathFor(packageName, 'infrastructure/serialization/DomainProtoSerializer.scala');

// An independent, compact stress input: extend a checked-in nonbank request, not a bank checkout.
function fixture(ids = [], packageName = pkg) {
  const request = structuredClone(readProductRequest(fileURLToPath(new URL('files.json', root))));
  const domain = request.documents.find(d => d.id === 'domain').value;
  const layout = request.documents.find(d => d.id === 'references').value.layout;
  for (const id of ids) {
    const index = domain.valueObjects.length;
    domain.valueObjects.push({ context, name: id, version: '1', dataType: 'String' });
    layout.declarations.push({ ref: { context, kind: 'type', owner: [], id }, valueType: { form: 'primitive', name: 'string' },
      source: { document: 'domain', pointer: '/valueObjects/' + index }, dependencies: [] });
  }
  const compilation = compileProductSet(request);
  assert.deepEqual(compilation.diagnostics, []);
  const boundOptions = { ...options, packages: [{ context, package: packageName }] };
  const args = { compilation, manifest, options: boundOptions };
  const first = generate(args);
  assert.deepEqual(first.diagnostics, []);
  assert.deepEqual(generate(args), first);
  const products = Object.fromEntries(compilation.result.products.map(p => [p.id, p.payload]));
  return { entries: first.plan.entries, nodes: serializationModel(products, boundOptions), packageName };
}

// The pre-partition serializer, including its original generated marker and whitespace.
function legacy(nodes, packageName = pkg, index = 0) {
  const pb = packageName + '.infrastructure.proto.';
  return marker + 'package ' + packageName + '.infrastructure.serialization\n\nimport akka.serialization.SerializerWithStringManifest\nimport scalapb.GeneratedMessage\n\nfinal class DomainProtoSerializer extends SerializerWithStringManifest {\n' +
    '  override def identifier: Int = ' + (741000 + index) + '\n' +
    '  override def manifest(value: AnyRef): String = value match {\n' + nodes.map(n => '    case _: ' + pb + n.name + ' => ' + JSON.stringify(n.name) + '\n').join('') +
    '    case _ => throw new IllegalArgumentException("unregistered protobuf value")\n  }\n' +
    '  override def toBinary(value: AnyRef): Array[Byte] = { manifest(value); value.asInstanceOf[GeneratedMessage].toByteArray }\n' +
    '  override def fromBinary(bytes: Array[Byte], manifest: String): AnyRef = manifest match {\n' + nodes.map(n => '    case ' + JSON.stringify(n.name) + ' => ' + pb + n.name + '.parseFrom(bytes)\n').join('') +
    '    case _ => throw new IllegalArgumentException("unknown protobuf manifest")\n  }\n}\n';
}

function checkPartition({ entries, nodes, packageName }) {
  const facade = entries.find(e => e.path === serializerPath(packageName));
  const parts = entries.filter(e => /DomainProtoSerializerPart\d+\.scala$/.test(e.path))
    .sort((a, b) => Number(a.path.match(/Part(\d+)/)[1]) - Number(b.path.match(/Part(\d+)/)[1]));
  assert.ok(legacy(nodes, packageName).length > 65536);
  assert.ok(parts.length >= 2);
  assert.ok([facade, ...parts].every(e => e.content.length <= 60000));
  assert.match(facade.content, /final class DomainProtoSerializer extends SerializerWithStringManifest with DomainProtoSerializerPart0/);
  assert.match(facade.content, /override def identifier: Int = 741000/);
  assert.ok(facade.content.includes('override def toBinary(value: AnyRef): Array[Byte] = { manifest(value); value.asInstanceOf[GeneratedMessage].toByteArray }'));
  assert.deepEqual(facade.deps, [parts[0].path]);
  assert.deepEqual(facade.knowledgeIds, [...new Set(nodes.flatMap(n => n.sources.map(knowledge)))]);
  const allPaths = new Set(entries.map(e => e.path));
  const pb = packageName + '.infrastructure.proto.';
  const manifestNames = [], binaryNames = [];
  parts.forEach((part, i) => {
    const rows = [...part.content.matchAll(/^    case _: (\S+) => ("[^"]+")$/gm)];
    const binaryRows = [...part.content.matchAll(/^    case ("[^"]+") => (\S+)\.parseFrom\(bytes\)$/gm)];
    assert.ok(rows.length > 0 && rows.length <= 128);
    const names = rows.map(row => JSON.parse(row[2]));
    assert.deepEqual(rows.map(row => row[1]), names.map(name => pb + name));
    assert.deepEqual(binaryRows.map(row => JSON.parse(row[1])), names);
    assert.deepEqual(binaryRows.map(row => row[2]), names.map(name => pb + name));
    manifestNames.push(...names); binaryNames.push(...binaryRows.map(row => JSON.parse(row[1])));
    assert.deepEqual(part.productFootprint, facade.productFootprint);
    assert.deepEqual(part.knowledgeIds, [...new Set(nodes.filter(n => names.includes(n.name)).flatMap(n => n.sources.map(knowledge)))]);
    assert.deepEqual(part.deps, ['app/protobuf/' + packageName.replaceAll('.', '_') + '_domain.proto', ...(i + 1 < parts.length ? [parts[i + 1].path] : [])]);
    assert.ok(part.deps.every(path => allPaths.has(path)));
    assert.ok(!/\b(?:catch|try|null)\b/.test(part.content));
    if (i + 1 < parts.length) {
      assert.ok(part.content.includes('trait DomainProtoSerializerPart' + i + ' extends DomainProtoSerializerPart' + (i + 1)));
      assert.ok(part.content.includes('case _ => manifestPart' + (i + 1) + '(value)'));
      assert.ok(part.content.includes('case _ => fromBinaryPart' + (i + 1) + '(bytes, manifest)'));
      assert.ok(!part.content.includes('throw new IllegalArgumentException'));
    } else {
      assert.ok(part.content.includes('case _ => throw new IllegalArgumentException("unregistered protobuf value")'));
      assert.ok(part.content.includes('case _ => throw new IllegalArgumentException("unknown protobuf manifest")'));
    }
  });
  assert.deepEqual(manifestNames, nodes.map(n => n.name));
  assert.deepEqual(binaryNames, manifestNames);
  assert.equal(new Set(manifestNames).size, nodes.length);
  assert.equal(Math.max(...manifestNames.map(n => n.length)), Math.max(...nodes.map(n => n.name.length)));
  return parts;
}

test('small real domain serializers retain their exact legacy bytes', () => {
  const f = fixture();
  assert.equal(f.entries.find(e => e.path === serializerPath(pkg)).content, legacy(f.nodes));
  assert.ok(!f.entries.some(e => /DomainProtoSerializerPart\d+\.scala$/.test(e.path)));
});

test('large nonbank serializers yield complete deterministic bounded source plans', () => {
  const f = fixture(Array.from({ length: 720 }, (_, i) => 'PassengerCarrier' + String(i).padStart(4, '0')));
  checkPartition(f);
  const baseline = fixture();
  for (const entry of baseline.entries.filter(e => e.path.endsWith('Adapters.scala'))) {
    assert.deepEqual(f.entries.find(e => e.path === entry.path), entry);
  }
});

test('long manifests and packages are measured, never truncated or dispatched by hash', () => {
  const packageName = 'example.' + 'a'.repeat(70) + '.tickets';
  const f = fixture(Array.from({ length: 130 }, (_, i) => 'Passenger' + 'x'.repeat(175) + String(i).padStart(4, '0')), packageName);
  const parts = checkPartition(f);
  assert.ok(parts.some(p => [...p.content.matchAll(/^    case _: /gm)].length < 100));
});

function simpleContext(ids) {
  return { options, products: {
    'reference-layout': { contexts: [context], declarations: ids.map((id, i) => ({
      ref: { context, kind: 'type', owner: [], id }, valueType: { form: 'primitive', name: 'string' },
      source: { document: 'domain', pointer: '/valueObjects/' + i }, dependencies: [],
    })) },
    'domain-dependencies': { events: [] }, 'domain-folds': { defaults: [] },
    'exact-value-types': [], 'exact-value-codecs': [],
  } };
}

test('the entire existing 64K window stays byte-identical and the next case partitions', () => {
  const name = i => 'Carrier' + String(i).padStart(4, '0') + 'PB';
  const rowSize = legacy([{ name: name(0) }]).length - legacy([]).length;
  const count = Math.floor((65536 - legacy([]).length) / rowSize);
  const ids = Array.from({ length: count }, (_, i) => name(i).slice(0, -2));
  const small = simpleContext(ids), nodes = serializationModel(small.products, small.options);
  const expected = legacy(nodes);
  assert.ok(expected.length > 60000 && expected.length <= 65536);
  assert.equal(renderAdapters(small, [])[0].content, expected);
  const large = simpleContext([...ids, name(count).slice(0, -2)]);
  const entries = renderAdapters(large, []);
  assert.ok(entries.length > 1);
  assert.ok(entries.every(e => e.content.length <= 60000));
});

test('one unsplittable manifest case fails instead of emitting an oversized helper', () => {
  const input = simpleContext(['Carrier' + 'x'.repeat(17000)]);
  assert.throws(() => renderAdapters(input, []), /protobuf serializer case exceeds bounded source entry/);
});
