// Domain-entity family derivation and emission tests (emitter-unification plan
// F2/F4, rulings 2026-11-23 §17). The acceptance itself is `node emitter/parity.mjs`
// (golden parity + double-run determinism + 21-case battery); this suite pins
// the knowledge→contract derivation seam, the fail-closed diagnostics, the
// flip-manifest scoping, codeMappings anchor preservation, and the emission
// wrapper's replacement guarantees.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseStrictJson } from '../lib/strict-json.mjs';
import { deriveDomainEntities } from '../lib/derivation/domain-entity.mjs';
import { isDomainEntityFlipped, withFlippedDomainEntities } from '../lib/derivation/domain-entity-emission.mjs';
import { renderDomainEntityFiles, runNegatives } from '../emitter/families/domain-entity.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GOLDEN = path.join(ROOT, 'test/reference/curated/domain-entity/v1');
const FIXTURE = path.join(ROOT, 'test/fixtures/domain-entity-v1');

const products = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'knowledge-products.json'), 'utf8'));
const contract = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'input.json'), 'utf8'));

const classicAggregateEntries = layoutDeclarations => {
  const packages = new Map(products().options.packages.map(p => [p.context, p.package.replaceAll('.', '/')]));
  const aggs = layoutDeclarations.filter(d => d.ref.kind === 'aggregate');
  const entries = aggs.flatMap(d => {
    const pkgRoot = packages.get(d.ref.context);
    return [
      {
        path: 'app/' + pkgRoot + '/domain/' + d.ref.id + 'State.scala',
        content: '// @generated by truthsrc scala-cqrs-domain:1\npackage example.bankwealth.domain\n',
        kind: 'state',
        deps: [],
        knowledgeIds: ['source:' + d.source.document + '#' + d.source.pointer],
        productFootprint: [
          { id: 'reference-layout', version: '1' },
          { id: 'domain-folds', version: '6' },
          { id: 'exact-value-types', version: '1' },
          { id: 'domain-dependencies', version: '6' },
        ],
        merge: null,
      },
      {
        path: 'app/' + pkgRoot + '/domain/entities/' + d.ref.id + 'Entity.scala',
        content: '// @generated by truthsrc scala-cqrs-domain:1\npackage example.bankwealth.domain.entities\n',
        kind: 'entity',
        deps: [],
        knowledgeIds: ['source:' + d.source.document + '#' + d.source.pointer],
        productFootprint: [
          { id: 'reference-layout', version: '1' },
          { id: 'domain-folds', version: '6' },
          { id: 'exact-value-types', version: '1' },
          { id: 'domain-dependencies', version: '6' },
        ],
        merge: null,
      },
    ];
  });
  return [...entries, {
    path: 'app/example/bankwealth/domain/CreditBalanceAggregate.scala',
    content: '// classic layered aggregate, untouched\n',
    kind: 'aggregate',
    deps: [],
    knowledgeIds: ['source:x#/y'],
    productFootprint: [{ id: 'reference-layout', version: '1' }],
    merge: null,
  }];
};

test('the derived domain-entity contract deep-equals the curated technical input', () => {
  const data = products();
  const derived = deriveDomainEntities(data, data.options);
  assert.deepEqual(derived, contract());
  assert.equal(derived.aggregates.length, 3);
  const fundOrder = derived.aggregates.find(a => a.name === 'FundOrder');
  assert.equal(fundOrder.fields.length, 30);
  assert.equal(fundOrder.events.length, 32);
  const amount = fundOrder.fields.find(f => f.name === 'amount');
  assert.deepEqual(amount.default, { kind: 'nominal-exact-unit-decimal', context: 'bankwealth', name: 'Money', amount: '0.00', unit: 'CNY' });
});

test('the wrapper renders manifest contexts through the family, byte-equal to the golden tree with exact codeMappings', () => {
  const data = products();
  const context = { products: data, options: data.options };
  const classic = classicAggregateEntries(data['reference-layout'].declarations);
  const flipped = withFlippedDomainEntities(() => classic, context);

  assert.equal(flipped.length, classic.length);
  assert.equal(flipped.filter(e => e.kind === 'aggregate').length, 1);
  const states = flipped.filter(e => e.kind === 'state');
  const entities = flipped.filter(e => e.kind === 'entity');
  assert.equal(states.length, 3);
  assert.equal(entities.length, 3);

  for (const entry of [...states, ...entities]) {
    const golden = fs.readFileSync(path.join(GOLDEN, entry.path), 'utf8');
    assert.equal(entry.content, golden, entry.path);
    assert.equal(entry.merge, null);
    assert.deepEqual(entry.productFootprint, [
      { id: 'reference-layout', version: '1' },
      { id: 'domain-folds', version: '6' },
      { id: 'exact-value-types', version: '1' },
      { id: 'domain-dependencies', version: '6' },
    ]);
  }
  for (const entity of entities) {
    assert.equal(entity.codeMappings.length, 1);
    const m = entity.codeMappings[0];
    assert.match(m.knowledgeKey, /^source:bank-v1#\/aggregates\/\d+$/);
    const buf = Buffer.from(entity.content, 'utf8');
    assert.equal(buf.subarray(m.span.start, m.span.end).toString('utf8'), m.span.text);
    assert.match(m.span.text, /^  def empty: State = State\(.*\)\n$/);
    assert.deepEqual(m.scope, m.span);
  }
  // Double-run determinism
  assert.deepEqual(withFlippedDomainEntities(() => classic, context), flipped);
});

test('the wrapper passes through projects without any manifest aggregate declaration', () => {
  const empty = { options: { packages: [{ context: 'other', package: 'example.other' }] }, 'reference-layout': { declarations: [] }, 'domain-folds': { defaults: [] }, 'exact-value-types': [] };
  const classic = [{ path: 'app/example/other/domain/OrderState.scala', content: 'x', kind: 'state', deps: [], knowledgeIds: [], productFootprint: [], merge: null }];
  assert.deepEqual(withFlippedDomainEntities(() => classic, { products: empty, options: empty.options }), classic);
  assert.equal(isDomainEntityFlipped('other'), true);
  assert.equal(isDomainEntityFlipped('other', { emission: 'classic' }), false);
});

test('the wrapper refuses a classic plan that does not carry exactly the state/entity flip set or carries orphans', () => {
  const data = products();
  const context = { products: data, options: data.options };
  const classic = classicAggregateEntries(data['reference-layout'].declarations);
  const minusOne = classic.filter(e => e.path !== 'app/example/bankwealth/domain/CreditBalanceState.scala');
  assert.throws(() => withFlippedDomainEntities(() => minusOne, context),
    /the classic aggregate plan must carry exactly the state\/entity flip set: 5 of 6 classic files present/);
  const extra = [...classic, { ...classic[0], path: 'app/example/bankwealth/domain/InventedState.scala' }];
  assert.throws(() => withFlippedDomainEntities(() => extra, context),
    /classic aggregate plan carries a state\/entity file outside the derived contract: app\/example\/bankwealth\/domain\/InventedState.scala/);
});

test('derivation fails closed on missing declarations and unsupported forms', () => {
  const data = products();
  assert.throws(() => deriveDomainEntities({ ...data, 'reference-layout': { declarations: [] } }, data.options),
    /DE_DERIVATION: no aggregate declarations/);
  assert.throws(() => deriveDomainEntities(data, { packages: [] }),
    /DE_DERIVATION: context bankwealth has no package binding/);
});

test('embedded negatives battery rejects every malformed input with DE_INPUT', () => {
  const result = runNegatives(contract());
  assert.equal(result.rejected, result.expected);
  assert.deepEqual(result.failures, []);
  assert.ok(result.expected >= 20);
  // Also confirm renderDomainEntityFiles returns 6 files in order
  assert.equal(renderDomainEntityFiles(contract()).length, 6);
});
