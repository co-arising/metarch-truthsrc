// scala-cqrs-es-ddl-metarch.test.mjs — V4-14 gate: the dual-dialect projection DDL face
// (gen_projection_ddl.mjs port) byte-identical to the live conf/sql files.
//   • conf/sql/2.sql       — the ③-layer GATED DecisionViews minus graph cards (S2-65: no SQL
//                            dialect) minus mongo document views (2026-10-10 redesign: old
//                            tables not dropped = rollback-safe), the deterministic type map
//                            (description/content/info→TEXT·payloadJson→MEDIUMTEXT 毒丸判例)
//                            and faithful sorted keys as PRIMARY KEY. Corpus: 19 views.
//   • conf/sql/5-pgvector.sql — the M3 vector dialect over the ①-layer vectorViews slot
//                            (不经 ③层门): CREATE EXTENSION + camel→snake columns +
//                            declaration-order composite PK + HNSW index via distance→ops.
// Ledger parity: 2.sql families = the承载视图 sourceAggregates union (bounded-wide); the
// vector DDL is families=[] (vector views have no sourceAggregates truth source — same 口径 as
// VectorSearchApiController); noteIds = the derived CONTAINER carries its views' note ids
// (S7 #1c — DDL 是视图的派生容器·挂载体视图号).
import { equal, ok } from 'node:assert';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { plan } from '../src/core/generate.mjs';

const GEN = join(import.meta.dirname, '..', 'generators', '_deprecated', 'scala-cqrs-es-ddl');
const CANON = join(import.meta.dirname, '..', 'golden', 'scala-cqrs-es-metarch', 'model-catalog.canonical.json');
const GOLD = join(import.meta.dirname, '..', 'golden', 'scala-cqrs-es-ddl-metarch', 'expected');

const { entries } = await plan({ canonicalFile: CANON, generatorDir: GEN, options: {} });
equal(entries.length, 2);
for (const e of entries) {
  const want = readFileSync(join(GOLD, e.path), 'utf8');
  equal(e.content, want, `byte identity: ${e.path}`);
}

const mysql = entries.find((e) => e.path === 'conf/sql/2.sql');
const vector = entries.find((e) => e.path === 'conf/sql/5-pgvector.sql');

// 2.sql: header + one CREATE TABLE per gated DecisionView (graph/mongo excluded)
ok(mysql.content.startsWith('-- GENERATED by gen_projection_ddl.mjs (EP_Generated_Patch_Pipeline §九)\n'), 'mysql header stamp');
equal((mysql.content.match(/^CREATE TABLE IF NOT EXISTS /gm) || []).length, 19, '19 gated non-graph non-mongo DecisionViews (corpus)');
ok(mysql.content.includes('`content` TEXT'), 'content → TEXT (S2-75 毒丸判例)');
ok(mysql.content.includes('PRIMARY KEY (`noteId`, `questionId`)'), 'composite key faithful + sorted (CaptureNote)');
ok(!/`payloadJson` VARCHAR/.test(mysql.content), 'payloadJson never VARCHAR (MEDIUMTEXT when present)');
equal(mysql.families.length > 0, true, '2.sql families = sourceAggregates union (bounded-wide)');
ok(mysql.noteIds.length > 0, '2.sql noteIds = the承载视图 readModel note ids (container carries载体号)');

// 5-pgvector.sql: the vector slot
ok(vector.content.startsWith('-- GENERATED by gen_projection_ddl.mjs (M3 vector dialect · pgvector)\n'), 'vector header stamp');
ok(vector.content.includes('CREATE EXTENSION IF NOT EXISTS vector;'), 'CREATE EXTENSION');
ok(vector.content.includes('embedding vector(1024) NOT NULL'), 'embedding column vector(1024)');
ok(vector.content.includes('PRIMARY KEY (tenant_id, source_type, source_id)'), 'declaration-order composite PK');
ok(vector.content.includes('USING hnsw (embedding vector_cosine_ops)'), 'HNSW + cosine ops');
equal(vector.families.length, 0, 'vector DDL is a global artifact (families=[] — no sourceAggregates truth)');
equal(vector.noteIds.length, 1, 'vector noteIds = the KnowledgeSemanticView note id');

console.log('scala-cqrs-es-ddl: conf/sql/2.sql + conf/sql/5-pgvector.sql byte-identical to live');
