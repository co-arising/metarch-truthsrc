test('implementation selector and exported view keep handwritten evidence separate and file-only', async t => {
  const f = fixture(t); await generate(f);
  const query = projectQueryCli('query-project', ['--project', f.project, '--out', f.out, '--implementation', 'repository']);
  assert.equal(query.state, 'mapped'); assert.equal(query.result.length, 1);
  assert.equal(query.result[0].generationInput, 'matches-last-generated-input');
  assert.equal(query.result[0].spanVerified, false); assert.equal(query.runtimeVerified, false);
  assert.throws(() => queryProject({ ...f, file: query.result[0].file }), /outside output/);
  assert.throws(() => queryProject({ ...f, implementation: 'repository', line: 1 }), /file precision/);
  assert.throws(() => queryProject({ ...f, implementation: 'repository', knowledge: 'Route' }), /exactly one/);
  const view = viewProject(f);
  assert.equal(view.implementations.files, 3);
  assert.equal(view.evidence.filter(row => row.id.startsWith('implementation:')).length, 3);
  assert.ok(view.nodes.length > 0, 'module seam signatures are selected by the default view');
  const root = view.implementations.roots[0].path;
  assert.throws(() => viewProjectCli(['--project', f.project, '--out', f.out, '--html', join(root, 'view.html')]), /handwritten source roots/);
  assert.equal(existsSync(join(root, 'view.html')), false);
});
