async function fixture(t) {
  const root = mkdtempSync(join(realpathSync(tmpdir()), 'truthsrc-verify-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const initialized = initProject([join(root, 'counter')]), out = join(initialized.root, 'generated');
  await projectCli('generate-project', ['--project', initialized.project, '--out', out]);
  return { ...initialized, out };
}

test('verifies current producer, complete graph anchors and required source spans read-only', async t => {
  const f = await fixture(t), before = readFileSync(projectGraphFile(f.project));
  const inspected = inspectProject({ project: f.project, out: f.out, required: ['SetCount'] });
  assert.equal(inspected.result.passed, true, JSON.stringify(inspected.result.diagnostics));
  assert.ok(Object.values(inspected.result.checks).every(Boolean));
  assert.ok(inspected.result.counts.spans > 0);
  assert.ok(inspected.result.coverage[0].passed);
  assert.equal(inspected.result.runtimeVerified, false);
  assert.ok(readFileSync(projectGraphFile(f.project)).equals(before));
  assert.deepEqual(verifyProject({ project: f.project, out: f.out, required: ['SetCount'] }), inspected.result);
  assert.ok(inspected.query.forward('SetCount').some(row => row.origins.length));
});

test('rejects modified generated bytes without repairing them', async t => {
  const f = await fixture(t), valid = inspectProject({ project: f.project, out: f.out });
  assert.equal(valid.result.passed, true, JSON.stringify(valid.result.diagnostics));
  const file = join(f.out, valid.result.files.find(row => row.file.endsWith('.scala')).file);
  const changed = readFileSync(file, 'utf8') + '\n// unexpected edit\n';
  writeFileSync(file, changed);
  assert.equal(verifyProject({ project: f.project, out: f.out }).passed, false);
  assert.equal(readFileSync(file, 'utf8'), changed);
});

test('detects removed second span even if exchange and graph agree', async t => {
  const f = await fixture(t), inputs = JSON.parse(readFileSync(join(f.out, '.truthsrc/inputs.json')));
  const store = new SqliteKnowledgeGraphStore(projectGraphFile(f.project));
  try {
    const selection = { project: f.project, snapshot: inputs.graph.snapshot, generation: inputs.graph.generation };
    const published = structuredClone(store.queryCodeAnchors(selection)), row = Object.values(published.anchors.anchors).find(rows => rows.length > 1);
    assert.ok(row, 'fixture must contain more than one location for a knowledge key');
    row.pop();
    store.publishCodeAnchors({ ...selection, ...published, replace: true });
    writeFileSync(join(f.out, 'anchors.json'), JSON.stringify(published.anchors));
  } finally { store.close(); }
  const result = verifyProject({ project: f.project, out: f.out });
  assert.equal(result.passed, false);
  assert.match(result.diagnostics[0].message, /associations differ/);
});

