for (const mode of ['empty', 'wrong-identity']) test(`rejects ${mode} persisted graph identity associations`, async t => {
  const f = await fixture(t), input = JSON.parse(readFileSync(join(f.out, '.truthsrc/inputs.json')));
  const store = new SqliteKnowledgeGraphStore(projectGraphFile(f.project));
  try {
    const selection = { project: f.project, snapshot: input.graph.snapshot, generation: input.graph.generation };
    const published = structuredClone(store.queryCodeAnchors(selection));
    if (mode === 'empty') published.receipt.associations = [];
    else {
      const row = published.receipt.associations.find(row => row.identities.length);
      const other = input.sourceIndex.records.find(record => !row.identities.includes(record.identity));
      row.identities = [other.identity];
    }
    store.publishCodeAnchors({ ...selection, ...published, replace: true });
  } finally { store.close(); }
  const result = verifyProject({ project: f.project, out: f.out });
  assert.equal(result.passed, false);
  assert.match(result.diagnostics[0].message, /identity associations differ/);
});

test('rejects invented symbol certification even when graph and exchange agree', async t => {
  const f = await fixture(t), input = JSON.parse(readFileSync(join(f.out, '.truthsrc/inputs.json')));
  const store = new SqliteKnowledgeGraphStore(projectGraphFile(f.project));
  try {
    const selection = { project: f.project, snapshot: input.graph.snapshot, generation: input.graph.generation };
    const published = structuredClone(store.queryCodeAnchors(selection));
    const location = Object.values(published.anchors.anchors).flat().find(row => row.span && row.span.end - row.span.start > 4);
    location.symbol = 'ZZZZ'; location.verification.level = 'symbol'; location.verification.symbolVerified = true;
    location.verification.symbolEvidence = { symbol: 'ZZZZ', method: 'invented-parser', span: { start: location.span.start, end: location.span.start + 4, text: 'ZZZZ' } };
    store.publishCodeAnchors({ ...selection, ...published, replace: true });
    writeFileSync(join(f.out, 'anchors.json'), JSON.stringify(published.anchors));
  } finally { store.close(); }
  const result = verifyProject({ project: f.project, out: f.out });
  assert.equal(result.passed, false);
  assert.match(result.diagnostics[0].message, /symbol/);
});

test('technical binding forward lookup never matches a sibling pointer by document identity', async t => {
  const f = await fixture(t), captured = captureProject(f.project, { roundtripCheck: false });
  const original = JSON.parse(readFileSync(join(f.out, 'anchors.json'))), location = structuredClone(Object.values(original.anchors).flat().find(row => row.span));
  const document = captured.request.documents[0].id;
  captured.request = { ...captured.request, documents: captured.request.documents.map((doc, index) => index ? doc :
    { ...doc, value: { ...doc.value, rows: [{ name: 'first' }, { name: 'second' }] } }) };
  captured.sources.push({ document, file: join(f.root, 'technical.json'), sha256: 'fixture', bytes: 0 });
  captured.config = { ...captured.config, canonicalId: 'other-canonical-id' };
  const session = createProjectQuerySession({ captured, anchors: { version: original.version, anchors: { ['source:' + document + '#/rows/1']: [location] } } });
  assert.equal(session.forward('source:' + document + '#/rows/0').length, 0);
  assert.equal(session.forward('source:' + document + '#/rows/1').length, 1);
});

test('requirements reject FIFO and oversized inputs before full reads', async t => {
  const f = await fixture(t), fifo = join(f.root, 'fifo'), large = join(f.root, 'large.json');
  execFileSync('/usr/bin/mkfifo', [fifo]);
  assert.throws(() => verifyProjectCli(['--project', f.project, '--out', f.out, '--requirements', fifo]), /regular/);
  writeFileSync(large, ''); truncateSync(large, 9 * 1024 * 1024);
  assert.throws(() => verifyProjectCli(['--project', f.project, '--out', f.out, '--requirements', large]), /bounded/);
});
