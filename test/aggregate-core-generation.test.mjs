import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { aggregateCoreFixture, aggregateCoreReference } from './aggregate-core-fixture.mjs';
import { buildModels } from '../generators/scala-cqrs-aggregate-core-v1/build-models.mjs';
import { render } from '../generators/scala-cqrs-aggregate-core-v1/render.mjs';
import { generate } from '../generators/scala-cqrs-aggregate-core-v1/generate.mjs';
import { validateCodeMappings } from '../src/core/code-mappings.mjs';

const manifest = JSON.parse(readFileSync(fileURLToPath(new URL('../generators/scala-cqrs-aggregate-core-v1/generator.json', import.meta.url))));
const referenceFiles = (directory, prefix = '') => readdirSync(directory + '/' + prefix, { withFileTypes: true }).flatMap(entry => {
  const path = prefix ? prefix + '/' + entry.name : entry.name;
  return entry.isDirectory() ? referenceFiles(directory, path) : [path];
}).sort();

test('complete aggregate-core production body matches the independently authored reference', () => {
  const f = aggregateCoreFixture();
  const model = buildModels({ products: f.products, options: f.config.options });
  const entries = render(model, manifest.products.map(({ id, version }) => ({ id, version })));
  const production = entries.filter(entry => entry.kind !== 'generated-test');
  assert.deepEqual(production.map(entry => entry.path).sort(), referenceFiles(aggregateCoreReference));
  for (const entry of production) {
    const reference = readFileSync(aggregateCoreReference + '/' + entry.path, 'utf8');
    const header = (entry.path.endsWith('.properties') ? '# ' : '// ') + '@generated by truthsrc scala-cqrs-aggregate-core:1\n';
    assert.equal(entry.content, header + reference, entry.path);
    assert.ok(entry.codeMappings.length > 0, entry.path);
    validateCodeMappings(entry);
  }
  const planned = generate({ compilation: f.compilation, manifest, options: f.config.options });
  assert.deepEqual(planned.diagnostics, []);
  assert.deepEqual(planned.plan.entries, generate({ compilation: f.compilation, manifest, options: f.config.options }).plan.entries);
  assert.equal(planned.plan.entries.length, entries.length);
  assert.ok(entries.every(entry => entry.deps.every(dep => entries.some(target => target.path === dep))));
  assert.ok(entries.some(entry => entry.kind === 'generated-test'));
  assert.ok(!entries.some(entry => /Entity\.scala$/.test(entry.path)), 'no compatibility carrier alias');
});

test('candidate entry rejects the wrong target profile rather than inferring a migration', () => {
  const f = aggregateCoreFixture();
  assert.throws(() => generate({ compilation: f.compilation, manifest: { ...manifest, targetProfile: 'scala-cqrs-domain-kernel@1' }, options: f.config.options }));
});
