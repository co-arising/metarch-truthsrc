import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, realpathSync, readFileSync, writeFileSync, existsSync, rmSync, cpSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { compileTree } from '../lib/compile.mjs';
import { captureProject, projectCli } from '../lib/project/cli.mjs';

const bank = process.env.TRUTHSRC_BANK_ROOT;
test('current bank uses its actual root project, fourteen products and only named current inputs', { skip: !bank }, async t => {
  const root = mkdtempSync(join(realpathSync(tmpdir()), 'truthsrc-bank-project-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const original = resolve(bank), config = JSON.parse(readFileSync(join(original, 'truthsrc.project.json')));
  const source = join(root, config.tree);
  cpSync(join(original, config.tree), source, { recursive: true });
  for (const d of config.documents) d.file = join(original, d.file);
  config.options.runtimeArtifact.repository = new URL('file://' + join(original, '.local/truthsrc-runtime/maven/')).href;
  config.options.service.externalSourceRoots = [join(original, 'v1/handwritten/scala')];
  const project = join(root, 'truthsrc.project.json'), out = join(root, 'service-source');
  writeFileSync(project, JSON.stringify(config, null, 2) + '\n', { flag: 'wx' });
  const captured = captureProject(project);
  assert.deepEqual(captured.compilation.diagnostics, []);
  assert.equal(captured.compilation.result.products.length, 14);
  assert.equal(captured.canonical.aggregates.length, 3);
  assert.equal(captured.canonical.sagas.length, 2);
  assert.equal(captured.canonical.pipelines.length, 4);
  assert.ok(captured.sources.filter(s => s.file).every(s => !s.file.includes('/v1/tree/') && !s.file.includes('/formal-inputs/') && !s.file.endsWith('/request.json')));
  const args = ['--project', project, '--out', out];
  const plan = await projectCli('generate-project', [...args, '--plan']);
  assert.equal(existsSync(out), false);
  const applied = await projectCli('generate-project', args);
  assert.equal(applied.applied, true);
  assert.equal(applied.result.total, plan.plan.entries.length);
  for (const name of ['SipPlan', 'FundOrder', 'CreditBalance']) assert.ok(plan.plan.entries.some(e => e.content.includes(name)));
  assert.equal((await projectCli('generate-project', args)).result.written, 0);
  assert.equal(compileTree(source), JSON.stringify(captured.canonical, null, 2) + '\n');
});
