import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { compileTree } from '../lib/compile.mjs';
import { lowerSagaRuntimeBindingV3 } from '../lib/saga/runtime-binding.mjs';
import { emitStrictFiles } from '../generators/saga-dsl/emit-strict.mjs';
import { emitStrictHostFiles } from '../generators/saga-dsl/emit-strict-host.mjs';
import { emitStrictSpecFiles } from '../generators/saga-dsl/emit-strict-spec.mjs';

const example = fileURLToPath(new URL('../example/saga-money-transfer-serial/', import.meta.url));
const canonical = JSON.parse(compileTree(join(example, 'tree')));
const binding = JSON.parse(readFileSync(join(example, 'bindings.json'), 'utf8'));
const runtimeBinding = JSON.parse(readFileSync(join(example, 'runtime-binding.json'), 'utf8'));
const { plan, diagnostics } = lowerSagaRuntimeBindingV3({ canonical, binding, runtimeBinding });
assert.deepEqual(diagnostics, []);

function emitted(source = canonical) {
  const { model } = emitStrictFiles(plan.sagas[0], source);
  return { model, host: emitStrictHostFiles(model).find(f => f.name === 'FixtureHost.scala').content };
}

test('money Prepare derives value evidence from the real txid-keyed amount folds', () => {
  const { model } = emitted();
  const prepare = model.phases.filter(p => p.runtime === 'Prepare');
  assert.equal(prepare.length, 2);
  assert.deepEqual(prepare.map(p => p.prepareValueEvidence), [
    { mapField: 'reservedAmount', valueSlot: 'amount' },
    { mapField: 'incomingCredits', valueSlot: 'amount' },
  ]);
});

test('money Prepare query and command replies compare durable money, never synthesize a conflicting receipt', () => {
  const { host } = emitted();
  assert.equal((host.match(/durable\.minorUnits == input\.amount\.minorUnits/g) || []).length, 2);
  assert.equal((host.match(/durable\.currency == input\.amount\.currency/g) || []).length, 2);
  assert.match(host, /Reserve_sourcePrepareReceipt\(input\.txid, durable\)/);
  assert.match(host, /Reserve_targetPrepareReceipt\(input\.txid, durable\)/);
  assert.match(host, /MONEY_PREPARE_PAYLOAD_CONFLICT/);
  assert.match(host, /MONEY_PREPARE_TERMINAL_FACT/);
});

test('money safety spec emits explicit refusal and real durable ACK-loss recovery oracles', () => {
  const { model } = emitted();
  const spec = emitStrictSpecFiles(model).find(f => f.name === 'FixtureSafetySpec.scala').content;
  assert.match(spec, /import net\.imadz\.infra\.saga\.strict\.\{ConfirmedReceipt,/);
  assert.match(spec, /import scala\.concurrent\.Future/);
  assert.match(spec, /participants = \(args: SagaModule\.Args\) =>/);
  assert.match(spec, /test-only pre-dispatch target refusal/);
  assert.match(spec, /P19_TEST_PRE_DISPATCH_REFUSAL/);
  assert.match(spec, /case ConfirmedReceipt\(_, receipt\) => durable\.trySuccess\(receipt\); held\.future/);
  assert.match(spec, /kit\.stop\(first\)/);
  assert.match(spec, /StrictSagaCoordinator\.Reconcile\(recovered\.identity\.get/);
  assert.match(spec, /assert\(executes\.get == 1\)/);
  assert.doesNotMatch(spec, /B3 full saga: compensated \(source confirmed, target safely not executed\)/);
});

test('money Host and safety spec match actual independent application source goldens', () => {
  const { model } = emitted();
  const header = '// @generated by truthsrc run-all:strict-scala\n';
  const files = [...emitStrictHostFiles(model, { header }), ...emitStrictSpecFiles(model, { header })];
  for (const name of ['FixtureHost.scala', 'FixtureSafetySpec.scala']) {
    const expected = readFileSync(new URL(`./golden/money-prepare-evidence/${name}`, import.meta.url), 'utf8');
    assert.equal(files.find(f => f.name === name).content, expected, name);
  }
});

test('money Prepare refuses an additional conflicting origin for the same evidence slot', () => {
  for (const slot of ['txid', 'amount']) {
    const source = structuredClone(canonical);
    source.aggregates.find(a => a.name === 'CreditBalance').events.find(e => e.name === 'ReserveFundsConfirmed')
      .bindings.push({ slot, expr: 'param.resource' });
    assert.throws(() => emitted(source), /Prepare value evidence/);
  }
});

test('money Prepare refuses missing, ambiguous and wrong-value durable folds', () => {
  for (const mutate of [
    a => { a.events.find(e => e.name === 'ReserveFundsConfirmed').foldAssignments = []; },
    a => { const rows = a.events.find(e => e.name === 'ReserveFundsConfirmed').foldAssignments; rows.push(structuredClone(rows[1])); },
    a => { a.events.find(e => e.name === 'ReserveFundsConfirmed').foldAssignments[1].value = 'event.txid'; },
    a => { a.events.find(e => e.name === 'ReserveFundsConfirmed').bindings[1].expr = 'param.resource'; },
    a => { a.stateFields.find(f => f.name === 'reservedAmount').dataType = 'Map[TxId, AccountId]'; },
  ]) {
    const source = structuredClone(canonical);
    mutate(source.aggregates.find(a => a.name === 'CreditBalance'));
    assert.throws(() => emitted(source), /Prepare value evidence/);
  }
});
