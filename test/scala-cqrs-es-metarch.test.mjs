// scala-cqrs-es-metarch.test.mjs — inc4 gate: golden byte identity against LIVE CodegenMain
// output from the REAL metarch truth source (IngestedSystem, multi-module), for the Subdomain
// aggregate. Exercises the @knowledge anchor layer: fields carry noteId, and the hash suffix is
// looked up from the elementHashes sidecar (a slice of the pinned graph export v55).
import { equal, ok } from 'node:assert';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { plan } from '../src/core/generate.mjs';

const GEN = join(import.meta.dirname, '..', 'generators', 'scala-cqrs-es');
const GOLD = join(import.meta.dirname, '..', 'golden', 'scala-cqrs-es-metarch');
const GOLDEN_VERSION = 'af096839';
const elementHashes = JSON.parse(readFileSync(join(GOLD, 'elementHashes.json'), 'utf8'));

const { entries } = await plan({
  canonicalFile: join(GOLD, 'subdomain.canonical.json'),
  generatorDir: GEN,
  options: { generatorVersion: GOLDEN_VERSION, elementHashes },
});
equal(entries.length, 8);
for (const e of entries) {
  const want = readFileSync(join(GOLD, 'expected', e.path), 'utf8');
  equal(e.content, want, `byte identity: ${e.path}`);
}

// anchors actually rendered: the Protocol must carry a @knowledge <uuid>@<hash> line.
const proto = entries.find((e) => e.path.endsWith('SubdomainProtocol.scala')).content;
ok(/@knowledge [0-9a-f-]{36}@[0-9a-f]{16}/.test(proto), 'protocol renders @knowledge anchors with hash');

// a noteId with no sidecar entry falls back to a bare anchor (no @hash) — mirrors internal getOrElse "".
const { entries: noHash } = await plan({
  canonicalFile: join(GOLD, 'subdomain.canonical.json'),
  generatorDir: GEN,
  options: { generatorVersion: GOLDEN_VERSION, elementHashes: {} },
});
const protoNoHash = noHash.find((e) => e.path.endsWith('SubdomainProtocol.scala')).content;
ok(/@knowledge 1d4ff2f9-aa52-4480-822a-3c1c31ab4b53(?!@)/.test(protoNoHash), 'missing hash → bare noteId anchor');

// --- V4-16: the shared value-object face over the FULL-CORPUS canonical ---------------------
// canonical.voCatalog = fieldTree.valueObjects RAW (the engine's VO metadata list); expected
// bytes are the live tree's stamped files. UcStep rides the relics skip list (its live copy is
// handwritten and predates the declaration — the incremental gate never rewrote it).
const CORPUS = join(GOLD, 'full-corpus.canonical.json');
const corpusHashes = JSON.parse(readFileSync(join(GOLD, 'full-corpus.elementHashes.json'), 'utf8'));
const { entries: corpus } = await plan({
  canonicalFile: CORPUS,
  generatorDir: GEN,
  options: { generatorVersion: GOLDEN_VERSION, elementHashes: corpusHashes, relics: { skipValueObjects: ['UcStep'] } },
});
const vos = corpus.filter((e) => e.kind === 'value-object');
equal(vos.length, 30, '30 value objects emitted (31 declared − UcStep relic)');
ok(!corpus.some((e) => e.path.endsWith('UcStep.scala')), 'UcStep skipped as disclosed relic');
equal(corpus.filter((e) => e.families.length === 0).length, 30, 'VO rows are global (families [])');
const VO_STAMP = /^\/\/ @generated by [^\n]*\n/; // generation-run fact — never compared (inc3)
for (const name of ['ConceptDelta', 'CatalogConflict', 'EdgeTarget', 'FieldSpec', 'RuleRef', 'AggregateRelationSpec', 'DoRVerdict', 'ChecklistItem']) {
  const e = vos.find((v) => v.path.endsWith(`${name}.scala`));
  const want = readFileSync(join(GOLD, 'expected', e.path), 'utf8');
  equal(e.content.replace(VO_STAMP, ''), want.replace(VO_STAMP, ''), `vo byte identity: ${name}`);
}
const cd = vos.find((v) => v.path.endsWith('ConceptDelta.scala'));
ok(cd.content.includes('new Reads[ConceptDelta]'), '>22 fields → explicit reads/writes (Function22 wall)');
ok(cd.content.includes('.getOrElse(Nil)'), 'default members → tolerant reads');
ok(vos.find((v) => v.path.endsWith('CatalogConflict.scala')).content.includes('private implicit val instantFormat'), 'Instant member → private instantFormat');
ok(vos.find((v) => v.path.endsWith('EdgeTarget.scala')).content.includes('Json.using[play.api.libs.json.Json.MacroOptions with play.api.libs.json.Json.DefaultValues]'), 'default member → DefaultValues reads');

console.log('✅ scala-cqrs-es-metarch — golden byte identity (Subdomain, 8 kinds, live metarch + @knowledge + VO face 30/30)');
