import test from 'node:test';
import assert from 'node:assert/strict';
import { domainKernelFixture } from './domain-kernel-fixture.mjs';
import { buildModels } from '../generators/scala-cqrs-domain-kernel-v1/build-models.mjs';
import { serializationModel } from '../generators/scala-cqrs-domain-kernel-v1/serialization-model.mjs';
import { productionJobs, renderJobs, render } from '../generators/scala-cqrs-domain-kernel-v1/render.mjs';
import { buildArtifacts, buildTemplate } from '../generators/scala-cqrs-domain-kernel-v1/templates/build.mjs';
import { generatedTestArtifacts, generatedTestsTemplate } from '../generators/scala-cqrs-domain-kernel-v1/templates/generated-tests.mjs';
import { sourceEntry, aggregateSourceEntry } from '../generators/scala-cqrs-domain-kernel-v1/entry.mjs';
import { validateCodeMappings } from '../src/core/code-mappings.mjs';

const fixture = domainKernelFixture();
const model = buildModels({ products: fixture.products, options: fixture.config.options });
const serialization = serializationModel(model);
const footprint = fixture.config.products;
const source = { document: 'counter-domain', pointer: '/aggregates/0' };
const spec = { path: 'modules/kernel/src/main/scala/example/Example.scala', kind: 'rules', sources: [source], footprint, deps: [] };

test('composition preserves the complete family1 plan including mapping offsets and ordering', () => {
  const jobs = productionJobs(model, serialization);
  assert.equal(jobs.length, 14);
  assert.ok(jobs.every(job => !['build', 'generated-test'].includes(job.artifact.kind)));
  const support = [
    ...buildArtifacts(model).map(artifact => ({ artifact, template: out => buildTemplate(artifact, out) })),
    ...generatedTestArtifacts(model, serialization).map(artifact => ({ artifact: { ...artifact, kind: 'generated-test' }, template: out => generatedTestsTemplate(artifact, out) })),
  ];
  const complete = renderJobs([...jobs, ...support], footprint);
  assert.equal(complete.length, 18);
  assert.deepEqual(complete, render(model, serialization, footprint));
  assert.deepEqual(productionJobs(model, serialization).map(job => job.artifact), jobs.map(job => job.artifact));
});

test('new owner uses the same mapper on final UTF-8 bytes without patching an old header', () => {
  const template = out => { out.append('// café 🚚\n'); out.append('object Example {}\n', [source]); };
  const original = sourceEntry(spec, template);
  const candidate = aggregateSourceEntry(spec, template);
  assert.match(original.content, /^\/\/ @generated by truthsrc scala-cqrs-domain-kernel:1\n/);
  assert.match(candidate.content, /^\/\/ @generated by truthsrc scala-cqrs-aggregate-core:1\n/);
  assert.equal(validateCodeMappings(candidate).length, 1);
  const { start, end, text } = candidate.codeMappings[0].span;
  assert.equal(Buffer.from(candidate.content).subarray(start, end).toString(), text);
  assert.notEqual(start, original.codeMappings[0].span.start);
  assert.deepEqual(candidate.knowledgeIds, original.knowledgeIds);
  assert.throws(() => aggregateSourceEntry({ ...spec, owner: 'untrusted' }, template));
  const properties = aggregateSourceEntry({ ...spec, path: 'project/build.properties' }, out => out.append('sbt.version=1.4.9\n'));
  assert.match(properties.content, /^# @generated by truthsrc scala-cqrs-aggregate-core:1\n/);
});

test('composed jobs enforce the whole actual dependency graph before emitting any source', () => {
  let calls = 0;
  const make = (path, directDeps = []) => ({ artifact: { path, kind: 'rules', sources: [source], directDeps }, template: out => { calls++; out.append('object Example {}\n', [source]); } });
  for (const jobs of [
    [make('a.scala', ['missing.scala'])],
    [make('a.scala', ['b.scala']), make('b.scala', ['a.scala'])],
    [make('a.scala'), make('A.scala')],
    [make('valid.scala'), make('last.scala', ['missing.scala'])],
  ]) {
    calls = 0;
    assert.throws(() => renderJobs(jobs, footprint, aggregateSourceEntry));
    assert.equal(calls, 0);
  }
  const entries = renderJobs([make('a.scala', ['b.scala']), make('b.scala', ['c.scala']), make('c.scala')], footprint, aggregateSourceEntry);
  assert.deepEqual(entries[0].deps, ['b.scala', 'c.scala']);
  assert.equal(calls, 3);
});
