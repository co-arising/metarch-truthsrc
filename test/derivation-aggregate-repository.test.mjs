// Aggregate-repository family derivation and emission tests (emitter-unification
// plan F2/F4, rulings 2026-11-23 §20). Pins the knowledge→contract derivation
// seam, 3/3 golden byte parity and double-run determinism, non-manifest
// passthrough, fail-closed missing/orphan/collision guards, and the 18-case
// embedded negative battery.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseStrictJson } from '../lib/strict-json.mjs';
import { deriveAggregateRepositories } from '../lib/derivation/aggregate-repository.mjs';
import {
  isAggregateRepositoryFlipped,
  withFlippedAggregateRepositories,
} from '../lib/derivation/aggregate-repository-emission.mjs';
import { renderAggregateRepositoryFiles, runNegatives } from '../emitter/families/aggregate-repository.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GOLDEN = path.join(ROOT, 'test/reference/curated/aggregate-repository/v1');
const FIXTURE = path.join(ROOT, 'test/fixtures/aggregate-repository-v1');

const products = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'knowledge-products.json'), 'utf8'));
const contract = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'input.json'), 'utf8'));

const classicRepositoryEntries = layoutDeclarations => {
  const packages = new Map(products().options.packages.map(p => [p.context, p.package.replaceAll('.', '/')]));
  const aggs = layoutDeclarations.filter(d => d.ref.kind === 'aggregate');
  const repos = aggs.map(d => {
    const pkgRoot = packages.get(d.ref.context);
    return {
      path: 'app/' + pkgRoot + '/application/aggregates/' + d.ref.id + 'Repository.scala',
      content: '// @generated by truthsrc scala-cqrs-domain:1\npackage example.bankwealth.application.aggregates\n',
      kind: 'aggregate-repository',
      deps: ['app/' + pkgRoot + '/application/aggregates/' + d.ref.id + 'Protocol.scala'],
      knowledgeIds: ['source:' + d.source.document + '#' + d.source.pointer],
      productFootprint: [
        { id: 'reference-layout', version: '1' },
        { id: 'domain-folds', version: '6' },
        { id: 'exact-value-types', version: '1' },
        { id: 'domain-dependencies', version: '6' },
      ],
      merge: null,
    };
  });
  return [...repos, {
    path: 'app/example/bankwealth/infrastructure/bootstrap/CreditBalanceBootstrap.scala',
    content: '// classic bootstrap, untouched\n',
    kind: 'aggregate-bootstrap',
    deps: [],
    knowledgeIds: ['source:bank-v1#/aggregates/0'],
    productFootprint: [{ id: 'reference-layout', version: '1' }],
    merge: null,
  }];
};

test('the derived aggregate-repository contract deep-equals the curated technical input', () => {
  const data = products();
  const derived = deriveAggregateRepositories(data, data.options);
  assert.deepEqual(derived, contract());
  assert.equal(derived.repositories.length, 3);
  assert.deepEqual(derived.repositories.map(r => r.name), ['CreditBalance', 'FundOrder', 'SipPlan']);
});

test('the wrapper renders manifest contexts through the family, byte-equal to the golden tree and deterministic', () => {
  const data = products();
  const context = { products: data, options: data.options };
  const classic = classicRepositoryEntries(data['reference-layout'].declarations);
  const flipped = withFlippedAggregateRepositories(() => classic, context);

  assert.equal(flipped.length, classic.length);
  assert.equal(flipped.filter(e => e.kind === 'aggregate-bootstrap').length, 1);
  const repos = flipped.filter(e => e.kind === 'aggregate-repository');
  assert.equal(repos.length, 3);

  for (const entry of repos) {
    const golden = fs.readFileSync(path.join(GOLDEN, entry.path), 'utf8');
    assert.equal(entry.content, golden, entry.path);
    assert.equal(entry.merge, null);
    assert.equal(entry.deps.length, 1);
    assert.equal(entry.knowledgeIds.length, 1);
    assert.deepEqual(entry.productFootprint, [
      { id: 'reference-layout', version: '1' },
      { id: 'domain-folds', version: '6' },
      { id: 'exact-value-types', version: '1' },
      { id: 'domain-dependencies', version: '6' },
    ]);
  }
  assert.deepEqual(withFlippedAggregateRepositories(() => classic, context), flipped);
});

test('the wrapper passes through projects without any manifest aggregate declaration', () => {
  const other = {
    options: { packages: [{ context: 'inventory', package: 'example.inventory' }], emission: 'classic' },
    'reference-layout': {
      declarations: [{ ref: { context: 'inventory', kind: 'aggregate', owner: [], id: 'Warehouse' }, source: { document: 'inv', pointer: '/aggregates/0' } }],
    },
  };
  const classic = [{
    path: 'app/example/inventory/application/aggregates/WarehouseRepository.scala',
    content: '// classic inventory repo\n',
    kind: 'aggregate-repository',
    deps: [],
    knowledgeIds: [],
    productFootprint: [],
    merge: null,
  }];
  assert.deepEqual(withFlippedAggregateRepositories(() => classic, { products: other, options: other.options }), classic);
  assert.equal(isAggregateRepositoryFlipped('inventory'), true);
  assert.equal(isAggregateRepositoryFlipped('inventory', { emission: 'classic' }), false);
});

test('the wrapper refuses missing flip targets, orphans, and derivation errors fail-closed', () => {
  const data = products();
  const context = { products: data, options: data.options };
  const classic = classicRepositoryEntries(data['reference-layout'].declarations);

  const minusOne = classic.filter(e => e.path !== 'app/example/bankwealth/application/aggregates/CreditBalanceRepository.scala');
  assert.throws(() => withFlippedAggregateRepositories(() => minusOne, context),
    /AR_EMISSION: the classic aggregate plan must carry exactly the repository flip set: 2 of 3 classic files present/);

  const extra = [...classic, { ...classic[0], path: 'app/example/bankwealth/application/aggregates/InventedRepository.scala' }];
  assert.throws(() => withFlippedAggregateRepositories(() => extra, context),
    /AR_EMISSION: the classic aggregate plan carries a repository file outside the derived contract/);

  assert.throws(() => deriveAggregateRepositories({ 'reference-layout': { declarations: [] } }, data.options),
    /AR_DERIVATION: no aggregate declarations/);
  assert.throws(() => deriveAggregateRepositories(data, { packages: [] }),
    /AR_DERIVATION: context bankwealth has no package binding/);
});

test('embedded negatives battery rejects every malformed input with AR_INPUT', () => {
  const result = runNegatives(contract());
  assert.equal(result.rejected, result.expected);
  assert.deepEqual(result.failures, []);
  assert.ok(result.expected >= 18);
  assert.equal(renderAggregateRepositoryFiles(contract()).length, 3);
});
