// plan F2/F4, rulings 2026-11-24 §21). Pins the knowledge→contract derivation
// seam, 6/6 golden byte parity and double-run determinism, 188 exact byte-span
// codeMappings validation, non-manifest passthrough, fail-closed missing/orphan/
// derivation guards, and the 20-case embedded negative battery.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseStrictJson } from '../lib/strict-json.mjs';
import { validateCodeMappings } from '../src/core/code-mappings.mjs';
import { deriveEventHandlers } from '../lib/derivation/event-handler.mjs';
import {
  EVENT_HANDLER_FLIP_CONTEXTS,
  isEventHandlerFlipped,
  withFlippedEventHandlers,
} from '../lib/derivation/event-handler-emission.mjs';
import { renderEventHandlerFiles, runNegatives } from '../emitter/families/event-handler.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GOLDEN = path.join(ROOT, 'test/reference/curated/event-handler/v1');
const FIXTURE = path.join(ROOT, 'test/fixtures/event-handler-v1');

const fixtureData = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'knowledge-products.json'), 'utf8'));
const contract = () => parseStrictJson(fs.readFileSync(path.join(FIXTURE, 'input.json'), 'utf8'));

const classicEventHandlerEntries = (layoutDeclarations, options) => {
  const packages = new Map(options.packages.map(p => [p.context, p.package.replaceAll('.', '/')]));
  const aggs = layoutDeclarations.filter(d => d.ref.kind === 'aggregate');
  const handlers = aggs.flatMap(d => {
    const pkgRoot = packages.get(d.ref.context);
    const corePath = 'app/' + pkgRoot + '/domain/entities/behaviors/' + d.ref.id + 'EventHandler.scala';
    const facadePath = 'app/' + pkgRoot + '/domain/' + d.ref.id + 'EventHandler.scala';
    const fp = [
      { id: 'reference-layout', version: '1' },
      { id: 'domain-decision', version: '4' },
      { id: 'domain-folds', version: '6' },
      { id: 'exact-value-types', version: '1' },
    ];
    return [
      {
        path: corePath,
        content: '// @generated by truthsrc scala-cqrs-domain:1\npackage example.bankwealth.domain.entities.behaviors\n',
        kind: 'event-handler',
        deps: [],
        knowledgeIds: ['source:' + d.source.document + '#' + d.source.pointer],
        productFootprint: fp,
        merge: null,
      },
      {
        path: facadePath,
        content: '// @generated by truthsrc scala-cqrs-domain:1\npackage example.bankwealth.domain\n',
        kind: 'event-handler',
        deps: [],
        knowledgeIds: ['source:' + d.source.document + '#' + d.source.pointer],
        productFootprint: fp,
        merge: null,
      },
    ];
  });
  return [
    {
      path: 'app/example/bankwealth/domain/CreditBalanceRules.scala',
      content: '// flipped rules, untouched\n',
      kind: 'rules',
      deps: [],
      knowledgeIds: ['source:bank-v1#/aggregates/0'],
      productFootprint: [{ id: 'reference-layout', version: '1' }],
      merge: null,
    },
    ...handlers,
  ];
};

test('the derived event-handler contract deep-equals the curated technical input', () => {
  const { products, options } = fixtureData();
  const derived = deriveEventHandlers(products, options);
  assert.deepEqual(derived, contract());
  assert.equal(derived.handlers.length, 3);
  assert.deepEqual(derived.handlers.map(h => h.name), ['CreditBalance', 'FundOrder', 'SipPlan']);
  assert.deepEqual(derived.handlers.map(h => h.events.length), [7, 32, 18]);
});

test('the wrapper renders manifest contexts through the family, byte-equal to the golden tree, deterministic, with 188 valid span mappings', () => {
  const { products, options } = fixtureData();
  const context = { products, options };
  const classic = classicEventHandlerEntries(products['reference-layout'].declarations, options);
  const flipped = withFlippedEventHandlers(() => classic, context);

  assert.equal(flipped.length, classic.length);
  assert.equal(flipped.filter(e => e.kind === 'rules').length, 1);
  const handlers = flipped.filter(e => e.kind === 'event-handler');
  assert.equal(handlers.length, 6);

  let totalMappings = 0;
  for (const entry of handlers) {
    const golden = fs.readFileSync(path.join(GOLDEN, entry.path), 'utf8');
    assert.equal(entry.content, golden, entry.path);
    assert.equal(entry.merge, null);
    assert.deepEqual(entry.productFootprint, [
      { id: 'reference-layout', version: '1' },
      { id: 'domain-decision', version: '4' },
      { id: 'domain-folds', version: '6' },
      { id: 'exact-value-types', version: '1' },
    ]);
    if (entry.path.includes('/entities/behaviors/')) {
      assert.ok(Array.isArray(entry.codeMappings) && entry.codeMappings.length > 0, entry.path + ' must carry codeMappings');
      assert.doesNotThrow(() => validateCodeMappings(entry), entry.path + ' codeMappings must validate');
      totalMappings += entry.codeMappings.length;
    } else {
      assert.equal(entry.codeMappings, undefined, entry.path + ' facade has no codeMappings');
    }
  }
  assert.equal(totalMappings, 188);
  assert.deepEqual(withFlippedEventHandlers(() => classic, context), flipped);
});

test('the wrapper passes through projects without any manifest aggregate declaration', () => {
  const other = {
    options: { packages: [{ context: 'inventory', package: 'example.inventory' }] },
    products: {
      'reference-layout': {
        declarations: [{ ref: { context: 'inventory', kind: 'aggregate', owner: [], id: 'Warehouse' }, source: { document: 'inv', pointer: '/aggregates/0' } }],
      },
    },
  };
  const classic = [{
    path: 'app/example/inventory/domain/WarehouseEventHandler.scala',
    content: '// classic inventory event handler\n',
    kind: 'event-handler',
    deps: [],
    knowledgeIds: [],
    productFootprint: [],
    merge: null,
  }];
  assert.deepEqual(withFlippedEventHandlers(() => classic, other), classic);
  assert.equal(isEventHandlerFlipped('inventory'), false);
  assert.deepEqual(EVENT_HANDLER_FLIP_CONTEXTS, ['bankwealth']);
});

test('the wrapper refuses missing flip targets, orphans, and derivation errors fail-closed', () => {
  const { products, options } = fixtureData();
  const context = { products, options };
  const classic = classicEventHandlerEntries(products['reference-layout'].declarations, options);

  const minusOne = classic.filter(e => e.path !== 'app/example/bankwealth/domain/CreditBalanceEventHandler.scala');
  assert.throws(() => withFlippedEventHandlers(() => minusOne, context),
    /EH_EMISSION: the classic invariant plan must carry exactly the event-handler flip set: 5 of 6 classic files present/);

  const extra = [...classic, { ...classic[1], path: 'app/example/bankwealth/domain/InventedEventHandler.scala' }];
  assert.throws(() => withFlippedEventHandlers(() => extra, context),
    /EH_EMISSION: the classic invariant plan carries an event-handler file outside the derived contract/);

  assert.throws(() => deriveEventHandlers({ 'reference-layout': { declarations: [] }, 'domain-folds': { events: [] }, 'exact-value-types': [] }, options),
    /EH_DERIVATION: no aggregate declarations/);
  assert.throws(() => deriveEventHandlers(products, { packages: [] }),
    /EH_DERIVATION: context bankwealth has no unique exact package binding/);
});

test('embedded negatives battery rejects every malformed input with EH_INPUT', () => {
  const result = runNegatives(contract());
  assert.equal(result.rejected, result.expected);
  assert.deepEqual(result.failures, []);
  assert.ok(result.expected >= 20);
  assert.equal(renderEventHandlerFiles(contract()).length, 6);
});
