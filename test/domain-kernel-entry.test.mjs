import test from 'node:test';
import assert from 'node:assert/strict';
import { sourceEntry } from '../generators/scala-cqrs-domain-kernel-v1/entry.mjs';
import { validateCodeMappings, finalMappingSpan } from '../src/core/code-mappings.mjs';

const source = { document: 'domain', pointer: '/valueObjects/0' };
const field = { document: 'domain', pointer: '/valueObjects/0/fields/0' };
const spec = { path: 'modules/kernel/src/main/scala/example/Value.scala', kind: 'value-object',
  sources: [source], footprint: [{ id: 'reference-layout', version: '1' }], deps: [] };

test('candidate entries map exact UTF-8 final bytes with a distinct generator header', () => {
  const entry = sourceEntry(spec, out => {
    out.append('package example\n\n// café 🚚\n');
    out.append('final case class Value(', [source]);
    out.append('`type`: String', [field]);
    out.append(')\n');
  });
  assert.match(entry.content, /^\/\/ @generated by truthsrc scala-cqrs-domain-kernel:1\n/);
  assert.doesNotMatch(entry.content, /@knowledge/);
  assert.equal(validateCodeMappings(entry).length, 2);
  const mapping = entry.codeMappings.find(row => row.knowledgeKey.endsWith('/fields/0'));
  assert.equal(Buffer.from(entry.content).subarray(mapping.span.start, mapping.span.end).toString(), '`type`: String');
  assert.ok(mapping.span.start > entry.content.indexOf('`type`'));
  assert.deepEqual(entry.knowledgeIds, ['source:domain#/valueObjects/0', 'source:domain#/valueObjects/0/fields/0']);
  assert.equal(entry.merge, null);
  assert.deepEqual(entry.productFootprint, spec.footprint);
});

test('identical source references for the same text produce one mapping', () => {
  const entry = sourceEntry(spec, out => out.append('final case class Value()\n', [source, source]));
  assert.equal(validateCodeMappings(entry).length, 1);
  assert.equal(entry.knowledgeIds.length, 1);
});

test('source entries detach metadata and keep emitted scopes relocatable', () => {
  const input = structuredClone(spec);
  const entry = sourceEntry(input, out => out.append('final case class Value()\n', [field]));
  input.footprint[0].version = 'wrong'; input.deps.push('outside.scala');
  assert.deepEqual(entry.productFootprint, spec.footprint);
  assert.deepEqual(entry.deps, []);
  assert.ok(Object.isFrozen(entry));
  const finalBytes = Buffer.from('// preserved user material\n' + entry.content);
  assert.equal(finalMappingSpan(entry.codeMappings[0], entry.content, finalBytes).text, 'final case class Value()\n');
});

test('properties metadata uses the format comment syntax rather than a Scala line comment', () => {
  const entry = sourceEntry({ ...spec, path: 'project/build.properties', kind: 'build' }, out => out.append('sbt.version=1.4.9\n', [source]));
  assert.match(entry.content, /^# @generated by truthsrc scala-cqrs-domain-kernel:1\n/);
  assert.doesNotMatch(entry.content, /^\/\//);
  assert.equal(validateCodeMappings(entry).length, 1);
});

test('empty mapped text and malformed source identity fail instead of inventing an anchor', () => {
  assert.throws(() => sourceEntry(spec, out => out.append('', [source])));
  assert.throws(() => sourceEntry(spec, out => out.append('value', [{ document: 'domain' }])));
  assert.throws(() => sourceEntry(spec, out => out.append('value', [{ document: 'domain#suffix', pointer: '/valid' }])));
  assert.throws(() => sourceEntry(spec, out => out.append('value', [{ document: 'domain', pointer: '/valid', extra: true }])));
});
