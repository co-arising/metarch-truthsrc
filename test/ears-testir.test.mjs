import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { parseEars } from '../lib/ears/parser.mjs';
import { normalizeEars } from '../lib/ears/normalize.mjs';
import { verifyEarsWithSmt } from '../lib/ears/clarification-card.mjs';
import { buildTestIr } from '../lib/ears/test-ir.mjs';
import { emitGherkinFeature } from '../lib/ears/emit-gherkin.mjs';
import { getEmitter, listEmitters } from '../lib/ears/emitters/interface.mjs';
import { scalaScalaTestEmitter } from '../lib/ears/emitters/scala-scalatest.mjs';

const QUOTA_SPEC = `
slice QuotaPool.ReserveQuota

where:
  validAmount   = amount in [pool.minLimit..pool.maxLimit] as "single amount valid"
  withinPoolCap = pool.totalUsed + amount <= pool.totalCap as "within pool cap"

axioms:
  [AX-Q-1] ALWAYS pool.totalUsed <= pool.totalCap

rules:
  [Q_RANGE] IF not validAmount   THEN SHALL reject request with Q_RANGE
  [Q_POOL]  IF not withinPoolCap THEN SHALL reject request with Q_POOL
  [Q_OK]    WHILE validAmount and withinPoolCap
            WHEN ReserveQuota
            SHALL emit QuotaReserved
            post:
              pool.totalUsed' = pool.totalUsed + amount
`;

test('builds deterministic TestIR, locked Gherkin feature, and ScalaTest oracle with @CoArisingSpec anchors', () => {
  const norm = normalizeEars(parseEars(QUOTA_SPEC, { file: 'quota-reserve.ears' }));
  const smt = verifyEarsWithSmt(norm, { solver: 'z3' });
  assert.equal(smt.passed, true);

  const ir1 = buildTestIr(norm, smt, { sourceFile: 'quota-reserve.ears', sourceText: QUOTA_SPEC });
  const ir2 = buildTestIr(norm, smt, { sourceFile: 'quota-reserve.ears', sourceText: QUOTA_SPEC });
  assert.equal(ir1.sha256, ir2.sha256);

  const feature = emitGherkinFeature(ir1);
  assert.match(feature.content, /AUTO-GENERATED BY co-arising EARS 1\.0 \(LOCKED — DO NOT EDIT\)/);
  assert.match(feature.content, /@layer:domain @aggregate:QuotaPool @slice:ReserveQuota/);
  assert.match(feature.content, /@spec:Q_RANGE @spec:Q_POOL @spec:Q_OK @z3-witness/);

  assert.equal(getEmitter('scala', 'scalatest'), scalaScalaTestEmitter);
  assert.ok(listEmitters().some(e => e.language === 'scala' && e.framework === 'scalatest'));

  const scala = scalaScalaTestEmitter.emitDomainSpec(ir1, { packageName: 'example.demo.ears' });
  assert.equal(scala.path, 'example/demo/ears/QuotaPoolReserveQuotaEarsSpec.scala');
  assert.match(scala.content, /LOCKED BDD ORACLE — GENERATED BY co-arising EARS 1\.0/);
  assert.match(scala.content, /@CoArisingSpec\(id="Q_OK"/);
  assert.match(scala.content, /final class QuotaPoolReserveQuotaEarsSpec extends AnyFunSuite/);
});

test('CLI check-spec, project-spec, and emit-tests execute end-to-end', () => {
  const dir = mkdtempSync(join(tmpdir(), 'truthsrc-ears-cli-'));
  try {
    const specFile = join(dir, 'quota-reserve.ears');
    writeFileSync(specFile, QUOTA_SPEC, 'utf8');
    const cli = join(process.cwd(), 'bin/truthsrc.js');

    const checkOut = execFileSync(process.execPath, [cli, 'check-spec', '--in', specFile, '--format', 'json'], { encoding: 'utf8' });
    const checkJson = JSON.parse(checkOut);
    assert.equal(checkJson.passed, true);
    assert.equal(checkJson.results[0].smt.logic, 'QF_AUFLIA');

    const outAc = join(dir, 'projections/ac');
    const outTables = join(dir, 'projections/tables');
    const projOut = execFileSync(process.execPath, [cli, 'project-spec', '--in', specFile, '--out-ac', outAc, '--out-tables', outTables], { encoding: 'utf8' });
    const projJson = JSON.parse(projOut);
    assert.equal(projJson.written.length, 2);

    const outFeat = join(dir, 'generated-tests/features');
    const outScala = join(dir, 'generated-tests/scala');
    const manifest = join(dir, 'generated-tests/manifest.sha256.json');
    const emitOut = execFileSync(process.execPath, [
      cli, 'emit-tests', '--in', specFile,
      '--out-features', outFeat, '--out-scala', outScala,
      '--package', 'example.demo.ears', '--manifest', manifest,
    ], { encoding: 'utf8' });
    const emitJson = JSON.parse(emitOut);
    assert.equal(emitJson.manifestCount, 2);

    const manifestJson = JSON.parse(readFileSync(manifest, 'utf8'));
    assert.equal(manifestJson.schemaVersion, 'co-arising.locked-tests-manifest/v1');
    assert.equal(manifestJson.files.length, 2);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
