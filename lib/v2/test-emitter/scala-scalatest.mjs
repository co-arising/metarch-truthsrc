import { createHash } from 'node:crypto';
import { materializeDomainWitness } from './witness-materialize.mjs';

function toPascal(name) {
  return name
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map(p => p[0].toUpperCase() + p.slice(1))
    .join('');
}

function scalaLiteral(val, resolvedType) {
  if (!resolvedType) return JSON.stringify(String(val ?? ''));
  switch (resolvedType.kind) {
    case 'int': return `${Math.trunc(Number(val ?? 0))}L`;
    case 'bool': return val ? 'true' : 'false';
    case 'string': return JSON.stringify(String(val ?? ''));
    case 'decimal': return `BigDecimal(${JSON.stringify(String(val ?? '0.00'))})`;
    case 'optional': return val === null || val === undefined ? 'None' : `Some(${scalaLiteral(val, resolvedType.element)})`;
    case 'map': {
      const entries = Object.entries(val ?? {}).map(([k, v]) => `${JSON.stringify(k)} -> ${scalaLiteral(v, resolvedType.value)}`);
      return entries.length === 0 ? `Map.empty[String, ${resolvedType.value?.kind === 'decimal' ? 'BigDecimal' : 'String'}]` : `Map(${entries.join(', ')})`;
    }
    case 'record': {
      const args = Object.entries(resolvedType.fields ?? {}).map(([k, ft]) => scalaLiteral(val?.[k], ft)).join(', ');
      return `${resolvedType.typeName}(${args})`;
    }
    default: return JSON.stringify(String(val ?? ''));
  }
}

export function emitExecutableScalaDomainSpec(canonicalV2, behavior, { packageName = 'example.v2' } = {}) {
  const aggName = behavior.target.split('.')[0];
  const agg = canonicalV2.structures.aggregates.find(a => a.name === aggName);
  if (!agg) throw new Error(`V2_TEST_EMIT: unknown aggregate "${aggName}"`);
  const className = `${toPascal(behavior.target)}EarsSpec`;
  const hasCloze = behavior.theory.codegenChannel === 'cloze-tdd';
  const clozeObj = `${toPascal(behavior.target)}Cloze`;
  const cmdMap = new Map(agg.commands.map(c => [c.name, c]));

  const lines = [
    '// LOCKED EXECUTABLE BDD ORACLE — GENERATED BY co-arising 2.0 (DO NOT MODIFY)',
    `// source: ${behavior.sourceFile}`,
    `// canonicalSha256: ${behavior.verification.canonicalSha256}`,
    `// testIrSha256: ${behavior.testIr.sha256}`,
    `// layer: domain | tier: ${behavior.theory.tier} | logic: ${behavior.theory.logic}`,
    `package ${packageName}`,
    '',
    'import org.scalatest.funsuite.AnyFunSuite',
    '',
    `final class ${className} extends AnyFunSuite {`,
  ];

  const emitCase = (cmd, ex, witnessLabel, witnessData) => {
    const mat = materializeDomainWitness(agg, cmd, witnessData);
    const stateArgs = agg.stateFields.map(sf => `${sf.name} = ${scalaLiteral(mat.state[sf.name], sf.resolvedType)}`).join(', ');
    const cmdArgs = cmd.parameters.map(p => `${p.name} = ${scalaLiteral(mat.command[p.name], p.resolvedType)}`).join(', ');
    const witnessId = `z3-${behavior.theory.logic.toLowerCase()}-${ex.ruleId.toLowerCase()}-${witnessLabel}`;
    const rejectAct = ex.actions.find(a => a.kind === 'reject' && a.modality === 'SHALL');
    const emitActs = ex.actions.filter(a => a.kind === 'emit' && a.modality === 'SHALL');
    const clozeArg = hasCloze ? `, ${clozeObj}` : '';

    lines.push(`  // @CoArisingSpec(id="${ex.ruleId}", witness="${witnessId}")`);
    lines.push(`  test(${JSON.stringify(`[${ex.ruleId}] (${witnessLabel}) ${cmd.name} -> ${ex.outcome}`)}) {`);
    lines.push(`    val state = ${aggName}State(${stateArgs})`);
    lines.push(`    val cmd = ${cmd.name}(${cmdArgs})`);
    lines.push(`    val outcome = ${aggName}Behavior.handleCommand(state, cmd${clozeArg})`);
    if (rejectAct) {
      lines.push('    outcome match {');
      lines.push(`      case Left(rej) => assert(rej.code == ${JSON.stringify(rejectAct.code)})`);
      lines.push('      case Right(acc) => fail(s"expected rejection, got accepted: $acc")');
      lines.push('    }');
    } else {
      lines.push('    outcome match {');
      lines.push('      case Right(acc) =>');
      lines.push(`        assert(acc.events.map(_.getClass.getSimpleName) == Seq(${emitActs.map(a => JSON.stringify(a.event)).join(', ')}))`);
      lines.push(`        val nextState = ${aggName}Behavior.replay(state, acc.events)`);
      lines.push(`        assert(${aggName}Behavior.checkAxioms(nextState).isEmpty)`);
      for (const assign of ex.post ?? []) {
        if (assign.source === 'transition' && assign.value?.kind === 'string') {
          const f = assign.target.segments[assign.target.segments.length - 1];
          lines.push(`        assert(nextState.${f} == ${JSON.stringify(assign.value.value)})`);
        }
      }
      lines.push('      case Left(rej) => fail(s"expected acceptance, got rejection: $rej")');
      lines.push('    }');
    }
    lines.push('  }');
    lines.push('');
  };

  for (const sc of behavior.testIr.scenarios) {
    if (sc.kind === 'bmc') continue;
    const cmd = cmdMap.get(sc.command);
    if (!cmd) continue;
    for (const ex of sc.examples) {
      emitCase(cmd, ex, 'primary', ex.witness);
      if (ex.secondaryWitness) emitCase(cmd, ex, 'secondary', ex.secondaryWitness);
      (ex.boundaryWitnesses ?? []).forEach((bw, bIdx) => {
        emitCase(cmd, ex, `boundary-${bIdx + 1}`, bw);
      });
    }
  }

  lines.push('}');
  lines.push('');

  const content = lines.join('\n');
  const pkgPath = packageName.split('.').join('/');
  return {
    path: `scala/${pkgPath}/${className}.scala`,
    className,
    content,
    sha256: createHash('sha256').update(content).digest('hex'),
  };
}
