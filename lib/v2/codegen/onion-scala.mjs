// Onion 5-Layer Scala 2.12/2.13 artifact emitters for co-arising 2.0:
//   1. domain/          (DomainFacade — zero framework imports)
//   2. application/     (Connectors — outbound external-system ports)
//   3. interfaces/      (api/ApiDto + http/<Story>Controller + http/HttpRouter)
//   4. infrastructure/  (persistence/InMemoryStore + connectors/EffectAdapters)
//   5. modules/         (BootstrapModule — pure DI Composition Root)
import { deriveStoryHttpRoutes, toCamel, toPascal } from './onion-routes.mjs';

function emitScalaDomainFacade(canonicalV2, packageName) {
  const aggs = (canonicalV2.structures.aggregates ?? []).map(a => JSON.stringify(a.name)).join(', ');
  return [
    '// @generated by co-arising 2.0 (Onion Layer: domain — DO NOT MODIFY)',
    '// Pure domain facade with zero framework or outer-layer imports.',
    '// @ProvenanceId(layer:domain)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.domain`,
    '',
    'object DomainFacade {',
    `  val system: String = ${JSON.stringify(canonicalV2.system)}`,
    `  val context: String = ${JSON.stringify(canonicalV2.context)}`,
    `  val canonicalSha256: String = ${JSON.stringify(canonicalV2.canonicalSha256)}`,
    `  val aggregates: Seq[String] = Seq(${aggs})`,
    '}',
    '',
  ].join('\n');
}

function emitScalaApplicationConnectors(canonicalV2, packageName) {
  const appBehaviors = (canonicalV2.behaviors ?? []).filter(b => b.layer === 'application');
  const lines = [
    '// @generated by co-arising 2.0 (Onion Layer: application.connectors — DO NOT MODIFY)',
    '// Outbound ports to external systems and persistence; implemented by infrastructure.connectors.',
    '// @ProvenanceId(layer:application:connectors)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.application`,
    '',
    'final case class OutboundEffectRecord(kind: String, target: String, payload: Map[String, Any])',
    '',
    'trait OutboundConnectorsPort {',
  ];
  for (const beh of appBehaviors) {
    const pascal = toPascal(beh.target);
    const camel = toCamel(pascal);
    lines.push(`  def ${camel}Externs: ${packageName}.${pascal}ExternPorts`);
    lines.push(`  def ${camel}Effects: ${packageName}.${pascal}EffectsPort`);
  }
  lines.push('  def recordedEffects: Seq[OutboundEffectRecord]');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitScalaInterfacesApiDto(canonicalV2, packageName) {
  return [
    '// @generated by co-arising 2.0 (Onion Layer: interfaces.api — DO NOT MODIFY)',
    '// Inbound HTTP DTOs and deterministic rejection-to-HTTP status mapping (Play-compatible, stdlib-only).',
    '// @ProvenanceId(layer:interfaces:api)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.interfaces.api`,
    '',
    'final case class Principal(id: String, roles: Set[String] = Set.empty)',
    '',
    'trait HttpAuthority {',
    '  def authenticate(req: HttpRequest): Option[Principal]',
    '  def authorize(principal: Principal, route: RouteDescriptor): Boolean',
    '  def verifyCsrf(req: HttpRequest): Boolean = true',
    '}',
    '',
    'object AllowAllAuthority extends HttpAuthority {',
    '  override def authenticate(req: HttpRequest): Option[Principal] = Some(Principal("system-default", Set("*")))',
    '  override def authorize(principal: Principal, route: RouteDescriptor): Boolean = true',
    '}',
    '',
    'final case class HttpRequest(',
    '  method: String,',
    '  path: String,',
    '  headers: Map[String, String] = Map.empty,',
    '  query: Map[String, String] = Map.empty,',
    '  body: Map[String, Any] = Map.empty,',
    '  stateSnapshot: Map[String, Any] = Map.empty,',
    '  principal: Option[Principal] = None',
    ')',
    '',
    'final case class HttpResponse(',
    '  status: Int,',
    '  body: Map[String, Any],',
    '  headers: Map[String, String] = Map("content-type" -> "application/json; charset=utf-8")',
    ')',
    '',
    'final case class RouteDescriptor(method: String, path: String, story: String, operation: String)',
    '',
    'object HttpStatusMapper {',
    '  def statusForRejection(code: String): Int = {',
    '    val upper = Option(code).getOrElse("").toUpperCase',
    '    if (upper.contains("UNAUTHORIZED") || upper.contains("CSRF") || upper.contains("AUTH")) 401',
    '    else if (upper.contains("FORBIDDEN")) 403',
    '    else if (upper.contains("CONFLICT") || upper.contains("ALREADY")) 409',
    '    else if (upper.contains("NOT_FOUND") || upper.contains("UNKNOWN")) 404',
    '    else 400',
    '  }',
    '}',
    '',
  ].join('\n');
}

function emitScalaStoryController(beh, canonicalV2, packageName) {
  const storyName = beh.target;
  const pascal = toPascal(storyName);
  return [
    `// @generated by co-arising 2.0 (Onion Layer: interfaces.http — DO NOT MODIFY)`,
    `// Inbound HTTP Controller for application story ${storyName}.`,
    `// @ProvenanceId(interfaces:http:${storyName})`,
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.interfaces.http`,
    '',
    `import ${packageName}.interfaces.api.{HttpRequest, HttpResponse, HttpStatusMapper}`,
    '',
    `final class ${pascal}Controller(`,
    `  handler: ${packageName}.${pascal}Handler,`,
    `  externs: ${packageName}.${pascal}ExternPorts,`,
    `  effects: ${packageName}.${pascal}EffectsPort`,
    ') {',
    '  def handleOperation(operation: String, req: HttpRequest): HttpResponse = {',
    '    val mergedPayload: Map[String, Any] = req.query.map { case (k, v) => k -> (v: Any) } ++ req.body',
    `    val appReq = ${packageName}.${pascal}Request(operation = operation, payload = mergedPayload, stateSnapshot = req.stateSnapshot)`,
    '    handler.handle(appReq, externs, effects) match {',
    '      case Left(rej) =>',
    '        HttpResponse(',
    '          status = HttpStatusMapper.statusForRejection(rej.code),',
    '          body = Map("ok" -> false, "code" -> rej.code, "ruleId" -> rej.ruleId)',
    '        )',
    '      case Right(res) =>',
    '        val base: Map[String, Any] = Map("ok" -> true, "ruleId" -> res.ruleId)',
    '        val withResp = res.responseType.map(rt => base + ("responseType" -> rt) + ("response" -> res.response)).getOrElse(base)',
    '        val withView = res.viewName.map(vn => withResp + ("viewName" -> vn) + ("view" -> res.view)).getOrElse(withResp)',
    '        HttpResponse(status = 200, body = withView)',
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
}

function emitScalaHttpRouter(canonicalV2, routes, packageName) {
  const appBehaviors = (canonicalV2.behaviors ?? []).filter(b => b.layer === 'application');
  const lines = [
    '// @generated by co-arising 2.0 (Onion Layer: interfaces.http — DO NOT MODIFY)',
    '// Unified inbound HTTP router dispatching /health and all declared application ports.',
    '// @ProvenanceId(layer:interfaces:http)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.interfaces.http`,
    '',
    `import ${packageName}.interfaces.api.{AllowAllAuthority, HttpAuthority, HttpRequest, HttpResponse, RouteDescriptor}`,
    '',
    'final class HttpRouter(',
  ];
  const ctorParams = [
    ...appBehaviors.map(b => `  ${toCamel(toPascal(b.target))}Controller: Option[${toPascal(b.target)}Controller] = None`),
    '  authority: HttpAuthority = AllowAllAuthority',
  ];
  lines.push(ctorParams.join(',\n'));
  lines.push(') {');
  lines.push('  val declaredRoutes: Seq[RouteDescriptor] = Seq(');
  for (let i = 0; i < routes.length; i += 1) {
    const r = routes[i];
    const comma = i + 1 < routes.length ? ',' : '';
    lines.push(`    RouteDescriptor(${JSON.stringify(r.method)}, ${JSON.stringify(r.path)}, ${JSON.stringify(r.storyName)}, ${JSON.stringify(r.operation)})${comma}`);
  }
  lines.push('  )');
  lines.push('');
  lines.push('  private def enforceAuth(routeDesc: RouteDescriptor, req: HttpRequest): Either[HttpResponse, HttpRequest] = {');
  lines.push('    authority.authenticate(req) match {');
  lines.push('      case None => Left(HttpResponse(401, Map("ok" -> false, "code" -> "NOT_AUTHENTICATED", "route" -> routeDesc.path)))');
  lines.push('      case Some(principal) =>');
  lines.push('        if (!authority.authorize(principal, routeDesc)) {');
  lines.push('          Left(HttpResponse(403, Map("ok" -> false, "code" -> "NOT_AUTHORIZED", "route" -> routeDesc.path)))');
  lines.push('        } else if (routeDesc.method == "POST" && !authority.verifyCsrf(req)) {');
  lines.push('          Left(HttpResponse(403, Map("ok" -> false, "code" -> "CSRF_INVALID", "route" -> routeDesc.path)))');
  lines.push('        } else {');
  lines.push('          Right(req.copy(principal = Some(principal)))');
  lines.push('        }');
  lines.push('    }');
  lines.push('  }');
  lines.push('');
  lines.push('  def route(req: HttpRequest): HttpResponse = {');
  lines.push('    val method = req.method.toUpperCase');
  lines.push('    val path = req.path.split("\\\\?")(0)');
  lines.push('    (method, path) match {');
  lines.push('      case ("GET", "/health") =>');
  lines.push(`        HttpResponse(200, Map("status" -> "ok", "system" -> ${JSON.stringify(canonicalV2.system)}, "context" -> ${JSON.stringify(canonicalV2.context)}, "routes" -> declaredRoutes.size))`);
  for (let i = 0; i < routes.length; i += 1) {
    const r = routes[i];
    const ctrlParam = `${toCamel(r.storyPascal)}Controller`;
    lines.push(`      case (${JSON.stringify(r.method)}, ${JSON.stringify(r.path)}) =>`);
    lines.push(`        enforceAuth(declaredRoutes(${i}), req) match {`);
    lines.push('          case Left(denied) => denied');
    lines.push('          case Right(authedReq) =>');
    lines.push(`            ${ctrlParam}.map(_.handleOperation(${JSON.stringify(r.operation)}, authedReq)).getOrElse(`);
    lines.push(`              HttpResponse(501, Map("ok" -> false, "code" -> "HANDLER_NOT_WIRED", "story" -> ${JSON.stringify(r.storyName)}))`);
    lines.push('            )');
    lines.push('        }');
  }
  lines.push('      case _ =>');
  lines.push('        HttpResponse(404, Map("ok" -> false, "code" -> "ROUTE_NOT_FOUND", "method" -> method, "path" -> path))');
  lines.push('    }');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitScalaInMemoryStore(canonicalV2, packageName) {
  return [
    '// @generated by co-arising 2.0 (Onion Layer: infrastructure.persistence — DO NOT MODIFY)',
    '// Default in-memory persistence and idempotency pin ledger.',
    '// @ProvenanceId(layer:infrastructure:persistence)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.infrastructure.persistence`,
    '',
    'import scala.collection.mutable',
    '',
    'final case class PinnedRecord(artifact: String, inputs: Map[String, Any])',
    'final case class DispatchedRecord(target: String, payload: Map[String, Any])',
    '',
    'final class InMemoryStore {',
    '  private val pinsBuf = mutable.LinkedHashMap.empty[String, PinnedRecord]',
    '  private val dispatchesBuf = mutable.ListBuffer.empty[DispatchedRecord]',
    '',
    '  def pin(artifact: String, inputs: Map[String, Any]): Unit = {',
    '    val key = s"$artifact:${inputs.toSeq.sortBy(_._1).mkString(",")}"',
    '    if (!pinsBuf.contains(key)) pinsBuf.put(key, PinnedRecord(artifact, inputs))',
    '  }',
    '',
    '  def recordDispatch(target: String, payload: Map[String, Any]): Unit = {',
    '    dispatchesBuf += DispatchedRecord(target, payload)',
    '  }',
    '',
    '  def pins: Seq[PinnedRecord] = pinsBuf.values.toSeq',
    '  def dispatches: Seq[DispatchedRecord] = dispatchesBuf.toSeq',
    '}',
    '',
  ].join('\n');
}

function emitScalaEffectAdapters(canonicalV2, packageName) {
  const appBehaviors = (canonicalV2.behaviors ?? []).filter(b => b.layer === 'application');
  const lines = [
    '// @generated by co-arising 2.0 (Onion Layer: infrastructure.connectors — DO NOT MODIFY)',
    '// Default runnable outbound adapters implementing application.connectors ports.',
    '// @ProvenanceId(layer:infrastructure:connectors)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.infrastructure.connectors`,
    '',
    'import scala.collection.mutable',
    '',
    `final class DefaultOutboundConnectors(store: ${packageName}.infrastructure.persistence.InMemoryStore) extends ${packageName}.application.OutboundConnectorsPort {`,
    `  private val recorded = mutable.ListBuffer.empty[${packageName}.application.OutboundEffectRecord]`,
  ];
  for (const beh of appBehaviors) {
    const pascal = toPascal(beh.target);
    const camel = toCamel(pascal);
    lines.push(`  override val ${camel}Externs: ${packageName}.${pascal}ExternPorts = new ${packageName}.${pascal}ExternPorts {`);
    for (const ext of beh.externs ?? []) {
      const defVal = /exists|recorded|already/iu.test(ext.name) ? 'false' : 'true';
      const sig = (ext.params ?? []).map(p => `${p}: Any`).join(', ');
      lines.push(`    override def ${ext.name}(${sig}): Boolean = ${defVal}`);
    }
    lines.push('  }');
    lines.push(`  override val ${camel}Effects: ${packageName}.${pascal}EffectsPort = new ${packageName}.${pascal}EffectsPort {`);
    lines.push('    override def pin(artifact: String, inputs: Map[String, Any]): Unit = {');
    lines.push('      store.pin(artifact, inputs)');
    lines.push(`      recorded += ${packageName}.application.OutboundEffectRecord("pin", artifact, inputs)`);
    lines.push('    }');
    lines.push('    override def dispatch(target: String, payload: Map[String, Any]): Unit = {');
    lines.push('      store.recordDispatch(target, payload)');
    lines.push(`      recorded += ${packageName}.application.OutboundEffectRecord("dispatch", target, payload)`);
    lines.push('    }');
    lines.push('  }');
  }
  lines.push(`  override def recordedEffects: Seq[${packageName}.application.OutboundEffectRecord] = recorded.toSeq`);
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitScalaBootstrapModule(canonicalV2, packageName) {
  const appBehaviors = (canonicalV2.behaviors ?? []).filter(b => b.layer === 'application');
  const lines = [
    '// @generated by co-arising 2.0 (Onion Layer: modules.bootstrap — DO NOT MODIFY)',
    '// Pure Dependency-Inversion Composition Root wiring domain, application, interfaces, and infrastructure.',
    '// @ProvenanceId(layer:modules:bootstrap)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    `package ${packageName}.modules`,
    '',
    'final case class OnionRuntime(',
    `  router: ${packageName}.interfaces.http.HttpRouter,`,
    `  store: ${packageName}.infrastructure.persistence.InMemoryStore,`,
    `  connectors: ${packageName}.application.OutboundConnectorsPort`,
    ')',
    '',
    'object BootstrapModule {',
    '  def createRuntime(',
  ];
  const params = [];
  for (const beh of appBehaviors) {
    const pascal = toPascal(beh.target);
    const camel = toCamel(pascal);
    params.push(`    ${camel}Handler: Option[${packageName}.${pascal}Handler] = None`);
    params.push(`    ${camel}Externs: Option[${packageName}.${pascal}ExternPorts] = None`);
  }
  params.push(`    authority: ${packageName}.interfaces.api.HttpAuthority = ${packageName}.interfaces.api.AllowAllAuthority`);
  params.push(`    store: ${packageName}.infrastructure.persistence.InMemoryStore = new ${packageName}.infrastructure.persistence.InMemoryStore()`);
  lines.push(params.join(',\n'));
  lines.push('  ): OnionRuntime = {');
  lines.push(`    val connectors = new ${packageName}.infrastructure.connectors.DefaultOutboundConnectors(store)`);
  lines.push(`    val router = new ${packageName}.interfaces.http.HttpRouter(`);
  const ctrlArgs = [
    ...appBehaviors.map(b => {
      const pascal = toPascal(b.target);
      const camel = toCamel(pascal);
      return `      ${camel}Controller = ${camel}Handler.map(h => new ${packageName}.interfaces.http.${pascal}Controller(h, ${camel}Externs.getOrElse(connectors.${camel}Externs), connectors.${camel}Effects))`;
    }),
    '      authority = authority',
  ];
  lines.push(ctrlArgs.join(',\n'));
  lines.push('    )');
  lines.push('    OnionRuntime(router = router, store = store, connectors = connectors)');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

export function emitOnionArtifactsScala(canonicalV2, packageName) {
  const pkgDir = packageName.split('.').join('/');
  const routes = deriveStoryHttpRoutes(canonicalV2);
  const appBehaviors = (canonicalV2.behaviors ?? []).filter(b => b.layer === 'application');

  const artifacts = [
    { path: `generated-scaffold/scala/${pkgDir}/domain/DomainFacade.scala`, content: emitScalaDomainFacade(canonicalV2, packageName) },
    { path: `generated-scaffold/scala/${pkgDir}/application/Connectors.scala`, content: emitScalaApplicationConnectors(canonicalV2, packageName) },
    { path: `generated-scaffold/scala/${pkgDir}/interfaces/api/ApiDto.scala`, content: emitScalaInterfacesApiDto(canonicalV2, packageName) },
  ];

  for (const beh of appBehaviors) {
    const pascal = toPascal(beh.target);
    artifacts.push({
      path: `generated-scaffold/scala/${pkgDir}/interfaces/http/${pascal}Controller.scala`,
      content: emitScalaStoryController(beh, canonicalV2, packageName),
    });
  }

  artifacts.push(
    { path: `generated-scaffold/scala/${pkgDir}/interfaces/http/HttpRouter.scala`, content: emitScalaHttpRouter(canonicalV2, routes, packageName) },
    { path: `generated-scaffold/scala/${pkgDir}/infrastructure/persistence/InMemoryStore.scala`, content: emitScalaInMemoryStore(canonicalV2, packageName) },
    { path: `generated-scaffold/scala/${pkgDir}/infrastructure/connectors/EffectAdapters.scala`, content: emitScalaEffectAdapters(canonicalV2, packageName) },
    { path: `generated-scaffold/scala/${pkgDir}/modules/BootstrapModule.scala`, content: emitScalaBootstrapModule(canonicalV2, packageName) },
  );

  return artifacts;
}
