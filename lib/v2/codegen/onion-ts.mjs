function emitInterfacesApiDtoTs(canonicalV2) {
  return [
    '// @generated by co-arising 2.0 (Onion Layer: interfaces.api — DO NOT MODIFY)',
    '// Inbound HTTP wire DTOs and deterministic rejection-to-HTTP status mapping.',
    '// @ProvenanceId(layer:interfaces:api)',
    `// canonicalSha256: ${canonicalV2.canonicalSha256}`,
    '',
    'export interface Principal {',
    '  readonly id: string;',
    '  readonly roles: readonly string[];',
    '  readonly tenantId?: string;',
    '  readonly attributes?: Readonly<Record<string, unknown>>;',
    '}',
    '',
    'export interface AuthzDecisionQuery {',
    '  readonly principal: Principal;',
    '  readonly callerKind: string;',
    '  readonly action: string;',
    '  readonly scope?: string;',
    '  readonly policyRef?: string;',
    '  readonly context: Readonly<Record<string, unknown>>;',
    '}',
    '',
    '/** Pluggable PDP seam: bridge to auth-core RoleResolver, Workday Org-Role, OPA, or OpenFGA. */',
    'export interface AuthorizationPort {',
    '  readonly decide: (query: AuthzDecisionQuery) => boolean;',
    '}',
    '',
    'export interface HttpAuthority {',
    '  readonly authenticate: (req: HttpRequestDto) => Principal | null;',
    '  readonly authorize: (principal: Principal, route: RouteDescriptor, req?: HttpRequestDto) => boolean;',
    '  readonly verifyCsrf?: (req: HttpRequestDto) => boolean;',
    '}',
    '',
    'export const allowAllAuthority: HttpAuthority = {',
    '  authenticate: () => ({ id: "system-default", roles: ["*"] }),',
    '  authorize: () => true,',
    '  verifyCsrf: () => true,',
    '};',
    '',
    'export function extractAuthzContext(route: RouteDescriptor, req?: HttpRequestDto, principal?: Principal): Record<string, unknown> {',
    '  const out: Record<string, unknown> = {};',
    '  const payload: Record<string, unknown> = { ...(req?.query ?? {}), ...(req?.body ?? {}) };',
    '  for (const cp of route.contextParams ?? []) {',
    '    if (cp.from.startsWith("param.")) out[cp.name] = payload[cp.from.slice(6)];',
    '    else if (cp.from.startsWith("token.")) {',
    '      const key = cp.from.slice(6);',
    '      out[cp.name] = key === "tenantId" ? principal?.tenantId : principal?.attributes?.[key];',
    '    } else if (cp.from.startsWith("header.")) {',
    '      out[cp.name] = req?.headers?.[cp.from.slice(7)];',
    '    }',
    '  }',
    '  return out;',
    '}',
    '',
    'export function createRoleBasedAuthority(',
    '  authenticate: (req: HttpRequestDto) => Principal | null,',
    '  pdp?: AuthorizationPort,',
    '  verifyCsrf?: (req: HttpRequestDto) => boolean,',
    '): HttpAuthority {',
    '  return {',
    '    authenticate,',
    '    authorize(principal: Principal, route: RouteDescriptor, req?: HttpRequestDto): boolean {',
    '      if (route.authzMode === "public") return true;',
    '      if (route.authzMode === "external-pdp") {',
    '        if (!pdp) return false;',
    '        return pdp.decide({',
    '          principal,',
    '          callerKind: route.callerKind ?? "human",',
    '          action: route.action ?? route.operation,',
    '          scope: route.scope,',
    '          policyRef: route.policyRef,',
    '          context: extractAuthzContext(route, req, principal),',
    '        });',
    '      }',
    '      const allowed = route.allowedRoles ?? [];',
    '      if (allowed.length === 0) return true;',
    '      if (principal.roles.includes("*")) return true;',
    '      return principal.roles.some(r => allowed.includes(r));',
    '    },',
    '    verifyCsrf: verifyCsrf ?? (() => true),',
    '  };',
    '}',
    '',
    'export interface HttpRequestDto {',
    '  readonly method: string;',
    '  readonly path: string;',
    '  readonly headers?: Readonly<Record<string, string | undefined>>;',
    '  readonly query?: Readonly<Record<string, string | undefined>>;',
    '  readonly body?: Readonly<Record<string, unknown>>;',
    '  readonly stateSnapshot?: Readonly<Record<string, unknown>>;',
    '  readonly principal?: Principal;',
    '}',
    '',
    'export interface HttpResponseDto {',
    '  readonly status: number;',
    '  readonly headers: Readonly<Record<string, string>>;',
    '  readonly body: Readonly<Record<string, unknown>>;',
    '}',
    '',
    'export interface RouteContextParam {',
    '  readonly name: string;',
    '  readonly from: string;',
    '}',
    '',
    'export interface RouteDescriptor {',
    '  readonly method: "GET" | "POST";',
    '  readonly path: string;',
    '  readonly story: string;',
    '  readonly operation: string;',
    '  readonly callerKind?: string;',
    '  readonly authzMode?: string;',
    '  readonly action?: string;',
    '  readonly scope?: string;',
    '  readonly allowedRoles?: readonly string[];',
    '  readonly policyRef?: string;',
    '  readonly contextParams?: readonly RouteContextParam[];',
    '}',
    '',
    'export function mapRejectionToHttpStatus(code: string): number {',
    '  const upper = String(code ?? "").toUpperCase();',
    '  if (upper.includes("UNAUTHORIZED") || upper.includes("CSRF") || upper.includes("AUTH")) return 401;',
    '  if (upper.includes("FORBIDDEN")) return 403;',
    '  if (upper.includes("CONFLICT") || upper.includes("ALREADY")) return 409;',
    '  if (upper.includes("NOT_FOUND") || upper.includes("UNKNOWN")) return 404;',
    '  return 400;',
    '}',
    '',
    'export function jsonResponse(status: number, body: Readonly<Record<string, unknown>>): HttpResponseDto {',
    '  return {',
    '    status,',
    '    headers: { "content-type": "application/json; charset=utf-8" },',
    '    body,',
    '  };',
    '}',
    '',
  ].join('\n');
}

