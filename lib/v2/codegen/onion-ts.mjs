// Onion 5-Layer TypeScript artifact emitters for co-arising 2.0:
//   1. domain/          (pure barrel, zero outer/framework imports)
//   2. application/     (outbound connector ports + port barrel)
//   3. interfaces/      (inbound api/dto + http/<story>.controller + http/router)
//   4. infrastructure/  (in-memory persistence store + outbound effect adapters)
//   5. modules/         (pure DIP bootstrap + runnable zero-dependency node:http server)
