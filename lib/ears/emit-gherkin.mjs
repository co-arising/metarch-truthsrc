// Projection 4a: Locked Gherkin (.feature) emitter from TestIR.
import { createHash } from 'node:crypto';

function escapePipe(val) {
  return String(val).replaceAll('|', '\\|');
}

function collectSampleColumns(examples) {
  const keys = new Set();
  for (const ex of examples) {
    for (const k of Object.keys(ex.witness ?? {})) {
      if (!k.startsWith('@host(')) keys.add(k);
    }
  }
  return [...keys].sort().slice(0, 6);
}

export function emitGherkinFeature(testIr) {
  const { meta, scenarios } = testIr;
  const featureTags = [`@layer:${meta.layer}`];
  if (meta.aggregate) featureTags.push(`@aggregate:${meta.aggregate}`);
  if (meta.slice) featureTags.push(`@slice:${meta.slice}`);
  if (meta.story) featureTags.push(`@story:${meta.story}`);

  const lines = [
    '# AUTO-GENERATED BY co-arising EARS 1.0 (LOCKED — DO NOT EDIT)',
    `# source: ${meta.sourceFile} | sha256: ${meta.sourceSha256} | logic: ${meta.logic}`,
    '',
    featureTags.join(' '),
    `Feature: ${meta.target} (${meta.layer})`,
    '',
  ];

  for (const sc of scenarios) {
    lines.push(`  ${sc.tags.join(' ')}`);
    if (sc.kind === 'bmc') {
      lines.push(`  Scenario: ${sc.title}`);
      lines.push(`    Given ${meta.target} satisfies all declared global axioms at step 0`);
      lines.push(`    When any valid ${sc.bmc.steps}-step sequence of declared commands executes`);
      lines.push(`    Then safety property "${sc.id}" holds (${sc.bmc.status})`);
      lines.push('');
      continue;
    }

    const cols = collectSampleColumns(sc.examples);
    if (cols.length > 0 && sc.examples.length > 0) {
      lines.push(`  Scenario Outline: ${sc.title}`);
      lines.push(`    Given state and inputs satisfying Z3 witness for <ruleId>`);
      lines.push(`    When executing ${sc.command} with ${cols.map(c => `${c}=<${c}>`).join(', ')}`);
      lines.push(`    Then outcome shall be <outcome>`);
      lines.push('');
      lines.push('    Examples:');
      const header = ['ruleId', ...cols, 'outcome'];
      lines.push(`      | ${header.map(escapePipe).join(' | ')} |`);
      for (const ex of sc.examples) {
        const row = [
          ex.ruleId,
          ...cols.map(c => (Object.hasOwn(ex.witness, c) ? JSON.stringify(ex.witness[c]) : '-')),
          ex.outcome,
        ];
        lines.push(`      | ${row.map(escapePipe).join(' | ')} |`);
      }
      lines.push('');
    } else {
      lines.push(`  Scenario: ${sc.title}`);
      for (const ex of sc.examples) {
        lines.push(`    When rule [${ex.ruleId}] matches ${sc.command}`);
        lines.push(`    Then outcome shall be ${ex.outcome}`);
      }
      lines.push('');
    }
  }

  const content = lines.join('\n');
  const slug = meta.target.replace(/[^A-Za-z0-9]+/gu, '-').replace(/^-|-$/gu, '').toLowerCase();
  return {
    path: `${slug}.feature`,
    content,
    sha256: createHash('sha256').update(content).digest('hex'),
  };
}
