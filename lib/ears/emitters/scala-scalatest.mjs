// Projection 4b: Locked ScalaTest (AnyFunSuite) EarsTestEmitter with @CoArisingSpec anchors.
import { createHash } from 'node:crypto';
import { registerEmitter } from './interface.mjs';

function toPascal(raw) {
  return raw
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function escapeScalaString(str) {
  return String(str)
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n');
}

function formatWitnessLiteral(witness) {
  const entries = Object.entries(witness ?? {})
    .filter(([k]) => !k.startsWith('@host('))
    .sort(([a], [b]) => a.localeCompare(b));
  if (entries.length === 0) return 'Map.empty[String, String]';
  const pairs = entries.map(([k, v]) => `"${escapeScalaString(k)}" -> "${escapeScalaString(String(v))}"`);
  return `Map(${pairs.join(', ')})`;
}

function renderScalaSuite(testIr, { packageName = 'example.ears', layerKind }) {
  const { meta, scenarios } = testIr;
  const className = `${toPascal(meta.target)}EarsSpec`;
  const lines = [
    '// LOCKED BDD ORACLE — GENERATED BY co-arising EARS 1.0 (DO NOT MODIFY)',
    `// source: ${meta.sourceFile}`,
    `// sourceSha256: ${meta.sourceSha256}`,
    `// testIrSha256: ${testIr.sha256}`,
    `// layer: ${layerKind} | logic: ${meta.logic} | verified: ${meta.verified}`,
    `package ${packageName}`,
    '',
    'import org.scalatest.funsuite.AnyFunSuite',
    '',
    `final class ${className} extends AnyFunSuite {`,
    `  private val specTarget: String = "${escapeScalaString(meta.target)}"`,
    `  private val specLogic: String = "${escapeScalaString(meta.logic)}"`,
    `  private val sourceSha256: String = "${meta.sourceSha256}"`,
    '',
  ];

  for (const sc of scenarios) {
    if (sc.kind === 'bmc') {
      const ruleId = sc.ruleIds[0] ?? sc.id;
      lines.push(`  // @CoArisingSpec(id="${escapeScalaString(ruleId)}", witness="${escapeScalaString(sc.id)}")`);
      lines.push(`  test("[${escapeScalaString(ruleId)}] ${escapeScalaString(sc.title)}") {`);
      lines.push(`    assert(specTarget == "${escapeScalaString(meta.target)}")`);
      lines.push(`    assert(${sc.bmc.passed}, "SMT ${sc.bmc.steps}-step BMC safety property failed: ${escapeScalaString(sc.id)}")`);
      lines.push('  }');
      lines.push('');
      continue;
    }

    for (const ex of sc.examples) {
      const witnessId = `z3-${meta.logic.toLowerCase()}-${ex.ruleId.toLowerCase()}`;
      lines.push(`  // @CoArisingSpec(id="${escapeScalaString(ex.ruleId)}", witness="${escapeScalaString(witnessId)}")`);
      lines.push(`  test("[${escapeScalaString(ex.ruleId)}] ${escapeScalaString(sc.command)} -> ${escapeScalaString(ex.outcome)}") {`);
      lines.push(`    val witness: Map[String, String] = ${formatWitnessLiteral(ex.witness)}`);
      lines.push(`    val expectedOutcome: String = "${escapeScalaString(ex.outcome)}"`);
      lines.push(`    assert(sourceSha256.nonEmpty && specLogic.nonEmpty)`);
      lines.push(`    assert(expectedOutcome.nonEmpty && witness != null)`);
      lines.push('  }');
      lines.push('');
    }
  }

  lines.push('}');
  lines.push('');

  const content = lines.join('\n');
  const pkgPath = packageName.replaceAll('.', '/');
  return {
    path: `${pkgPath}/${className}.scala`,
    className,
    content,
    sha256: createHash('sha256').update(content).digest('hex'),
  };
}

export const scalaScalaTestEmitter = registerEmitter({
  language: 'scala',
  framework: 'scalatest',
  emitDomainSpec(testIr, options = {}) {
    return renderScalaSuite(testIr, { ...options, layerKind: 'domain' });
  },
  emitApplicationSpec(testIr, options = {}) {
    return renderScalaSuite(testIr, { ...options, layerKind: 'application' });
  },
});

export function buildLockedManifest(generatedFiles, { generatorVersion = 'co-arising-ears/1.0' } = {}) {
  const entries = [...generatedFiles]
    .sort((a, b) => a.relativePath.localeCompare(b.relativePath))
    .map(f => ({
      path: f.relativePath,
      sha256: f.sha256,
      sourceFile: f.sourceFile ?? null,
      sourceSha256: f.sourceSha256 ?? null,
    }));
  return {
    schemaVersion: 'co-arising.locked-tests-manifest/v1',
    generator: generatorVersion,
    files: entries,
  };
}
