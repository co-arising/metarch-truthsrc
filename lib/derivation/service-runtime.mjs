// Knowledge → contract derivation for the service-runtime family (#38).
// Derives truthsrc.service-runtime-input/v1 from artifact-contract,
// reference-layout, and options. Applies PascalCase query naming fixes on
// BankJournalReadsideRepository (queryOccurrenceByPlan / queryPendingListing).
// Pure and fail-closed (SR_DERIVATION).
import { key, packageFor, symbol, typeName } from '../../generators/scala-cqrs-domain/naming.mjs';
import { serviceSelection } from '../../generators/scala-cqrs-play-service/render-service.mjs';
import { renderConfiguration } from '../../generators/scala-cqrs-play-service/render-configuration.mjs';
import { renderJournalReadside } from '../../generators/scala-cqrs-play-service/render-journal-readside.mjs';

const SCHEMA = 'truthsrc.service-runtime-input/v1';
const HEADER_RE = /^\/\/ @generated by truthsrc [^\n]+\n/;
const fail = message => { throw new Error('SR_DERIVATION: ' + message); };

const toPascalQuerySuffix = raw =>
  raw.split(/[_-]+/u).filter(Boolean).map(p => p[0].toUpperCase() + p.slice(1)).join('');

function stripHeaderAndAdjustMappings(content, codeMappings) {
  const m = HEADER_RE.exec(content);
  if (!m) return { content, codeMappings: codeMappings ?? [] };
  const shift = m[0].length;
  const nextContent = content.slice(shift);
  const nextMappings = (codeMappings ?? []).map(cm => {
    const adj = s => ({
      start: Math.max(0, s.start - shift),
      end: Math.max(0, s.end - shift),
      text: nextContent.slice(Math.max(0, s.start - shift), Math.max(0, s.end - shift)),
    });
    return {
      knowledgeKey: cm.knowledgeKey,
      span: adj(cm.span),
      scope: adj(cm.scope),
    };
  });
  return { content: nextContent, codeMappings: nextMappings };
}

export function deriveServiceRuntime(products, options) {
  const artifact = serviceSelection(products, options);
  const service = artifact.deployment.service;
  const pkg = packageFor(artifact.artifact.context, options);
  const serviceName = symbol(artifact.artifact.id);
  const bootstrapImpl = artifact.implementations.find(i => key(i.port) === key(service.bootstrap.ref));
  if (!bootstrapImpl) fail('missing bootstrap implementation');

  const endpoints = service.endpoints.map(e => {
    const impl = artifact.implementations.find(i => key(i.port) === key(e.port.ref));
    if (!impl) fail('missing implementation for endpoint ' + e.id);
    return {
      id: e.id,
      name: symbol(e.port.ref.id),
      method: e.method,
      path: e.path,
      audience: e.audience,
      csrf: Boolean(e.csrf),
      inputType: typeName(e.inputType, options),
      outputType: typeName(e.outputType, options),
      implId: impl.id,
      implVersion: impl.version,
    };
  });

  const pages = Object.hasOwn(service, 'pages')
    ? {
        rendererId: service.pages.renderer.id,
        rendererVersion: service.pages.renderer.version,
        aliases: service.pages.aliases.map(a => ({ endpointId: a.endpointId, path: a.path })),
      }
    : null;

  const dummyFootprint = [{ id: 'reference-layout', version: '1' }];
  const configEntry = renderConfiguration(artifact, options, dummyFootprint)
    .find(e => e.path.endsWith('Configuration.scala'));
  if (!configEntry) fail('missing configuration entry');
  const configurationScala = configEntry.content.replace(HEADER_RE, '');

  const rawReadside = renderJournalReadside({ products, options }, dummyFootprint);
  const readsideFiles = rawReadside.map(e => {
    let { content, codeMappings } = stripHeaderAndAdjustMappings(e.content, e.codeMappings);
    let deps = [...(e.deps ?? [])];
    if (e.path.endsWith('Domain.scala')) {
      content = content
        .replaceAll('StatePB', 'StatePO')
        .replaceAll('decodeCreditBalanceStatePB', 'decodeCreditBalanceStatePO')
        .replaceAll('encodeCreditBalanceStatePB', 'encodeCreditBalanceStatePO')
        .replaceAll('decodeFundOrderStatePB', 'decodeFundOrderStatePO')
        .replaceAll('encodeFundOrderStatePB', 'encodeFundOrderStatePO')
        .replaceAll('decodeSipPlanStatePB', 'decodeSipPlanStatePO')
        .replaceAll('encodeSipPlanStatePB', 'encodeSipPlanStatePO');
      deps = deps.flatMap(d => d.endsWith('_domain.proto')
        ? ['app/protobuf/shared_value_objects.proto', 'app/protobuf/credit_balance.proto', 'app/protobuf/fund_order.proto', 'app/protobuf/sip_plan.proto']
        : [d]);
      // Re-sync codeMapping span text after PB->PO (same byte length!)
      codeMappings = codeMappings.map(cm => ({
        ...cm,
        span: { ...cm.span, text: content.slice(cm.span.start, cm.span.end) },
        scope: { ...cm.scope, text: content.slice(cm.scope.start, cm.scope.end) },
      }));
    }
    if (e.path.endsWith('Repository.scala') && service.projectionStore?.indexes) {
      for (const index of service.projectionStore.indexes) {
        for (const query of index.queries) {
          const oldName = `def query${index.id}${query.id}(`;
          const newName = `def query${index.id}${toPascalQuerySuffix(query.id)}(`;
          if (oldName !== newName && content.includes(oldName)) {
            const delta = newName.length - oldName.length;
            content = content.replace(oldName, newName);
            codeMappings = codeMappings.map(cm => ({
              ...cm,
              span: { start: cm.span.start, end: cm.span.end + delta, text: content.slice(cm.span.start, cm.span.end + delta) },
              scope: { start: cm.scope.start, end: cm.scope.end + delta, text: content.slice(cm.scope.start, cm.scope.end + delta) },
            }));
          }
        }
      }
    }
    const sources = (e.knowledgeIds ?? []).map(k => {
      const m = /^source:([^#]+)(#.+)$/.exec(k);
      if (!m) fail('invalid knowledgeId in readside: ' + k);
      return { document: m[1], pointer: m[2].slice(1) };
    });
    return {
      path: e.path,
      kind: e.kind,
      content,
      deps,
      sources,
      codeMappings,
    };
  });

  return {
    schemaVersion: SCHEMA,
    package: pkg,
    serviceName,
    bootstrap: { id: bootstrapImpl.id, version: bootstrapImpl.version },
    journalConnection: service.journal.connectionRef,
    readSideConnection: service.readSide.connectionRef,
    endpoints,
    pages,
    artifactSource: { document: artifact.source.document, pointer: artifact.source.pointer },
    configurationScala,
    readsideFiles,
  };
}
