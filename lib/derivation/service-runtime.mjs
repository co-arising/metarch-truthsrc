// Knowledge → contract derivation for the service-runtime family (#38).
// Derives truthsrc.service-runtime-input/v1 from artifact-contract,
// reference-layout, and options. Applies PascalCase query naming fixes on
// BankJournalReadsideRepository (queryOccurrenceByPlan / queryPendingListing).
// Pure and fail-closed (SR_DERIVATION).
import { key, packageFor, symbol, typeName } from '../../generators/scala-cqrs-domain/naming.mjs';
import { valueObjectPackage, valueObjectSubpackage } from './value-object-package.mjs';
import { serviceSelection } from '../../generators/scala-cqrs-play-service/render-service.mjs';
import { renderConfiguration } from '../../generators/scala-cqrs-play-service/render-configuration.mjs';
import { renderJournalReadside } from '../../generators/scala-cqrs-play-service/render-journal-readside.mjs';

const SCHEMA = 'truthsrc.service-runtime-input/v1';
const HEADER_RE = /^\/\/ @generated by truthsrc [^\n]+\n/;
const fail = message => { throw new Error('SR_DERIVATION: ' + message); };

const toPascalQuerySuffix = raw =>
  raw.split(/[_-]+/u).filter(Boolean).map(p => p[0].toUpperCase() + p.slice(1)).join('');

function stripHeaderAndAdjustMappings(content, codeMappings) {
  const m = HEADER_RE.exec(content);
  if (!m) return { content, codeMappings: codeMappings ?? [] };
  const shift = m[0].length;
  const nextContent = content.slice(shift);
  const nextMappings = (codeMappings ?? []).map(cm => {
    const adj = s => ({
      start: Math.max(0, s.start - shift),
      end: Math.max(0, s.end - shift),
      text: nextContent.slice(Math.max(0, s.start - shift), Math.max(0, s.end - shift)),
    });
    return {
      knowledgeKey: cm.knowledgeKey,
      span: adj(cm.span),
      scope: adj(cm.scope),
    };
  });
  return { content: nextContent, codeMappings: nextMappings };
}

export function deriveServiceRuntime(products, options) {
  const artifact = serviceSelection(products, options);
  const service = artifact.deployment.service;
  const pkg = packageFor(artifact.artifact.context, options);
  const serviceName = symbol(artifact.artifact.id);
  const bootstrapImpl = artifact.implementations.find(i => key(i.port) === key(service.bootstrap.ref));
  if (!bootstrapImpl) fail('missing bootstrap implementation');

  const resolveServiceType = t => {
    if (t?.form === 'nominal') return valueObjectPackage(packageFor(t.ref.context, options), symbol(t.ref.id)) + '.' + symbol(t.ref.id);
    return typeName(t, options);
  };
  const endpoints = service.endpoints.map(e => {
    const impl = artifact.implementations.find(i => key(i.port) === key(e.port.ref));
    if (!impl) fail('missing implementation for endpoint ' + e.id);
    return {
      id: e.id,
      name: symbol(e.port.ref.id),
      method: e.method,
      path: e.path,
      audience: e.audience,
      csrf: Boolean(e.csrf),
      inputType: resolveServiceType(e.inputType),
      outputType: resolveServiceType(e.outputType),
      implId: impl.id,
      implVersion: impl.version,
    };
  });

  const pages = Object.hasOwn(service, 'pages')
    ? {
        rendererId: service.pages.renderer.id,
        rendererVersion: service.pages.renderer.version,
        aliases: service.pages.aliases.map(a => ({ endpointId: a.endpointId, path: a.path })),
      }
    : null;

  const dummyFootprint = [{ id: 'reference-layout', version: '1' }];
  const configEntry = renderConfiguration(artifact, options, dummyFootprint)
    .find(e => e.path.endsWith('Configuration.scala'));
  if (!configEntry) fail('missing configuration entry');
  const configurationScala = configEntry.content
    .replace(HEADER_RE, '')
    .replace(`package ${pkg}.service`, `package ${pkg}.infrastructure.bootstrap`);

  const relocateReadsidePath = p => {
    if (p.endsWith('Repository.scala') || p.endsWith('Schema.scala')) return p.replace('/infrastructure/projection/', '/infrastructure/repositories/projection/');
    if (p.includes('/infrastructure/projection/')) return p.replace('/infrastructure/projection/', '/application/projection/');
    return p;
  };
  const relocateDep = d => {
    const voMatch = /^(.+)\/domain\/values\/([A-Za-z0-9_]+)\.scala$/.exec(d);
    if (voMatch) {
      return [voMatch[1] + '/' + valueObjectSubpackage(voMatch[2]).replaceAll('.', '/') + '/' + voMatch[2] + '.scala'];
    }
    if (d.endsWith('_domain.proto')) {
      return ['app/protobuf/shared_value_objects.proto', 'app/protobuf/credit_balance.proto', 'app/protobuf/fund_order.proto', 'app/protobuf/sip_plan.proto'];
    }
    if (d.includes('/infrastructure/serialization/DomainConverters.scala')) {
      return [d.replace('/infrastructure/serialization/', '/infrastructure/persistence/converters/')];
    }
    if (d.includes('/infrastructure/serialization/')) {
      return [d.replace('/infrastructure/serialization/', '/infrastructure/persistence/')];
    }
    for (const agg of ['CreditBalance', 'FundOrder', 'SipPlan']) {
      if (d.endsWith('/domain/' + agg + 'State.scala')) return [d.replace('/domain/' + agg + 'State.scala', '/domain/entities/' + agg + 'Entity.scala')];
      if (d.endsWith('/domain/' + agg + 'Protocol.scala')) return [d.replace('/domain/' + agg + 'Protocol.scala', '/domain/entities/' + agg + 'Entity.scala')];
      if (d.endsWith('/domain/' + agg + 'EventHandler.scala')) return [d.replace('/domain/' + agg + 'EventHandler.scala', '/domain/entities/behaviors/' + agg + 'EventHandler.scala')];
    }
    return [relocateReadsidePath(d)];
  };
  const resyncMappings = (nextContent, mappings, rewriteText = x => x) => mappings.map(cm => {
    const spanText = rewriteText(cm.span.text);
    const scopeText = rewriteText(cm.scope.text);
    const scopeIdx = nextContent.indexOf(scopeText);
    if (scopeIdx < 0) fail('resync scope text not found: ' + scopeText.slice(0, 60));
    const relSpanIdx = scopeText.indexOf(spanText);
    const spanIdx = relSpanIdx >= 0 ? scopeIdx + relSpanIdx : nextContent.indexOf(spanText);
    if (spanIdx < 0) fail('resync span text not found: ' + spanText.slice(0, 60));
    const spanStart = Buffer.byteLength(nextContent.slice(0, spanIdx));
    const spanEnd = spanStart + Buffer.byteLength(spanText);
    const scopeStart = Buffer.byteLength(nextContent.slice(0, scopeIdx));
    const scopeEnd = scopeStart + Buffer.byteLength(scopeText);
    return {
      knowledgeKey: cm.knowledgeKey,
      span: { start: spanStart, end: spanEnd, text: spanText },
      scope: { start: scopeStart, end: scopeEnd, text: scopeText },
    };
  });

  const rawReadside = renderJournalReadside({ products, options }, dummyFootprint);
  const readsideFiles = rawReadside.map(e => {
    let content = e.content.replace(HEADER_RE, '');
    let codeMappings = (e.codeMappings ?? []).map(cm => ({
      knowledgeKey: cm.knowledgeKey,
      span: { ...cm.span },
      scope: { ...cm.scope },
    }));
    let deps = [...new Set((e.deps ?? []).flatMap(relocateDep))];
    const nextPath = relocateReadsidePath(e.path);
    if (e.path.endsWith('Repository.scala') || e.path.endsWith('Schema.scala')) {
      const renames = [];
      if (service.projectionStore?.indexes) {
        for (const index of service.projectionStore.indexes) {
          for (const query of index.queries) {
            const oldName = `def query${index.id}${query.id}(`;
            const newName = `def query${index.id}${toPascalQuerySuffix(query.id)}(`;
            if (oldName !== newName) renames.push([oldName, newName]);
          }
        }
      }
      const rewriteRepo = txt => {
        let out = txt.replace(`package ${pkg}.infrastructure.projection`, `package ${pkg}.infrastructure.repositories.projection`);
        for (const [o, n] of renames) out = out.replaceAll(o, n);
        return out;
      };
      content = rewriteRepo(content);
      codeMappings = resyncMappings(content, codeMappings, rewriteRepo);
    } else if (e.path.includes('/infrastructure/projection/')) {
      const rewriteProj = txt => {
        let out = txt.replace(`package ${pkg}.infrastructure.projection`, `package ${pkg}.application.projection`);
        if (e.path.endsWith('Projection.scala') || e.path.endsWith('Domain.scala')) {
          out = out.replace(
            `package ${pkg}.application.projection\n`,
            `package ${pkg}.application.projection\n\nimport ${pkg}.infrastructure.repositories.projection.BankJournalReadsideRepository\n`
          );
        }
        if (e.path.endsWith('Domain.scala')) {
          out = out
            .replaceAll(`${pkg}.infrastructure.serialization.DomainConverters`, `${pkg}.infrastructure.persistence.converters.DomainConverters`)
            .replaceAll(`${pkg}.infrastructure.serialization.`, `${pkg}.infrastructure.persistence.`)
            .replaceAll(`${pkg}.domain.CreditBalanceState.empty`, `${pkg}.domain.entities.CreditBalanceEntity.empty`)
            .replaceAll(`${pkg}.domain.FundOrderState.empty`, `${pkg}.domain.entities.FundOrderEntity.empty`)
            .replaceAll(`${pkg}.domain.SipPlanState.empty`, `${pkg}.domain.entities.SipPlanEntity.empty`)
            .replaceAll(`${pkg}.domain.CreditBalanceState`, `${pkg}.domain.entities.CreditBalanceEntity.State`)
            .replaceAll(`${pkg}.domain.FundOrderState`, `${pkg}.domain.entities.FundOrderEntity.State`)
            .replaceAll(`${pkg}.domain.SipPlanState`, `${pkg}.domain.entities.SipPlanEntity.State`)
            .replaceAll(`${pkg}.domain.CreditBalanceProtocol.`, `${pkg}.domain.entities.CreditBalanceEntity.`)
            .replaceAll(`${pkg}.domain.FundOrderProtocol.`, `${pkg}.domain.entities.FundOrderEntity.`)
            .replaceAll(`${pkg}.domain.SipPlanProtocol.`, `${pkg}.domain.entities.SipPlanEntity.`)
            .replaceAll(`${pkg}.domain.CreditBalanceEventHandler`, `${pkg}.domain.entities.behaviors.CreditBalanceEventHandler`)
            .replaceAll(`${pkg}.domain.FundOrderEventHandler`, `${pkg}.domain.entities.behaviors.FundOrderEventHandler`)
            .replaceAll(`${pkg}.domain.SipPlanEventHandler`, `${pkg}.domain.entities.behaviors.SipPlanEventHandler`)
            .replaceAll('StatePB', 'StatePO')
            .replaceAll('decodeCreditBalanceStatePB', 'decodeCreditBalanceStatePO')
            .replaceAll('encodeCreditBalanceStatePB', 'encodeCreditBalanceStatePO')
            .replaceAll('decodeFundOrderStatePB', 'decodeFundOrderStatePO')
            .replaceAll('encodeFundOrderStatePB', 'encodeFundOrderStatePO')
            .replaceAll('decodeSipPlanStatePB', 'decodeSipPlanStatePO')
            .replaceAll('encodeSipPlanStatePB', 'encodeSipPlanStatePO');
        }
        return out;
      };
      content = rewriteProj(content);
      codeMappings = resyncMappings(content, codeMappings, rewriteProj);
    }
    const sources = (e.knowledgeIds ?? []).map(k => {
      const m = /^source:([^#]+)(#.+)$/.exec(k);
      if (!m) fail('invalid knowledgeId in readside: ' + k);
      return { document: m[1], pointer: m[2].slice(1) };
    });
    return {
      path: nextPath,
      kind: e.kind,
      content,
      deps,
      sources,
      codeMappings,
    };
  });

  return {
    schemaVersion: SCHEMA,
    package: pkg,
    serviceName,
    bootstrap: { id: bootstrapImpl.id, version: bootstrapImpl.version },
    journalConnection: service.journal.connectionRef,
    readSideConnection: service.readSide.connectionRef,
    endpoints,
    pages,
    artifactSource: { document: artifact.source.document, pointer: artifact.source.pointer },
    configurationScala,
    readsideFiles,
  };
}
