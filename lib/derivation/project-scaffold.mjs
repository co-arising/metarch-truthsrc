// Knowledge → contract derivation for the project-scaffold family (#39).
// Derives truthsrc.project-scaffold-input/v1 for build files, the 2-parent-
// class conf/serialization.conf, and unit/generated test specs.
// Pure and fail-closed (PSC_DERIVATION).
import { packageFor } from '../../generators/scala-cqrs-domain/naming.mjs';
import { flipHostBase } from './pipeline-invocation-face.mjs';
import { effectFlipHostClass } from './effect-face.mjs';
import { collectProcessOriginalNames, valueObjectPath } from './value-object-package.mjs';
import { resolveRuntimeProfile } from '../runtime-profile.mjs';

const SCHEMA = 'truthsrc.project-scaffold-input/v1';
const HEADER_RE = /^\/\/ @generated by truthsrc [^\n]+\n/;
const fail = message => { throw new Error('PSC_DERIVATION: ' + message); };

const parseSources = knowledgeIds =>
  (knowledgeIds ?? []).map(k => {
    const m = /^source:([^#]+)(#.+)$/.exec(k);
    if (!m) fail('invalid knowledgeId: ' + k);
    return { document: m[1], pointer: m[2].slice(1) };
  });

export function deriveProjectScaffold(products, options, scaffoldEntries) {
  const layout = products?.['reference-layout'];
  if (!layout || !Array.isArray(scaffoldEntries)) fail('reference-layout and scaffoldEntries required');

  const domainSerializers = layout.contexts.map((ctx, i) => ({
    key: 'domainProto' + i,
    className: packageFor(ctx, options) + '.infrastructure.persistence.DomainProtoSerializer',
  }));

  const serEntry = scaffoldEntries.find(e => e.path === 'conf/serialization.conf' || e.path === 'src/main/resources/application.conf');
  const hosts = serEntry && Object.hasOwn(products, 'saga-host-contract')
    ? (products['saga-host-contract']?.hosts ?? []).map((h, i) => {
        const pkg = packageFor(h.saga.ref.context, options);
        const base = flipHostBase(h.id);
        return {
          key: 'host' + i,
          serializerClass: pkg + '.infrastructure.persistence.' + base + 'HostSerializer',
          eventClass: pkg + '.infrastructure.process.' + base + 'Host$Event',
        };
      })
    : [];

  const effects = serEntry && Object.hasOwn(products, 'effect-host-contract')
    ? (products['effect-host-contract']?.hosts ?? []).map((h, i) => {
        const pkg = packageFor(h.pipeline.ref.context, options);
        const cls = effectFlipHostClass(h.id);
        return {
          key: 'effect' + i,
          serializerClass: pkg + '.infrastructure.persistence.' + cls + 'Serializer',
          eventClass: pkg + '.infrastructure.connectors.' + cls + '$Event',
        };
      })
    : [];

  const serSources = serEntry ? parseSources(serEntry.knowledgeIds) : layout.declarations.filter(d => d.ref.kind === 'aggregate').map(a => a.source);

  const runtimeProfile = resolveRuntimeProfile(options);
  const primaryPkg = packageFor(layout.contexts[0], options);
  const aggNames = layout.declarations.filter(d => d.ref?.kind === 'aggregate').map(d => d.ref.id);
  const processOriginals = collectProcessOriginalNames(
    layout.declarations.filter(d => d.ref?.kind === 'type').map(d => d.ref.id)
  );
  const serviceArtifact = Object.hasOwn(products, 'artifact-contract')
    ? (products['artifact-contract']?.artifacts ?? []).find(a => a.id === options?.service?.artifact && a.status === 'selected')
    : null;
  const serviceName = serviceArtifact?.artifact?.id ?? null;
  const relocateScaffoldDep = d => {
    const voMatch = /^(.+)\/domain\/values\/([A-Za-z0-9_]+)\.scala$/.exec(d);
    if (voMatch) {
      if (/PO$/u.test(voMatch[2])) return 'app/protobuf/shared_value_objects.proto';
      return valueObjectPath(primaryPkg, voMatch[2], { processOriginals });
    }
    const svcMatch = /\/service\/([A-Za-z0-9_]+)Service\.scala$/.exec(d);
    if (svcMatch) return d.replace(`/service/${svcMatch[1]}Service.scala`, `/infrastructure/bootstrap/${svcMatch[1]}Contract.scala`);
    if (d.includes('/service/')) return d.replace('/service/', '/infrastructure/bootstrap/');
    if (d.includes('/infrastructure/serialization/DomainConverters.scala')) return d.replace('/infrastructure/serialization/', '/infrastructure/persistence/converters/');
    if (d.includes('/infrastructure/serialization/')) return d.replace('/infrastructure/serialization/', '/infrastructure/persistence/');
    for (const agg of aggNames) {
      if (d.endsWith('/domain/' + agg + 'State.scala')) return d.replace('/domain/' + agg + 'State.scala', '/domain/entities/' + agg + 'Entity.scala');
      if (d.endsWith('/domain/' + agg + 'Protocol.scala')) return d.replace('/domain/' + agg + 'Protocol.scala', '/domain/invariants/params/' + agg + 'RuleParams.scala');
      if (d.endsWith('/domain/' + agg + 'CommandHelpers.scala')) return d.replace('/domain/' + agg + 'CommandHelpers.scala', '/domain/services/' + agg + 'Computations.scala');
      if (d.endsWith('/domain/' + agg + 'Aggregate.scala')) return d.replace('/domain/' + agg + 'Aggregate.scala', '/application/aggregates/' + agg + 'Protocol.scala');
    }
    return d;
  };

  const files = scaffoldEntries
    .filter(e => e.path !== 'conf/serialization.conf' && e.path !== 'src/main/resources/application.conf')
    .map(e => {
      let content = e.path.endsWith('.scala') ? e.content.replace(HEADER_RE, '') : e.content;
      if (e.path === 'build.sbt') {
        content = content.replaceAll(`${primaryPkg}.service.UnitTestMain`, `${primaryPkg}.infrastructure.bootstrap.UnitTestMain`);
      }
      if (e.path.startsWith('src/test/scala/') && e.path.endsWith('.scala')) {
        if (!/^package\s+/m.test(content)) {
          content = `package ${primaryPkg}.generated\n\n` + content;
        } else {
          content = content.replace(`package ${primaryPkg}.service`, `package ${primaryPkg}.infrastructure.bootstrap`);
        }
        content = content
          .replaceAll(`${primaryPkg}.service.UnitConfigurationCheck`, `${primaryPkg}.infrastructure.bootstrap.UnitConfigurationCheck`)
          .replaceAll(`${primaryPkg}.infrastructure.serialization.DomainConverters`, `${primaryPkg}.infrastructure.persistence.converters.DomainConverters`)
          .replaceAll(`${primaryPkg}.infrastructure.serialization.`, `${primaryPkg}.infrastructure.persistence.`);
        if (serviceName) {
          content = content.replaceAll(`${serviceName}Service`, `${serviceName}Contract`);
        } else {
          content = content.replace(/\b([A-Z][A-Za-z0-9_]*Service)Service\b/g, '$1Contract');
        }
        for (const agg of aggNames) {
          const protoRe = new RegExp(`${primaryPkg.replaceAll('.', '\\.')}\\.domain\\.${agg}Protocol\\.([A-Za-z0-9_]+)`, 'g');
          content = content
            .replaceAll(`${primaryPkg}.domain.${agg}State.empty`, `${primaryPkg}.domain.entities.${agg}Entity.empty`)
            .replaceAll(`${primaryPkg}.domain.${agg}State`, `${primaryPkg}.domain.entities.${agg}Entity.State`)
            .replace(protoRe, `${primaryPkg}.domain.invariants.params.${agg}RuleParams.$1Params`)
            .replaceAll(`${primaryPkg}.domain.${agg}Computations`, `${primaryPkg}.domain.services.${agg}Computations`)
            .replaceAll(`${primaryPkg}.domain.${agg}AggregateFactory.create(`, `${primaryPkg}.infrastructure.bootstrap.${agg}Bootstrap.create(`)
            .replaceAll(`${primaryPkg}.domain.${agg}Aggregate.`, `${primaryPkg}.application.aggregates.${agg}Protocol.`);
        }
      }
      if (e.path === 'src/test/scala/GeneratedActorStateSpec.scala') {
        content = content.replace(
          /^(\s+def )([A-Z])([A-Za-z0-9_]*)\(state: ([^)]+)\): ([^\s=]+) = throw new UnsupportedOperationException\("([^"]+)"\)/gm,
          (_, p, first, rest, params, ret, msg) =>
            `${p}${first.toLowerCase()}${rest}(state: ${params}): Either[${runtimeProfile.commonPackage}.CommonTypes.iMadzError, ${ret}] = Left(${runtimeProfile.commonPackage}.CommonTypes.iMadzError("UNSUPPORTED", "${msg}"))`
        );
        const guiceTest = [
          '  test("BootstrapModule satisfies all ApplicationBootstrap Guice DI bindings") {',
          '    val playStub = new com.google.inject.AbstractModule {',
          '      override def configure(): Unit = {',
          '        bind(classOf[akka.actor.ActorSystem]).toProvider(new javax.inject.Provider[akka.actor.ActorSystem] {',
          '          override def get(): akka.actor.ActorSystem = throw new UnsupportedOperationException("Stage.TOOL only")',
          '        })',
          '        bind(classOf[play.api.Configuration]).toInstance(play.api.Configuration.empty)',
          '      }',
          '    }',
          '    val injector = com.google.inject.Guice.createInjector(',
          '      com.google.inject.Stage.TOOL,',
          '      playStub,',
          `      new ${primaryPkg}.modules.BootstrapModule()`,
          '    )',
          `    assert(injector.getBinding(classOf[${primaryPkg}.infrastructure.bootstrap.ApplicationBootstrap]) != null)`,
          '  }',
          '}',
          '',
        ].join('\n');
        content = content.replace(/\}\s*$/, guiceTest);
      }
      if (e.path === 'src/test/scala/GeneratedDomainRoundtripSpec.scala') {
        content = content
          .replaceAll('StatePB', 'StatePO')
          .replaceAll('AmountDecimalPB', 'AmountDecimalPO')
          .replaceAll('MoneyPB', 'MoneyPO')
          .replace('AmountDecimalPO(encoded.copy(f0 = "1e2"))', 'AmountDecimalPO(encoded.copy(value = "1e2"))')
          .replace('MoneyPO(encoded.copy(f0 = "1e2"))', 'MoneyPO(encoded.copy(amount = "1e2"))');
      }
      return {
        path: e.path,
        kind: e.kind,
        content,
        deps: [...new Set((e.deps ?? []).map(relocateScaffoldDep))],
        sources: parseSources(e.knowledgeIds),
      };
    });

  return {
    schemaVersion: SCHEMA,
    serialization: { domainSerializers, hosts, effects, sources: serSources },
    files,
  };
}
