// Knowledge → contract derivation for the project-scaffold family (#39).
// Derives truthsrc.project-scaffold-input/v1 for build files, the 2-parent-
// class conf/serialization.conf, and unit/generated test specs.
// Pure and fail-closed (PSC_DERIVATION).
import { packageFor } from '../../generators/scala-cqrs-domain/naming.mjs';
import { flipHostBase } from './pipeline-invocation-face.mjs';
import { effectFlipHostClass } from './effect-face.mjs';

const SCHEMA = 'truthsrc.project-scaffold-input/v1';
const HEADER_RE = /^\/\/ @generated by truthsrc [^\n]+\n/;
const fail = message => { throw new Error('PSC_DERIVATION: ' + message); };

const parseSources = knowledgeIds =>
  (knowledgeIds ?? []).map(k => {
    const m = /^source:([^#]+)(#.+)$/.exec(k);
    if (!m) fail('invalid knowledgeId: ' + k);
    return { document: m[1], pointer: m[2].slice(1) };
  });

export function deriveProjectScaffold(products, options, scaffoldEntries) {
  const layout = products?.['reference-layout'];
  if (!layout || !Array.isArray(scaffoldEntries)) fail('reference-layout and scaffoldEntries required');

  const domainSerializers = layout.contexts.map((ctx, i) => ({
    key: 'domainProto' + i,
    className: packageFor(ctx, options) + '.infrastructure.serialization.DomainProtoSerializer',
  }));

  const serEntry = scaffoldEntries.find(e => e.path === 'conf/serialization.conf' || e.path === 'src/main/resources/application.conf');
  const hosts = serEntry && Object.hasOwn(products, 'saga-host-contract')
    ? (products['saga-host-contract']?.hosts ?? []).map((h, i) => {
        const pkg = packageFor(h.saga.ref.context, options);
        const base = flipHostBase(h.id);
        return {
          key: 'host' + i,
          serializerClass: pkg + '.application.' + base + 'HostSerializer',
          eventClass: pkg + '.application.' + base + 'Host$Event',
        };
      })
    : [];

  const effects = serEntry && Object.hasOwn(products, 'effect-host-contract')
    ? (products['effect-host-contract']?.hosts ?? []).map((h, i) => {
        const pkg = packageFor(h.pipeline.ref.context, options);
        const cls = effectFlipHostClass(h.id);
        return {
          key: 'effect' + i,
          serializerClass: pkg + '.application.' + cls + 'Serializer',
          eventClass: pkg + '.application.' + cls + '$Event',
        };
      })
    : [];

  const serSources = serEntry ? parseSources(serEntry.knowledgeIds) : layout.declarations.filter(d => d.ref.kind === 'aggregate').map(a => a.source);

  const files = scaffoldEntries
    .filter(e => e.path !== 'conf/serialization.conf' && e.path !== 'src/main/resources/application.conf')
    .map(e => {
      let content = e.path.endsWith('.scala') ? e.content.replace(HEADER_RE, '') : e.content;
      if (e.path === 'src/test/scala/GeneratedDomainRoundtripSpec.scala') {
        content = content
          .replaceAll('StatePB', 'StatePO')
          .replaceAll('AmountDecimalPB', 'AmountDecimalPO')
          .replaceAll('MoneyPB', 'MoneyPO')
          .replace('AmountDecimalPO(encoded.copy(f0 = "1e2"))', 'AmountDecimalPO(encoded.copy(value = "1e2"))')
          .replace('MoneyPO(encoded.copy(f0 = "1e2"))', 'MoneyPO(encoded.copy(amount = "1e2"))');
      }
      return {
        path: e.path,
        kind: e.kind,
        content,
        deps: [...(e.deps ?? [])],
        sources: parseSources(e.knowledgeIds),
      };
    });

  return {
    schemaVersion: SCHEMA,
    serialization: { domainSerializers, hosts, effects, sources: serSources },
    files,
  };
}
