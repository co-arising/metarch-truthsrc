import { at, fail, object, text } from '../products/request.mjs';
import { createClassicContext } from './context.mjs';
import { collectDependencies, fqn, typeRef } from './types.mjs';
import { getProtoOneOfCaseName } from './naming.mjs';

function pathOf(model) {
  return 'app/' + model.selfType.packageName.replaceAll('.', '/') + '/' + model.selfType.name + '.scala';
}
export function artifact(model, render, kind, source, references = []) {
  return { model, render, kind, source, references, path: pathOf(model) };
}
export function rawArtifact(model, render, kind, source, output, references = []) {
  object(output, ['path', 'stamp', 'ownerType'], at('classic-architecture'));
  if (!['scala', 'proto', 'none'].includes(output.stamp) || typeof output.path !== 'string' ||
      output.path.startsWith('/') || output.path.includes('\\') || output.path.includes('\0') ||
      output.path.split('/').some(part => !part || ['.', '..'].includes(part)))
    fail('CLASSIC_OUTPUT_PATH', 'explicit safe raw output path and stamp required', source);
  return { model, render, kind, source, references, path: output.path, stamp: output.stamp, ownerType: output.ownerType };
}
function header(options) {
  text(options.generatorVersion, at('options', '/generatorVersion'));
  if (!/^[A-Za-z0-9._-]+$/u.test(options.generatorVersion)) fail('CLASSIC_STAMP', 'single token generator version required', at('options'));
  const generated = '// @generated by CodegenMain:' + options.generatorVersion + '\n';
  if (options.knowledgeRelease === null) return generated;
  text(options.knowledgeRelease, at('options', '/knowledgeRelease'));
  if (/[\r\n\x00]/u.test(options.knowledgeRelease)) fail('CLASSIC_STAMP', 'single-line knowledge release required', at('options'));
  return generated + '// @knowledge-release ' + options.knowledgeRelease + '\n';
}
function fieldTypes(definitions) {
  return definitions.flatMap(definition => [
    ...(definition.fields ?? []).map(field => field.typeRef), ...(definition.superTypes ?? []),
  ]);
}
function sourceReferences({ model, kind, references }) {
  const roots = [...(model.dependencies ?? []), ...(references ?? [])];
  if (kind === 'domain-entity') roots.push(...fieldTypes([model.state, ...model.eventFamily.events, model.eventFamily]));
  if (kind === 'application-protocol') roots.push(model.stateType, model.eventType,
    ...fieldTypes([...model.commandFamily.commands, ...model.replies, model.commandFamily]));
  if (kind === 'command-helper') roots.push(...model.helpers.flatMap(helper =>
    [helper.commandType, helper.stateType, helper.paramType, helper.replyType, helper.errorType]));
  if (kind === 'aggregate-behavior') roots.push(model.commandHelpers, model.stateType, model.eventType, model.commandType);
  if (kind === 'aggregate-root') roots.push(model.commandFamilyType, model.stateType, model.eventType, model.behaviorObject);
  if (kind === 'aggregate-factory') roots.push(model.aggregateType, model.commandFamily,
    ...model.factoryMethods.flatMap(method => [method.returnType, ...method.parameters.map(param => param.typeRef)]));
  if (kind === 'aggregate-repository-port') roots.push(model.aggregateType, model.isImplementedBy,
    ...model.methods.flatMap(method => [method.returnType, ...method.parameters.map(param => param.typeRef)]));
  if (kind === 'aggregate-repository-implementation') roots.push(model.aggregateType, model.interfaceType,
    ...model.methods.flatMap(method => [method.paramType, method.returnType]));
  if (kind === 'value-object') roots.push(...fieldTypes([model]));
  if (kind === 'invariant-rule') roots.push(model.outputType, model.subjectType, model.triggerType, model.superInterface);
  if (kind === 'event-handler') roots.push(model.handlerTypeAlias, model.stateType, model.eventFamilyType,
    ...model.mutations.map(mutation => mutation.eventType),
    ...model.helperMethods.flatMap(method => [method.returnType, ...method.params.map(param => param.typeRef)]));
  return collectDependencies(roots.filter(Boolean));
}
function localDependencies(entry, owners) {
  const paths = new Set();
  for (const ref of sourceReferences(entry)) {
    let owner = fqn(ref);
    while (owner) {
      const path = owners.get(owner);
      if (path && path !== entry.path) paths.add(path);
      const end = owner.lastIndexOf('.');
      owner = end < 0 ? '' : owner.slice(0, end);
    }
  }
  return [...paths].sort();
}
function protoOwnerAliases(entry) {
  if (entry.kind !== 'protobuf-schema') return [];
  const { model, source } = entry;
  if (typeof model.fileName !== 'string' || !model.fileName.endsWith('.proto') ||
      !Array.isArray(model.messages) || !Array.isArray(model.enums))
    fail('CLASSIC_PROTO_OWNER', 'structured proto filename/messages/enums required for file association', source);
  const fileBase = model.fileName.slice(0, -'.proto'.length);
  // The frozen ScalaPB consumers use the file-specific package, not the proto
  // package as a catch-all owner. Nested proto declarations are not emitted.
  const pkg = model.javaPackage ?? model.packageName;
  const scalaPackage = pkg ? pkg + '.' + fileBase : fileBase;
  // Keep the declaration position and raw name: PascalCase can map different
  // members to the same FQN even inside one file. That is not a duplicate owner.
  const alias = (ref, identity) => ({ ref, identity: JSON.stringify(identity) });
  const aliases = model.enums.map((value, index) =>
    alias(typeRef(value.name, scalaPackage), ['enums', index, value.name]));
  model.messages.forEach((message, messageIndex) => {
    const messageIdentity = ['messages', messageIndex, message.name];
    aliases.push(alias(typeRef(message.name, scalaPackage), messageIdentity));
    message.oneOfs.forEach((oneOf, oneOfIndex) => {
      const oneOfIdentity = [...messageIdentity, 'oneOfs', oneOfIndex, oneOf.name];
      const owner = typeRef(getProtoOneOfCaseName(oneOf.name), scalaPackage + '.' + message.name);
      aliases.push(alias(owner, oneOfIdentity));
      oneOf.fields.forEach((field, fieldIndex) => aliases.push(alias(
        typeRef(getProtoOneOfCaseName(field.name), fqn(owner)),
        [...oneOfIdentity, 'fields', fieldIndex, field.name])));
    });
  });
  return aliases;
}
function artifactOwners(artifacts, version) {
  const declarations = artifacts.flatMap(entry => {
    const owner = entry.ownerType ?? entry.model.selfType;
    return [
      ...(owner ? [{ name: fqn(owner), path: entry.path, source: entry.source,
        identity: JSON.stringify(['ownerType', fqn(owner)]) }] : []),
      ...(version === '5' ? protoOwnerAliases(entry).map(({ ref, identity }) =>
        ({ name: fqn(ref), path: entry.path, source: entry.source, identity })) : []),
    ];
  });
  if (version === '5') {
    const seen = new Map();
    for (const declaration of declarations) {
      const key = declaration.name.normalize('NFC').toLowerCase(), previous = seen.get(key);
      if (previous && (previous.name !== declaration.name || previous.path !== declaration.path ||
          previous.identity !== declaration.identity))
        fail('CLASSIC_OWNER_COLLISION', 'conflicting source owner: ' + declaration.name, declaration.source);
      seen.set(key, declaration);
    }
  }
  return new Map(declarations.map(({ name, path }) => [name, path]));
}
function validatePackages(options) {
  for (const key of ['rootPackage', 'frameworkPackage', 'moduleName']) {
    text(options[key], at('options', '/' + key));
    if (!options[key].split('.').every(part => /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(part)))
      fail('CLASSIC_PACKAGE', 'package option must be a dotted identifier: ' + key, at('options', '/' + key));
  }
}

/** Shared complete-file assembly. The versioned target owns the family selection. */
export function emitClassicArtifacts(product, options, version, buildArtifacts) {
  object(options, ['rootPackage', 'frameworkPackage', 'moduleName', 'generatorVersion', 'knowledgeRelease'], at('options'));
  validatePackages(options);
  const ctx = createClassicContext(product.system, {
    rootPackage: options.rootPackage, frameworkPackage: options.frameworkPackage, moduleName: options.moduleName,
    ...(version === '5' ? { multiProject: product.technical?.multiProject ?? false,
      formalSemantics: product.technical?.formalSemantics ?? null,
      strictInput: product.technical?.strictInput ?? null, composition: product.technical?.composition ?? null } : {}),
  }, version);
  const stamp = header(options), artifacts = buildArtifacts(product, ctx);
  if (['4', '5'].includes(version)) {
    const paths = artifacts.map(entry => entry.path.normalize('NFC').toLowerCase());
    if (new Set(paths).size !== paths.length) fail('CLASSIC_REPOSITORY_PATH', 'classic source paths must be unique before ownership assembly', at('classic-architecture'));
  }
  const owners = artifactOwners(artifacts, version);
  const footprint = Object.freeze([{ id: 'classic-architecture', version }]);
  return artifacts.map(entry => ({
    path: entry.path, content: (entry.stamp === 'none' ? '' : stamp) + entry.render(entry.model), kind: entry.kind,
    deps: localDependencies(entry, owners),
    knowledgeIds: ['source:' + entry.source.document + '#' + entry.source.pointer], productFootprint: footprint, merge: null,
  }));
}
